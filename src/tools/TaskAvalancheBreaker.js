import React, { useCallback, useEffect, useMemo, useState } from 'react';
import { useClaudeAPI } from '../hooks/useClaudeAPI';
import { useTheme } from '../hooks/useTheme';
import { useRegisterActions } from '../components/ActionBarContext';
import { useTranslation } from '../i18n/useTranslation';
import { pickExample } from '../utils/exampleRotation';
import { toolTagline } from '../utils/toolTagline';

const BRAND = '\n\n— Generated by DeftBrain · deftbrain.com';

const REASONS = [
  { value: 'too_many_steps', labelKey: 'tab_reason_too_many_steps' },
  { value: 'dont_know_start', labelKey: 'tab_reason_dont_know_start' },
  { value: 'emotionally_difficult', labelKey: 'tab_reason_emotionally_difficult' },
  { value: 'boring', labelKey: 'tab_reason_boring' },
  { value: 'unfamiliar', labelKey: 'tab_reason_unfamiliar' },
];

const TIME_OPTIONS = [
  { value: '2', labelKey: 'tab_time_2' },
  { value: '5', labelKey: 'tab_time_5' },
  { value: '10', labelKey: 'tab_time_10' },
  { value: '20', labelKey: 'tab_time_20' },
];

// Two rotated scenarios spanning the tool's range: a logistics-heavy project
// with no obvious first move, and an emotionally difficult one where the
// overwhelm is as much about the content as the size.
const EXAMPLES = [
  { projectKey: 'tab_ex1_project', reasons: ['too_many_steps', 'dont_know_start', 'unfamiliar'], time: '5' },
  { projectKey: 'tab_ex2_project', reasons: ['too_many_steps', 'emotionally_difficult', 'dont_know_start'], time: '5' },
];

const TaskAvalancheBreaker = ({ tool }) => {
  const { callToolEndpoint, loading } = useClaudeAPI();
  const { isDark } = useTheme();
  const { t } = useTranslation();

  const c = {
    card: isDark ? 'bg-zinc-800' : 'bg-white',
    cardAlt: isDark ? 'bg-zinc-900/55' : 'bg-slate-50',
    text: isDark ? 'text-zinc-50' : 'text-slate-900',
    textSecondary: isDark ? 'text-zinc-300' : 'text-slate-600',
    textMuted: isDark ? 'text-zinc-400' : 'text-slate-500',
    labelText: isDark ? 'text-zinc-200' : 'text-slate-700',
    required: isDark ? 'text-amber-400' : 'text-amber-700',
    input: isDark
      ? 'bg-zinc-900 border-zinc-600 text-zinc-50 placeholder:text-zinc-500'
      : 'bg-white border-slate-300 text-slate-900 placeholder:text-slate-400',
    btnPrimary: isDark ? 'bg-cyan-600 hover:bg-cyan-500 text-white' : 'bg-cyan-700 hover:bg-cyan-800 text-white',
    btnIdle: isDark ? '!bg-transparent !border-2 !border-cyan-500/85 !text-cyan-300 cursor-not-allowed'
                    : '!bg-transparent !border-2 !border-cyan-600/85 !text-cyan-800 cursor-not-allowed',
    btnSecondary: isDark ? 'bg-zinc-700 hover:bg-zinc-600 text-zinc-100' : 'bg-slate-100 hover:bg-slate-200 text-slate-800',
    border: isDark ? 'border-zinc-700' : 'border-slate-200',
    pillActive: isDark ? 'border-emerald-500 bg-emerald-900/30 text-emerald-200' : 'border-emerald-600 bg-emerald-100 text-emerald-900',
    pillInactive: isDark ? 'border-zinc-600 text-zinc-400 hover:border-zinc-500' : 'border-slate-300 text-slate-600 hover:border-slate-400',
    danger: isDark ? 'bg-red-900/20 border-red-700 text-red-200' : 'bg-red-50 border-red-200 text-red-800',
    success: isDark ? 'bg-emerald-900/20 border-emerald-700 text-emerald-200' : 'bg-emerald-50 border-emerald-300 text-emerald-800',
    warning: isDark ? 'bg-amber-900/20 border-amber-700 text-amber-200' : 'bg-amber-50 border-amber-300 text-amber-800',
    foothold: isDark ? 'bg-emerald-950/25 border-emerald-800/60' : 'bg-emerald-50 border-emerald-200',
  };
  c.textMuteded = c.textMuted;
  c.label = c.labelText;

  const linkStyle = isDark
    ? 'text-cyan-400 hover:text-cyan-300 underline underline-offset-2'
    : 'text-cyan-700 hover:text-cyan-800 underline underline-offset-2';

  const [project, setProject] = useState('');
  const [reasons, setReasons] = useState([]);
  const [time, setTime] = useState('5');
  const [result, setResult] = useState(null);
  const [showSmaller, setShowSmaller] = useState(false);
  const [stepIndex, setStepIndex] = useState(0);
  const [error, setError] = useState('');

  const hasDraft = !!(project.trim() || reasons.length || result);

  const handleReset = useCallback(() => {
    setProject('');
    setReasons([]);
    setTime('5');
    setResult(null);
    setShowSmaller(false);
    setStepIndex(0);
    setError('');
  }, []);

  const loadExample = useCallback(() => {
    const ex = pickExample('TaskAvalancheBreaker', EXAMPLES);
    setProject(t(ex.projectKey));
    setReasons(ex.reasons);
    setTime(ex.time);
    setResult(null);
    setShowSmaller(false);
    setStepIndex(0);
    setError('');
  }, [t]);

  const toggleReason = value => setReasons(prev => prev.includes(value) ? prev.filter(x => x !== value) : [...prev, value]);

  const run = useCallback(async () => {
    setError('');
    if (!project.trim()) {
      setError(t('tab_error_need_project'));
      return;
    }
    try {
      const data = await callToolEndpoint('task-avalanche-breaker', {
        project: project.trim(),
        stuckReasons: reasons,
        availableTime: time,
      });
      setResult(data);
      setShowSmaller(false);
      setStepIndex(0);
    } catch (e) {
      setError(e?.message || t('tab_error_generic'));
    }
  }, [project, reasons, time, callToolEndpoint, t]);

  // Cmd/Ctrl+Enter submits from anywhere on the form.
  useEffect(() => {
    const handler = (e) => {
      if (e.key === 'Enter' && (e.metaKey || e.ctrlKey) && !loading && project.trim() && !result) run();
    };
    document.addEventListener('keydown', handler);
    return () => document.removeEventListener('keydown', handler);
  }, [loading, project, result, run]);

  const current = useMemo(() => {
    if (!result) return null;
    if (stepIndex === 0) return { ...result.first_move, first: true };
    return { ...(result.after_that?.[stepIndex - 1] || {}), first: false };
  }, [result, stepIndex]);

  const totalSteps = result ? 1 + (result.after_that?.length || 0) : 0;

  const summaryText = useMemo(() => {
    if (!result) return '';
    return [
      t('tab_copy_header'),
      '',
      `${t('tab_your_foothold')}: ${result.first_move?.action}`,
      `${t('tab_done_when')} ${result.first_move?.done_when}`,
      BRAND,
    ].join('\n');
  }, [result, t]);
  useRegisterActions(result ? summaryText : '', tool?.title);

  return (
    <div className={`space-y-4 ${c.text}`}>
      <div className={`border rounded-2xl p-5 ${c.card} ${c.border}`}>
        <div className="flex items-start justify-between gap-4">
          <div>
            {/* PF-30 — the wrapper already prints the name as the page <h1>. */}
            <p className={`text-base ${c.textSecondary}`}>
              <span className="me-2 text-lg">{tool?.icon ?? '⛏️'}</span>{toolTagline(tool?.tagline ?? t('tab_tagline'))}
            </p>
            <button onClick={loadExample} disabled={loading} style={{ backgroundColor: (tool?.headerColor ?? '#888888') + '80' }} className="mt-2 px-4 py-2 rounded-full text-sm font-semibold border border-black/25 text-zinc-900 shadow-sm hover:brightness-105 hover:shadow transition disabled:opacity-40 whitespace-nowrap">✨ {t('try_example')}</button>
          </div>
          {hasDraft && (
            <button onClick={handleReset} className={`shrink-0 rounded-lg px-3 py-2 text-sm font-semibold ${c.btnSecondary}`}>↺ {t('start_over')}</button>
          )}
        </div>
      </div>

      {!result && (
        <section className={`border rounded-2xl p-4 sm:p-5 ${c.card} ${c.border}`}>
          <label className={`font-bold ${c.text}`}>{t('tab_project_label')} <span className={c.required}>*</span></label>
          <textarea
            value={project}
            onChange={e => setProject(e.target.value)}
            rows={5}
            placeholder={t('tab_project_ph')}
            className={`mt-2 w-full rounded-xl border p-3 ${c.input}`}
          />

          <div className="mt-5">
            <div className={`text-sm font-semibold ${c.text}`}>{t('tab_why_label')} <span className={`font-normal ${c.textMuted}`}>{t('tab_why_optional')}</span></div>
            <div className="mt-2 flex flex-wrap gap-2">
              {REASONS.map(r => (
                <button
                  key={r.value}
                  type="button"
                  onClick={() => toggleReason(r.value)}
                  className={`rounded-full border px-3 py-2 text-sm font-semibold transition-colors ${reasons.includes(r.value) ? c.pillActive : c.pillInactive}`}
                >{t(r.labelKey)}</button>
              ))}
            </div>
          </div>

          <div className="mt-5">
            <div className={`text-sm font-semibold ${c.text}`}>{t('tab_time_label')}</div>
            <div className="mt-2 flex flex-wrap gap-2">
              {TIME_OPTIONS.map(opt => (
                <button
                  key={opt.value}
                  type="button"
                  onClick={() => setTime(opt.value)}
                  className={`rounded-full border px-3 py-2 text-sm font-semibold transition-colors ${time === opt.value ? c.pillActive : c.pillInactive}`}
                >{t(opt.labelKey)}</button>
              ))}
            </div>
          </div>

          {error && <div className={`mt-4 p-3 rounded-xl border text-sm ${c.danger}`}><span className="me-1">⚠️</span>{error}</div>}
          <button title={t('cmd_enter')} onClick={run} disabled={loading || !project.trim()}
            className={`relative mt-6 w-full py-3 rounded-xl font-black flex items-center justify-center gap-2 ${!project.trim() ? c.btnIdle : c.btnPrimary} disabled:opacity-50`}>
            {loading
              ? <><span className="inline-block animate-spin">{tool?.icon ?? '⛏️'}</span> {t('tab_processing')}</>
              : <><span>{tool?.icon ?? '⛏️'}</span> {t('tab_submit_btn')}</>}
            {!loading && project.trim() && (
              <kbd aria-hidden="true"
                className="hidden sm:flex items-center absolute end-3 top-1/2 -translate-y-1/2 px-1.5 py-0.5 rounded border border-white/30 bg-white/15 text-[10px] font-bold tracking-wide">
                ⌘↵
              </kbd>
            )}
          </button>

          <p className={`mt-4 text-xs text-center ${c.textMuted}`}>
            {t('tab_xref_q')} <a href="/BrainDumpBuddy" className={linkStyle}>{t('tab_xref_name')}</a> {t('tab_xref_tail')}
          </p>
        </section>
      )}

      {result && (
        <>
          {result.project_read && (
            <section className={`border rounded-2xl p-4 ${c.cardAlt} ${c.border}`}>
              <div className={`text-sm ${c.textSecondary}`}>{result.project_read}</div>
            </section>
          )}

          <section className={`border rounded-2xl p-5 ${c.foothold}`}>
            <div className={`text-xs font-black uppercase tracking-wide ${c.textMuted}`}>
              {stepIndex === 0 ? t('tab_your_foothold') : t('tab_next_foothold', { n: stepIndex + 1, total: totalSteps })}
            </div>
            <div className={`mt-2 text-xl sm:text-2xl font-black leading-snug ${c.text}`}>{current?.action}</div>
            {current?.why_this && <div className={`mt-3 text-sm leading-6 ${c.textSecondary}`}><strong>{t('tab_why_this')}</strong> {current.why_this}</div>}
            {current?.done_when && (
              <div className={`mt-3 rounded-xl border p-3 ${c.card} ${c.border}`}>
                <span className={`font-semibold ${c.text}`}>{t('tab_done_when')} </span>
                <span className={c.textSecondary}>{current.done_when}</span>
              </div>
            )}

            {stepIndex === 0 && current?.if_too_hard && (
              <div className="mt-4">
                <button onClick={() => setShowSmaller(v => !v)} className={`rounded-lg px-3 py-2 text-sm font-semibold ${c.btnSecondary}`}>{t('tab_still_too_much')}</button>
                {showSmaller && (
                  <div className={`mt-3 rounded-xl border p-3 ${c.card} ${c.border}`}>
                    <span className={`font-semibold ${c.text}`}>{t('tab_make_smaller')} </span>
                    <span className={c.textSecondary}>{current.if_too_hard}</span>
                  </div>
                )}
              </div>
            )}
          </section>

          <section className={`border rounded-2xl p-4 ${c.card} ${c.border}`}>
            <div className={`text-sm ${c.textSecondary}`}>{result.permission_to_stop}</div>
            <div className="mt-4 flex flex-wrap gap-3">
              {stepIndex < totalSteps - 1 && (
                <button onClick={() => { setStepIndex(i => i + 1); setShowSmaller(false); }} className={`rounded-xl px-4 py-2.5 font-bold ${c.btnPrimary}`}>✓ {t('tab_did_it_next')}</button>
              )}
              {stepIndex >= totalSteps - 1 && (
                <button onClick={() => handleReset()} className={`rounded-xl px-4 py-2.5 font-bold ${c.btnPrimary}`}>✓ {t('tab_enough_for_now')}</button>
              )}
              <button onClick={() => setResult(null)} className={`rounded-xl px-4 py-2.5 font-semibold ${c.btnSecondary}`}>{t('tab_change_project')}</button>
            </div>
          </section>

          {stepIndex === 0 && result.after_that?.length > 0 && (
            <details className={`border rounded-2xl p-4 ${c.card} ${c.border}`}>
              <summary className={`cursor-pointer font-semibold ${c.text}`}>{t('tab_see_path_ahead')}</summary>
              <div className="mt-3 space-y-2">
                {result.after_that?.map((x, i) => (
                  <div key={i} className={`rounded-lg p-3 ${c.cardAlt}`}>
                    <span className={`font-semibold ${c.text}`}>{i + 2}. {x.action}</span>
                  </div>
                ))}
              </div>
            </details>
          )}

          <p className={`text-xs text-center ${c.textMuted}`}>
            {t('tab_xref_q')} <a href="/BrainDumpBuddy" className={linkStyle}>{t('tab_xref_name')}</a> {t('tab_xref_tail')}
          </p>
        </>
      )}
    </div>
  );
};

TaskAvalancheBreaker.displayName = 'TaskAvalancheBreaker';
export default TaskAvalancheBreaker;
