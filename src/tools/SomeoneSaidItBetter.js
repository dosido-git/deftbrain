import React, { useState, useEffect, useCallback, useRef } from 'react';
import { useClaudeAPI } from '../hooks/useClaudeAPI';
import { useTheme } from '../hooks/useTheme';
import { usePersistentState } from '../hooks/usePersistentState';
import { useRegisterActions } from '../components/ActionBarContext';
import { useTranslation } from '../i18n/useTranslation';
import { pickExample } from '../utils/exampleRotation';
import { revealSection } from '../utils/revealSection';

const BRAND = '\n\n— Generated by DeftBrain · deftbrain.com';

const NEEDS = [
  { value: 'perspective',   key: 'ssib_need_perspective' },
  { value: 'courage',       key: 'ssib_need_courage' },
  { value: 'comfort',       key: 'ssib_need_comfort' },
  { value: 'motivation',    key: 'ssib_need_motivation' },
  { value: 'reality_check', key: 'ssib_need_reality_check' },
  { value: 'humor',         key: 'ssib_need_humor' },
  { value: 'surprise_me',   key: 'ssib_need_surprise_me' },
];

const VOICES = [
  { value: 'any',        key: 'ssib_voice_any' },
  { value: 'wise',       key: 'ssib_voice_wise' },
  { value: 'reassuring', key: 'ssib_voice_reassuring' },
  { value: 'bracing',    key: 'ssib_voice_bracing' },
  { value: 'witty',      key: 'ssib_voice_witty' },
  { value: 'unexpected', key: 'ssib_voice_unexpected' },
];

// Five, rotated: spans 5 of the tool's 7 needs and 5 of its 6 voices across
// genuinely different life situations — not five versions of "hard day at
// the office" with the dropdowns changed underneath.
const EXAMPLES = [
  { situationKey: 'ssib_ex1_situation', need: 'perspective', voice: 'bracing' },
  { situationKey: 'ssib_ex2_situation', need: 'comfort',      voice: 'wise' },
  { situationKey: 'ssib_ex3_situation', need: 'motivation',   voice: 'unexpected' },
  { situationKey: 'ssib_ex4_situation', need: 'courage',      voice: 'witty' },
  { situationKey: 'ssib_ex5_situation', need: 'reality_check', voice: 'reassuring' },
];

const SomeoneSaidItBetter = ({ tool }) => {
  const { callToolEndpoint, loading, userLocale, userCurrency, userRegion } = useClaudeAPI();
  const { isDark } = useTheme();
  const { t } = useTranslation();

  const c = {
    card:          isDark ? 'bg-zinc-800' : 'bg-white',
    cardAlt:       isDark ? 'bg-zinc-700/50' : 'bg-slate-50',
    input:         isDark ? 'bg-zinc-900 border-zinc-600 text-zinc-100 placeholder-zinc-400 focus:border-cyan-500 focus:ring-cyan-500/20' : 'bg-white border-gray-300 text-gray-900 placeholder-gray-400 focus:border-cyan-500 focus:ring-cyan-100',
    text:          isDark ? 'text-zinc-50' : 'text-gray-900',
    textSecondary: isDark ? 'text-zinc-300' : 'text-gray-600',
    textMuted:     isDark ? 'text-zinc-400' : 'text-gray-500',
    labelText:     isDark ? 'text-zinc-200' : 'text-gray-700',
    required:      isDark ? 'text-amber-400' : 'text-amber-700',
    accentTxt:     isDark ? 'text-cyan-400' : 'text-cyan-600',
    btnPrimary:    isDark ? 'bg-cyan-600 hover:bg-cyan-500 text-white' : 'bg-cyan-600 hover:bg-cyan-700 text-white',
    // Waiting for input: an outline, not a smudge. Empty fill keeps "filled"
    // meaning "ready"; the border and label carry the visibility. Important
    // modifiers because tools carry their own border/text utilities on the
    // submit and Tailwind resolves conflicts by stylesheet order, not class
    // order. See the PF-13 exception in audit/audit_v2-3-2.py.
    btnIdle:       isDark ? '!bg-transparent !border-2 !border-cyan-500/85 !text-cyan-300 cursor-not-allowed'
                          : '!bg-transparent !border-2 !border-cyan-600/85 !text-cyan-800 cursor-not-allowed',
    btnSecondary:  isDark ? 'bg-zinc-700 hover:bg-zinc-600 text-zinc-200' : 'bg-gray-100 hover:bg-gray-200 text-gray-700',
    border:        isDark ? 'border-zinc-700' : 'border-gray-200',
    success:       isDark ? 'bg-emerald-900/20 border-emerald-700 text-emerald-200' : 'bg-emerald-50 border-emerald-300 text-emerald-800',
    warning:       isDark ? 'bg-amber-900/20 border-amber-700 text-amber-200' : 'bg-amber-50 border-amber-300 text-amber-800',
    danger:        isDark ? 'bg-red-900/20 border-red-700 text-red-200' : 'bg-red-50 border-red-200 text-red-800',
    pillActive:    isDark ? 'border-cyan-500 bg-cyan-900/30 text-cyan-200' : 'border-cyan-600 bg-cyan-100 text-cyan-900',
    pillInactive:  isDark ? 'border-zinc-600 text-zinc-400 hover:border-zinc-500' : 'border-gray-300 text-gray-500 hover:border-gray-400',
    quoteBg:       isDark ? 'bg-zinc-900/60 border-zinc-700' : 'bg-[#faf8f5] border-[#e8e1d5]',
  };
  c.textMuteded = c.textMuted;
  c.label = c.labelText;

  const linkStyle = isDark
    ? 'text-cyan-400 hover:text-cyan-300 underline underline-offset-2'
    : 'text-cyan-700 hover:text-cyan-800 underline underline-offset-2';

  // ── State ──
  const [situation, setSituation] = useState('');
  const [need, setNeed] = useState('perspective');
  const [voice, setVoice] = useState('any');
  const [results, setResults] = usePersistentState('someone-said-it-better-result', null);
  const [sessionHistory, setSessionHistory] = usePersistentState('someone-said-it-better-history', []);
  const [showHistory, setShowHistory] = useState(false);
  const [error, setError] = useState('');
  const resultsRef = useRef(null);

  const canSubmit = situation.trim().length > 0;

  const handleSubmit = useCallback(async () => {
    if (!canSubmit || loading) return;
    setError(''); setResults(null);
    try {
      const data = await callToolEndpoint('someone-said-it-better', {
        situation: situation.trim(), need, voice, userLocale, userCurrency, userRegion,
      });
      setResults(data);
      setSessionHistory(prev => [{
        id: Date.now(), date: new Date().toISOString(),
        // Exception: this is preview-text truncation, not the history-array
        // cap (that's the outer .slice(0, 6) below, PF-25 standard).
        preview: situation.trim().slice(0, 40),
        situation: situation.trim(), need, voice, result: data,
      }, ...prev].slice(0, 6));
    } catch (e) { setError(e.message || t('ssib_error_generic')); }
  }, [canSubmit, loading, situation, need, voice, callToolEndpoint, setResults, setSessionHistory, userLocale, userCurrency, userRegion, t]);

  // Cmd/Ctrl+Enter submits from anywhere
  useEffect(() => {
    const handler = (e) => {
      const tag = document.activeElement?.tagName;
      if (tag === 'SELECT') return;
      if (e.key === 'Enter' && (e.metaKey || e.ctrlKey) && !loading) handleSubmit();
    };
    document.addEventListener('keydown', handler);
    return () => document.removeEventListener('keydown', handler);
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [loading, handleSubmit]);

  const loadExample = useCallback(() => {
    const ex = pickExample('SomeoneSaidItBetter', EXAMPLES);
    setSituation(t(ex.situationKey));
    setNeed(ex.need);
    setVoice(ex.voice);
    setResults(null);
    setError('');
  }, [setResults, t]);

  const handleReset = useCallback(() => {
    setSituation(''); setNeed('perspective'); setVoice('any'); setResults(null); setError('');
  }, [setResults]);

  const loadHistoryEntry = useCallback((entry) => {
    setSituation(entry.situation || '');
    setNeed(entry.need || 'perspective');
    setVoice(entry.voice || 'any');
    setResults(entry.result || null);
    setError('');
    setShowHistory(false);
  }, [setResults]);

  const roleLabel = (role) => {
    if (role === 'different_way') return t('ssib_role_different_way');
    if (role === 'one_to_keep') return t('ssib_role_one_to_keep');
    return t('ssib_role_another_angle');
  };

  const buildText = useCallback(() => {
    if (!results) return '';
    const lines = [`💬 ${tool?.title || t('ssib_title')}`, '', `${t('ssib_your_situation')}: ${results.situation_as_understood}`, ''];
    results.picks?.forEach((p) => {
      lines.push(`— ${roleLabel(p.role)} —`);
      lines.push(`"${p.quote.text}"`);
      lines.push(`— ${p.quote.author}${p.quote.work ? `, ${p.quote.work}` : ''}`);
      lines.push('');
      lines.push(`${t('ssib_why_this_one')}: ${p.why_this_one}`);
      lines.push(`${t('ssib_verify_link')}: ${p.quote.url}`);
      lines.push('');
    });
    return lines.join('\n') + BRAND;
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [results, tool, t]);

  // ─── Register export content ───
  useRegisterActions(results ? buildText() : '', tool?.title);

  // ─── Scroll to results ───
  useEffect(() => {
    if (!results) return;
    const timer = setTimeout(() => revealSection(resultsRef.current), 100);
    return () => clearTimeout(timer);
  }, [results]);

  return (
    <div className={`space-y-4 ${c.text}`}>

      {/* Input card */}
      <div className={`${c.card} border ${c.border} rounded-xl p-6`}>
        <div className={`mb-5 pb-4 border-b ${c.border}`}>
          <div className="flex items-start justify-between gap-3">
            <div>
              {/* PF-30 — the wrapper already prints the name as the page <h1>. */}
              <p className={`text-base ${c.textSecondary}`}>
                <span className="me-2 text-lg">{tool?.icon ?? '📚'}</span>{tool?.tagline ?? t('ssib_tagline')}
              </p>
              <button onClick={loadExample} disabled={loading} style={{ backgroundColor: (tool?.headerColor ?? '#888888') + '80' }} className="mt-2 px-4 py-2 rounded-full text-sm font-semibold border border-black/25 text-zinc-900 shadow-sm hover:brightness-105 hover:shadow transition disabled:opacity-40 whitespace-nowrap">✨ {t('try_example')}</button>
            </div>
            <div className="flex items-center gap-2 flex-shrink-0">
              {sessionHistory.length > 0 && (
                <button onClick={() => setShowHistory(s => !s)} className={`${c.btnSecondary} px-3 py-1.5 rounded-lg text-xs font-bold`}>
                  🕓 {sessionHistory.length}
                </button>
              )}
              {(results || situation.trim()) && (
                <button onClick={handleReset} className={`${c.btnSecondary} px-3 py-1.5 rounded-lg text-xs font-bold`}>
                  ↺ {t('start_over')}
                </button>
              )}
            </div>
          </div>

          {showHistory && sessionHistory.length > 0 && (
            <div className="mt-3 space-y-1">
              {sessionHistory.map(h => (
                <button key={h.id} onClick={() => loadHistoryEntry(h)}
                  className={`w-full text-start p-2 rounded-lg text-xs ${isDark ? 'hover:bg-zinc-700' : 'hover:bg-gray-100'} transition-colors flex items-center justify-between`}>
                  <span className={c.text}>{h.preview}</span>
                  <span className={c.textMuteded}>{new Date(h.date).toLocaleDateString()}</span>
                </button>
              ))}
            </div>
          )}
        </div>

        {!results && (
          <div className="space-y-4">
            <div>
              <label className={`block text-sm font-semibold mb-1.5 ${c.text}`}>
                {t('ssib_situation_label')} <span className={c.required}>*</span>
              </label>
              <textarea value={situation} onChange={e => setSituation(e.target.value)}
                onKeyDown={e => { if (e.key === 'Enter' && (e.metaKey || e.ctrlKey) && !loading && canSubmit) { e.preventDefault(); handleSubmit(); } }}
                placeholder={t('ssib_situation_ph')}
                rows={5} maxLength={2200}
                className={`w-full px-4 py-3 rounded-xl border text-sm resize-none ${c.input}`} />
            </div>

            <div>
              <label className={`block text-sm font-semibold mb-1.5 ${c.text}`}>{t('ssib_need_label')}</label>
              <div className="flex flex-wrap gap-2">
                {NEEDS.map(n => (
                  <button key={n.value} onClick={() => setNeed(n.value)}
                    className={`px-3 py-1.5 rounded-full border text-sm font-medium transition-colors ${need === n.value ? c.pillActive : c.pillInactive}`}>
                    {t(n.key)}
                  </button>
                ))}
              </div>
            </div>

            <div>
              <label className={`block text-sm font-semibold mb-1.5 ${c.text}`}>{t('ssib_voice_label')}</label>
              <div className="flex flex-wrap gap-2">
                {VOICES.map(v => (
                  <button key={v.value} onClick={() => setVoice(v.value)}
                    className={`px-3 py-1.5 rounded-full border text-sm font-medium transition-colors ${voice === v.value ? c.pillActive : c.pillInactive}`}>
                    {t(v.key)}
                  </button>
                ))}
              </div>
            </div>

            <p className={`text-xs ${c.textMuted}`}>{t('ssib_source_rule')}</p>

            {error && <div className={`p-3 rounded-xl border text-sm ${c.danger}`}><span className="me-1">⚠️</span>{error}</div>}

            <button title={t('cmd_enter')} onClick={handleSubmit} disabled={loading || !canSubmit}
              className={`relative w-full py-3 rounded-xl font-bold min-h-[48px] flex items-center justify-center gap-2 ${!canSubmit ? c.btnIdle : c.btnPrimary}`}>
              {loading
                ? <><span className="inline-block animate-spin">{tool?.icon ?? '📚'}</span> {t('ssib_processing')}</>
                : <><span>{tool?.icon ?? '📚'}</span> {t('ssib_submit')}</>}
              {!loading && (
                <kbd aria-hidden="true"
                  className="hidden sm:flex items-center absolute end-3 top-1/2 -translate-y-1/2 px-1.5 py-0.5 rounded border border-white/30 bg-white/15 text-[10px] font-bold tracking-wide">
                  ⌘↵
                </kbd>
              )}
            </button>

            <p className={`text-xs text-center ${c.textMuted}`}>
              {t('ssib_xref_own_words_q')} <a href="/TruthBomb" className={linkStyle}>{t('ssib_xref_own_words')}</a>
            </p>
          </div>
        )}
      </div>

      {/* Results */}
      {results && (
        <div className="space-y-4">
          <div data-copy-results ref={resultsRef} data-results-anchor className="scroll-mt-24" />

          <div className={`${c.card} border ${c.border} rounded-xl p-5`}>
            <p className={`text-xs font-black uppercase tracking-widest ${c.textMuted}`}>{t('ssib_your_situation')}</p>
            <p className={`mt-2 text-lg font-semibold ${c.text}`}>{results.situation_as_understood}</p>
            <p className={`mt-2 text-xs ${c.textMuted}`}>{t('ssib_verified_note')}</p>
          </div>

          {results.picks?.map((p) => (
            <div key={p.quote_id} className={`rounded-xl border p-6 ${c.quoteBg}`}>
              <div className={`text-xs font-bold tracking-widest ${c.accentTxt}`}>{roleLabel(p.role)}</div>
              <blockquote className={`mt-4 text-xl font-medium leading-relaxed ${c.text}`}>"{p.quote.text}"</blockquote>
              <div className={`mt-3 ${c.textSecondary}`}>
                — <strong>{p.quote.author}</strong>
                {p.quote.work ? <> , <em>{p.quote.work}</em></> : null}
                {p.quote.date ? ` · ${p.quote.date}` : ''}
              </div>
              <div className="mt-5">
                <p className={`text-xs font-bold uppercase tracking-wide ${c.textMuted}`}>{t('ssib_why_this_one')}</p>
                <p className={`mt-1 text-sm leading-relaxed ${c.textSecondary}`}>{p.why_this_one}</p>
              </div>
              <a href={p.quote.url} target="_blank" rel="noreferrer" className={`mt-5 inline-block text-sm ${linkStyle}`}>
                ↗ {t('ssib_verify_link')} · {p.quote.publisher || p.quote.source_title}
              </a>
            </div>
          ))}

          <p className={`text-xs text-center ${c.textMuted}`}>
            {t('ssib_xref_toast_q')} <a href="/ToastWriter" className={linkStyle}>{t('ssib_xref_toast')}</a>
          </p>
        </div>
      )}
    </div>
  );
};

SomeoneSaidItBetter.displayName = 'SomeoneSaidItBetter';
export default SomeoneSaidItBetter;
