const TRACK_INITIAL = { currentIdx: 0, elapsed: 0, totalElapsed: 0, paused: false, extended: 0 };

function trackReducer(state, action) {
  switch (action.type) {
    case 'tick':    return { ...state, elapsed: state.elapsed + 1, totalElapsed: state.totalElapsed + 1 };
    case 'next':    return { ...state, currentIdx: state.currentIdx + 1, elapsed: 0, extended: 0 };
    case 'prev':    return { ...state, currentIdx: Math.max(0, state.currentIdx - 1), elapsed: 0, extended: 0 };
    case 'extend':  return { ...state, extended: state.extended + action.secs };
    case 'pause':   return { ...state, paused: !state.paused };
    default:        return state;
  }
}

function KeepOnTrack({ results, c, isDark, onFinish, t }) {
  const [s, dispatch] = useReducer(trackReducer, TRACK_INITIAL);
  const { currentIdx, elapsed, totalElapsed, paused, extended } = s;
  const timerRef = useRef(null);

  const items = results?.meeting_plan?.agenda || [];
  const current = items[currentIdx];
  const allocated = (Number(current?.minutes) || 0) * 60 + extended;
  const remaining = Math.max(allocated - elapsed, 0);
  const progress = allocated > 0 ? Math.min(elapsed / allocated, 1) : 0;
  const overTime = elapsed > allocated;

  useEffect(() => {
    if (paused) return undefined;
    timerRef.current = setInterval(() => dispatch({ type: 'tick' }), 1000);
    return () => clearInterval(timerRef.current);
  }, [paused]);

  const fmt = (n) => `${Math.floor(n / 60)}:${String(n % 60).padStart(2, '0')}`;
  const next = () => { if (currentIdx < items.length - 1) dispatch({ type: 'next' }); else onFinish(); };

  const watch = results?.watch_for || [];

  return (
    <div className="space-y-4">
      <div className={`${c.card} border ${c.border} rounded-xl p-4`}>
        <div className="flex items-center gap-2 mb-2">
          {items.map((_, i) => (
            <div key={i} className={`flex-1 h-2 rounded-full ${i < currentIdx ? 'bg-emerald-500' : i === currentIdx ? (overTime ? 'bg-red-500' : 'bg-cyan-500') : (isDark ? 'bg-zinc-700' : 'bg-slate-200')}`} />
          ))}
        </div>
        <p className={`text-xs ${c.textMuted}`}>{t('mhp_item_of', { n: currentIdx + 1, total: items.length })} · {t('mhp_total_elapsed', { time: fmt(totalElapsed) })}</p>
      </div>

      <div className={`${c.timerBg} rounded-xl p-6 text-center`}>
        <p className={`text-sm ${c.timerText} opacity-70 mb-1`}>{current?.title}</p>
        <p className={`text-6xl font-black ${overTime ? 'text-red-400' : c.timerText} font-mono`}>
          {overTime ? '-' : ''}{fmt(overTime ? elapsed - allocated : remaining)}
        </p>
        <p className={`text-xs ${c.timerText} opacity-50 mt-1`}>{t('mhp_elapsed_allocated', { elapsed: fmt(elapsed), allocated: fmt(allocated) })}</p>
        <div className="w-full h-2 rounded-full bg-white/10 mt-4 overflow-hidden">
          <div className={`h-full rounded-full transition-all ${overTime ? 'bg-red-500' : progress > 0.8 ? 'bg-amber-400' : 'bg-emerald-400'}`} style={{ width: `${Math.min(progress * 100, 100)}%` }} />
        </div>
        <div className="flex items-center justify-center gap-4 mt-4">
          <button onClick={() => dispatch({ type: 'prev' })} disabled={currentIdx === 0} aria-label={t('mhp_prev_block')}
            className="text-white/60 hover:text-white disabled:opacity-40 text-lg min-h-[44px] px-2">⏮️</button>
          <button onClick={() => dispatch({ type: 'pause' })} aria-label={paused ? t('mhp_resume') : t('mhp_pause')}
            className="text-white text-2xl min-h-[44px] px-2">{paused ? '▶️' : '⏸️'}</button>
          <button onClick={next} aria-label={t('mhp_next_block')}
            className="text-white text-lg min-h-[44px] px-2">{currentIdx < items.length - 1 ? '⏭️' : '🏁'}</button>
        </div>
        <div className="flex items-center justify-center gap-2 mt-3">
          {[60, 120, 300].map(sec => (
            <button key={sec} onClick={() => dispatch({ type: 'extend', secs: sec })}
              className="text-xs text-white/60 hover:text-white border border-white/20 px-2 py-1 rounded">
              {t('mhp_add_minutes', { n: sec / 60 })}
            </button>
          ))}
        </div>
      </div>

      <div className={`${c.card} border ${c.border} rounded-xl p-5 space-y-3`}>
        {current?.purpose && (
          <div>
            <p className={`text-[10px] font-bold ${c.textMuted} uppercase`}>{t('mhp_why_its_here')}</p>
            <p className={`text-sm ${c.textSecondary}`}>{current.purpose}</p>
          </div>
        )}
        {current?.how_to_run_it && (
          <div>
            <p className={`text-[10px] font-bold ${c.textMuted} uppercase`}>{t('mhp_how_to_run')}</p>
            <p className={`text-sm ${c.textSecondary}`}>{current.how_to_run_it}</p>
          </div>
        )}
        {current?.say_this_if_helpful && (
          <div className={`${c.infoBox} border rounded-lg p-3`}>
            <p className="text-[10px] font-bold mb-1">{t('mhp_you_could_say')}</p>
            <p className="text-sm">{current.say_this_if_helpful}</p>
          </div>
        )}
      </div>

      {watch.length > 0 && (
        <div className={`${c.card} border ${c.border} rounded-xl p-5`}>
          <p className={`text-xs font-bold ${c.labelText} mb-3`}>🛡️ {t('mhp_if_it_wanders')}</p>
          <div className="space-y-2">
            {watch.map((w, i) => w.say_this && (
              <div key={i} className={`${c.cardAlt} border ${c.border} rounded-lg p-3`}>
                <p className={`text-[11px] font-bold ${c.text}`}>{w.situation}</p>
                <p className={`text-xs ${c.textSecondary} mt-1`}>{w.say_this}</p>
              </div>
            ))}
          </div>
        </div>
      )}

      <button onClick={onFinish} className={`w-full ${c.btnDanger} border py-3 rounded-lg text-sm font-semibold min-h-[48px]`}>
        🏁 {t('mhp_meeting_over')}
      </button>
    </div>
  );
}

