import React, { useState, useEffect, useRef, useCallback } from 'react';
import Caret from '../components/Caret';
import { useClaudeAPI } from '../hooks/useClaudeAPI';
import { useTheme } from '../hooks/useTheme';
import { usePersistentState } from '../hooks/usePersistentState';
import { useRegisterActions } from '../components/ActionBarContext';
import { useTranslation } from '../i18n/useTranslation';
import { currencySymbol } from '../utils/formatLocale';
import { pickExample } from '../utils/exampleRotation';
import { revealSection } from '../utils/revealSection';

const BRAND = '\n\n— Generated by DeftBrain · deftbrain.com';

const VIBES = [
  { value: 'chill', labelKey: 'pa_vibe_chill', emoji: '🌿' },
  { value: 'fun', labelKey: 'pa_vibe_fun', emoji: '🎉' },
  { value: 'elegant', labelKey: 'pa_vibe_elegant', emoji: '✨' },
  { value: 'wild', labelKey: 'pa_vibe_wild', emoji: '🔥' },
  { value: 'cozy', labelKey: 'pa_vibe_cozy', emoji: '🕯️' },
];

const DURATIONS = [
  { value: '2_hours', labelKey: 'pa_dur_2h', emoji: '⚡' },
  { value: '3_hours', labelKey: 'pa_dur_3h', emoji: '📖' },
  { value: '4_hours', labelKey: 'pa_dur_4h', emoji: '🎤' },
  { value: 'all_day', labelKey: 'pa_dur_allday', emoji: '☀️' },
];

const phaseEmoji = (phase) => {
  const map = { 'Arrival': '🚪', 'Settling In': '🌡️', 'Shared Moment': '✨', 'Open': '💬', 'Wind-down': '🌙' };
  return map[phase] || '⏱️';
};

const PartyArchitect = ({ tool }) => {
  const { callToolEndpoint, loading, userLocale, userCurrency, userRegion } = useClaudeAPI();
  const { isDark } = useTheme();
  const { t } = useTranslation();
  const sym = currencySymbol(userLocale, userCurrency);

  const c = {
    card:          isDark ? 'bg-zinc-800' : 'bg-white',
    cardAlt:       isDark ? 'bg-zinc-700/50' : 'bg-slate-50',
    input:         isDark ? 'bg-zinc-900 border-zinc-600 text-zinc-100 placeholder-zinc-400 focus:border-cyan-500 focus:ring-cyan-500/20'
                          : 'bg-white border-gray-300 text-gray-900 placeholder-gray-400 focus:border-cyan-500 focus:ring-cyan-100',
    text:          isDark ? 'text-zinc-50' : 'text-gray-900',
    textSecondary: isDark ? 'text-zinc-300' : 'text-gray-600',
    textMuted:     isDark ? 'text-zinc-400' : 'text-gray-500',
    labelText:     isDark ? 'text-zinc-200' : 'text-gray-700',
    accentTxt:     isDark ? 'text-cyan-400' : 'text-cyan-600',
    btnPrimary:    isDark ? 'bg-cyan-600 hover:bg-cyan-500 text-white'
                          : 'bg-cyan-600 hover:bg-cyan-700 text-white',
    // Waiting for input: an outline, not a smudge. Empty fill keeps "filled"
    // meaning "ready"; the border and label carry the visibility. Important
    // modifiers because tools carry their own border/text utilities on the
    // submit and Tailwind resolves conflicts by stylesheet order, not class
    // order. See the PF-13 exception in audit/audit_v2-3-2.py.
    btnIdle:       isDark ? '!bg-transparent !border-2 !border-cyan-500/85 !text-cyan-300 cursor-not-allowed'
                          : '!bg-transparent !border-2 !border-cyan-600/85 !text-cyan-800 cursor-not-allowed',
    btnSecondary:  isDark ? 'bg-zinc-700 hover:bg-zinc-600 text-zinc-200'
                          : 'bg-gray-100 hover:bg-gray-200 text-gray-700',
    border:        isDark ? 'border-zinc-700' : 'border-gray-200',
    success:       isDark ? 'bg-emerald-900/20 border-emerald-700 text-emerald-200'
                          : 'bg-emerald-50 border-emerald-300 text-emerald-800',
    warning:       isDark ? 'bg-amber-900/20 border-amber-700 text-amber-200'
                          : 'bg-amber-50 border-amber-300 text-amber-800',
    danger:        isDark ? 'bg-red-900/20 border-red-700 text-red-200'
                          : 'bg-red-50 border-red-200 text-red-800',
    successTxt:    isDark ? 'text-emerald-300' : 'text-emerald-800',
    warningTxt:    isDark ? 'text-amber-300' : 'text-amber-800',
    pillActive:    isDark ? 'border-cyan-500 bg-cyan-900/30 text-cyan-200'
                          : 'border-cyan-600 bg-cyan-100 text-cyan-900',
    pillInactive:  isDark ? 'border-zinc-600 text-zinc-400 hover:border-zinc-500'
                          : 'border-gray-300 text-gray-500 hover:border-gray-400',
    required:      isDark ? 'text-amber-400' : 'text-amber-700',
    badgeNeutral:  isDark ? 'bg-zinc-700 text-zinc-300' : 'bg-gray-100 text-gray-600',
  };
  c.textMuteded = c.textMuted;
  c.label = c.labelText;

  const linkStyle = isDark
    ? 'text-cyan-400 hover:text-cyan-300 underline underline-offset-2'
    : 'text-cyan-700 hover:text-cyan-800 underline underline-offset-2';

  const [occasion, setOccasion] = useState('');
  const [guestCount, setGuestCount] = useState('');
  const [whoIsComing, setWhoIsComing] = useState('');
  const [space, setSpace] = useState('');
  const [budget, setBudget] = useState('');
  const [vibe, setVibe] = useState('');
  const [duration, setDuration] = useState('3_hours');
  const [constraints, setConstraints] = useState('');
  const [error, setError] = useState('');
  const [expandedSections, setExpandedSections] = useState({ timeline: true });

  const resultsRef = useRef(null);

  const [results, setResults] = usePersistentState('party-results', null);
  // Recent Plans, rewritten 2026-09-05: `party-history` (old) held only
  // {id, date, preview} — no stored plan, so "View" could only re-show a
  // caption, never reopen the actual design. `party-plans` is a NEW store
  // (inputs + generated plan + date); old entries stay read-only, muted,
  // non-interactive below the new ones — never fabricated into a fake plan.
  const [plans, setPlans] = usePersistentState('party-plans', []);
  const [legacyHistory] = usePersistentState('party-history', []);
  const [showAllPlans, setShowAllPlans] = useState(false);

  const toggleSection = useCallback((key) => {
    setExpandedSections(p => ({ ...p, [key]: !p[key] }));
  }, []);

  const generate = useCallback(async () => {
    if (!occasion.trim()) return;
    setError(''); setResults(null);
    try {
      const durMeta = DURATIONS.find(d => d.value === duration);
      const inputs = {
        occasion: occasion.trim(),
        guestCount: guestCount.trim(),
        whoIsComing: whoIsComing.trim(),
        space: space.trim(),
        budget: budget.trim(),
        vibe,
        duration,
        constraints: constraints.trim(),
      };
      const data = await callToolEndpoint('party-architect', {
        occasion: inputs.occasion,
        guestCount: inputs.guestCount || null,
        whoIsComing: inputs.whoIsComing || null,
        space: inputs.space || null,
        budget: inputs.budget || null,
        vibe: vibe || null,
        duration: durMeta ? t(durMeta.labelKey) : duration,
        constraints: inputs.constraints || null,
        userLocale, userCurrency, userRegion,
      });
      setPlans(prev => [{
        id: 'plan_' + Date.now(),
        createdAt: new Date().toISOString(),
        // PF-25 exception: standard 40-char preview truncation.
        preview: (occasion || t('pa_history_fallback')).trim().slice(0, 40),
        inputs,
        plan: data,
        // PF-25 exception: capped at 15 — more headroom than the standard 6
        // since this stores a full plan, not just a preview.
      }, ...prev].slice(0, 15));
      setResults(data);
    } catch (err) { setError(err.message || t('pa_error')); }
  }, [occasion, guestCount, whoIsComing, space, budget, vibe, duration, constraints, callToolEndpoint, setResults, setPlans, t, userLocale, userCurrency, userRegion]);

  const loadExample = useCallback(() => {
    const ex = pickExample('PartyArchitect', [
      { occasion: '40th birthday', guests: '22', vibe: 'chill', duration: '4_hours', budget: 900,
        mix: "Mostly close friends from the last 15 years, a few work people, 3 kids under 10. About a third haven't met each other.",
        space: 'Backyard with covered patio, fits ~25 standing. Kitchen and living room flow out to it. Late September — should be warm but cool by 9pm.',
        constraints: "Two guests have tree nut allergies, one is gluten-free, one is sober (they're fine with others drinking)." },
      { occasion: 'Housewarming', guests: '9', vibe: 'chill', duration: '3_hours', budget: 120,
        mix: 'Three couples from my old job, my brother, and the neighbours from downstairs who I have spoken to twice. Nobody knows anybody outside their own pair.',
        space: 'One-bed flat. Living room seats five if two people take the floor. Kitchen is a corridor. No outdoor space.',
        constraints: 'Building has a noise rule after 10pm and thin floors. Nine people is already more than the room comfortably holds.' },
    ]);
    setOccasion(ex.occasion);
    setGuestCount(ex.guests);
    setWhoIsComing(ex.mix);
    setSpace(ex.space);
    setBudget(`${sym}${ex.budget}`);
    setVibe(ex.vibe);
    setDuration(ex.duration);
    setConstraints(ex.constraints);
    setResults(null);
  }, [sym, setResults]);

  const handleReset = useCallback(() => {
    setOccasion(''); setGuestCount(''); setWhoIsComing(''); setSpace('');
    setBudget(''); setVibe(''); setDuration('3_hours'); setConstraints('');
    setResults(null); setError('');
  }, [setResults]);

  // Reopens a STORED plan — never regenerates. Also repopulates the input
  // fields so "Duplicate & Edit" (editing after) or "Start Over" has
  // something sensible to work from.
  const viewPlan = useCallback((p) => {
    setOccasion(p.inputs?.occasion || '');
    setGuestCount(p.inputs?.guestCount || '');
    setWhoIsComing(p.inputs?.whoIsComing || '');
    setSpace(p.inputs?.space || '');
    setBudget(p.inputs?.budget || '');
    setVibe(p.inputs?.vibe || '');
    setDuration(p.inputs?.duration || '3_hours');
    setConstraints(p.inputs?.constraints || '');
    setResults(p.plan);
    setError('');
  }, [setResults]);

  // Same as View, but leaves results empty so the visitor lands back on the
  // input form with everything pre-filled, ready to change one thing and
  // regenerate — useful for a recurring gathering or trying another version.
  const duplicateAndEdit = useCallback((p) => {
    setOccasion(p.inputs?.occasion || '');
    setGuestCount(p.inputs?.guestCount || '');
    setWhoIsComing(p.inputs?.whoIsComing || '');
    setSpace(p.inputs?.space || '');
    setBudget(p.inputs?.budget || '');
    setVibe(p.inputs?.vibe || '');
    setDuration(p.inputs?.duration || '3_hours');
    setConstraints(p.inputs?.constraints || '');
    setResults(null);
    setError('');
  }, [setResults]);

  const removePlan = useCallback((id) => {
    setPlans(prev => prev.filter(p => p.id !== id));
  }, [setPlans]);

  const buildFullText = useCallback(() => {
    if (!results) return '';
    const r = results;
    let text = `🎪 ${t('pa_copy_header')}: ${occasion}\n`;
    if (r.event_shape) text += `\n${t('pa_copy_shape')} ${r.event_shape}\n`;
    if (r.timeline?.length) {
      text += `\n${t('pa_copy_timeline')}\n`;
      r.timeline.forEach(item => { text += `\n${item.time} [${item.phase}]: ${item.action}\n  ${t('pa_host_job_label')}: ${item.host_job}\n`; });
    }
    if (r.helping_people_connect?.length) {
      text += `\n${t('pa_copy_connect')}\n`;
      r.helping_people_connect.forEach(m => { text += `\n${m.idea}: ${m.how}\n`; });
    }
    if (r.food_and_drink) {
      text += `\n${t('pa_copy_food')}\n${r.food_and_drink.format}\n${t('pa_copy_timing')} ${r.food_and_drink.timing}`;
      if (r.food_and_drink.special_touch) text += `\n${t('pa_copy_signature')} ${r.food_and_drink.special_touch}`;
    }
    if (r.budget_priorities?.approach) text += `\n\n${t('pa_copy_budget')}\n${r.budget_priorities.approach}`;
    if (r.wind_down) text += `\n\n👋 ${t('pa_copy_wind_down')} ${r.wind_down.signals?.[0] || ''}\n${t('pa_copy_say')} "${r.wind_down.script}"`;
    return text + BRAND;
  }, [results, occasion, t]);

  useRegisterActions(buildFullText(), tool?.title || 'PartyArchitect');

  useEffect(() => {
    if (!results) return;
    const timer = setTimeout(() => revealSection(resultsRef.current), 100);
    return () => clearTimeout(timer);
  }, [results]);

  useEffect(() => {
    const handler = (e) => {
      if (e.key === 'Enter' && (e.metaKey || e.ctrlKey) && !loading) generate();
    };
    document.addEventListener('keydown', handler);
    return () => document.removeEventListener('keydown', handler);
  }, [loading, generate]);

  const r = results;
  const vibeLabel = (v) => { const m = VIBES.find(x => x.value === v); return m ? `${m.emoji} ${t(m.labelKey)}` : ''; };

  return (
    <div className={`space-y-4 ${c.text}`}>

      {/* ── INPUT CARD ── */}
      <div className={`${c.card} border ${c.border} rounded-xl shadow-sm px-5 pt-2.5 pb-5 space-y-4`}>
        <div className="pb-3 border-b border-zinc-500">
          <div className="flex items-start justify-between gap-3">
            <div>
              {/* PF-30 — the wrapper already prints the name as the page <h1>. */}
              <p className={`text-base ${c.textSecondary}`}>
                <span className="me-2 text-lg">{tool?.icon ?? '🎪'}</span>{t('pa_tagline')}
              </p>
              <button onClick={loadExample} disabled={loading} style={{ backgroundColor: (tool?.headerColor ?? '#888888') + '80' }} className="mt-2 px-4 py-2 rounded-full text-sm font-semibold border border-black/25 text-zinc-900 shadow-sm hover:brightness-105 hover:shadow transition disabled:opacity-40 whitespace-nowrap">✨ {t('try_example')}</button>
            </div>
            {(results || occasion.trim()) && (
              <button onClick={handleReset} className={`flex-shrink-0 ${c.btnSecondary} px-3 py-1.5 rounded-lg text-xs font-medium`}>
                {t('pa_start_over')}
              </button>
            )}
          </div>
        </div>

        <div>
          <label className={`block text-sm font-medium ${c.labelText} mb-1`}>
            {t('pa_occasion_label')} <span className={c.required}>*</span>
          </label>
          <input type="text" value={occasion} onChange={e => setOccasion(e.target.value)}
            placeholder={t('pa_occasion_ph')}
            className={`w-full px-4 py-3 border rounded-xl text-sm ${c.input} outline-none focus:ring-2`} />
        </div>

        <div className="grid grid-cols-2 gap-3">
          <div>
            <label className={`block text-sm font-medium ${c.labelText} mb-1`}>{t('pa_guests_label')}</label>
            <input type="text" value={guestCount} onChange={e => setGuestCount(e.target.value)}
              placeholder={t('pa_guests_ph')}
              className={`w-full px-4 py-3 border rounded-xl text-sm ${c.input} outline-none focus:ring-2`} />
          </div>
          <div>
            <label className={`block text-sm font-medium ${c.labelText} mb-1`}>{t('pa_budget_label')}</label>
            <input type="text" value={budget} onChange={e => setBudget(e.target.value)}
              placeholder={t('pa_budget_ph', { sym })}
              className={`w-full px-4 py-3 border rounded-xl text-sm ${c.input} outline-none focus:ring-2`} />
          </div>
        </div>

        <div>
          <label className={`block text-sm font-medium ${c.labelText} mb-1`}>{t('pa_who_label')}</label>
          <p className={`text-xs ${c.textMuted} mb-1.5`}>{t('pa_who_hint')}</p>
          <input type="text" value={whoIsComing} onChange={e => setWhoIsComing(e.target.value)}
            placeholder={t('pa_who_ph')}
            className={`w-full px-4 py-3 border rounded-xl text-sm ${c.input} outline-none focus:ring-2`} />
        </div>

        <div>
          <label className={`block text-sm font-medium ${c.labelText} mb-1`}>{t('pa_space_label')}</label>
          <input type="text" value={space} onChange={e => setSpace(e.target.value)}
            placeholder={t('pa_space_ph')}
            className={`w-full px-4 py-3 border rounded-xl text-sm ${c.input} outline-none focus:ring-2`} />
        </div>

        <div>
          <label className={`block text-sm font-medium ${c.labelText} mb-1`}>{t('pa_vibe_label')}</label>
          <div className="flex flex-wrap gap-1.5">
            {VIBES.map(v => (
              <button key={v.value} onClick={() => setVibe(vibe === v.value ? '' : v.value)}
                className={`px-3 py-1.5 rounded-lg text-xs font-bold border transition-colors min-h-[32px] ${
                  vibe === v.value ? c.pillActive : c.pillInactive}`}>
                {v.emoji} {t(v.labelKey)}
              </button>
            ))}
          </div>
        </div>

        <div>
          <label className={`block text-sm font-medium ${c.labelText} mb-1`}>{t('pa_duration_label')}</label>
          <div className="flex gap-2">
            {DURATIONS.map(d => (
              <button key={d.value} onClick={() => setDuration(d.value)}
                className={`flex-1 py-2 rounded-xl text-[11px] font-bold border transition-colors min-h-[36px] ${
                  duration === d.value ? c.pillActive : c.pillInactive}`}>
                {d.emoji} {t(d.labelKey)}
              </button>
            ))}
          </div>
        </div>

        <div>
          <label className={`block text-sm font-medium ${c.labelText} mb-1`}>
            {t('pa_constraints_label')} <span className={`font-normal ${c.textMuted}`}>{t('pa_constraints_hint')}</span>
          </label>
          <p className={`text-xs ${c.textMuted} mb-1.5`}>{t('pa_constraints_help')}</p>
          <input type="text" value={constraints} onChange={e => setConstraints(e.target.value)}
            placeholder={t('pa_constraints_ph')}
            className={`w-full px-4 py-3 border rounded-xl text-sm ${c.input} outline-none focus:ring-2`} />
        </div>

        <div className="flex gap-3">
          <button title={t('cmd_enter')} onClick={generate} disabled={loading || !occasion.trim()}
          className={`relative w-full ${(!occasion.trim()) ? c.btnIdle : c.btnPrimary} disabled:cursor-not-allowed font-bold py-3 rounded-lg flex items-center justify-center gap-2 min-h-[48px]`}>
          {loading
            ? <><span className="inline-block animate-spin">{tool?.icon ?? '🎪'}</span> {t('pa_designing')}</>
            : <><span className="me-1">{tool?.icon ?? '🎪'}</span> {t('pa_design_btn')}</>}
          {!loading && (
            <kbd aria-hidden="true"
              className="hidden sm:flex items-center absolute end-3 top-1/2 -translate-y-1/2 px-1.5 py-0.5 rounded border border-white/30 bg-white/15 text-[10px] font-bold tracking-wide">
              ⌘↵
            </kbd>
          )}
          </button>
        </div>

        <p className={`text-xs text-center ${c.textMuted}`}>
          {t('pa_xref_datenight_q')} <a href="/DateNight" className={linkStyle}>💘 {t('pa_xref_datenight')}</a> {t('pa_xref_datenight_tail')}
        </p>
      </div>

      {/* ── ERROR ── */}
      {error && (
        <div className={`${c.danger} border rounded-xl p-4 flex items-start gap-3`}>
          <span className="flex-shrink-0 mt-0.5">⚠️</span>
          <p className="text-sm">{error}</p>
        </div>
      )}

      {/* ── RESULTS ── */}
      {results && (
        <div className="space-y-4">
          <div data-copy-results ref={resultsRef} className="scroll-mt-24"/>

          {r.event_read?.what_matters && (
            <div className={`${c.card} border ${c.border} rounded-xl p-5`}>
              <p className={`text-[10px] font-bold ${c.textMuted} mb-2`}>🎯 {t('pa_the_plan')}</p>
              <p className={`text-sm ${c.textSecondary} leading-relaxed`}>{r.event_read.what_matters}</p>
              {r.event_read.design_priority && (
                <p className={`text-xs ${c.textMuted} mt-2 italic`}>{t('pa_design_priority_label')}: {r.event_read.design_priority}</p>
              )}
            </div>
          )}

          {r.event_shape && (
            <div className={`${c.warning} border rounded-xl p-4`}>
              <p className={`text-[10px] font-bold ${c.warningTxt} mb-1`}>🎚️ {t('pa_the_shape')}</p>
              <p className={`text-sm font-medium leading-relaxed`}>{r.event_shape}</p>
            </div>
          )}

          {r.timeline?.length > 0 && (
            <div className={`${c.card} border ${c.border} rounded-xl overflow-hidden`}>
              <button onClick={() => toggleSection('timeline')}
                className="w-full p-4 flex items-center justify-between text-start min-h-[44px]">
                <h3 className={`text-sm font-bold ${c.text} flex items-center gap-2`}><span>⏱️</span> {t('pa_event_plan')}</h3>
                <Caret open={expandedSections.timeline} />
              </button>
              {expandedSections.timeline && (
                <div className={`px-4 pb-4 border-t ${c.border} pt-3 space-y-3`}>
                  {r.timeline.map((item, i) => (
                    <div key={i} className="flex gap-3">
                      <div className="flex flex-col items-center flex-shrink-0">
                        <span className="text-lg">{phaseEmoji(item.phase)}</span>
                        {i < r.timeline.length - 1 && <div className={`w-0.5 flex-1 mt-1 border-s ${c.border}`} />}
                      </div>
                      <div className={`flex-1 ${c.cardAlt} rounded-lg p-3`}>
                        <div className="flex items-center gap-2 mb-1">
                          <span className={`text-xs font-bold ${c.text}`}>{item.time}</span>
                          <span className={`text-[9px] font-bold px-2 py-0.5 rounded-full ${c.badgeNeutral}`}>{item.phase}</span>
                        </div>
                        <p className={`text-xs ${c.text} mb-1`}>{item.action}</p>
                        <p className={`text-[10px] ${c.textMuted} italic`}>🎯 {t('pa_host_job_label')}: {item.host_job}</p>
                        {item.why && <p className={`text-[10px] ${c.textMuted} mt-1`}>💡 {item.why}</p>}
                        {item.adjust_if && <p className={`text-[10px] ${c.accentTxt} mt-1`}>↺ {t('pa_adjust_label')}: {item.adjust_if}</p>}
                      </div>
                    </div>
                  ))}
                </div>
              )}
            </div>
          )}

          {r.helping_people_connect?.length > 0 && (
            <div className={`${c.card} border ${c.border} rounded-xl overflow-hidden`}>
              <button onClick={() => toggleSection('connect')}
                className="w-full p-4 flex items-center justify-between text-start min-h-[44px]">
                <h3 className={`text-sm font-bold ${c.text} flex items-center gap-2`}><span>🤝</span> {t('pa_helping_connect')}</h3>
                <Caret open={expandedSections.connect} />
              </button>
              {expandedSections.connect && (
                <div className={`px-4 pb-4 border-t ${c.border} pt-3 space-y-3`}>
                  {r.helping_people_connect.map((m, i) => (
                    <div key={i} className={`${c.cardAlt} rounded-lg p-4`}>
                      <p className={`text-xs font-bold ${c.text} mb-1`}>{m.idea}</p>
                      <p className={`text-xs ${c.textSecondary} mb-2`}>{m.how}</p>
                      <div className="flex gap-3">
                        {m.when && <p className={`text-[10px] ${c.textMuted}`}>⏱ {m.when}</p>}
                        {m.why_it_fits && <p className={`text-[10px] ${c.textMuted} italic`}>{m.why_it_fits}</p>}
                      </div>
                    </div>
                  ))}
                </div>
              )}
            </div>
          )}

          {r.conversation_catalysts?.length > 0 && (
            <div className={`${c.card} border ${c.border} rounded-xl p-4`}>
              <p className={`text-xs font-bold ${c.text} mb-2`}>💬 {t('pa_conversation')}</p>
              <div className="space-y-1.5">
                {r.conversation_catalysts.map((s, i) => (
                  <p key={i} className={`text-xs ${c.textSecondary}`}>• {s}</p>
                ))}
              </div>
            </div>
          )}

          {r.food_and_drink && (
            <div className={`${c.card} border ${c.border} rounded-xl p-4`}>
              <p className={`text-xs font-bold ${c.text} mb-2`}>🍽️ {t('pa_food_drink')}</p>
              <div className="space-y-2">
                {r.food_and_drink.format && <p className={`text-xs ${c.textSecondary}`}>{r.food_and_drink.format}</p>}
                {r.food_and_drink.timing && <p className={`text-xs ${c.textSecondary}`}>⏱ {r.food_and_drink.timing}</p>}
                {r.food_and_drink.dietary_considerations && (
                  <p className={`text-xs font-semibold ${c.warningTxt}`}>⚠️ {r.food_and_drink.dietary_considerations}</p>
                )}
                {r.food_and_drink.special_touch && (
                  <p className={`text-xs ${c.successTxt}`}>✨ {r.food_and_drink.special_touch}</p>
                )}
              </div>
            </div>
          )}

          {r.music?.show && (r.music.arrival || r.music.later || r.music.wind_down) && (
            <div className={`${c.card} border ${c.border} rounded-xl p-4`}>
              <p className={`text-xs font-bold ${c.text} mb-2`}>🎵 {t('pa_music')}</p>
              <div className="space-y-1.5">
                {[[t('pa_music_arrival'), r.music.arrival], [t('pa_music_later'), r.music.later], [t('pa_music_winddown'), r.music.wind_down]]
                  .filter(([, v]) => v).map(([label, value], i) => (
                    <p key={i} className={`text-xs ${c.textSecondary}`}>{label}: {value}</p>
                  ))}
              </div>
            </div>
          )}

          {r.budget_priorities && (r.budget_priorities.approach || r.budget_priorities.protect_spending_on?.length > 0) && (
            <div className={`${c.card} border ${c.border} rounded-xl p-4`}>
              <p className={`text-xs font-bold ${c.text} mb-2`}>💰 {t('pa_budget_priorities')}</p>
              <div className="space-y-1.5">
                {r.budget_priorities.approach && <p className={`text-xs ${c.textSecondary}`}>{r.budget_priorities.approach}</p>}
                {r.budget_priorities.protect_spending_on?.length > 0 && (
                  <div className="mt-1">
                    <p className={`text-[10px] font-bold ${c.textMuted} mb-1`}>{t('pa_protect_label')}</p>
                    {r.budget_priorities.protect_spending_on.map((v, i) => <p key={i} className={`text-xs ${c.textSecondary}`}>• {v}</p>)}
                  </div>
                )}
                {r.budget_priorities.keep_secondary?.length > 0 && (
                  <div className="mt-1">
                    <p className={`text-[10px] font-bold ${c.textMuted} mb-1`}>{t('pa_keep_secondary_label')}</p>
                    {r.budget_priorities.keep_secondary.map((v, i) => <p key={i} className={`text-xs ${c.textSecondary}`}>• {v}</p>)}
                  </div>
                )}
                {r.budget_priorities.use_what_you_have?.length > 0 && (
                  <div className="mt-1">
                    <p className={`text-[10px] font-bold ${c.textMuted} mb-1`}>{t('pa_use_what_you_have_label')}</p>
                    {r.budget_priorities.use_what_you_have.map((v, i) => <p key={i} className={`text-xs ${c.successTxt}`}>• {v}</p>)}
                  </div>
                )}
              </div>
            </div>
          )}

          {r.things_to_plan_for?.length > 0 && (
            <div className={`${c.card} border ${c.border} rounded-xl p-4`}>
              <p className={`text-xs font-bold ${c.text} mb-2`}>🧯 {t('pa_things_to_plan_for')}</p>
              <div className="space-y-2">
                {r.things_to_plan_for.map((d, i) => (
                  <div key={i}>
                    <p className={`text-xs font-semibold ${c.text}`}>{d.issue}</p>
                    <p className={`text-xs ${c.textSecondary}`}>{d.plan}</p>
                  </div>
                ))}
              </div>
            </div>
          )}

          {r.wind_down && (
            <div className={`${c.warning} border rounded-xl p-4`}>
              <p className={`text-[10px] font-bold ${c.warningTxt} mb-1`}>👋 {t('pa_wind_down')}</p>
              {r.wind_down.signals?.length > 0 && (
                <div className="mb-2 space-y-0.5">
                  {r.wind_down.signals.map((s, i) => <p key={i} className={`text-xs ${c.warningTxt}`}>{s}</p>)}
                </div>
              )}
              {r.wind_down.script && (
                <p className={`text-xs font-bold ${c.warningTxt}`}>{t('pa_say')} "{r.wind_down.script}"</p>
              )}
            </div>
          )}

          {/* Related tools */}
          <div className={`${c.cardAlt} border ${c.border} rounded-xl p-4`}>
            <p className={`text-[10px] font-bold ${c.textMuted} uppercase mb-2`}>🔗 {t('pa_related')}</p>
            <div className="flex flex-wrap gap-3">
              <a href="/MicroAdventureMapper" className={`text-xs ${linkStyle}`}>🗺️ {t('pa_xref_mam')}</a>
              <a href="/AwkwardSilenceFiller" className={`text-xs ${linkStyle}`}>💬 {t('pa_xref_asf')}</a>
            </div>
          </div>

          <p className={`text-xs text-center ${c.textMuted}`}>
            {t('pa_disclaimer')}
          </p>
        </div>
      )}

      {/* ── RECENT PLANS — sits below the form/results either way ── */}
      {(plans.length > 0 || legacyHistory.length > 0) && (
        <div className={`${c.cardAlt} border ${c.border} rounded-xl p-4`}>
          <h3 className={`text-sm font-semibold mb-2 ${c.textSecondary}`}>{t('pa_recent_plans')}</h3>
          <div className="space-y-2">
            {(showAllPlans ? plans : plans.slice(0, 5)).map((p) => {
              const dateStr = (() => { try { return new Date(p.createdAt).toLocaleDateString(userLocale || undefined, { month: 'short', day: 'numeric' }); } catch { return ''; } })();
              const metaBits = [p.inputs?.guestCount, p.inputs?.space, vibeLabel(p.inputs?.vibe)].filter(Boolean);
              return (
                <div key={p.id} className={`${c.card} border ${c.border} rounded-lg p-3`}>
                  <div className="flex items-start justify-between gap-2">
                    <div className="flex-1 min-w-0">
                      <p className={`text-sm font-semibold ${c.text} truncate`}>{p.preview || t('pa_history_fallback')}</p>
                      {metaBits.length > 0 && (
                        <p className={`text-xs ${c.textMuted} mt-0.5 truncate`}>{metaBits.join(' · ')}</p>
                      )}
                      <p className={`text-[10px] ${c.textMuted} mt-0.5`}>{dateStr}</p>
                    </div>
                    <div className="flex items-center gap-2 flex-shrink-0">
                      <button onClick={() => viewPlan(p)} className={`text-xs font-bold ${linkStyle}`}>{t('pa_view')} →</button>
                      <button onClick={() => duplicateAndEdit(p)} className={`text-xs font-bold ${linkStyle}`}>{t('pa_duplicate_edit')} →</button>
                      <button onClick={() => removePlan(p.id)} className={`text-xs ${c.textMuted} hover:${c.text}`} aria-label={t('pa_remove')}>✕</button>
                    </div>
                  </div>
                </div>
              );
            })}
            {plans.length > 5 && (
              <button onClick={() => setShowAllPlans(p => !p)} className={`text-xs font-bold ${linkStyle}`}>
                {showAllPlans ? t('pa_show_less') : t('pa_view_all')}
              </button>
            )}
            {/* Legacy entries from before this rework — no stored plan to
                reopen, so no View/Duplicate action; shown muted, read-only. */}
            {legacyHistory.length > 0 && (
              <div className="space-y-1 pt-1">
                {legacyHistory.map((h, i) => (
                  <div key={h.id || i} className="flex items-center justify-between opacity-60">
                    <span className={`text-xs ${c.textMuted} truncate`}>{h.preview || t('pa_history_fallback')}</span>
                    <span className={`text-[10px] ${c.textMuted} ms-2`}>{h.date ? new Date(h.date).toLocaleDateString() : ''}</span>
                  </div>
                ))}
              </div>
            )}
          </div>
        </div>
      )}
    </div>
  );
};

PartyArchitect.displayName = 'PartyArchitect';
export default PartyArchitect;
