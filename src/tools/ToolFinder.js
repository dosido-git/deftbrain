import React, { useState, useCallback, useEffect, useRef } from 'react';
import { useRegisterActions } from '../components/ActionBarContext';
import Caret from '../components/Caret';
import { useClaudeAPI } from '../hooks/useClaudeAPI';
import { usePersistentState } from '../hooks/usePersistentState';
import { useTheme } from '../hooks/useTheme';
import { useTranslation } from '../i18n/useTranslation';
import IdeaPrompt from '../components/IdeaPrompt';
import { pickExample } from '../utils/exampleRotation';
import { TOOL_FINDER_PAUSED } from '../data/toolFinderPaused';

const BRAND = '\n\n— Generated by DeftBrain · deftbrain.com';

// ════════════════════════════════════════════════════════════
// EXAMPLE SITUATIONS — not categories
// ════════════════════════════════════════════════════════════
const QUICK_PICKS = [
  { labelKey: 'tf_sit_brother' },
  { labelKey: 'tf_sit_date' },
  { labelKey: 'tf_sit_torn' },
  { labelKey: 'tf_sit_email' },
];

// ════════════════════════════════════════════════════════════
// COMPONENT
// ════════════════════════════════════════════════════════════
const EXAMPLE_KEYS = ['tf_ex1', 'tf_ex2', 'tf_ex3'];
const ToolFinder = ({ tool }) => {
  const { callToolEndpoint, loading } = useClaudeAPI();
  const { isDark } = useTheme();
  const { t } = useTranslation();

  // ─── Navy & Gold palette ───
  const c = {
    card:          isDark ? 'bg-zinc-800' : 'bg-white',
    cardAlt:       isDark ? 'bg-zinc-700/50' : 'bg-slate-50',
    input:         isDark ? 'bg-zinc-900 border-zinc-600 text-zinc-100 placeholder-zinc-400 focus:border-cyan-500 focus:ring-cyan-500/20' : 'bg-white border-gray-300 text-gray-900 placeholder-gray-400 focus:border-cyan-500 focus:ring-cyan-100',
    text:          isDark ? 'text-zinc-50' : 'text-gray-900',
    textSecondary: isDark ? 'text-zinc-300' : 'text-gray-600',
    textMuted:     isDark ? 'text-zinc-400' : 'text-gray-500',
    required:      isDark ? 'text-amber-400' : 'text-amber-700',
    btnPrimary:    isDark ? 'bg-cyan-600 hover:bg-cyan-500 text-white' : 'bg-cyan-600 hover:bg-cyan-700 text-white',
    // Waiting for input: an outline, not a smudge. Empty fill keeps "filled"
    // meaning "ready"; the border and label carry the visibility. Important
    // modifiers because tools carry their own border/text utilities on the
    // submit and Tailwind resolves conflicts by stylesheet order, not class
    // order. See the PF-13 exception in audit/audit_v2-3-2.py.
    btnIdle:       isDark ? '!bg-transparent !border-2 !border-cyan-500/85 !text-cyan-300 cursor-not-allowed'
                          : '!bg-transparent !border-2 !border-cyan-600/85 !text-cyan-800 cursor-not-allowed',
    btnSecondary:  isDark ? 'bg-zinc-700 hover:bg-zinc-600 text-zinc-200' : 'bg-gray-100 hover:bg-gray-200 text-gray-700',
    border:        isDark ? 'border-zinc-700' : 'border-gray-200',
    success:       isDark ? 'bg-emerald-900/20 border-emerald-700 text-emerald-200' : 'bg-emerald-50 border-emerald-300 text-emerald-800',
    warning:       isDark ? 'bg-amber-900/20 border-amber-700 text-amber-200' : 'bg-amber-50 border-amber-300 text-amber-800',
    danger:        isDark ? 'bg-red-900/20 border-red-700 text-red-200' : 'bg-red-50 border-red-200 text-red-800',
    pillInactive:  isDark ? 'border-zinc-600 text-zinc-400 hover:border-zinc-500' : 'border-gray-300 text-gray-500 hover:border-gray-400',
    badge:         isDark ? 'bg-cyan-900/30 text-cyan-300' : 'bg-cyan-100 text-cyan-800',
    cardHover:     isDark ? 'group-hover:border-cyan-600' : 'group-hover:border-cyan-400',
  };

  const linkStyle = isDark
    ? 'text-cyan-400 hover:text-cyan-300 underline underline-offset-2'
    : 'text-cyan-700 hover:text-cyan-800 underline underline-offset-2';

  // ─── State ───
  const [error, setError] = useState('');
  const [problem, setProblem] = usePersistentState('toolfinder-problem', '');
  const [results, setResults] = usePersistentState('toolfinder-result', null);
  const [sessionHistory, setSessionHistory] = usePersistentState('toolfinder-history', []);
  const loadExample = () => {
    const key = pickExample('ToolFinder', EXAMPLE_KEYS);
    setProblem(t(key));
  };

  const resultsRef = useRef(null);

  // ─── Actions (declared before useEffect to avoid stale closures) ───
  const findTools = useCallback(async (text, correction, rejected) => {
    const query = (text !== undefined ? text : problem);
    if (!query.trim()) return;
    setError('');
    setResults(null);
    try {
      const data = await callToolEndpoint('tool-finder', {
        problem: query.trim(),
        refinement: correction?.trim() || undefined,
        rejected: rejected?.length ? rejected : undefined,
      });
      setResults(data);
      setSessionHistory(prev => [{
        id: Date.now(), date: new Date().toISOString(),
        preview: query.trim().substring(0, 40),
        result: data,
      }, ...prev].slice(0, 6));
    } catch (err) {
      setError(err.message || t('tf_err'));
    } }, [problem, callToolEndpoint, setError, setResults, setSessionHistory, t]);

  const [refineOpen, setRefineOpen] = useState(false);
  const [refinement, setRefinement] = useState('');
  const submitRefinement = useCallback(() => {
    if (!refinement.trim()) return;
    const rejected = (results?.recommendations || []).map(x => x.id).filter(Boolean);
    setRefineOpen(false);
    findTools(undefined, refinement, rejected);
  }, [refinement, results, findTools]);

  // Arrive from the home page with the problem already typed: /ToolFinder?q=...
  // The home hero is a text box now, so whatever was typed there should not
  // have to be typed again. Runs once, and strips the param afterwards so a
  // refresh or a back-navigation does not silently re-run the search.
  const ranFromUrlRef = useRef(false);
  useEffect(() => {
    if (ranFromUrlRef.current) return;
    const q = new URLSearchParams(window.location.search).get('q');
    if (!q || !q.trim()) return;
    ranFromUrlRef.current = true;
    setProblem(q);
    findTools(q);
    window.history.replaceState({}, '', window.location.pathname);
  }, [findTools, setProblem]);

  const handleQuickPick = useCallback((label) => {
    setProblem(label);
    findTools(label);
  }, [findTools, setProblem]);

  const handleReset = useCallback(() => {
    setProblem('');
    setResults(null);
    setError('');
  }, [setProblem, setResults, setError]);

  const buildFullText = useCallback(() => {
    if (!results) return '';
    let text = t('tf_copy_header') + '\n';
    if (results?.understanding) text += `\n${results?.understanding}\n`;
    if (results?.recommendations?.length) {
      text += `\n${t('tf_copy_recommended')}\n`;
      results?.recommendations?.forEach((rec, i) => {
        text += `\n${i + 1}. ${rec.icon || '🔧'} ${rec.title} — ${rec.why}`;
        if (rec.what_to_do) text += `\n   → ${rec.what_to_do}`;
      });
    } if (results?.workflow) text += `\n\n${t('tf_copy_workflow')} ${results?.workflow}`;
    return text + BRAND;
  }, [results, t]);

  // ─── Register export content ───
  useRegisterActions(results ? buildFullText() : '', tool?.title);

  // ─── Scroll to results ───
  useEffect(() => {
    if (!results) return;
    const t = setTimeout(() => resultsRef.current?.scrollIntoView({ behavior: 'smooth', block: 'start' }), 100);
    return () => clearTimeout(t);
  }, [results]);

  // Global Cmd/Ctrl+Enter listener — after all handlers to avoid TDZ
  useEffect(() => {
    const handler = (e) => {
      const tag = document.activeElement?.tagName;
      if (tag === 'SELECT') return;
      if (e.key === 'Enter' && (e.metaKey || e.ctrlKey) && !loading) findTools(problem);
    };
    document.addEventListener('keydown', handler);
    return () => document.removeEventListener('keydown', handler);
  }, [loading, findTools, problem]);

  const r = results;

  // ════════════════════════════════════════════════════════════
  // RENDER
  // ════════════════════════════════════════════════════════════
  // ── PAUSED 2026-08-22 ──────────────────────────────────────────────
  // Off while the routing metadata is written. Recommendations are unreliable
  // until every tool has an entry: a tool WITH one can be ruled out by its own
  // notFor line, a tool WITHOUT one can never be ruled out at all, so the least
  // verified tools win. Better to send people to the full list than to answer
  // badly. Delete this block and the constant to bring it back.
  if (TOOL_FINDER_PAUSED) {
    return (
      <div className={`${c.card} border ${c.border} rounded-xl p-8 ${c.text}`}>
        <p className="text-3xl mb-3" aria-hidden="true">{tool?.icon ?? '🧰'}</p>
        <p className="text-xl font-semibold mb-2">{t('tf_paused_title')}</p>
        <p className={`${c.textSecondary} mb-6`}>{t('tf_paused_body')}</p>
        <a href="/" className={`inline-block px-5 py-2.5 rounded-lg font-semibold ${c.btnPrimary}`}>
          {t('tf_paused_cta')} <span aria-hidden="true">→</span>
        </a>
      </div>
    );
  }

  return (<div className={`space-y-4 ${c.text}`}>

      {/* ── HEADER ── */} <div className={`${c.card} border ${c.border} rounded-xl p-6`}>
        <div className={`mb-5 pb-4 border-b ${c.border}`}>
          <div className="flex items-start justify-between gap-3">
            <div>
              {/* PF-30: the wrapper already renders the name as the page h1, so
                  the icon moves onto the tagline. The tagline reads from the
                  locale rather than the catalog, which is English by design. */}
              <p className={`text-base ${c.textSecondary}`}>
                <span className="me-2 text-lg">{tool?.icon ?? '🧰'}</span>{t('tf_tagline')}
              </p>
              <button onClick={loadExample} disabled={loading} style={{ backgroundColor: (tool?.headerColor ?? '#888888') + '80' }} className="mt-2 px-4 py-2 rounded-full text-sm font-semibold border border-black/25 text-zinc-900 shadow-sm hover:brightness-105 hover:shadow transition disabled:opacity-40 whitespace-nowrap">✨ {t('try_example')}</button>
            </div>
            {(results || problem.trim()) && (
              <button onClick={handleReset} className={`${c.btnSecondary} px-3 py-1.5 rounded-lg text-xs font-bold flex-shrink-0`}>
                ↺ {t('start_over')}
              </button>
            )}
          </div>
        </div>

        {/* ── PROBLEM INPUT ── */} <div className="mb-4">
          <label className={`text-sm font-bold ${c.text} block mb-1.5`}>
            {t('tf_input_label')} <span className={c.required}>*</span>
          </label>
          <textarea
            value={problem} onChange={e => setProblem(e.target.value)} placeholder={t('tf_input_ph')}
            rows={3} className={`w-full px-4 py-3 border rounded-xl text-sm ${c.input} ${c.border} ${c.text} outline-none focus:ring-2 resize-none placeholder:${c.textMuted}`} />
        </div>

        {/* ── EXAMPLE SITUATIONS ── */} {!results && (<div className="mb-5">
            <p className={`text-xs font-bold ${c.textMuted} mb-2`}>{t('tf_situations_label')}</p>
            <div className="space-y-1.5">
              {QUICK_PICKS.map(qp => (<button
                  key={qp.labelKey} onClick={() => handleQuickPick(t(qp.labelKey))} disabled={loading} className={`w-full text-start px-3 py-2 rounded-lg text-xs font-medium border transition-colors ${c.pillInactive} disabled:opacity-40`} >
                  {t(qp.labelKey)} </button>
              ))} </div>
          </div>
        )} {/* ── SUBMIT ── */} <div className="flex gap-3">
          <button title={t('cmd_enter')}
            onClick={() => findTools()} data-print-keep disabled={loading || !problem.trim()} className={`relative flex-1 ${(!problem.trim()) ? c.btnIdle : c.btnPrimary} disabled:cursor-not-allowed font-bold py-3 px-6 rounded-xl flex items-center justify-center gap-2 min-h-[48px] shadow-lg transition-all`} >
            {loading
              ? <><span className="inline-block animate-spin">{tool?.icon ?? '🧰'}</span> {t('tf_searching')}</>
              : <><span>{tool?.icon ?? '🧰'}</span> {t('tf_find_cta')}</>} {!loading && (
            <kbd aria-hidden="true"
              className="hidden sm:flex items-center absolute end-3 top-1/2 -translate-y-1/2 px-1.5 py-0.5 rounded border border-white/30 bg-white/15 text-[10px] font-bold tracking-wide">
              ⌘↵
            </kbd>
          )}
          </button>
        </div>
      </div>

      {/* Error */} {error && (<div className={`${c.danger} border rounded-xl p-4 flex items-start gap-3`}>
          <span className="flex-shrink-0 mt-0.5">⚠️</span>
          <p className="text-sm">{error}</p>
        </div>
      )} {/* ══════════════════════════════════════════════════════════ */} {/* RESULTS                                                  */} {/* ══════════════════════════════════════════════════════════ */} {results && (<div className="space-y-4">
          <div data-copy-results ref={resultsRef} data-results-anchor />
          {/* ── UNDERSTANDING ── */} {r.understanding && (<div className={`${c.card} border ${c.border} rounded-xl p-5`}>
              <p className={`text-sm ${c.textSecondary} leading-relaxed`}>
                <span className={`font-bold ${c.text}`}>{t('tf_understanding_label')} </span>
                {r.understanding} </p>
            </div>
          )} {/* ── RECOMMENDATIONS ── */} {r.recommendations && r.recommendations.length > 0 && (<div className="space-y-3">
              <div className="flex items-center justify-between">
                <h3 className={`text-sm font-bold ${c.text}`}>
                  {t('tf_id_start_with', { title: r.recommendations[0]?.title || '' })} </h3>

              </div>

              {/* The backend drops any id that is not in the catalog before this
                  ever renders, so the href below can be the plain shape — which
                  also lets the cross-ref audit see that these ARE the post-result
                  links, rather than reading a ternary and concluding the results
                  block has none. */}
              {r.recommendations.map((rec, idx) => (<a
                  key={rec.id}
                  href={`/${rec.id}`}
                  target="_blank"
                  rel="noopener noreferrer"
                  className="block no-underline group"
                >
                  <div className={`${c.card} border ${c.border} rounded-xl p-5 transition-all group-hover:shadow-md ${c.cardHover}`}>
                    {/* Tool header */} <div className="flex items-start gap-3 mb-3">
                      <span className="text-2xl flex-shrink-0">{rec.icon || '🔧'}</span>
                      <div className="flex-1 min-w-0">
                        <div className="flex items-center gap-2 flex-wrap">
                          <h4 className={`text-base font-bold ${c.text} group-hover:underline`}>
                            {rec.title} </h4>
                          {idx > 0 && (<span className={`text-[9px] font-bold px-2 py-0.5 rounded-full ${c.badge}`}>
                              {t('tf_also')}
                            </span>
                          )}
                        </div>
                      </div>
                      <span className={`text-sm ${c.textMuted} group-hover:translate-x-1 transition-transform flex-shrink-0`}>→</span>
                    </div>

                    {/* Why this tool */} <p className={`text-sm ${c.textSecondary} leading-relaxed mb-2`}>
                      {rec.why} </p>

                    {/* What to do */} {rec.what_to_do && (<div className={`${c.cardAlt} rounded-lg px-3 py-2 mt-2`}>
                        <p className={`text-xs ${c.textMuted}`}>
                          <span className="font-bold">{t('tf_when_you_get_there')}</span> {rec.what_to_do} </p>
                      </div>
                    )} </div>
                </a>
              ))} </div>
          )} {/* ── NO PERFECT FIT ── */} {r.no_perfect_fit && (<div className={`${c.card} border ${c.border} rounded-xl p-4`}>
              <p className={`text-xs font-bold ${c.textMuted} mb-1`}>{t('tf_closest_note')}</p>
              <p className={`text-sm ${c.textSecondary}`}>{r.no_perfect_fit}</p>
            </div>
          )} {/* Demand capture — the AI just confirmed no tool fits */} {r.no_perfect_fit && (
            <IdeaPrompt source="toolfinder-nofit" query={problem} />
          )} {/* ── NOT QUITE IT ── */} {!r.no_perfect_fit && (
            !refineOpen ? (
              <button onClick={() => setRefineOpen(true)} className={`flex items-center gap-1.5 text-sm font-semibold ${linkStyle}`}>
                {t('tf_not_what_you_meant')} <Caret open={false} />
              </button>
            ) : (<div className={`${c.cardAlt} border ${c.border} rounded-xl p-4`}>
                <div className="space-y-2">
                  <p className={`text-xs font-bold ${c.textMuted}`}>{t('tf_whats_different')}</p>
                  <textarea
                    value={refinement} onChange={e => setRefinement(e.target.value)} autoFocus
                    placeholder={t('tf_refine_ph')} rows={2} maxLength={400}
                    onKeyDown={e => { if ((e.metaKey || e.ctrlKey) && e.key === 'Enter') submitRefinement(); }}
                    className={`w-full px-3 py-2 border rounded-lg text-sm ${c.input} ${c.border} ${c.text} outline-none focus:ring-2 resize-none`} />
                  <button onClick={submitRefinement} disabled={loading || !refinement.trim()}
                    className={`w-full ${(!refinement.trim()) ? c.btnIdle : c.btnPrimary} disabled:cursor-not-allowed font-bold py-2 rounded-lg text-sm`}>
                    {loading ? t('tf_searching') : t('tf_find_better')}
                  </button>
                </div>
              </div>
            )
          )} {/* ── BROWSE ALL ── */} <p className={`text-xs text-center ${c.textMuted}`}>{t('tf_ai_disclaimer')}</p>
          {/* Demand capture, and now unmistakably its own path: this one means
              DeftBrain has nothing, not that the first guess was poor. */}
          {!r.no_perfect_fit && <IdeaPrompt source="toolfinder-results" query={problem} compact />}
          <p className={`text-xs ${c.textMuted} text-center`}>
            {t('tf_not_found')}{' '}
            <a href="/" className={`font-semibold underline ${linkStyle}`}>{t('tf_browse_all')}</a>
          </p>
        </div>
      )} {/* Session sessionHistory */} {/* eslint-disable-next-line no-restricted-globals */} {sessionHistory.length > 0 && (<details className={`group ${c.cardAlt} border ${c.border} rounded-xl px-4 py-3 mt-4`}>
          <summary className="cursor-pointer list-none [&::-webkit-details-marker]:hidden">
            <span className={`text-xs font-bold ${c.textMuted} flex items-center gap-2`}>
              {t('tf_recent')}
              {/* eslint-disable-next-line no-restricted-globals */}
              <span className="font-normal">({sessionHistory.length})</span>
              <Caret groupOpen className="ms-auto" />
            </span>
          </summary>
          <div className="space-y-1 mt-3">
            {/* eslint-disable-next-line no-restricted-globals */} {sessionHistory.map(s => (<div key={s.id} className="flex items-center justify-between">
                <span className={`text-xs ${c.textSecondary} truncate`}>{s.preview || t('tf_session')}</span>
                <span className={`text-xs ${c.textMuted} ms-2 shrink-0`}>{new Date(s.date).toLocaleDateString()}</span>
              </div>
            ))} </div>
        </details>
      )} </div>
  );
};

ToolFinder.displayName = 'ToolFinder';
export default ToolFinder;
