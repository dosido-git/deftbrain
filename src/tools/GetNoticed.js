import React, { useState, useCallback, useRef, useEffect } from 'react';
import Caret from '../components/Caret';
import { useClaudeAPI } from '../hooks/useClaudeAPI';
import { useTheme } from '../hooks/useTheme';
import { usePersistentState } from '../hooks/usePersistentState';
import { useRegisterActions } from '../components/ActionBarContext';
import { useTranslation } from '../i18n/useTranslation';
import { pickExample } from '../utils/exampleRotation';
import { revealSection } from '../utils/revealSection';

const BRAND = '\n\n— Generated by DeftBrain · deftbrain.com';

// Emoji + color config per mechanism; the label text is localized at render time.
const MECHANISM_CONFIG = {
  signal:   { icon: '📢', labelKey: 'lks_mech_signal',   color: (d) => d ? 'bg-[rgb(44,74,110)]/20 text-[rgb(168,185,206)] border-[rgb(44,74,110)]/40' : 'bg-[rgb(232,238,245)] text-[rgb(44,74,110)] border-[rgb(168,185,206)]' },
  enter:    { icon: '🚪', labelKey: 'lks_mech_enter',    color: (d) => d ? 'bg-[rgb(200,135,46)]/15 text-[rgb(217,160,78)] border-[rgb(200,135,46)]/40' : 'bg-[rgb(253,243,228)] text-[rgb(147,84,31)] border-[rgb(224,196,154)]' },
  create:   { icon: '✍️', labelKey: 'lks_mech_create',   color: (d) => d ? 'bg-[rgb(90,138,92)]/15 text-[rgb(138,186,140)] border-[rgb(90,138,92)]/40' : 'bg-[rgb(233,243,233)] text-[rgb(52,92,54)] border-[rgb(160,196,161)]' },
  connect:  { icon: '🧲', labelKey: 'lks_mech_connect',  color: (d) => d ? 'bg-[rgb(181,74,63)]/15 text-[rgb(232,169,163)] border-[rgb(181,74,63)]/40' : 'bg-[rgb(252,234,232)] text-[rgb(138,48,40)] border-[rgb(212,144,138)]' },
  compound: { icon: '⚡', labelKey: 'lks_mech_compound', color: (d) => d ? 'bg-[rgb(61,54,48)]/60 text-[rgb(200,195,185)] border-[rgb(61,54,48)]' : 'bg-[rgb(240,236,229)] text-[rgb(61,57,53)] border-[rgb(213,202,184)]' },
};

const EXAMPLES = [
  {
    desc: 'Software engineer, WFH, same team for 3 years. Live in Denver. Go to the gym, cook, watch TV. Small tight friend group. Work is fine but I feel invisible professionally.',
    goals: 'Better job opportunities, interesting collaborators, maybe a co-founder someday',
  },
  {
    desc: 'Freelance designer, mostly work through referrals from 2 clients. Active on Instagram but not professionally. Go to the same coffee shop every day. Haven\'t been to an industry event in 2 years.',
    goals: 'More and better clients, creative collaborators, maybe an agent or gallery connection',
  },
];

const GetNoticed = ({ tool }) => {
  const { isDark } = useTheme();
  const { callToolEndpoint, loading, userLocale, userCurrency, userRegion } = useClaudeAPI();
  const { t } = useTranslation();

  const c = {
    card:          isDark ? 'bg-[rgb(42,38,35)]' : 'bg-white',
    cardAlt:       isDark ? 'bg-[rgb(51,46,42)]' : 'bg-[rgb(250,248,245)]',
    input:         isDark ? 'bg-[rgb(26,24,22)] border-[rgb(61,54,48)] text-[rgb(240,238,234)] placeholder-zinc-400 focus:border-cyan-500 focus:ring-cyan-500/20'
                          : 'bg-[rgb(250,248,245)] border-[rgb(213,202,184)] text-[rgb(61,57,53)] placeholder-gray-400 focus:border-cyan-500 focus:ring-cyan-100',
    text:          isDark ? 'text-[rgb(240,238,234)]' : 'text-[rgb(61,57,53)]',
    textSecondary: isDark ? 'text-[rgb(200,195,185)]' : 'text-[rgb(90,84,74)]',
    textMuted:     isDark ? 'text-zinc-400' : 'text-[#6e675c]',
    labelText:     isDark ? 'text-zinc-200' : 'text-gray-700',
    accentTxt:     isDark ? 'text-cyan-400' : 'text-cyan-600',
    btnPrimary:    isDark ? 'bg-cyan-600 hover:bg-cyan-500 text-white'
                          : 'bg-cyan-600 hover:bg-cyan-700 text-white',
    // Waiting for input: an outline, not a smudge. Empty fill keeps "filled"
    // meaning "ready"; the border and label carry the visibility. Important
    // modifiers because tools carry their own border/text utilities on the
    // submit and Tailwind resolves conflicts by stylesheet order, not class
    // order. See the PF-13 exception in audit/audit_v2-3-2.py.
    btnIdle:       isDark ? '!bg-transparent !border-2 !border-cyan-500/85 !text-cyan-300 cursor-not-allowed'
                          : '!bg-transparent !border-2 !border-cyan-600/85 !text-cyan-800 cursor-not-allowed',
    btnSecondary:  isDark ? 'bg-[rgb(51,46,42)] hover:bg-[rgb(61,54,48)] text-[rgb(200,195,185)] border border-[rgb(61,54,48)]'
                          : 'bg-[rgb(243,239,232)] hover:bg-[rgb(232,225,213)] text-[rgb(94,80,66)] border border-[rgb(213,202,184)]',
    border:        isDark ? 'border-zinc-700' : 'border-gray-200',
    success:       isDark ? 'bg-emerald-900/20 border-emerald-700 text-emerald-200'
                          : 'bg-emerald-50 border-emerald-300 text-emerald-800',
    warning:       isDark ? 'bg-amber-900/20 border-amber-700 text-amber-200'
                          : 'bg-amber-50 border-amber-300 text-amber-800',
    danger:        isDark ? 'bg-red-900/20 border-red-700 text-red-200'
                          : 'bg-red-50 border-red-200 text-red-800',
    required:      isDark ? 'text-amber-400' : 'text-amber-700',
    // Tool-specific keys
  };
  c.textMuteded = c.textMuted;
  c.label = c.labelText;

  const linkStyle = isDark
    ? 'text-cyan-400 hover:text-cyan-300 underline underline-offset-2'
    : 'text-cyan-700 hover:text-cyan-800 underline underline-offset-2';

  const [description, setDescription] = useState('');
  const [goals, setGoals] = useState('');
  const [currentExposures, setCurrentExposures] = useState('');
  const [results, setResults] = usePersistentState('getnoticed-results-v2', null);
  const [error, setError] = useState('');
  const [expanded, setExpanded] = useState({});

  // ── Persistent state ──
  const toggle = (k) => setExpanded(p => ({ ...p, [k]: !p[k] }));

  const handleSubmit = async () => {
    if (!description.trim()) return;
    setError(''); setResults(null);
    try {
      const data = await callToolEndpoint('get-noticed', {
        description: description.trim(),
        goals: goals.trim() || undefined,
        currentExposures: currentExposures.trim() || undefined,
        userLocale, userCurrency, userRegion,
      });
      // PF-25 exception: 40-char preview-text truncation; session history is capped at 6.
      setResults({ ...data, _input: { description: description.trim(), goals: goals.trim(), currentExposures: currentExposures.trim() } });
    } catch (e) { setError(e.message || t('lks_error')); }
  };

  const loadExample = () => {
    const ex = pickExample('GetNoticed', EXAMPLES);
    setDescription(ex.desc); setGoals(ex.goals); setResults(null);
  };

  const handleReset = () => { setResults(null); setDescription(''); setGoals(''); setCurrentExposures(''); setExpanded({}); setError(''); };

  const buildFullText = useCallback(() => {
    if (!results) return '';
    const cs = results?.current_surface;
    let out = `🧲 ${t('lks_copy_header')}\n\n`;
    if (cs) {
      out += `${t('lks_h_surface')}: ${t(`lks_b_${cs.breadth || 'mixed'}`)}\n${cs.summary || ''}\n\n`;
      if (cs.limits?.length) out += `${t('lks_h_limits')}\n${cs.limits.map(x => `- ${x}`).join('\n')}\n\n`;
      if (cs.already_working?.length) out += `${t('lks_h_working')}\n${cs.already_working.map(x => `- ${x}`).join('\n')}\n\n`;
    }
    if (results?.moves?.length) {
      out += `${t('lks_h_moves')}\n`;
      results.moves.forEach((m, i) => {
        out += `${i + 1}. ${m.title}\n${m.action}\n${t('lks_l_why')} ${m.why_it_expands_opportunity}\n${t('lks_l_first')} ${m.first_step}\n\n`;
      });
    }
    if (results?.start_here) {
      out += `${t('lks_start_here')}\n${results.start_here.move_title || ''}\n${results.start_here.why_this_one || ''}\n${results.start_here.first_step || ''}\n`;
    }
    return out + BRAND;
  }, [results, t]);

  useRegisterActions(buildFullText(), tool?.title || 'Luck Surface');

  // ── Keyboard + scroll refs ──
  const handleSubmitRef = useRef(null);
  const canSubmitRef = useRef(false);
  const resultsRef = useRef(null);
  handleSubmitRef.current = handleSubmit;
  canSubmitRef.current = !!description.trim();

  useEffect(() => {
    if (!results || !resultsRef.current) return;
    const t = setTimeout(() => revealSection(resultsRef.current), 200);
    return () => clearTimeout(t);
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [results]);

  useEffect(() => {
    const handler = (e) => {
      const tag = document.activeElement?.tagName;
      if (tag === 'SELECT') return;
      if ((e.metaKey || e.ctrlKey) && e.key === 'Enter' && !loading && canSubmitRef.current) {
        e.preventDefault();
        handleSubmitRef.current?.();
      }
    };
    document.addEventListener('keydown', handler);
    return () => document.removeEventListener('keydown', handler);
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [loading]);

  return (
    <div className={`space-y-4 ${c.text}`}>

      {/* ── Persistent Header ── */}
      <div className={`${c.card} border ${c.border} rounded-xl shadow-sm`}>
        <div className="px-5 pt-2.5">
          <div className="pb-3 border-b border-zinc-500 flex items-start justify-between gap-3">
            <div>
            {/* PF-30 — the wrapper already prints the name as the page <h1>. */}
            <p className={`text-base ${c.textSecondary}`}>
              <span className="me-2 text-lg">{tool?.icon ?? '🧲'}</span>{tool?.tagline ?? t('lks_tagline')}
            </p>
            <button onClick={loadExample} disabled={loading} style={{ backgroundColor: (tool?.headerColor ?? '#888888') + '80' }} className="mt-2 px-4 py-2 rounded-full text-sm font-semibold border border-black/25 text-zinc-900 shadow-sm hover:brightness-105 hover:shadow transition disabled:opacity-40 whitespace-nowrap">✨ {t('try_example')}</button>
            </div>
            {(results || description.trim() || goals.trim()) && (
              <button onClick={handleReset}
                className={`px-3 py-1.5 rounded-lg text-xs font-medium ${c.btnSecondary} border ${c.border} shrink-0`}>
                ↻ {t('lks_reset')}
              </button>
            )}
          </div>
        </div>
      </div>

      {!results && (
          <div className={`rounded-2xl border p-6 shadow-sm space-y-4 ${c.card} ${c.border}`}>
            <p className={`text-xs ${c.textMuted}`}>
              {t('lks_xref_pre')} <a href="/SixDegreesOfMe" className={linkStyle}>🔗 {t('lks_xref_sixdegrees')}</a> {t('lks_xref_post')}
            </p>
            <div>
              <label className={`block text-sm font-semibold mb-1.5 ${c.text}`}>
                {t('lks_desc_label')} <span className={c.required}>*</span>
              </label>
              <textarea value={description} onChange={e => setDescription(e.target.value)}
                placeholder={t('lks_desc_ph')}
                rows={5} maxLength={800}
                className={`w-full px-4 py-3 rounded-xl border text-sm resize-none ${c.input}`} />
            </div>
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
              <div>
                <label className={`block text-sm font-semibold mb-1.5 ${c.text}`}>{t('lks_goals_label')} <span className={`font-normal ${c.textMuteded}`}>{t('lks_optional')}</span></label>
                <input type="text" value={goals} onChange={e => setGoals(e.target.value)}
                  placeholder={t('lks_goals_ph')}
                  className={`w-full px-4 py-3 rounded-xl border text-sm ${c.input}`} />
              </div>
              <div>
                <label className={`block text-sm font-semibold mb-1.5 ${c.text}`}>{t('lks_exposures_label')} <span className={`font-normal ${c.textMuteded}`}>{t('lks_optional')}</span></label>
                <input type="text" value={currentExposures} onChange={e => setCurrentExposures(e.target.value)}
                  placeholder={t('lks_exposures_ph')}
                  className={`w-full px-4 py-3 rounded-xl border text-sm ${c.input}`} />
              </div>
            </div>
            {error && <div className={`p-3 rounded-xl border text-sm ${c.danger}`}><span className="me-1">⚠️</span>{error}</div>}
            <button title={t('cmd_enter')} onClick={handleSubmit} disabled={loading || !description.trim()}
              className={`relative w-full py-3 rounded-xl font-bold ${(!description.trim()) ? c.btnIdle : c.btnPrimary}`}>
              {loading
              ? <><span className="inline-block animate-spin">{tool?.icon ?? '🧲'}</span> {t('lks_calculating')}</>
              : <><span className="me-1">{tool?.icon ?? '🧲'}</span> {t('lks_calculate')}</>}
            {!loading && (
              <kbd aria-hidden="true"
                className="hidden sm:flex items-center absolute end-3 top-1/2 -translate-y-1/2 px-1.5 py-0.5 rounded border border-white/30 bg-white/15 text-[10px] font-bold tracking-wide">
                ⌘↵
              </kbd>
            )}
            </button>
          </div>
        )}

        {results && (
          <div className="scroll-mt-24 space-y-4" ref={resultsRef}>

            {/* Recap of what the user told us — anchors persisted results on revisits */}
            {results?._input?.description && (
              <div className={`rounded-xl border p-4 ${c.cardAlt} ${c.border}`}>
                <p className={`text-xs font-semibold uppercase tracking-wide mb-1.5 ${c.textMuteded}`}>📝 {t('lks_your_situation')}</p>
                <p className={`text-sm ${c.textSecondary}`}>{results._input.description}</p>
                {results._input.goals && <p className={`text-xs mt-1.5 ${c.textMuteded}`}>🎯 {results._input.goals}</p>}
              </div>
            )}


            {/* Current surface — a word, not a number. There is no denominator
                for "available serendipity", so the old 14% was a figure with
                nothing under it. */}
            {results?.current_surface && (
              <div className={`rounded-2xl border p-6 ${c.card} ${c.border}`}>
                <div className="flex items-center justify-between gap-3 mb-3">
                  <p className={`text-xs font-black uppercase tracking-widest ${c.textMuteded}`}>{t('lks_h_surface')}</p>
                  <span className={`text-xs font-black uppercase tracking-widest px-3 py-1 rounded-full border ${
                    results.current_surface.breadth === 'broad'
                      ? (isDark ? 'bg-[rgb(90,138,92)]/15 text-[rgb(138,186,140)] border-[rgb(90,138,92)]/40' : 'bg-[rgb(233,243,233)] text-[rgb(52,92,54)] border-[rgb(160,196,161)]')
                      : results.current_surface.breadth === 'mixed'
                        ? (isDark ? 'bg-[rgb(200,135,46)]/15 text-[rgb(217,160,78)] border-[rgb(200,135,46)]/40' : 'bg-[rgb(253,243,228)] text-[rgb(147,84,31)] border-[rgb(224,196,154)]')
                        : (isDark ? 'bg-[rgb(44,74,110)]/20 text-[rgb(168,185,206)] border-[rgb(44,74,110)]/40' : 'bg-[rgb(232,238,245)] text-[rgb(44,74,110)] border-[rgb(168,185,206)]')}`}>
                    {t(`lks_b_${results.current_surface.breadth || 'mixed'}`)}
                  </span>
                </div>
                {results.current_surface.summary && (
                  <p className={`text-sm leading-relaxed ${c.textSecondary}`}>{results.current_surface.summary}</p>
                )}
              </div>
            )}

            {results?.current_surface?.limits?.length > 0 && (
              <div className={`rounded-2xl border p-5 ${c.card} ${c.border}`}>
                <p className={`text-xs font-black uppercase tracking-widest mb-3 ${c.textMuteded}`}>{t('lks_h_limits')}</p>
                <ul className="space-y-1.5">
                  {results.current_surface.limits.map((x, i) => (
                    <li key={i} className={`text-sm ${c.textSecondary}`}>• {x}</li>
                  ))}
                </ul>
              </div>
            )}

            {results?.current_surface?.already_working?.length > 0 && (
              <div className={`rounded-2xl border p-5 ${c.card} ${c.border}`}>
                <p className={`text-xs font-black uppercase tracking-widest mb-3 ${c.textMuteded}`}>{t('lks_h_working')}</p>
                <ul className="space-y-1.5">
                  {results.current_surface.already_working.map((x, i) => (
                    <li key={i} className={`text-sm ${c.textSecondary}`}>✓ {x}</li>
                  ))}
                </ul>
              </div>
            )}

            {results?.moves?.length > 0 && (
              <div className="space-y-3">
                <p className={`text-xs font-black uppercase tracking-widest px-1 ${c.textMuteded}`}>⚡ {t('lks_h_moves')}</p>
                {results.moves.map((move, i) => {
                  const mcfg = MECHANISM_CONFIG[move.mechanism] || MECHANISM_CONFIG.signal;
                  const isOpen = expanded[i];
                  return (
                    <div key={i} className={`rounded-2xl border overflow-hidden ${c.card} ${c.border}`}>
                      <button onClick={() => toggle(i)} className="w-full text-start p-5">
                        <div className="flex items-start justify-between gap-3">
                          <div className="flex items-center gap-3 min-w-0">
                            <span className={`flex-shrink-0 w-7 h-7 rounded-full flex items-center justify-center text-sm font-black ${isDark ? 'bg-[rgb(44,74,110)] text-white' : 'bg-[rgb(232,238,245)] text-[rgb(44,74,110)]'}`}>{i + 1}</span>
                            <div className="min-w-0">
                              <p className={`font-bold text-sm ${c.text}`}>{move.title}</p>
                              <span className={`text-xs font-semibold px-2 py-0.5 rounded-full border ${mcfg.color(isDark)}`}>{mcfg.icon} {t(mcfg.labelKey)}</span>
                            </div>
                          </div>
                          <Caret open={isOpen} className="flex-shrink-0" />
                        </div>
                        {!isOpen && <p className={`text-sm mt-2 line-clamp-2 ${c.textMuteded}`}>{move.action}</p>}
                      </button>
                      {isOpen && (
                        <div className={`px-5 pb-5 space-y-3 border-t ${c.border}`}>
                          <div className="pt-3">
                            <p className={`text-xs font-bold uppercase tracking-wide mb-1 ${c.textMuteded}`}>{t('lks_l_action')}</p>
                            <p className={`text-sm ${c.text}`}>{move.action}</p>
                          </div>
                          {move.why_it_expands_opportunity && (
                            <p className={`text-xs ${c.textMuteded}`}><span className="font-semibold">{t('lks_l_why')}</span> {move.why_it_expands_opportunity}</p>
                          )}
                          {move.first_step && (
                            <p className={`text-xs ${c.textMuteded}`}><span className="font-semibold">{t('lks_l_first')}</span> {move.first_step}</p>
                          )}
                        </div>
                      )}
                    </div>
                  );
                })}
              </div>
            )}

            {results?.start_here && (
              <div className={`rounded-2xl border-2 p-5 ${isDark ? 'border-[rgb(44,74,110)] bg-[rgb(44,74,110)]/10' : 'border-[rgb(44,74,110)] bg-[rgb(232,238,245)]'}`}>
                <p className={`text-xs font-black uppercase tracking-widest mb-2 ${isDark ? 'text-[rgb(168,185,206)]' : 'text-[rgb(44,74,110)]'}`}>⚡ {t('lks_start_here')}</p>
                {results.start_here.move_title && <p className={`text-sm font-bold ${c.text}`}>{results.start_here.move_title}</p>}
                {results.start_here.why_this_one && <p className={`text-sm mt-1.5 ${c.textSecondary}`}>{results.start_here.why_this_one}</p>}
                {results.start_here.first_step && <p className={`text-sm mt-2 font-medium ${c.text}`}>{results.start_here.first_step}</p>}
              </div>
            )}

            <div className={`rounded-xl border p-4 ${c.cardAlt} ${c.border}`}>
              <p className={`text-xs font-semibold uppercase tracking-wide mb-3 ${c.textMuteded}`}>{t('lks_related')}</p>
              <div className="flex flex-wrap gap-2">
                {[
                  { id: 'BeforeHello', icon: '🌀', label: t('lks_xref_gravitywell') },
                  { id: 'ChaosPilot', icon: '🎰', label: t('lks_xref_chaospilot') },
                  { id: 'NotSoFast', icon: '🚪', label: t('lks_xref_rulebookbreaker') },
                ].map(r => (
                  <a key={r.id} href={`/${r.id}`}
                    className={`text-xs ${linkStyle}`}>
                    {r.icon} {r.label}
                  </a>
                ))}
              </div>
            </div>
          </div>
      )}

      {/* Disclaimer */}
      <div className={`${c.cardAlt} border ${c.border} rounded-xl p-3 text-center`}>
        <p className={`text-xs ${c.textMuted}`}>
          {t('lks_disclaimer')}
        </p>
      </div>

    </div>
  );
};

GetNoticed.displayName = 'GetNoticed';
export default GetNoticed;
