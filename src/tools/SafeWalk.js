let audioCtx = null;
const getAudioCtx = () => {
  if (!audioCtx || audioCtx.state === 'closed') {
    audioCtx = new (window.AudioContext || window.webkitAudioContext)();
  }
  if (audioCtx.state === 'suspended') audioCtx.resume();
  return audioCtx;
};

const createRingtone = () => {
  const ctx = getAudioCtx();
  const gain = ctx.createGain();
  gain.gain.value = 0.3;
  gain.connect(ctx.destination);

  const osc1 = ctx.createOscillator();
  osc1.frequency.value = 440;
  osc1.type = 'sine';
  osc1.connect(gain);

  const osc2 = ctx.createOscillator();
  osc2.frequency.value = 480;
  osc2.type = 'sine';
  osc2.connect(gain);

  // Pulsing pattern via gain scheduling
  const now = ctx.currentTime;
  for (let i = 0; i < 20; i++) {
    const t = now + i * 3;
    gain.gain.setValueAtTime(0.3, t);
    gain.gain.setValueAtTime(0, t + 1);
  }

  osc1.start(); osc2.start();
  return { stop: () => { try { osc1.stop(); osc2.stop(); gain.disconnect(); } catch {} } };
};

// A locally-triggered, locally-audible alarm sound — started and stopped only
// by the visitor tapping "Sound alarm." It does not run on a timer or an
// automatic escalation; see the EMERGENCY TOOLS section of SAFEWALK-NOTES.md.
const createAlarm = () => {
  const ctx = getAudioCtx();
  const gain = ctx.createGain();
  gain.gain.value = 0.8;
  gain.connect(ctx.destination);

  const osc = ctx.createOscillator();
  osc.type = 'sine';
  osc.connect(gain);

  // Siren sweep 800-1200Hz, scheduled for up to an hour — stopped manually.
  const now = ctx.currentTime;
  for (let i = 0; i < 7200; i++) {
    const t = now + i * 0.5;
    osc.frequency.setValueAtTime(800, t);
    osc.frequency.linearRampToValueAtTime(1200, t + 0.25);
    osc.frequency.linearRampToValueAtTime(800, t + 0.5);
  }

  osc.start();
  return { stop: () => { try { osc.stop(); gain.disconnect(); } catch {} } };
};

