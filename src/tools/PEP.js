import React, { useCallback, useEffect, useMemo, useRef, useState } from 'react';
import { useClaudeAPI } from '../hooks/useClaudeAPI';
import { useTheme } from '../hooks/useTheme';
import { usePersistentState } from '../hooks/usePersistentState';
import { useRegisterActions } from '../components/ActionBarContext';
import { useTranslation } from '../i18n/useTranslation';
import { pickExample } from '../utils/exampleRotation';
import { revealSection } from '../utils/revealSection';

const BRAND = '\n\n— Generated by DeftBrain · deftbrain.com';
const ENERGY_EMOJIS = ['', '😵', '😩', '😮‍💨', '😐', '🫤', '🙂', '😊', '😄', '🤩', '🔥'];

// Reused from the prior PEP rewrite — same values, same i18n keys, already
// localized in all 13 languages. Keep the `v` (English, sent to the backend)
// separate from `l` (localized display label).
// 'All evening' (pep_time_evening) was dropped — it mixed a daypart into a
// row of durations. Open-ended is a duration concept (no fixed end), not a
// time of day.
const TIME_META = [{ v: '5 minutes', lk: 'pep_time_5m' }, { v: '15 minutes', lk: 'pep_time_15m' }, { v: '30 minutes', lk: 'pep_time_30m' }, { v: '1 hour', lk: 'pep_time_1hr' }, { v: '2 hours', lk: 'pep_time_2hr' }, { v: 'open-ended', lk: 'pep_time_open_ended' }];
const MOOD_META = [{ v: 'stressed', e: '😤', lk: 'pep_mood_stressed' }, { v: 'sad', e: '😢', lk: 'pep_mood_sad' }, { v: 'anxious', e: '😰', lk: 'pep_mood_anxious' }, { v: 'restless', e: '🫠', lk: 'pep_mood_restless' }, { v: 'overstimulated', e: '🤯', lk: 'pep_mood_overstimulated' }, { v: 'bored', e: '😑', lk: 'pep_mood_bored' }, { v: 'numb', e: '😶', lk: 'pep_mood_numb' }];
const ENV_META = [{ v: 'home', e: '🏠', lk: 'pep_env_home' }, { v: 'office', e: '🏢', lk: 'pep_env_office' }, { v: 'commuting', e: '🚌', lk: 'pep_env_commuting' }, { v: 'outdoors', e: '🌳', lk: 'pep_env_outdoors' }, { v: 'in_bed', e: '🛏️', lk: 'pep_env_in_bed' }];

const PEP = ({ tool }) => {
  const { callToolEndpoint, loading, userLocale, userCurrency, userRegion } = useClaudeAPI();
  const { isDark } = useTheme();
  const { t } = useTranslation();

  // ─── PF-2: c block, aliases, linkStyle — must precede all useState ───
  const c = {
    card: isDark ? 'bg-zinc-800' : 'bg-white',
    cardAlt: isDark ? 'bg-zinc-700/50' : 'bg-slate-50',
    input: isDark ? 'bg-zinc-900 border-zinc-600 text-zinc-100 placeholder-zinc-400 focus:border-cyan-500 focus:ring-cyan-500/20' : 'bg-white border-gray-300 text-gray-900 placeholder-gray-400 focus:border-cyan-500 focus:ring-cyan-100',
    text: isDark ? 'text-zinc-50' : 'text-gray-900',
    textSecondary: isDark ? 'text-zinc-300' : 'text-gray-600',
    textMuted: isDark ? 'text-zinc-400' : 'text-gray-500',
    labelText: isDark ? 'text-zinc-200' : 'text-gray-700',
    accentTxt: isDark ? 'text-cyan-400' : 'text-cyan-600',
    btnPrimary: isDark ? 'bg-cyan-600 hover:bg-cyan-500 text-white' : 'bg-cyan-600 hover:bg-cyan-700 text-white',
    btnSecondary: isDark ? 'bg-zinc-700 hover:bg-zinc-600 text-zinc-200' : 'bg-gray-100 hover:bg-gray-200 text-gray-700',
    border: isDark ? 'border-zinc-700' : 'border-gray-200',
    success: isDark ? 'bg-emerald-900/20 border-emerald-700 text-emerald-200' : 'bg-emerald-50 border-emerald-300 text-emerald-800',
    warning: isDark ? 'bg-amber-900/20 border-amber-700 text-amber-200' : 'bg-amber-50 border-amber-300 text-amber-800',
    danger: isDark ? 'bg-red-900/20 border-red-700 text-red-200' : 'bg-red-50 border-red-200 text-red-800',
    highlight: isDark ? 'bg-cyan-900/20 border-cyan-700 text-cyan-200' : 'bg-cyan-50 border-cyan-200 text-cyan-800',
    savedBadge: isDark ? 'text-emerald-400' : 'text-emerald-600',
    required: isDark ? 'text-amber-400' : 'text-amber-700',
  };
  c.textMuteded = c.textMuted;
  c.label = c.labelText;

  const linkStyle = isDark
    ? 'text-cyan-400 hover:text-cyan-300 underline underline-offset-2'
    : 'text-cyan-700 hover:text-cyan-800 underline underline-offset-2';

  const chip = (active) => active
    ? (isDark ? 'bg-emerald-900/40 border-emerald-500 text-emerald-200' : 'bg-emerald-100 border-emerald-400 text-emerald-800')
    : (isDark ? 'border-zinc-600 text-zinc-300 hover:border-zinc-500' : 'border-gray-300 text-gray-600 hover:border-gray-400');

  // ─── State (useState before usePersistentState — PF-2 ordering) ───
  const [timeAvail, setTimeAvail] = useState('15 minutes');
  const [mood, setMood] = useState('');
  const [environment, setEnvironment] = useState('');
  const [context, setContext] = useState('');
  const [results, setResults] = useState(null);
  const [error, setError] = useState('');
  const [sessionAvoid, setSessionAvoid] = useState([]);
  const [showMenu, setShowMenu] = useState(false);
  const [showHistory, setShowHistory] = useState(false);
  const [ratingActivity, setRatingActivity] = useState(null);
  const [helpfulness, setHelpfulness] = useState(7);
  const [energyAfter, setEnergyAfter] = useState(5);
  const [rateNote, setRateNote] = useState('');
  const [reflection, setReflection] = useState(null);
  const [reflectLoading, setReflectLoading] = useState(false);
  // Which of the three generate-triggering buttons is in flight — `loading`
  // itself is one shared flag from useClaudeAPI, so without this all three
  // buttons would spin together no matter which one was actually clicked.
  const [activeAction, setActiveAction] = useState(null);

  const [energy, setEnergy] = usePersistentState('pep-energy', 5);
  const [myMenu, setMyMenu] = usePersistentState('pep-my-menu', []);
  const [activityLog, setActivityLog] = usePersistentState('pep-log', []);

  const TIME_OPTS = TIME_META.map(o => ({ v: o.v, l: t(o.lk) }));
  const MOOD_OPTS = MOOD_META.map(o => ({ v: o.v, e: o.e, l: t(o.lk) }));
  const ENV_OPTS = ENV_META.map(o => ({ v: o.v, e: o.e, l: t(o.lk) }));

  const examples = [
    { energy: 3, time: '30 minutes', mood: '', environment: '', context: t('pep_ex1_context') },
    { energy: 2, time: '15 minutes', mood: '', environment: 'home', context: t('pep_ex2_context') },
  ];

  const localeParams = { userLocale, userCurrency, userRegion };

  const menuNames = useMemo(() => myMenu.map((x) => x.name), [myMenu]);
  // PF-25 exception: 12 (not the standard 6) so the backend has enough
  // visitor-reported history to actually notice a pattern across attempts,
  // not just echo the single most recent one.
  const recentHistory = useMemo(() => activityLog.slice(0, 12), [activityLog]);

  const historyFor = useCallback((activity) => (
    activityLog.filter((x) => x.activity === activity).slice(0, 12)
  ), [activityLog]);

  const menuStats = useCallback((name) => {
    const rows = activityLog.filter((x) => x.activity === name);
    if (!rows.length) return null;
    const ratings = rows.map((x) => x.rating).filter((x) => Number.isFinite(x));
    const allSame = ratings.length > 0 && ratings.every((r) => r === ratings[0]);
    return {
      tries: rows.length,
      allSame,
      rating: ratings.length ? ratings[0] : null,
      min: ratings.length ? Math.min(...ratings) : null,
      max: ratings.length ? Math.max(...ratings) : null,
      last: rows[0]?.date || null,
    };
  }, [activityLog]);

  // The most literal summary the evidence supports — "typically rated" for
  // two identical 7/10s overstates a pattern from two data points. One
  // rating, one wording; identical repeats, another; genuine variation, a
  // range instead of a single misleadingly-precise average.
  const ratingSummary = useCallback((stats) => {
    if (!stats || stats.rating == null) return null;
    if (stats.tries === 1) return t('pep_menu_rated_once', { r: stats.rating });
    if (stats.allSame) {
      return stats.tries === 2
        ? t('pep_menu_rated_both_times', { r: stats.rating })
        : t('pep_menu_rated_all_times', { r: stats.rating, n: stats.tries });
    }
    return t('pep_menu_rated_range', { lo: stats.min, hi: stats.max });
  }, [t]);

  const addToMenu = useCallback((activity) => {
    if (!activity) return;
    setMyMenu((prev) => prev.some((x) => x.name === activity)
      ? prev
      : [{ id: `pep_menu_${Date.now()}`, name: activity, addedAt: new Date().toISOString() }, ...prev]);
  }, [setMyMenu]);

  const removeFromMenu = useCallback((id) => {
    setMyMenu((prev) => prev.filter((x) => x.id !== id));
  }, [setMyMenu]);

  const reset = () => {
    setError('');
    setResults(null);
    setReflection(null);
    setRatingActivity(null);
    setSessionAvoid([]);
    // Also clear the input form itself — otherwise "Try an example" (which
    // fills context/mood/environment/timeAvail) followed by Start Over left
    // every field showing the example's values, so nothing visibly changed
    // and the button looked broken.
    setContext('');
    setMood('');
    setEnvironment('');
    setTimeAvail('15 minutes');
    setEnergy(5);
  };

  const generate = async ({ oneOnly = false, fresh = false } = {}) => {
    setError('');
    setReflection(null);
    setActiveAction(oneOnly ? 'oneOnly' : fresh ? 'fresh' : 'main');
    try {
      const data = await callToolEndpoint('pep', {
        action: oneOnly ? 'just-do-this' : 'generate',
        energy,
        time_available: timeAvail || null,
        mood: mood || null,
        environment: environment || null,
        context: context.trim() || null,
        saved_menu: menuNames,
        history: recentHistory,
        avoid: fresh ? sessionAvoid : [],
        ...localeParams,
      });
      if (!data) return;

      if (oneOnly) {
        // No why_it_fits here on purpose — Just Tell Me What To Do is meant
        // to feel noticeably simpler than Show Me What Fits: one activity,
        // one first step, one stopping point, no analysis paragraph.
        const wrapped = {
          read: '',
          top_pick: {
            activity: data.activity,
            first_step: data.first_step,
            duration: data.duration,
            done_when: data.done_when,
          },
          alternatives: [],
          history_note: data.history_note || '',
          justDo: true,
        };
        setResults(wrapped);
        setSessionAvoid((prev) => [...new Set([...prev, data.activity].filter(Boolean))]);
      } else {
        setResults(data);
        const names = [data?.top_pick?.activity, ...(data?.alternatives || []).map((x) => x.activity)].filter(Boolean);
        setSessionAvoid((prev) => [...new Set([...prev, ...names])]);
      }
      setTimeout(() => revealSection(document.getElementById('pep-result')), 100);
    } catch (e) {
      setError(e.message || t('pep_err_request_failed'));
    } finally {
      setActiveAction(null);
    }
  };

  const loadExample = () => {
    const ex = pickExample('PEP', examples);
    setEnergy(ex.energy);
    setTimeAvail(ex.time);
    setMood(ex.mood);
    setEnvironment(ex.environment);
    setContext(ex.context);
    setResults(null);
    setReflection(null);
  };

  const startRating = (activity) => {
    setRatingActivity({ activity, energyBefore: energy });
    setHelpfulness(7);
    setEnergyAfter(energy);
    setRateNote('');
    setReflection(null);
  };

  const submitReflection = async () => {
    if (!ratingActivity?.activity) return;
    setReflectLoading(true);
    setError('');
    const entry = {
      id: `pep_log_${Date.now()}`,
      activity: ratingActivity.activity,
      rating: helpfulness,
      energy_before: ratingActivity.energyBefore,
      energy_after: energyAfter,
      mood: mood || '',
      location: environment || '',
      note: rateNote.trim(),
      // S1.5: a short preview line for the history list — what to show at a
      // glance without opening the entry (the visitor's own note, or the
      // activity name if they left no note).
      preview: rateNote.trim() || ratingActivity.activity,
      date: new Date().toISOString(),
    };

    try {
      const data = await callToolEndpoint('pep', {
        action: 'reflect',
        activity: entry.activity,
        energy_before: entry.energy_before,
        energy_after: entry.energy_after,
        helpfulness: entry.rating,
        note: entry.note || null,
        prior_same_activity: historyFor(entry.activity),
        ...localeParams,
      });
      // My Menu and What I've Tried stay distinct: rating an activity logs it
      // as an attempt (activityLog) but does NOT save it to My Menu on its
      // own — that stays an explicit "+ My Menu" choice on the Activity card.
      setActivityLog((prev) => [entry, ...prev].slice(0, 100));
      if (data) setReflection(data);
    } catch (e) {
      setError(e.message || t('pep_err_request_failed'));
    } finally {
      setReflectLoading(false);
    }
  };

  const buildText = useCallback(() => {
    if (!results?.top_pick) return '';
    const lines = [tool?.title || 'PEP — Personal Energy Planner', ''];
    if (results.read) lines.push(results.read, '');
    lines.push(`${t('pep_top_pick_label')}: ${results.top_pick.activity}`);
    if (results.top_pick.why_it_fits) lines.push(results.top_pick.why_it_fits);
    if (results.top_pick.first_step) lines.push(`${t('pep_first_step_label')}: ${results.top_pick.first_step}`);
    if (results.top_pick.duration) lines.push(`${t('pep_time_label_short')}: ${results.top_pick.duration}`);
    if (results.top_pick.done_when) lines.push(`${t('pep_done_when_label')}: ${results.top_pick.done_when}`);
    if (results.alternatives?.length) {
      lines.push('', `${t('pep_other_options')}:`);
      results.alternatives.forEach((x) => lines.push(`• ${x.activity}${x.duration ? ` — ${x.duration}` : ''}`));
    }
    lines.push(BRAND);
    return lines.join('\n');
  }, [results, t, tool]);

  useRegisterActions(buildText(), tool?.title || 'PEP');

  // ─── S2.1: Cmd/Ctrl+Enter submits — refs avoid a stale closure in the
  // module-level listener without re-binding on every keystroke. ───
  const generateRef = useRef(null);
  const canSubmitRef = useRef(false);
  generateRef.current = generate;
  canSubmitRef.current = !loading;

  useEffect(() => {
    const handler = (e) => {
      const tag = document.activeElement?.tagName;
      if (tag === 'SELECT') return;
      if (e.key === 'Enter' && (e.metaKey || e.ctrlKey) && canSubmitRef.current) {
        generateRef.current?.();
      }
    };
    document.addEventListener('keydown', handler);
    return () => document.removeEventListener('keydown', handler);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const Activity = ({ item, top = false }) => {
    if (!item?.activity) return null;
    const saved = myMenu.some((x) => x.name === item.activity);
    return <div className={`${c.card} border ${top ? 'border-emerald-400 border-2' : c.border} rounded-xl p-4 space-y-2`}>
      <div className="flex items-start justify-between gap-3">
        <h4 className={`font-bold ${top ? 'text-base' : 'text-sm'} ${c.text} flex-1 min-w-0`}>{item.activity}</h4>
        {item.duration && <span className={`text-xs ${c.textMuted} flex-shrink-0 max-w-[40%] text-end`}>{item.duration}</span>}
      </div>
      {item.why_it_fits && <p className={`text-sm ${c.textSecondary}`}>{item.why_it_fits}</p>}
      {item.first_step && <p className={`text-sm font-semibold ${c.text}`}>→ {item.first_step}</p>}
      {item.done_when && <p className={`text-xs ${c.textMuted}`}>✓ {item.done_when}</p>}
      <div className="flex flex-wrap gap-2 pt-1">
        {!saved ? <button onClick={() => addToMenu(item.activity)} className={`px-3 py-1.5 rounded-lg text-xs font-bold ${c.btnSecondary}`}>＋ {t('pep_add_my_menu')}</button>
          : <span className={`px-2 py-1 text-xs ${c.savedBadge}`}>✓ {t('pep_on_menu')}</span>}
        <button onClick={() => startRating(item.activity)} className={`px-3 py-1.5 rounded-lg text-xs font-bold ${c.btnSecondary}`}>⭐ {t('pep_i_tried_it')}</button>
      </div>
    </div>;
  };

  const hasSomethingToReset = !!(results || context.trim());

  return <div className={`max-w-4xl mx-auto space-y-4 ${c.text}`}>
    <div className={`${c.card} border ${c.border} rounded-xl shadow-sm px-5 pt-2.5 pb-5`}>
      <div className="pb-3 border-b border-zinc-500">
        <div className="flex items-start justify-between gap-3">
          <div>
            {/* PF-30 — the wrapper already prints the name as the page <h1>. */}
            <p className={`text-base ${c.textSecondary}`}>
              <span className="me-2 text-lg">{tool?.icon ?? '✨'}</span>{tool?.tagline ?? t('pep_tagline')}
            </p>
            <button onClick={loadExample} disabled={loading} style={{ backgroundColor: (tool?.headerColor ?? '#888888') + '80' }} className="mt-2 px-4 py-2 rounded-full text-sm font-semibold border border-black/25 text-zinc-900 shadow-sm hover:brightness-105 hover:shadow transition disabled:opacity-40 whitespace-nowrap">✨ {t('try_example')}</button>
          </div>
          {hasSomethingToReset && (
            <button onClick={reset} className={`${c.btnSecondary} px-3 py-1.5 rounded-lg text-xs font-bold flex-shrink-0`}>
              ↺ {t('pep_start_over')}
            </button>
          )}
        </div>
      </div>

      <div className="pt-4 space-y-5">
        <div>
          <h3 className="text-xl font-bold">{t('pep_input_intro_title')}</h3>
          <p className={`text-sm ${c.textSecondary}`}>{t('pep_input_intro_body')}</p>
        </div>

        <div>
          <div className="flex justify-between items-baseline"><label className="text-sm font-bold">{t('pep_energy_label')}</label><span className="text-lg font-bold">{ENERGY_EMOJIS[energy]} {energy}/10</span></div>
          <input type="range" min="1" max="10" value={energy} onChange={(e) => setEnergy(Number(e.target.value))} className="w-full accent-emerald-500" />
          <div className={`flex justify-between text-[11px] ${c.textMuted}`}><span>1 — {t('pep_energy_scale_low')}</span><span>10 — {t('pep_energy_scale_high')}</span></div>
        </div>

        <div>
          <label className="text-sm font-bold">{t('pep_time_label')}</label>
          <div className="flex flex-wrap gap-2 mt-2">{TIME_OPTS.map((x) => <button key={x.v} onClick={() => setTimeAvail(x.v)} className={`px-3 py-2 rounded-lg border text-sm font-semibold ${chip(timeAvail === x.v)}`}>{x.l}</button>)}</div>
        </div>

        <div>
          <label className="text-sm font-bold">{t('pep_mood_label')} <span className={`font-normal ${c.textMuted}`}>({t('optional')})</span></label>
          <div className="flex flex-wrap gap-2 mt-2">{MOOD_OPTS.map((x) => <button key={x.v} onClick={() => setMood(mood === x.v ? '' : x.v)} className={`px-3 py-2 rounded-lg border text-sm ${chip(mood === x.v)}`}>{x.e} {x.l}</button>)}</div>
        </div>

        <div>
          <label className="text-sm font-bold">{t('pep_location_label')} <span className={`font-normal ${c.textMuted}`}>({t('optional')})</span></label>
          <div className="flex flex-wrap gap-2 mt-2">{ENV_OPTS.map((x) => <button key={x.v} onClick={() => setEnvironment(environment === x.v ? '' : x.v)} className={`px-3 py-2 rounded-lg border text-sm ${chip(environment === x.v)}`}>{x.e} {x.l}</button>)}</div>
        </div>

        <div>
          <label className="text-sm font-bold">{t('pep_context_label')} <span className={`font-normal ${c.textMuted}`}>({t('optional')})</span></label>
          <textarea value={context} onChange={(e) => setContext(e.target.value)} rows={3} placeholder={t('pep_context_ph')} className={`w-full mt-2 p-3 border rounded-xl text-sm ${c.input}`} />
        </div>

        <div className="grid sm:grid-cols-[1fr_auto] gap-2">
          <button title={t('cmd_enter')} onClick={() => generate()} disabled={loading} className={`py-4 rounded-xl font-bold text-lg ${c.btnPrimary} disabled:opacity-50`}>{activeAction === 'main' ? <><span className="animate-spin inline-block">{tool?.icon ?? '✨'}</span> {t('pep_generate_loading')}</> : <>✨ {t('pep_generate_btn')}</>}</button>
          <button onClick={() => generate({ oneOnly: true })} disabled={loading} className={`px-5 py-3 rounded-xl font-bold border ${c.border} ${c.btnSecondary} disabled:opacity-50`}>{activeAction === 'oneOnly' ? <><span className="animate-spin inline-block">{tool?.icon ?? '✨'}</span> {t('pep_generate_loading')}</> : <>🧊 {t('pep_just_do_btn')}</>}</button>
        </div>
      </div>
    </div>

    {!results && (
      <p className={`text-xs ${c.textMuted} px-1`}>
        {t('pep_spiral_intro')} <a href="/SpiralStopper" className={linkStyle}>🌀 {t('pep_spiral_stopper')}</a> {t('pep_spiral_first')}
      </p>
    )}

    {error && <div className={`${c.warning} border rounded-xl p-4 text-sm`}>{error}</div>}

    {results && (results.top_pick && <div id="pep-result" className="space-y-4">
      {results.read && <div className={`${c.highlight} border rounded-xl p-4`}><p className="text-sm">{results.read}</p></div>}
      {/* Just Tell Me What To Do skips the "Top pick" framing — there was no menu to pick from. */}
      {results.justDo ? <Activity item={results.top_pick} top /> : <div><h3 className="font-bold text-lg mb-2">⭐ {t('pep_top_pick_label')}</h3><Activity item={results.top_pick} top /></div>}
      {results.alternatives?.length > 0 && <div><h3 className="font-bold text-base mb-2">{t('pep_other_options')}</h3><div className="space-y-2">{results.alternatives.slice(0, 2).map((x, i) => <Activity key={`${x.activity}-${i}`} item={x} />)}</div></div>}
      {results.history_note && <div className={`${c.highlight} border rounded-xl p-4`}><p className="text-xs font-bold uppercase mb-1">{t('pep_from_history')}</p><p className="text-sm">{results.history_note}</p></div>}
      <button onClick={() => generate({ fresh: true })} disabled={loading} className={`w-full py-3 rounded-xl border-2 border-dashed ${c.border} ${c.textSecondary}`}>{activeAction === 'fresh' ? <><span className="animate-spin inline-block">{tool?.icon ?? '✨'}</span> {t('pep_generate_loading')}</> : <>🔄 {t('pep_swap_cta')}</>}</button>

      <p className={`text-xs ${c.textMuted} text-center`}>
        {t('pep_xref_intro')}{' '}
        {t('pep_xref_crash_q')}{' '}<a href="/BeforeTheCrash" className={linkStyle}>{t('pep_crash_predictor')}</a>{' '}
        {t('pep_xref_crash_mid')}{' '}<a href="/BrainStateDeejay" className={linkStyle}>{t('pep_brain_state_deejay')}</a>{' '}
        {t('pep_xref_brain_end')}
      </p>
    </div>)}

    {ratingActivity && <div className={`${c.card} border-2 border-amber-400 rounded-xl p-5 space-y-4`}>
      <div className="flex justify-between gap-3"><div><h3 className="font-bold text-lg">⭐ {t('pep_rate_title')}</h3><p className={`text-sm ${c.textSecondary}`}>{ratingActivity.activity}</p></div><button onClick={() => { setRatingActivity(null); setReflection(null); }} className={c.textMuted}>✕</button></div>
      <div><div className="flex justify-between"><label className="text-sm font-bold">{t('pep_rate_helpful')}</label><span className="font-bold">{helpfulness}/10</span></div><input type="range" min="1" max="10" value={helpfulness} onChange={(e) => setHelpfulness(Number(e.target.value))} className="w-full accent-amber-500" /></div>
      <div><div className="flex justify-between"><label className="text-sm font-bold">{t('pep_energy_now_label')}</label><span className="font-bold">{energyAfter}/10</span></div><input type="range" min="1" max="10" value={energyAfter} onChange={(e) => setEnergyAfter(Number(e.target.value))} className="w-full accent-emerald-500" /></div>
      <textarea value={rateNote} onChange={(e) => setRateNote(e.target.value)} rows={2} placeholder={t('pep_rate_noticed_ph')} className={`w-full p-3 border rounded-xl text-sm ${c.input}`} />
      <button onClick={submitReflection} disabled={reflectLoading} className={`w-full py-3 rounded-xl font-bold ${c.btnPrimary}`}>{reflectLoading ? <><span className="animate-spin inline-block">{tool?.icon ?? '✨'}</span> {t('pep_save_reflection_loading')}</> : t('pep_save_reflection_btn')}</button>
      {reflection && <div className={`${c.success} border rounded-xl p-4 space-y-1`}><p className="text-sm">{reflection.reflection}</p>{reflection.history_observation && <p className="text-sm font-semibold">{reflection.history_observation}</p>}</div>}
    </div>}

    <div className="grid sm:grid-cols-2 gap-3">
      <button onClick={() => setShowMenu((x) => !x)} className={`${c.card} border ${c.border} rounded-xl p-4 text-left`}><span className="font-bold">📋 {t('pep_my_menu')}</span><span className={`ms-2 text-sm ${c.textMuted}`}>{t('pep_count_saved', { n: myMenu.length })}</span><p className={`text-xs mt-1 ${c.textMuted}`}>{t('pep_menu_nav_desc')}</p></button>
      <button onClick={() => setShowHistory((x) => !x)} className={`${c.card} border ${c.border} rounded-xl p-4 text-left`}><span className="font-bold">🧪 {t('pep_history_nav')}</span><span className={`ms-2 text-sm ${c.textMuted}`}>{t('pep_count_attempts', { n: activityLog.length })}</span><p className={`text-xs mt-1 ${c.textMuted}`}>{t('pep_history_nav_desc')}</p></button>
    </div>

    {showMenu && <div className={`${c.card} border ${c.border} rounded-xl p-5 space-y-3`}>
      <div className="flex justify-between"><h3 className="font-bold">📋 {t('pep_my_menu')}</h3><button onClick={() => setShowMenu(false)} className={c.textMuted}>✕</button></div>
      {!myMenu.length ? <p className={`text-sm ${c.textMuted}`}>{t('pep_my_menu_empty')}</p> : myMenu.map((x) => {
        const stats = menuStats(x.name);
        const summary = ratingSummary(stats);
        return <div key={x.id} className={`${c.cardAlt} rounded-lg p-3`}><div className="flex justify-between gap-3"><div><p className="font-semibold text-sm">{x.name}</p>{stats ? <p className={`text-xs ${c.textMuted}`}>{t('pep_menu_times_tried', { n: stats.tries })}{summary ? ` · ${summary}` : ''}{stats.last ? ` · ${t('pep_menu_last_tried', { d: new Date(stats.last).toLocaleDateString(userLocale || undefined, { month: 'short', day: 'numeric' }) })}` : ''}</p> : <p className={`text-xs ${c.textMuted}`}>{t('pep_menu_not_tried_yet')}</p>}</div><button onClick={() => removeFromMenu(x.id)} className={c.textMuted}>🗑️</button></div></div>;
      })}
    </div>}

    {showHistory && <div className={`${c.card} border ${c.border} rounded-xl p-5 space-y-3`}>
      <div className="flex justify-between"><h3 className="font-bold">🧪 {t('pep_history_nav')}</h3><button onClick={() => setShowHistory(false)} className={c.textMuted}>✕</button></div>
      {!activityLog.length ? <p className={`text-sm ${c.textMuted}`}>{t('pep_history_empty')}</p> : activityLog.slice(0, 12).map((x) => <div key={x.id} className={`${c.cardAlt} rounded-lg p-3`}><div className="flex justify-between gap-3"><p className="font-semibold text-sm">{x.preview || x.activity}</p><span className={`text-xs ${c.textMuted}`}>{new Date(x.date).toLocaleDateString(userLocale || undefined, { month: 'short', day: 'numeric' })}</span></div><p className={`text-xs ${c.textSecondary}`}>{t('pep_history_row_stats', { rating: x.rating, before: x.energy_before, after: x.energy_after })}</p></div>)}
    </div>}
  </div>;
};

PEP.displayName = 'PEP';
export default PEP;
