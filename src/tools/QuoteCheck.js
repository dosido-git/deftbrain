import React, { useState, useEffect, useRef, useCallback } from 'react';
import { useClaudeAPI } from '../hooks/useClaudeAPI';
import { useTheme } from '../hooks/useTheme';
import { usePersistentState } from '../hooks/usePersistentState';
import { useRegisterActions } from '../components/ActionBarContext';
import { useTranslation } from '../i18n/useTranslation';
import { currencySymbol } from '../utils/formatLocale';
import { pickExample } from '../utils/exampleRotation';
import { revealSection } from '../utils/revealSection';

const BRAND = '\n\n— Generated by DeftBrain · deftbrain.com';
const ALLOWED_FILE_TYPES = ['image/jpeg', 'image/png', 'application/pdf'];

// V2 (2026-09-07) — audit the quote you have, not the quote you wish you had.
// Dropped: invented "typical price range", automatic negotiation posture,
// automatic red flags for merely-missing information. See
// audit/tool-notes/QUOTECHECK-NOTES.md.
const VERDICTS = ['LOOKS_STRAIGHTFORWARD', 'NEEDS_CLARIFICATION', 'HARD_TO_COMPARE', 'SPECIFIC_CONCERNS_FOUND', 'NOT_ENOUGH_INFORMATION'];

// Five, rotated across appliance, car, and 'other' repair types.
const EXAMPLES = [
  { repairType: 'appliance', quotedPrice: '450', n: '' },
  // Itemised to the last bolt — here the question is not what they are hiding
  // but how much of it actually needed doing today.
  { repairType: 'car',       quotedPrice: '1290', n: '2' },
  { repairType: 'other',     quotedPrice: '1850', n: '3' },
  { repairType: 'car',       quotedPrice: '620',  n: '4' },
  { repairType: 'other',     quotedPrice: '8900', n: '5' },
];

function QuoteCheck({ tool }) {
  const { callToolEndpoint, loading, userLocale, userCurrency, userRegion } = useClaudeAPI();
  const { isDark } = useTheme();
  const { t } = useTranslation();
  const sym = currencySymbol(userLocale, userCurrency);

  const REPAIR_TYPES = [
    { id: 'appliance', label: t('qc_type_appliance'), icon: '🔌' },
    { id: 'car',       label: t('qc_type_car'),        icon: '🚗' },
    { id: 'other',     label: t('qc_type_other'),       icon: '🔧' },
  ];

  const c = {
    card:          isDark ? 'bg-zinc-800' : 'bg-white',
    cardAlt:       isDark ? 'bg-zinc-700/50' : 'bg-slate-50',
    input:         isDark ? 'bg-zinc-900 border-zinc-600 text-zinc-100 placeholder-zinc-400 focus:border-cyan-500 focus:ring-cyan-500/20'
                          : 'bg-white border-gray-300 text-gray-900 placeholder-gray-400 focus:border-cyan-500 focus:ring-cyan-100',
    text:          isDark ? 'text-zinc-50' : 'text-gray-900',
    textSecondary: isDark ? 'text-zinc-300' : 'text-gray-600',
    textMuted:     isDark ? 'text-zinc-400' : 'text-gray-500',
    labelText:     isDark ? 'text-zinc-200' : 'text-gray-700',
    accentTxt:     isDark ? 'text-cyan-400' : 'text-cyan-600',
    btnPrimary:    isDark ? 'bg-cyan-600 hover:bg-cyan-500 text-white'
                          : 'bg-cyan-600 hover:bg-cyan-700 text-white',
    // Waiting for input: an outline, not a smudge. Empty fill keeps "filled"
    // meaning "ready"; the border and label carry the visibility. Important
    // modifiers because tools carry their own border/text utilities on the
    // submit and Tailwind resolves conflicts by stylesheet order, not class
    // order. See the PF-13 exception in audit/audit_v2-3-2.py.
    btnIdle:       isDark ? '!bg-transparent !border-2 !border-cyan-500/85 !text-cyan-300 cursor-not-allowed'
                          : '!bg-transparent !border-2 !border-cyan-600/85 !text-cyan-800 cursor-not-allowed',
    btnSecondary:  isDark ? 'bg-zinc-700 hover:bg-zinc-600 text-zinc-200'
                          : 'bg-gray-100 hover:bg-gray-200 text-gray-700',
    border:        isDark ? 'border-zinc-700' : 'border-gray-200',
    success:       isDark ? 'bg-emerald-900/20 border-emerald-700 text-emerald-200'
                          : 'bg-emerald-50 border-emerald-300 text-emerald-800',
    warning:       isDark ? 'bg-amber-900/20 border-amber-700 text-amber-200'
                          : 'bg-amber-50 border-amber-300 text-amber-800',
    danger:        isDark ? 'bg-red-900/20 border-red-700 text-red-200'
                          : 'bg-red-50 border-red-200 text-red-800',
    infoBox:       isDark ? 'bg-sky-900/20 border-sky-700 text-sky-200'
                          : 'bg-sky-50 border-sky-200 text-sky-800',
    pillActive:    isDark ? 'border-cyan-500 bg-cyan-900/30 text-cyan-200'
                          : 'border-cyan-600 bg-cyan-100 text-cyan-900',
    pillInactive:  isDark ? 'border-zinc-600 text-zinc-400 hover:border-zinc-500'
                          : 'border-gray-300 text-gray-500 hover:border-gray-400',
    required:      isDark ? 'text-amber-400' : 'text-amber-700',
    warningTxt:    isDark ? 'text-amber-300' : 'text-amber-800',
    inset:         isDark ? 'bg-zinc-900/60' : 'bg-slate-50',
  };
  c.textMuteded = c.textMuted;
  c.label = c.labelText;

  const linkStyle = isDark
    ? 'text-cyan-400 hover:text-cyan-300 underline underline-offset-2'
    : 'text-cyan-700 hover:text-cyan-800 underline underline-offset-2';

  const [repairType, setRepairType]           = useState('appliance');
  const [itemDescription, setItemDescription] = useState('');
  const [whatWentWrong, setWhatWentWrong]     = useState('');
  const [whatTheyToldYou, setWhatTheyToldYou] = useState('');
  const [quotedPrice, setQuotedPrice]         = useState('');
  const [quotedBreakdown, setQuotedBreakdown] = useState('');
  const [secondQuotePrice, setSecondQuotePrice] = useState('');
  const [secondQuoteBreakdown, setSecondQuoteBreakdown] = useState('');
  const [itemAge, setItemAge]                 = useState('');
  const [uploadedFile, setUploadedFile]       = useState(null);
  const [fileBase64, setFileBase64]           = useState(null);
  const [results, setResults]                 = usePersistentState('quotecheck-results-v2', null);
  const [sessionHistory, setSessionHistory]   = usePersistentState('quotecheck-history-v2', []);
  const [error, setError]                     = useState('');

  const resultsRef      = useRef(null);
  const fileInputRef    = useRef(null);
  const handleCheckRef  = useRef(null);
  const canSubmitRef    = useRef(false);

  const canSubmit = itemDescription.trim().length > 0 && whatWentWrong.trim().length > 0 && quotedPrice !== '' && !isNaN(Number(quotedPrice));

  const handleReset = useCallback(() => {
    setResults(null);
    setError('');
    setRepairType('appliance');
    setItemDescription('');
    setWhatWentWrong('');
    setWhatTheyToldYou('');
    setQuotedPrice('');
    setQuotedBreakdown('');
    setSecondQuotePrice('');
    setSecondQuoteBreakdown('');
    setItemAge('');
    setUploadedFile(null);
    setFileBase64(null);
    if (fileInputRef.current) fileInputRef.current.value = '';
  }, [setResults]);

  // ── File upload — optional supplementary evidence (photo or PDF of the
  //    actual quote/invoice). The backend reads it directly and reports what
  //    it actually says in quote_summary — the visitor never has to
  //    transcribe a price or breakdown already clearly shown on the page. ──
  const handleFileUpload = useCallback((e) => {
    const file = e.target.files[0];
    if (!file) return;
    if (!ALLOWED_FILE_TYPES.includes(file.type)) { setError(t('qc_err_file_type')); return; }
    if (file.size > 10 * 1024 * 1024) { setError(t('qc_err_file_size')); return; }
    setError('');
    const reader = new FileReader();
    reader.onerror = () => setError(t('qc_err_file_read'));
    reader.onload = (event) => { setUploadedFile(file); setFileBase64(event.target.result); };
    reader.readAsDataURL(file);
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [t]);

  const removeFile = useCallback(() => {
    setUploadedFile(null);
    setFileBase64(null);
    setError('');
    if (fileInputRef.current) fileInputRef.current.value = '';
  }, []);

  const loadExample = useCallback(() => {
    const ex = pickExample('QuoteCheck', EXAMPLES);
    const k = f => `qc_example${ex.n}_${f}`;
    setRepairType(ex.repairType);
    setItemDescription(t(k('item')));
    setWhatWentWrong(t(k('wrong')));
    setWhatTheyToldYou(t(k('told')));
    setQuotedPrice(ex.quotedPrice);
    setQuotedBreakdown(t(k('breakdown')));
    setItemAge(t(k('age')));
    setSecondQuotePrice('');
    setSecondQuoteBreakdown('');
    setResults(null);
    setError('');
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [setResults, t]);

  // Restores a past check's INPUTS only — never its conclusions — so the
  // visitor can update or add information and run a fresh analysis. The
  // model's own prior verdict is not a fact to feed back in as if the
  // visitor had said it.
  const recheckFrom = useCallback((entry) => {
    const i = entry?.input || {};
    setRepairType(i.repairType || 'appliance');
    setItemDescription(i.itemDescription || '');
    setWhatWentWrong(i.whatWentWrong || '');
    setWhatTheyToldYou(i.whatTheyToldYou || '');
    setQuotedPrice(i.quotedPrice != null ? String(i.quotedPrice) : '');
    setQuotedBreakdown(i.quotedBreakdown || '');
    setSecondQuotePrice(i.secondQuotePrice != null ? String(i.secondQuotePrice) : '');
    setSecondQuoteBreakdown(i.secondQuoteBreakdown || '');
    setItemAge(i.itemAge || '');
    setUploadedFile(null);
    setFileBase64(null);
    setResults(null);
    setError('');
  }, [setResults]);

  // Shows a past check's ORIGINAL analysis without calling the model again.
  const viewFrom = useCallback((entry) => {
    if (!entry?.result) return;
    setResults(entry.result);
    setError('');
  }, [setResults]);

  const handleCheck = useCallback(async () => {
    if (!canSubmit || loading) return;
    setError('');
    setResults(null);

    const inputSnapshot = {
      repairType, itemDescription: itemDescription.trim(), whatWentWrong: whatWentWrong.trim(),
      whatTheyToldYou: whatTheyToldYou.trim(), quotedPrice: Number(quotedPrice),
      quotedBreakdown: quotedBreakdown.trim(), secondQuotePrice: secondQuotePrice ? Number(secondQuotePrice) : null,
      secondQuoteBreakdown: secondQuoteBreakdown.trim(), itemAge: itemAge.trim(),
    };

    try {
      const parsed = await callToolEndpoint('quote-check', {
        ...inputSnapshot,
        secondQuotePrice: inputSnapshot.secondQuotePrice ?? undefined,
        quoteFileBase64: fileBase64 || undefined,
        userLocale,
        userCurrency,
        userRegion,
      });
      const withRecap = { ...parsed, repairType, _input: inputSnapshot };
      setResults(withRecap);
      // PF-25 exception: 80 is an item-description preview length, not a history cap.
      setSessionHistory(prev => [{
        id: 'qc_' + Date.now(),
        ts: Date.now(),
        preview: itemDescription.slice(0, 80) + (itemDescription.length > 80 ? '…' : ''),
        verdict: parsed.verdict,
        input: inputSnapshot,
        result: withRecap,
      }, ...prev].slice(0, 8));
    } catch (err) {
      setError(err.message || t('qc_error'));
    }
  }, [canSubmit, loading, repairType, itemDescription, whatWentWrong, whatTheyToldYou, quotedPrice, quotedBreakdown, secondQuotePrice, secondQuoteBreakdown, itemAge, fileBase64, callToolEndpoint, setResults, setSessionHistory, userLocale, userCurrency, userRegion, t]);

  handleCheckRef.current = handleCheck;
  canSubmitRef.current   = canSubmit;

  const buildFullText = useCallback(() => {
    if (!results) return '';
    const lines = [t('qc_copy_header'), ''];
    const verdictLabel = VERDICTS.includes(results?.verdict) ? t(`qc_verdict_${results.verdict}`) : results?.verdict;
    lines.push(`${t('qc_copy_verdict')} ${verdictLabel}`);
    if (results?.verdict_explanation) lines.push(`\n${results.verdict_explanation}`);
    if (results?.safety_note) lines.push(`\n${t('qc_safety_heading')}: ${results.safety_note}`);
    if (results?.specific_concerns?.length) {
      lines.push(`\n${t('qc_copy_concerns')}`);
      results.specific_concerns.forEach(f => lines.push(`• ${f?.concern}${f?.why_it_matters ? ` — ${f.why_it_matters}` : ''}`));
    }
    if (results?.unknowns_that_matter?.length) {
      lines.push(`\n${t('qc_copy_unknowns')}`);
      results.unknowns_that_matter.forEach(u => lines.push(`• ${u}`));
    }
    if (results?.what_to_say) {
      lines.push(`\n${t('qc_copy_script')}`);
      lines.push(results.what_to_say);
    }
    if (results?.questions_to_ask?.length) {
      lines.push(`\n${t('qc_copy_questions')}`);
      results.questions_to_ask.forEach((q, i) => lines.push(`${i + 1}. ${q}`));
    }
    lines.push(BRAND);
    return lines.join('\n');
  }, [results, t]);

  useRegisterActions(buildFullText(), tool?.title || 'QuoteCheck');

  useEffect(() => {
    if (!results || !resultsRef.current) return;
    const timer = setTimeout(() => revealSection(resultsRef.current), 200);
    return () => clearTimeout(timer);
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [results]);

  useEffect(() => {
    const handler = (e) => {
      const tag = document.activeElement?.tagName;
      if (tag === 'SELECT') return;
      if (e.key === 'Enter' && (e.metaKey || e.ctrlKey) && !loading && canSubmitRef.current)
        handleCheckRef.current?.();
    };
    document.addEventListener('keydown', handler);
    return () => document.removeEventListener('keydown', handler);
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [loading]);

  const verdictConfig = results ? {
    LOOKS_STRAIGHTFORWARD:   { bg: isDark ? 'bg-emerald-900/40 border-emerald-600' : 'bg-emerald-50 border-emerald-400', txt: isDark ? 'text-emerald-200' : 'text-emerald-800', icon: '✅', label: t('qc_verdict_LOOKS_STRAIGHTFORWARD') },
    NEEDS_CLARIFICATION:     { bg: isDark ? 'bg-amber-900/40 border-amber-600'     : 'bg-amber-50 border-amber-400',     txt: isDark ? 'text-amber-200'   : 'text-amber-800',   icon: '❓', label: t('qc_verdict_NEEDS_CLARIFICATION') },
    HARD_TO_COMPARE:         { bg: isDark ? 'bg-zinc-700/60 border-zinc-500'       : 'bg-slate-100 border-slate-300',    txt: isDark ? 'text-zinc-200'    : 'text-slate-800',   icon: '⚖️', label: t('qc_verdict_HARD_TO_COMPARE') },
    SPECIFIC_CONCERNS_FOUND: { bg: isDark ? 'bg-red-900/40 border-red-600'         : 'bg-red-50 border-red-400',         txt: isDark ? 'text-red-200'     : 'text-red-800',     icon: '🚩', label: t('qc_verdict_SPECIFIC_CONCERNS_FOUND') },
    NOT_ENOUGH_INFORMATION:  { bg: isDark ? 'bg-zinc-700/60 border-zinc-500'       : 'bg-slate-100 border-slate-300',    txt: isDark ? 'text-zinc-200'    : 'text-slate-800',   icon: '🤔', label: t('qc_verdict_NOT_ENOUGH_INFORMATION') },
  }[results?.verdict] ?? { bg: c.warning, txt: c.warningTxt, icon: '📋', label: results?.verdict } : null;

  // The title row, shared by both phases. It used to live only inside
  // renderInput, which unmounts the moment a result exists — so with the
  // output on screen there was no way to start over at all.
  const renderHeaderRow = () => (
    <div className="pb-3 border-b border-zinc-500">
      <div className="flex items-start justify-between gap-3">
        <div>
          {/* PF-30 — the wrapper already prints the name as the page <h1>. */}
          <p className={`text-base ${c.textSecondary}`}>
            <span className="me-2 text-lg">{tool?.icon ?? '🧾'}</span>{t('qc_tagline')}
          </p>
          {!results && (
            <button onClick={loadExample} disabled={loading} style={{ backgroundColor: (tool?.headerColor ?? '#888888') + '80' }} className="mt-2 px-4 py-2 rounded-full text-sm font-semibold border border-black/25 text-zinc-900 shadow-sm hover:brightness-105 hover:shadow transition disabled:opacity-40 whitespace-nowrap">✨ {t('try_example')}</button>
          )}
        </div>
        {/* PF-16: the tool's one reset, on the title row, from the first keystroke. */}
        {(hasInput) ? (
          <button onClick={handleReset} className={`${c.btnSecondary} px-3 py-1.5 rounded-lg text-xs font-semibold flex-shrink-0 whitespace-nowrap`}>
            ↺ {t('qc_new_quote')}
          </button>
        ) : null}
      </div>
    </div>
  );

  const renderInput = () => (
    <div className={`${c.card} border ${c.border} rounded-xl shadow-sm px-5 pt-2.5 pb-5 space-y-4`}>
      {renderHeaderRow()}

      {/* Repair type */}
      <div>
        <label className={`block text-sm font-medium ${c.labelText} mb-2`}>{t('qc_type_label')}</label>
        <div className="flex flex-wrap gap-2">
          {REPAIR_TYPES.map(rt => (
            <button key={rt.id} onClick={() => setRepairType(rt.id)}
              className={`px-3 py-1.5 rounded-lg border text-xs font-medium transition-colors ${repairType === rt.id ? c.pillActive : c.pillInactive}`}>
              <span className="me-1">{rt.icon}</span>{rt.label}
            </button>
          ))}
        </div>
      </div>

      {/* Item */}
      <div>
        <label className={`block text-sm font-medium ${c.labelText} mb-1`}>
          {t('qc_item_label')} <span className={c.required}>*</span>
        </label>
        <p className={`text-xs ${c.textMuted} mb-1.5`}>{t('qc_item_hint')}</p>
        <input type="text" value={itemDescription} onChange={e => setItemDescription(e.target.value)}
          placeholder={t('qc_item_ph')}
          className={`w-full px-3 py-2 border rounded-xl text-sm focus:outline-none focus:ring-2 ${c.input}`}
        />
      </div>

      {/* What's wrong */}
      <div>
        <label className={`block text-sm font-medium ${c.labelText} mb-1`}>
          {t('qc_wrong_label')} <span className={c.required}>*</span>
        </label>
        <textarea value={whatWentWrong} onChange={e => setWhatWentWrong(e.target.value)}
          placeholder={t('qc_wrong_ph')} rows={2}
          className={`w-full px-3 py-2.5 border rounded-xl text-sm resize-y focus:outline-none focus:ring-2 ${c.input}`}
        />
      </div>

      {/* What they told you */}
      <div>
        <label className={`block text-sm font-medium ${c.labelText} mb-1`}>
          {t('qc_told_label')} <span className={`text-xs font-normal ${c.textMuted}`}>{t('qc_told_hint')}</span>
        </label>
        <textarea value={whatTheyToldYou} onChange={e => setWhatTheyToldYou(e.target.value)}
          placeholder={t('qc_told_ph')} rows={2}
          className={`w-full px-3 py-2.5 border rounded-xl text-sm resize-y focus:outline-none focus:ring-2 ${c.input}`}
        />
      </div>

      {/* Quoted price */}
      <div>
        <label className={`block text-sm font-medium ${c.labelText} mb-1`}>
          {t('qc_price_label')} <span className={c.required}>*</span>
        </label>
        <div className="flex items-center gap-1">
          <span className={`text-sm font-bold ${c.textMuteded}`}>{sym}</span>
          <input type="number" value={quotedPrice} onChange={e => setQuotedPrice(e.target.value)}
            placeholder="0.00"
            className={`flex-1 px-3 py-2.5 border rounded-lg text-sm ${c.input} outline-none focus:ring-2`}
          />
        </div>
      </div>

      {/* What the quote includes */}
      <div>
        <label className={`block text-sm font-medium ${c.labelText} mb-1`}>
          {t('qc_breakdown_label')} <span className={`text-xs font-normal ${c.textMuted}`}>{t('qc_breakdown_hint')}</span>
        </label>
        <p className={`text-xs ${c.textMuted} mb-1.5`}>{t('qc_breakdown_sub')}</p>
        <textarea value={quotedBreakdown} onChange={e => setQuotedBreakdown(e.target.value)}
          placeholder={t('qc_breakdown_ph', { sym })} rows={2}
          className={`w-full px-3 py-2.5 border rounded-xl text-sm resize-y focus:outline-none focus:ring-2 ${c.input}`}
        />
      </div>

      {/* Upload the actual quote — optional supplementary evidence */}
      <div>
        <label className={`block text-sm font-medium ${c.labelText} mb-1`}>
          {t('qc_upload_label')} <span className={`text-xs font-normal ${c.textMuted}`}>{t('qc_upload_hint')}</span>
        </label>
        {!uploadedFile ? (
          <div onClick={() => fileInputRef.current?.click()}
            className={`border-2 border-dashed rounded-xl p-4 text-center cursor-pointer transition-all ${isDark ? 'border-zinc-600 hover:border-cyan-500 hover:bg-zinc-700/50' : 'border-gray-300 hover:border-cyan-400 hover:bg-cyan-50'}`}>
            <span className="text-2xl block mb-1">📎</span>
            <p className={`text-sm font-medium ${c.text}`}>{t('qc_upload_cta')}</p>
          </div>
        ) : (
          <div className={`flex items-center justify-between p-3 rounded-xl border ${c.success}`}>
            <div className="flex items-center gap-2">
              <span className="text-xl">{uploadedFile.type === 'application/pdf' ? '📄' : '🖼️'}</span>
              <div>
                <p className={`text-sm font-semibold ${c.text}`}>{uploadedFile.name}</p>
                <p className={`text-xs ${c.textMuted}`}>{(uploadedFile.size / 1024).toFixed(1)} {t('qc_kb')}</p>
              </div>
            </div>
            <button onClick={removeFile} className={`text-sm ${c.textMuted}`}>✕</button>
          </div>
        )}
        <input ref={fileInputRef} type="file" accept="image/jpeg,image/png,application/pdf" onChange={handleFileUpload} className="hidden" />
      </div>

      {/* Second quote */}
      <div className={`pt-3 border-t ${c.border} space-y-3`}>
        <div>
          <label className={`block text-sm font-medium ${c.labelText} mb-1`}>
            {t('qc_second_label')} <span className={`text-xs font-normal ${c.textMuted}`}>{t('qc_second_hint')}</span>
          </label>
          <div className="flex items-center gap-1">
            <span className={`text-sm font-bold ${c.textMuteded}`}>{sym}</span>
            <input type="number" value={secondQuotePrice} onChange={e => setSecondQuotePrice(e.target.value)}
              placeholder="0.00"
              className={`flex-1 px-3 py-2 border rounded-lg text-sm ${c.input} outline-none focus:ring-2`}
            />
          </div>
        </div>
        {secondQuotePrice !== '' && (
          <div>
            <label className={`block text-sm font-medium ${c.labelText} mb-1`}>
              {t('qc_second_breakdown_label')} <span className={`text-xs font-normal ${c.textMuted}`}>{t('qc_breakdown_hint')}</span>
            </label>
            <p className={`text-xs ${c.textMuted} mb-1.5`}>{t('qc_second_breakdown_sub')}</p>
            <textarea value={secondQuoteBreakdown} onChange={e => setSecondQuoteBreakdown(e.target.value)}
              placeholder={t('qc_second_breakdown_ph')} rows={2}
              className={`w-full px-3 py-2.5 border rounded-xl text-sm resize-y focus:outline-none focus:ring-2 ${c.input}`}
            />
          </div>
        )}
      </div>

      {/* Item age */}
      <div>
        <label className={`block text-sm font-medium ${c.labelText} mb-1`}>
          {t('qc_age_label')} <span className={`text-xs font-normal ${c.textMuted}`}>{t('qc_age_hint')}</span>
        </label>
        <input type="text" value={itemAge} onChange={e => setItemAge(e.target.value)}
          placeholder={t('qc_age_ph')}
          className={`w-full px-3 py-2 border rounded-xl text-sm focus:outline-none focus:ring-2 ${c.input}`}
        />
      </div>

      {error && <p className={`text-sm ${c.danger} border rounded-lg px-3 py-2`}>{error}</p>}

      <p className={`text-xs ${c.textMuted}`}>
        🔗 <a href="/LeverageLogic" className={linkStyle}>⚖️ {t('qc_leverage')}</a> <a href="/ContractDecoder" className={linkStyle}>📋 {t('qc_contract')}</a>
      </p>

      <button title={t('cmd_enter')} onClick={handleCheck} disabled={!canSubmit || loading}
        className={`relative w-full ${(!canSubmit) ? c.btnIdle : c.btnPrimary} font-bold py-3 rounded-lg flex items-center justify-center gap-2 min-h-[48px]`}>
        {loading
          ? <><span className="inline-block animate-spin">{tool?.icon ?? '🧾'}</span> {t('qc_analyzing')}</>
          : <><span className="me-1">{tool?.icon ?? '🧾'}</span> {t('qc_check_it')}</>}
      {!loading && (
        <kbd aria-hidden="true"
          className="hidden sm:flex items-center absolute end-3 top-1/2 -translate-y-1/2 px-1.5 py-0.5 rounded border border-white/30 bg-white/15 text-[10px] font-bold tracking-wide">
          ⌘↵
        </kbd>
      )}
      </button>

      {sessionHistory.length > 0 && (
        <div className={`${c.cardAlt} border ${c.border} rounded-xl p-4`}>
          <div className="flex items-center justify-between mb-3">
            <p className={`text-xs font-bold ${c.textMuted} uppercase tracking-wide`}>🕓 {t('qc_recent')}</p>
            <button onClick={() => setSessionHistory([])} className={`text-xs ${c.textMuted}`}>{t('qc_clear')}</button>
          </div>
          <ul className="space-y-2">
            {sessionHistory.map((h) => {
              const vIcon = { LOOKS_STRAIGHTFORWARD: '✅', NEEDS_CLARIFICATION: '❓', HARD_TO_COMPARE: '⚖️', SPECIFIC_CONCERNS_FOUND: '🚩', NOT_ENOUGH_INFORMATION: '🤔' }[h.verdict] || '🤔';
              const vColor = h.verdict === 'SPECIFIC_CONCERNS_FOUND'
                ? (isDark ? 'text-red-400' : 'text-red-600')
                : h.verdict === 'LOOKS_STRAIGHTFORWARD'
                  ? (isDark ? 'text-emerald-400' : 'text-emerald-600')
                  : h.verdict === 'NEEDS_CLARIFICATION'
                    ? (isDark ? 'text-amber-400' : 'text-amber-600')
                    : c.textMuted;
              return (
                <li key={h.id} className={`text-xs ${c.textSecondary} rounded-lg ${c.inset} p-2.5`}>
                  <div className="flex items-start gap-2">
                    <span className="flex-shrink-0">{vIcon}</span>
                    <div className="flex-1 min-w-0">
                      <span className={`font-bold ${vColor}`}>{VERDICTS.includes(h.verdict) ? t(`qc_verdict_${h.verdict}`) : h.verdict?.replace(/_/g, ' ')}</span>
                      <span className={`block ${c.textMuted} mt-0.5`}>{h.preview}</span>
                    </div>
                  </div>
                  <div className="flex gap-3 mt-1.5 ms-6">
                    <button onClick={() => viewFrom(h)} className={`text-[11px] font-semibold ${c.accentTxt}`}>👁️ {t('qc_view')}</button>
                    <button onClick={() => recheckFrom(h)} className={`text-[11px] font-semibold ${c.accentTxt}`}>↻ {t('qc_recheck')}</button>
                  </div>
                </li>
              );
            })}
          </ul>
        </div>
      )}
    </div>
  );

  const renderResults = () => {
    if (!results || !verdictConfig) return null;
    const qs = results?.quote_summary;
    const arith = results?.arithmetic_check;
    const sq = results?.second_quote;
    const rvr = results?.repair_vs_replace;
    return (
      <div className="scroll-mt-24 space-y-4" ref={resultsRef}>

        {/* Recap of what the user told us — anchors persisted results on revisits */}
        {results?._input && (
          <div className={`${c.cardAlt} border ${c.border} rounded-xl p-4`}>
            <p className={`text-xs font-semibold uppercase tracking-wide mb-1.5 ${c.textMuted}`}>📝 {t('qc_your_situation')}</p>
            <p className={`text-sm ${c.textSecondary}`}>{results._input.itemDescription}{results._input.quotedPrice !== '' && results._input.quotedPrice != null ? ` — ${sym}${results._input.quotedPrice}` : ''}</p>
            {results._input.whatWentWrong && <p className={`text-xs mt-1.5 ${c.textMuted}`}>{results._input.whatWentWrong}</p>}
          </div>
        )}

        {/* Overall verdict */}
        <div className={`border-2 rounded-xl p-5 ${verdictConfig?.bg}`}>
          <div className="flex items-start gap-3">
            <span className="text-3xl">{verdictConfig?.icon}</span>
            <div>
              <p className={`text-xl font-black ${verdictConfig?.txt}`}>{verdictConfig?.label}</p>
              {results?.verdict_explanation && (
                <p className={`text-sm mt-2 ${verdictConfig?.txt}`}>{results.verdict_explanation}</p>
              )}
            </div>
          </div>
        </div>

        {/* Safety note — surfaced right after the verdict, when it applies */}
        {results?.safety_note && (
          <div className={`${c.danger} border rounded-xl p-4`}>
            <p className="text-xs font-bold uppercase tracking-wide mb-1.5">⚠️ {t('qc_safety_heading')}</p>
            <p className="text-sm">{results.safety_note}</p>
          </div>
        )}

        {/* What the quote includes */}
        {qs && (
          <div className={`${c.card} border ${c.border} rounded-xl p-4`}>
            <p className={`text-xs font-bold ${c.textMuted} uppercase tracking-wide mb-3`}>📋 {t('qc_summary_heading')}</p>
            <div className="space-y-1.5">
              {qs.stated_diagnosis && <p className={`text-sm ${c.textSecondary}`}><span className="font-semibold">{t('qc_summary_diagnosis')}:</span> {qs.stated_diagnosis}</p>}
              {qs.proposed_work && <p className={`text-sm ${c.textSecondary}`}><span className="font-semibold">{t('qc_summary_work')}:</span> {qs.proposed_work}</p>}
              {qs.parts?.length > 0 && <p className={`text-sm ${c.textSecondary}`}><span className="font-semibold">{t('qc_summary_parts')}:</span> {qs.parts.join(', ')}</p>}
              {qs.labor && <p className={`text-sm ${c.textSecondary}`}><span className="font-semibold">{t('qc_summary_labor')}:</span> {qs.labor}</p>}
              {qs.fees?.length > 0 && <p className={`text-sm ${c.textSecondary}`}><span className="font-semibold">{t('qc_summary_fees')}:</span> {qs.fees.join(', ')}</p>}
              {qs.warranty && <p className={`text-sm ${c.textSecondary}`}><span className="font-semibold">{t('qc_summary_warranty')}:</span> {qs.warranty}</p>}
              {qs.quoted_total != null && <p className={`text-sm ${c.textSecondary}`}><span className="font-semibold">{t('qc_summary_total')}:</span> {sym}{qs.quoted_total}</p>}
              {qs.itemization_level && (
                <p className={`text-xs ${c.textMuted} pt-1`}>{t('qc_itemization_level')}: {t(`qc_itemization_${qs.itemization_level}`) || qs.itemization_level}</p>
              )}
            </div>
          </div>
        )}

        {/* Document check — only when the upload and the typed answers disagree */}
        {results?.document_discrepancies?.length > 0 && (
          <div className={`${c.warning} border rounded-xl p-4`}>
            <p className="text-xs font-bold uppercase tracking-wide mb-2">📎 {t('qc_document_check_heading')}</p>
            <ul className="space-y-1.5">
              {results.document_discrepancies.map((d, i) => (
                <li key={i} className="text-sm">
                  <span className={c.textMuted}>{t('qc_you_said')}</span> {d?.user_said} <span className={c.textMuted}>{t('qc_document_says')}</span> {d?.document_says}
                </li>
              ))}
            </ul>
          </div>
        )}

        {/* Does the math work? — only when there was enough to actually check */}
        {arith?.possible && (
          <div className={`${c.card} border ${c.border} rounded-xl p-4`}>
            <p className={`text-xs font-bold ${c.textMuted} uppercase tracking-wide mb-2`}>🧮 {t('qc_arithmetic_heading')}</p>
            <p className={`text-sm ${c.textSecondary}`}>
              {t('qc_calculated')} {sym}{arith.calculated_total} — {t('qc_quoted')} {sym}{arith.quoted_total}
              {arith.difference ? ` (${arith.difference > 0 ? '+' : ''}${sym}${arith.difference})` : ''}
            </p>
            {arith.assessment && <p className={`text-sm mt-1 ${c.textSecondary}`}>{arith.assessment}</p>}
          </div>
        )}

        {/* Specific concerns */}
        <div className={`${c.card} border ${c.border} rounded-xl p-4`}>
          <p className={`text-xs font-bold ${c.textMuted} uppercase tracking-wide mb-3`}>🚩 {t('qc_concerns_heading')}</p>
          {results?.specific_concerns?.length > 0 ? (
            <ul className="space-y-2">
              {results.specific_concerns.map((f, i) => (
                <li key={i} className={`text-sm ${c.danger} border rounded-lg px-3 py-2`}>
                  <span className="font-semibold">{f?.concern}</span>
                  {f?.why_it_matters && <span className="block text-xs mt-0.5 opacity-80">{f.why_it_matters}</span>}
                </li>
              ))}
            </ul>
          ) : (
            <div>
              <p className={`text-sm ${c.success} border rounded-lg px-3 py-2`}>{t('qc_concerns_none')}</p>
              <p className={`text-xs ${c.textMuted} mt-1.5 px-1`}>{t('qc_concerns_none_caveat')}</p>
            </div>
          )}
        </div>

        {/* What the quote doesn't tell you */}
        {results?.unknowns_that_matter?.length > 0 && (
          <div className={`${c.card} border ${c.border} rounded-xl p-4`}>
            <p className={`text-xs font-bold ${c.textMuted} uppercase tracking-wide mb-3`}>❓ {t('qc_unknowns_heading')}</p>
            <ul className="space-y-1.5">
              {results.unknowns_that_matter.map((u, i) => (
                <li key={i} className={`text-sm ${c.textSecondary}`}>• {u}</li>
              ))}
            </ul>
          </div>
        )}

        {/* Second quote */}
        {sq?.provided && (
          <div className={`${c.card} border ${c.border} rounded-xl p-4`}>
            <p className={`text-xs font-bold ${c.textMuted} uppercase tracking-wide mb-3`}>🔄 {t('qc_second_quote_heading')}</p>
            {sq.price_difference != null && (
              <p className={`text-sm font-semibold ${c.textSecondary}`}>{sym}{results._input?.quotedPrice} {t('qc_vs')} {sym}{results._input?.secondQuotePrice} = {sym}{Math.abs(sq.price_difference)} {t('qc_difference')}</p>
            )}
            <p className={`text-xs mt-1.5 ${c.textMuted}`}>{t('qc_scope_comparable')}: {t(`qc_scope_${sq.scope_comparable}`) || sq.scope_comparable}</p>
            {sq.assessment && <p className={`text-sm mt-1.5 ${c.textSecondary}`}>{sq.assessment}</p>}
          </div>
        )}

        {/* Repair or replace */}
        {rvr?.applies && (
          <div className={`${c.card} border ${c.border} rounded-xl p-4`}>
            <p className={`text-xs font-bold ${c.textMuted} uppercase tracking-wide mb-3`}>♻️ {t('qc_replace_heading')}</p>
            {rvr.assessment && <p className={`text-sm ${c.textSecondary}`}>{rvr.assessment}</p>}
            {rvr.missing_information?.length > 0 && (
              <ul className="mt-2 space-y-1">
                {rvr.missing_information.map((m, i) => (
                  <li key={i} className={`text-xs ${c.textMuted}`}>• {m}</li>
                ))}
              </ul>
            )}
          </div>
        )}

        {/* Questions to ask */}
        {results?.questions_to_ask?.length > 0 && (
          <div className={`${c.card} border ${c.border} rounded-xl p-4`}>
            <p className={`text-xs font-bold ${c.textMuted} uppercase tracking-wide mb-3`}>❓ {t('qc_questions_heading')}</p>
            <ul className="space-y-2">
              {results.questions_to_ask.map((q, i) => (
                <li key={i} className={`text-sm ${c.textSecondary}`}>
                  <span className={`font-bold ${c.accentTxt}`}>{i + 1}.</span> {q}
                </li>
              ))}
            </ul>
          </div>
        )}

        {/* What to say */}
        {results?.what_to_say && (
          <div className={`${c.infoBox} border rounded-xl p-4`}>
            <p className="text-xs font-bold uppercase tracking-wide mb-2">💬 {t('qc_script_heading')}</p>
            <p className="text-sm">{results.what_to_say}</p>
          </div>
        )}

        {/* Second opinion */}
        {results?.second_opinion && (
          <div className={`${c.card} border ${c.border} rounded-xl p-4`}>
            <p className={`text-xs font-bold ${c.textMuted} uppercase tracking-wide mb-3`}>🙋 {t('qc_second_opinion_heading')}</p>
            <p className={`text-sm ${c.textSecondary}`}>
              {t(`qc_second_opinion_${results.second_opinion.assessment}`) || results.second_opinion.assessment}
              {results.second_opinion.reason && ` — ${results.second_opinion.reason}`}
            </p>
          </div>
        )}

        <p className={`text-xs ${c.textMuted} px-1`}>{t('qc_disclaimer')}</p>

        {/* Post-result cross-refs */}
        <div className={`${c.cardAlt} border ${c.border} rounded-xl p-4`}>
          <p className={`text-[10px] font-bold ${c.textMuted} uppercase mb-2`}>🔗 {t('qc_related')}</p>
          <div className="flex flex-wrap gap-3">
            <a href="/LeverageLogic" className={`text-xs ${linkStyle}`}>⚖️ {t('qc_leverage')}</a>
            <a href="/ContractDecoder" className={`text-xs ${linkStyle}`}>📋 {t('qc_contract')}</a>
            <a href="/ScamRadar" className={`text-xs ${linkStyle}`}>🎣 {t('qc_scam')}</a>
          </div>
        </div>
      </div>
    );
  };

  // Any sign the user has begun — drives the PF-16 reset on the title row.
  const hasInput = !!(results || fileBase64 || uploadedFile || itemAge.trim() || itemDescription.trim() || quotedBreakdown.trim() || quotedPrice.trim() || secondQuotePrice.trim() || secondQuoteBreakdown.trim() || whatTheyToldYou.trim() || whatWentWrong.trim());

  return (
    <div className={`space-y-4 ${c.text}`}>
      {!results && <p className={`text-xs ${c.textMuted} px-1`}>🔗 <a href="/LeverageLogic" className={linkStyle}>⚖️ {t('qc_leverage')}</a></p>}
      {!results && renderInput()}
      {results ? (
        <div className={`${c.card} border ${c.border} rounded-xl shadow-sm px-5 pt-2.5 pb-5`}>
          {renderHeaderRow()}
        </div>
      ) : null}
      {results && renderResults()}
    </div>
  );
}

QuoteCheck.displayName = 'QuoteCheck';
export default QuoteCheck;
