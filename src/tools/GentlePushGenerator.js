const GentlePushGenerator = ({ tool }) => {
  const { callToolEndpoint, loading, userLocale, userCurrency, userRegion } = useClaudeAPI();
  const { isDark } = useTheme();
  const { t } = useTranslation();

  const c = {
    card: isDark ? 'bg-zinc-800' : 'bg-white',
    cardAlt: isDark ? 'bg-zinc-700/50' : 'bg-slate-50',
    text: isDark ? 'text-zinc-50' : 'text-gray-900',
    textSecondary: isDark ? 'text-zinc-300' : 'text-gray-600',
    textMuted: isDark ? 'text-zinc-400' : 'text-gray-500',
    input: isDark
      ? 'bg-zinc-900 border-zinc-600 text-zinc-100 placeholder-zinc-400 focus:border-cyan-500 focus:ring-cyan-500/20'
      : 'bg-white border-gray-300 text-gray-900 placeholder-gray-400 focus:border-cyan-500 focus:ring-cyan-100',
    btnPrimary: isDark ? 'bg-cyan-600 hover:bg-cyan-500 text-white' : 'bg-cyan-600 hover:bg-cyan-700 text-white',
    btnIdle: isDark
      ? '!bg-transparent !border-2 !border-cyan-500/85 !text-cyan-300 cursor-not-allowed'
      : '!bg-transparent !border-2 !border-cyan-600/85 !text-cyan-800 cursor-not-allowed',
    border: isDark ? 'border-zinc-700' : 'border-gray-200',
    tag: isDark ? 'bg-zinc-700 text-zinc-200' : 'bg-gray-100 text-gray-700',
    tagActive: isDark ? 'bg-emerald-600 text-white' : 'bg-emerald-500 text-white',
    heroCard: isDark
      ? 'bg-gradient-to-br from-emerald-900/60 to-cyan-900/60 border-emerald-600'
      : 'bg-gradient-to-br from-emerald-100 to-cyan-100 border-emerald-300',
    heroText: isDark ? 'text-emerald-200' : 'text-emerald-900',
    success: isDark ? 'bg-emerald-900/40 border-emerald-700 text-emerald-300' : 'bg-emerald-50 border-emerald-200 text-emerald-800',
    warning: isDark ? 'bg-amber-900/40 border-amber-700 text-amber-300' : 'bg-amber-50 border-amber-200 text-amber-800',
    danger: isDark ? 'bg-red-900/30 border-red-700 text-red-300' : 'bg-red-50 border-red-200 text-red-800',
    btnSecondary: isDark ? 'bg-zinc-700 hover:bg-zinc-600 text-zinc-200' : 'bg-gray-100 hover:bg-gray-200 text-gray-700',
    labelText: isDark ? 'text-zinc-200' : 'text-gray-700',
    required: isDark ? 'text-amber-400' : 'text-amber-700',
  };
  c.textMuteded = c.textMuted;
  c.label = c.labelText;

  const linkStyle = isDark
    ? 'text-cyan-400 hover:text-cyan-300 underline underline-offset-2'
    : 'text-cyan-700 hover:text-cyan-800 underline underline-offset-2';

  const [view, setView] = useState('setup'); // setup | pick | active | log | reflection
  const [error, setError] = useState('');

  const [domain, setDomain] = useState('');
  const [comfortZone, setComfortZone] = useState('');
  const [growthArea, setGrowthArea] = useState('');
  const [capacity, setCapacity] = useState('medium');

  const [pushOptions, setPushOptions] = useState([]);
  const [acknowledgment, setAcknowledgment] = useState('');
  const [ifYouDont, setIfYouDont] = useState('');
  const [patternNote, setPatternNote] = useState('');
  const [activePush, setActivePush] = useState(null);

  const [showFeedback, setShowFeedback] = useState(false);
  const [feedbackType, setFeedbackType] = useState('');
  const [feedbackCustom, setFeedbackCustom] = useState('');

  const [attempted, setAttempted] = useState(null);
  const [scariness, setScariness] = useState(0);
  const [whatHappened, setWhatHappened] = useState('');
  const [reflectionData, setReflectionData] = useState(null);

  const [pushLog, setPushLog] = usePersistentState('gpg-push-log', []);
  const [pushDay, setPushDay] = usePersistentState('gpg-push-day', '');

  // Is today the day they picked? The calendar file is what reaches them when
  // the tab is closed; this is what greets them when it is open.
  const isPushDayToday = !!pushDay && PUSH_DAYS[(new Date().getDay() + 6) % 7]?.value === pushDay;

  const downloadReminder = () => {
    const ics = buildIcs({
      day: pushDay,
      title: t('gpg_ics_title'),
      note: t('gpg_ics_note'),
    });
    if (!ics) return;
    // A data: URI rather than a blob: URL. Safari — and iOS in particular —
    // frequently ignores the download attribute on a blob, so the click does
    // nothing visible and the visitor concludes the feature is broken. A data
    // URI with the calendar MIME type is handled in more places, and on iOS it
    // hands off to the calendar rather than silently failing.
    const a = document.createElement('a');
    a.href = `data:text/calendar;charset=utf-8,${encodeURIComponent(ics)}`;
    a.download = 'deftbrain-gentle-push.ics';
    a.rel = 'noopener';
    document.body.appendChild(a);
    a.click();
    a.remove();
  };

  const resultsRef = React.useRef(null);
  // The rule that places cross-refs keys off a `results` sentinel; this tool's
  // outcome is the reflection it writes after an attempt.
  const results = reflectionData;

  const loadExample = () => {
    const ex = pickExample('GentlePushGenerator', EXAMPLES);
    setDomain(ex.domain);
    setComfortZone(t(ex.comfortZoneKey));
    setGrowthArea(t(ex.growthAreaKey));
    setCapacity(ex.capacity);
  };

  // Anything the visitor has put in counts, so the button appears as soon as
  // there is something to clear. pushDay is deliberately excluded: it is a
  // saved preference that survives sessions, and their calendar day should not
  // disappear because they started a different push.
  const hasInput = !!(domain || comfortZone.trim() || growthArea.trim() || capacity !== 'medium');

  const handleReset = () => {
    // Start over means the form too. Without this the button was live on the
    // setup screen and changed nothing a visitor could see.
    setDomain('');
    setComfortZone('');
    setGrowthArea('');
    setCapacity('medium');
    setPushOptions([]);
    setAcknowledgment('');
    setIfYouDont('');
    setPatternNote('');
    setActivePush(null);
    setShowFeedback(false);
    setFeedbackType('');
    setFeedbackCustom('');
    setAttempted(null);
    setScariness(0);
    setWhatHappened('');
    setReflectionData(null);
    setError('');
    setView('setup');
  };

  const renderHeader = (showReset = true) => (
    <div className={`${c.card} border ${c.border} rounded-xl shadow-sm px-5 pt-2.5 pb-5`}>
      <div className="flex items-center justify-between gap-3">
        <p className={`text-base ${c.textSecondary}`}>
          <span className="me-2 text-lg">{tool?.icon ?? '🫸'}</span>{t('gpg_tagline')}
        </p>
        {showReset && (
          <button onClick={handleReset} className={`text-xs px-3 py-2 rounded-lg border ${c.border} ${c.text}`}>
            {t('gpg_start_over')}
          </button>
        )}
      </div>
      {view === 'setup' && (
        <button onClick={loadExample} disabled={loading}
          style={{ backgroundColor: (tool?.headerColor ?? '#888888') + '80' }}
          className="mt-2 px-4 py-2 rounded-full text-sm font-semibold border border-black/25 text-zinc-900 shadow-sm hover:brightness-105 hover:shadow transition disabled:opacity-40 whitespace-nowrap">
          ✨ {t('try_example')}
        </button>
      )}
    </div>
  );

  const renderRelatedTools = () => (
    <div className={`${c.cardAlt} border ${c.border} rounded-xl p-4`}>
      <p className={`text-[10px] font-bold ${c.textMuted} uppercase mb-2`}>{t('gpg_related_tools')}</p>
      <div className="flex flex-wrap gap-3">
        <a href="/DifficultTalkCoach" className={`text-xs ${linkStyle}`}>{t('gpg_xref_difficult_talk')}</a>
        <a href="/BeforeTheCrash" className={`text-xs ${linkStyle}`}>{t('gpg_xref_crash_predictor')}</a>
      </div>
    </div>
  );

  const renderPostResultRef = () => (
    <p className={`text-center text-xs ${c.textMuted}`}>
      {t('gpg_xref_pre_prefix')}<a href="/DifficultTalkCoach" className={linkStyle}>{t('gpg_xref_difficult_talk')}</a>{t('gpg_xref_pre_suffix')}
    </p>
  );

  // The reflection is this tool's result screen. Naming it renderResults is
  // also what lets the cross-ref rule find where the result begins: the
  // component returns one screen per view, so there is no inline
  // {results && (...)} anywhere for it to split on.
  const renderResults = () => (
    
      <div ref={resultsRef} className={`scroll-mt-24 space-y-4 ${c.text}`}>
        {renderHeader()}

        {reflectionData.celebration ? (
          <div className={`${c.heroCard} border-2 rounded-2xl p-6 text-center shadow-sm`}>
            <p className={`text-base font-medium ${c.heroText}`}>{reflectionData.celebration}</p>
          </div>
        ) : (
          <div className={`${c.card} ${c.border} border rounded-2xl p-6 text-center`}>
            <p className={`text-sm font-medium ${c.text}`}>{t('gpg_choosing_not_info')}</p>
          </div>
        )}

        {reflectionData.reflection && (
          <div className={`${c.card} ${c.border} border rounded-xl p-5`}>
            <p className={`text-[10px] font-bold uppercase ${c.textMuted} mb-2`}>{t('gpg_reflection_label')}</p>
            <p className={`text-sm ${c.text} leading-relaxed`}>{reflectionData.reflection}</p>
          </div>
        )}

        {reflectionData.growth_insight && (
          <div className={`${c.cardAlt} border ${c.border} rounded-xl p-4`}>
            <p className={`text-[10px] font-bold uppercase ${c.textMuted} mb-1`}>{t('gpg_growth_insight_label')}</p>
            <p className={`text-sm ${c.textSecondary}`}>{reflectionData.growth_insight}</p>
          </div>
        )}

        {reflectionData.scariness_note && (
          <div className={`${c.card} ${c.border} border rounded-xl p-4`}>
            <p className={`text-[10px] font-bold uppercase ${c.textMuted} mb-1`}>{t('gpg_calibration_label')}</p>
            <p className={`text-sm ${c.textSecondary}`}>{reflectionData.scariness_note}</p>
          </div>
        )}

        {reflectionData.next_suggestion && (
          <div className={`${c.warning} border rounded-xl p-4`}>
            <p className={`text-[10px] font-bold uppercase mb-1`}>{t('gpg_next_time_label')}</p>
            <p className="text-sm">{reflectionData.next_suggestion}</p>
          </div>
        )}

        {renderRelatedTools()}
        {renderPostResultRef()}
      </div>
  );


  // Refs, not deps: the listener attaches once and never sees a stale closure.
  const submitRef = useRef(null);
  const canSubmitRef = useRef(false);
  useEffect(() => {
    const handler = (e) => {
      if (e.key === 'Enter' && (e.metaKey || e.ctrlKey) && canSubmitRef.current) submitRef.current?.();
    };
    document.addEventListener('keydown', handler);
    return () => document.removeEventListener('keydown', handler);
  }, []);

  const handleGenerate = async () => {
    if (!growthArea.trim()) {
      setError(t('gpg_err_where_grow'));
      return;
    }
    setError('');
    setPushOptions([]);
    try {
      const data = await callToolEndpoint('gentle-push-generator', {
        action: 'generate',
        userLocale,
        userCurrency,
        userRegion,
        domain: domain || null,
        comfortZone: comfortZone.trim() || null,
        growthArea: growthArea.trim(),
        currentCapacity: capacity,
        pushHistory: pushLog.slice(0, 6),
      });
      setPushOptions(data.pushes || []);
      setAcknowledgment(data.acknowledgment || '');
      setIfYouDont(data.if_you_dont || '');
      setPatternNote(data.pattern_note || '');
      setView('pick');
    } catch (err) {
      setError(err.message || t('gpg_err_generate'));
    }
  };

  const handleRegenerate = async () => {
    const feedback = feedbackCustom.trim() || feedbackType;
    if (!feedback) {
      setError(t('gpg_err_what_different'));
      return;
    }
    setError('');
    try {
      const data = await callToolEndpoint('gentle-push-generator', {
        action: 'regenerate',
        userLocale,
        userCurrency,
        userRegion,
        previousPush: pushOptions?.[0]?.challenge || '',
        feedback,
        domain: domain || null,
        comfortZone: comfortZone.trim() || null,
        growthArea: growthArea.trim(),
        currentCapacity: capacity,
      });
      if (data.push) setPushOptions(prev => [data.push, ...prev].slice(0, 3));
      if (data.response_to_feedback) setAcknowledgment(data.response_to_feedback);
      setShowFeedback(false);
      setFeedbackType('');
      setFeedbackCustom('');
    } catch (err) {
      setError(err.message || t('gpg_err_regenerate'));
    }
  };

  const selectPush = (push) => {
    setActivePush(push);
    setAttempted(null);
    setScariness(0);
    setWhatHappened('');
    setView('active');
  };

  const startLog = didAttempt => {
    setAttempted(didAttempt);
    setView('log');
  };

  const handleReflect = async () => {
    if (!activePush?.challenge) return;
    setError('');
    try {
      const data = await callToolEndpoint('gentle-push-generator', {
        action: 'reflect',
        userLocale,
        userCurrency,
        userRegion,
        push: activePush.challenge,
        attempted,
        scariness: scariness || null,
        whatHappened: whatHappened.trim() || null,
      });
      setReflectionData(data);
      const entry = {
        id: Date.now(),
        preview: String(activePush.challenge || '').slice(0, 40),
        domain: domain || null,
        growthArea,
        challenge: activePush.challenge,
        approach: activePush.approach || null,
        label: activePush.label || null,
        attempted: !!attempted,
        scariness: scariness || null,
        outcome: whatHappened.trim() || null,
        capacity,
        date: new Date().toISOString(),
      };
      setPushLog(prev => [entry, ...prev].slice(0, 50));
      setView('reflection');
    } catch (err) {
      setError(err.message || t('gpg_err_reflect'));
    }
  };

  canSubmitRef.current = !loading && (
    (view === 'setup' && !!growthArea.trim()) ||
    (view === 'pick' && (!!feedbackType || !!feedbackCustom.trim()))
  );
  submitRef.current = view === 'setup' ? handleGenerate
    : view === 'pick' ? handleRegenerate
    : null;

  const buildFullText = useCallback(() => {
    if (view === 'pick' && pushOptions.length) {
      return [
        acknowledgment,
        '',
        ...pushOptions.flatMap(p => [
          p.label || '',
          p.challenge || '',
          p.time_frame || '',
          p.why_this_size || '',
          `✅ ${p.what_counts || ''}`,
          '',
        ]),
        BRAND,
      ].filter(Boolean).join('\n');
    }
    if (view === 'active' && activePush) {
      return [activePush.label, activePush.challenge, activePush.time_frame, activePush.why_this_size, `✅ ${activePush.what_counts || ''}`, BRAND]
        .filter(Boolean).join('\n');
    }
    if (view === 'reflection' && results) {
      return [reflectionData.celebration, reflectionData.reflection, reflectionData.growth_insight, reflectionData.scariness_note, reflectionData.next_suggestion, BRAND]
        .filter(Boolean).join('\n\n');
    }
    return '';
  }, [view, pushOptions, acknowledgment, activePush, reflectionData]);

  useRegisterActions(buildFullText(), tool?.title || t('gpg_title'));

  React.useEffect(() => {
    if (!resultsRef.current || view === 'setup') return;
    const timer = setTimeout(() => revealSection(resultsRef.current), 160);
    return () => clearTimeout(timer);
  }, [view]);

  if (view === 'setup') {
    return (
      <div className={`space-y-4 ${c.text}`}>
        {renderHeader(hasInput)}

        <div className={`${c.card} ${c.border} border rounded-xl p-4`}>
          <div className="flex items-center justify-between gap-4">
            <div>
              <p className={`text-xs font-semibold ${c.text}`}>{t('gpg_push_day_title')} <span className={`font-normal ${c.textMuted}`}>{t('gpg_optional')}</span></p>
              <p className={`text-[10px] ${c.textMuted}`}>{t('gpg_push_day_hint')}</p>
            </div>
            <select value={pushDay} onChange={e => setPushDay(e.target.value)} className={`text-xs p-2 rounded-lg border ${c.input}`}>
              <option value="">{t('gpg_push_day_off')}</option>
              {PUSH_DAYS.map(d => <option key={d.value} value={d.value}>{t(d.labelKey)}</option>)}
            </select>
          </div>
          {pushDay && (
            <div className={`mt-3 pt-3 border-t ${c.border}`}>
              <button onClick={downloadReminder} className={`text-xs font-semibold ${linkStyle}`}>
                📅 {t('gpg_add_to_calendar')}
              </button>
              <p className={`text-[10px] mt-1 ${c.textMuted}`}>{t('gpg_add_to_calendar_hint')}</p>
            </div>
          )}
        </div>

        {/* The day they chose, used. Nothing here can bring them back — that is
            the calendar's job — but if they are here on the day, say so. */}
        {isPushDayToday && (
          <div className={`${c.success} border rounded-xl p-3`}>
            <p className="text-xs font-semibold">{t('gpg_push_day_today', { day: t(PUSH_DAYS.find(d => d.value === pushDay).labelKey) })}</p>
          </div>
        )}

        <div className={`${c.card} ${c.border} border rounded-xl p-5 space-y-3`}>
          <label className={`block text-sm font-semibold ${c.text}`}>
            {t('gpg_which_area')} <span className={`font-normal ${c.textMuted}`}>{t('gpg_optional')}</span>
          </label>
          <div className="grid grid-cols-3 gap-2">
            {DOMAINS.map(d => (
              <button key={d.value} onClick={() => setDomain(domain === d.value ? '' : d.value)}
                className={`p-2.5 rounded-xl text-center transition-all ${domain === d.value ? c.tagActive : c.tag}`}>
                <span className="block text-lg">{d.icon}</span>
                <span className="block text-[10px] font-medium mt-0.5">{t(d.labelKey)}</span>
              </button>
            ))}
          </div>
        </div>

        <div className={`${c.card} ${c.border} border rounded-xl p-5 space-y-3`}>
          <label className={`block text-sm font-semibold ${c.text}`}>
            {t('gpg_comfort_zone_label')} <span className={`font-normal ${c.textMuted}`}>{t('gpg_optional')}</span>
          </label>
          <input value={comfortZone} onChange={e => setComfortZone(e.target.value)}
            placeholder={t('gpg_comfort_zone_ph')}
            className={`w-full p-3 rounded-xl border-2 ${c.input} text-sm outline-none`} />
        </div>

        <div className={`${c.card} ${c.border} border rounded-xl p-5 space-y-3`}>
          <label className={`block text-sm font-semibold ${c.text}`}>
            {t('gpg_growth_area_label')} <span className={c.required}>*</span>
          </label>
          <input value={growthArea} onChange={e => setGrowthArea(e.target.value)}
            placeholder={t('gpg_growth_area_ph')}
            className={`w-full p-3 rounded-xl border-2 ${c.input} text-sm outline-none`} />
        </div>

        <div className={`${c.card} ${c.border} border rounded-xl p-5 space-y-3`}>
          <label className={`block text-sm font-semibold ${c.text}`}>{t('gpg_capacity_label')}</label>
          <div className="flex gap-2">
            {CAPACITY_LEVELS.map(cap => (
              <button key={cap.value} onClick={() => setCapacity(cap.value)}
                className={`flex-1 py-3 rounded-xl text-center transition-all ${capacity === cap.value ? c.tagActive : c.tag}`}>
                <span className="block text-lg">{cap.icon}</span>
                <span className="block text-xs font-medium mt-0.5">{t(cap.labelKey)}</span>
                <span className={`block text-[9px] mt-0.5 ${capacity === cap.value ? 'text-white/75' : c.textMuted}`}>{t(cap.descKey)}</span>
              </button>
            ))}
          </div>
        </div>

        <button title={t('cmd_enter')} onClick={handleGenerate} disabled={loading || !growthArea.trim()}
          className={`relative w-full py-4 rounded-xl font-bold text-lg ${!growthArea.trim() ? c.btnIdle : c.btnPrimary} transition-all shadow-lg`}>
          {loading ? <span><span className="animate-spin inline-block me-1">{tool?.icon ?? '🫸'}</span>{t('gpg_generating')}</span> : <span><span className="me-1">{tool?.icon ?? '🫸'}</span>{t('gpg_generate_3')}</span>}
          {!loading && (
            <kbd aria-hidden="true"
              className="hidden sm:flex items-center absolute end-3 top-1/2 -translate-y-1/2 px-1.5 py-0.5 rounded border border-white/30 bg-white/15 text-[10px] font-bold tracking-wide">
              ⌘↵
            </kbd>
          )}
        </button>

        {/* Guarded explicitly rather than relying on position: this component
            returns one screen per view, so "before the result" is a state, not
            a place in the file. */}
        {!results && (
          <p className={`text-xs text-center ${c.textMuted}`}>
            {t('gpg_xref_pre_prefix')}<a href="/DifficultTalkCoach" className={linkStyle}>{t('gpg_xref_difficult_talk')}</a>{t('gpg_xref_pre_suffix')}
          </p>
        )}

        {error && <div className={`${c.danger} border rounded-xl p-4`}><p className="text-sm">⚠️ {error}</p></div>}

        {pushLog.length > 0 && (
          <div className={`${c.card} ${c.border} border rounded-xl p-5`}>
            <h3 className={`text-sm font-bold ${c.text} mb-3`}>🕐 {t('gpg_recent_pushes')}</h3>
            <div className="space-y-2">
              {pushLog.slice(0, 5).map(p => (
                <div key={p.id} className={`p-3 rounded-lg ${c.cardAlt}`}>
                  <div className="flex items-start justify-between gap-3">
                    <p className={`text-xs ${c.text} flex-1`}>{p.challenge}</p>
                    <span className="text-xs flex-shrink-0">{p.attempted ? '✓' : '—'}</span>
                  </div>
                  {p.scariness ? <p className={`text-[10px] ${c.textMuted} mt-1`}>{p.scariness}/5 · {new Date(p.date).toLocaleDateString()}</p> : <p className={`text-[10px] ${c.textMuted} mt-1`}>{new Date(p.date).toLocaleDateString()}</p>}
                </div>
              ))}
            </div>
          </div>
        )}
      </div>
    );
  }

  if (view === 'pick') {
    return (
      <div ref={resultsRef} className={`scroll-mt-24 space-y-4 ${c.text}`}>
        {renderHeader()}
        <button onClick={() => setView('setup')} className={`text-xs ${c.textMuted}`}>{t('gpg_back')}</button>

        {acknowledgment && (
          <div className={`${c.heroCard} border-2 rounded-2xl p-5 text-center shadow-sm`}>
            <p className={`text-sm font-medium ${c.heroText}`}>{acknowledgment}</p>
          </div>
        )}
        {patternNote && (
          <div className={`${c.cardAlt} border ${c.border} rounded-xl p-3`}>
            <p className={`text-xs ${c.textSecondary}`}>{patternNote}</p>
          </div>
        )}

        <h2 className={`text-sm font-bold ${c.text} text-center`}>{t('gpg_pick_your_push')}</h2>

        <div className="space-y-4">
          {pushOptions.map((push, i) => (
            <div key={`${push.approach || 'push'}-${i}`} className={`${c.card} border-2 ${c.border} rounded-xl p-5 space-y-3`}>
              <div className="flex items-start justify-between gap-3">
                <p className={`text-xs font-bold uppercase tracking-wide ${isDark ? 'text-emerald-300' : 'text-emerald-700'}`}>{push.label || ''}</p>
                {push.time_frame && <span className={`text-[10px] ${c.textMuted}`}>{push.time_frame}</span>}
              </div>
              <p className={`text-base font-semibold ${c.text}`}>{push.challenge}</p>
              {push.why_this_size && <p className={`text-xs ${c.textSecondary}`}>{push.why_this_size}</p>}
              {push.what_counts && <p className={`text-xs font-medium ${isDark ? 'text-emerald-300' : 'text-emerald-700'}`}>✅ {push.what_counts}</p>}
              <button onClick={() => selectPush(push)} className={`w-full py-2.5 rounded-lg font-semibold text-sm ${c.btnPrimary}`}>
                {t('gpg_pick_your_push')}
              </button>
            </div>
          ))}
        </div>

        {ifYouDont && (
          <div className={`${c.card} ${c.border} border rounded-xl p-4 text-center`}>
            <p className={`text-xs ${c.textSecondary} italic`}>{ifYouDont}</p>
          </div>
        )}

        {!showFeedback ? (
          <button onClick={() => setShowFeedback(true)} className={`w-full py-2.5 rounded-xl text-sm font-medium ${c.tag}`}>
            {t('gpg_none_fit')}
          </button>
        ) : (
          <div className={`${c.card} ${c.border} border rounded-xl p-5 space-y-3`}>
            <p className={`text-sm font-semibold ${c.text}`}>{t('gpg_what_different')}</p>
            <div className="grid grid-cols-2 gap-2">
              {FEEDBACK_OPTIONS.map(fb => (
                <button key={fb.value} onClick={() => setFeedbackType(fb.value)}
                  className={`px-3 py-2 rounded-lg text-xs font-medium ${feedbackType === fb.value ? c.tagActive : c.tag}`}>
                  {fb.icon} {t(fb.labelKey)}
                </button>
              ))}
            </div>
            <input value={feedbackCustom} onChange={e => setFeedbackCustom(e.target.value)}
              placeholder={t('gpg_feedback_custom_ph')}
              className={`w-full p-2.5 rounded-lg border ${c.input} text-sm`} />
            <div className="flex gap-2">
              <button onClick={handleRegenerate} disabled={loading || (!feedbackType && !feedbackCustom.trim())}
                className={`flex-1 py-2.5 rounded-lg font-medium text-sm ${c.btnPrimary} disabled:opacity-40`}>
                {loading ? <span className="animate-spin inline-block me-1">{tool?.icon ?? '🫸'}</span> : null}{t('gpg_generate_new')}
              </button>
              <button onClick={() => { setShowFeedback(false); setFeedbackType(''); setFeedbackCustom(''); }} className={`px-4 py-2.5 rounded-lg text-sm ${c.tag}`}>
                {t('gpg_cancel')}
              </button>
            </div>
          </div>
        )}

        {error && <div className={`${c.danger} border rounded-xl p-4`}><p className="text-sm">⚠️ {error}</p></div>}
        {renderRelatedTools()}
      </div>
    );
  }

  if (view === 'active' && activePush) {
    return (
      <div ref={resultsRef} className={`scroll-mt-24 space-y-4 ${c.text}`}>
        {renderHeader()}
        <button onClick={() => setView('pick')} className={`text-xs ${c.textMuted}`}>{t('gpg_pick_different')}</button>

        <div className={`${c.heroCard} border-2 rounded-2xl p-6 space-y-3 shadow-sm`}>
          {activePush.label && <p className={`text-xs font-bold uppercase text-center ${c.heroText}`}>{activePush.label}</p>}
          <p className={`text-xl font-bold ${c.text} text-center leading-snug`}>{activePush.challenge}</p>
          {activePush.time_frame && <p className={`text-sm ${c.heroText} text-center font-medium`}>⏰ {activePush.time_frame}</p>}
        </div>

        {activePush.why_this_size && (
          <div className={`${c.card} ${c.border} border rounded-xl p-4`}>
            <p className={`text-[10px] font-bold uppercase ${c.textMuted} mb-1`}>{t('gpg_why_this_size')}</p>
            <p className={`text-sm ${c.textSecondary}`}>{activePush.why_this_size}</p>
          </div>
        )}

        {activePush.what_counts && (
          <div className={`${c.success} border rounded-xl p-4`}>
            <p className="text-sm font-medium">✅ {activePush.what_counts}</p>
          </div>
        )}

        {activePush.if_too_much && (
          <div className={`${c.warning} border rounded-xl p-4`}>
            <p className={`text-[10px] font-bold uppercase mb-1`}>{t('gpg_if_too_big_label')}</p>
            <p className="text-sm">{activePush.if_too_much}</p>
          </div>
        )}

        <div className={`${c.card} ${c.border} border rounded-xl p-4`}>
          <p className={`text-[10px] font-bold uppercase ${c.textMuted}`}>{t('gpg_set_reminder_label')}</p>
          <p className={`text-xs ${c.textMuted} mt-1`}>{t('gpg_set_reminder_hint')}</p>
        </div>

        <div className="space-y-3">
          <button onClick={() => startLog(true)} className={`w-full py-4 rounded-xl font-bold text-lg ${c.btnPrimary} shadow-sm`}>
            {t('gpg_did_it')}
          </button>
          <button onClick={() => startLog(false)} className={`w-full py-3 rounded-xl font-medium text-sm ${c.tag}`}>
            {t('gpg_didnt_do_it')}
          </button>
        </div>
      </div>
    );
  }

  if (view === 'log') {
    return (
      <div ref={resultsRef} className={`scroll-mt-24 space-y-4 ${c.text}`}>
        {renderHeader()}
        <div className="text-center">
          <span className="text-3xl">{attempted ? '✓' : '○'}</span>
          <h2 className={`text-xl font-bold ${c.text} mt-2`}>{attempted ? t('gpg_did_scary_thing') : t('gpg_thats_okay')}</h2>
          <p className={`${c.textSecondary} text-sm mt-1`}>{attempted ? t('gpg_lets_record') : t('gpg_lets_capture')}</p>
        </div>

        {attempted && (
          <div className={`${c.card} ${c.border} border rounded-xl p-5 space-y-3`}>
            <label className={`block text-sm font-semibold ${c.text}`}>{t('gpg_actual_scary_label')}</label>
            <div className="flex gap-1.5">
              {[1, 2, 3, 4, 5].map(n => (
                <button key={n} onClick={() => setScariness(n)}
                  className={`flex-1 py-3 rounded-xl text-center ${scariness === n ? c.tagActive : c.tag}`}>
                  <span className="block text-lg">{['', '😌', '😅', '😰', '😬', '🫣'][n]}</span>
                  <span className="block text-[9px] mt-0.5">{n}/5</span>
                </button>
              ))}
            </div>
            {scariness > 0 && <p className={`text-center text-xs ${c.textSecondary}`}>{t(SCARINESS_LABEL_KEYS[scariness])}</p>}
          </div>
        )}

        <div className={`${c.card} ${c.border} border rounded-xl p-5 space-y-3`}>
          <label className={`block text-sm font-semibold ${c.text}`}>
            {attempted ? t('gpg_what_happened') : t('gpg_what_got_in_way')} <span className={`font-normal ${c.textMuted}`}>{t('gpg_optional')}</span>
          </label>
          <textarea value={whatHappened} onChange={e => setWhatHappened(e.target.value)}
            placeholder={attempted ? t('gpg_what_happened_ph') : t('gpg_what_got_in_way_ph')}
            className={`w-full p-3 rounded-xl border-2 ${c.input} text-sm resize-none outline-none`} rows={3} />
        </div>

        <button onClick={handleReflect} disabled={loading}
          className={`w-full py-4 rounded-xl font-bold text-lg ${c.btnPrimary} disabled:opacity-40 shadow-sm`}>
          {loading ? <span><span className="animate-spin inline-block me-1">{tool?.icon ?? '🫸'}</span>{t('gpg_reflecting')}</span> : <span><span className="me-1">{tool?.icon ?? '🫸'}</span>{t('gpg_get_reflection')}</span>}
        </button>

        {error && <div className={`${c.danger} border rounded-xl p-4`}><p className="text-sm">⚠️ {error}</p></div>}
      </div>
    );
  }

  if (view === 'reflection' && results) {
    return renderResults();
  }
  return null;
};

GentlePushGenerator.displayName = 'GentlePushGenerator';
export default GentlePushGenerator;
