import React, { useState, useEffect, useCallback, useRef } from 'react';
import { useClaudeAPI } from '../hooks/useClaudeAPI';
import { useTheme } from '../hooks/useTheme';
import { useRegisterActions } from '../components/ActionBarContext';
import { useTranslation } from '../i18n/useTranslation';
import { pickExample } from '../utils/exampleRotation';
import { toolTagline } from '../utils/toolTagline';
import { revealSection } from '../utils/revealSection';

const BRAND = '\n\n— Generated by DeftBrain · deftbrain.com';

const EXAMPLES = [
  { thoughtsKey: 'sps_ex1_thoughts', actualEventKey: 'sps_ex1_actual' },
  { thoughtsKey: 'sps_ex2_thoughts', actualEventKey: 'sps_ex2_actual' },
  { thoughtsKey: 'sps_ex3_thoughts', actualEventKey: 'sps_ex3_actual' },
  { thoughtsKey: 'sps_ex4_thoughts', actualEventKey: 'sps_ex4_actual' },
  { thoughtsKey: 'sps_ex5_thoughts', actualEventKey: 'sps_ex5_actual' },
];

// Declared above the main component per REWRITE-INSTALL-KIT §11.
function AttentionShift({ steps, step, onNext, onDone, doneLabel, c, t }) {
  return (
    <div className={`${c.cardAlt} border ${c.border} rounded-xl p-4 space-y-3`}>
      <p className={`text-xs font-bold tracking-wide ${c.textMuted}`}>{t('sps_shift_title')}</p>
      <p className={`font-bold ${c.text}`}>{steps[step].title}</p>
      <p className={`text-sm ${c.textSecondary}`}>{steps[step].body}</p>
      <div className="flex items-center justify-between gap-2">
        <span className={`text-xs ${c.textMuted}`}>{t('sps_shift_step_of', { n: step + 1, total: steps.length })}</span>
        {step < steps.length - 1 ? (
          <button onClick={onNext} className={`${c.btnSecondary} px-3 py-2 rounded-lg text-sm font-semibold`}>{t('sps_shift_done_btn')}</button>
        ) : (
          <button onClick={onDone} className={`${c.btnSecondary} px-3 py-2 rounded-lg text-sm font-semibold`}>{doneLabel}</button>
        )}
      </div>
    </div>
  );
}

const SpiralStopper = ({ tool }) => {
  const { callToolEndpoint, loading, userLocale, userCurrency, userRegion } = useClaudeAPI();
  const { isDark } = useTheme();
  const { t } = useTranslation();

  const c = {
    card: isDark ? 'bg-zinc-800' : 'bg-white',
    cardAlt: isDark ? 'bg-zinc-700/50' : 'bg-slate-50',
    text: isDark ? 'text-zinc-50' : 'text-gray-900',
    textSecondary: isDark ? 'text-zinc-300' : 'text-gray-600',
    textMuted: isDark ? 'text-zinc-400' : 'text-gray-500',
    labelText: isDark ? 'text-zinc-200' : 'text-gray-700',
    required: isDark ? 'text-amber-400' : 'text-amber-700',
    accentTxt: isDark ? 'text-cyan-400' : 'text-cyan-700',
    border: isDark ? 'border-zinc-700' : 'border-gray-200',
    input: isDark
      ? 'bg-zinc-900 border-zinc-600 text-zinc-100 placeholder-zinc-400'
      : 'bg-white border-gray-300 text-gray-900 placeholder-gray-400',
    btnPrimary: isDark ? 'bg-cyan-600 hover:bg-cyan-500 text-white' : 'bg-cyan-700 hover:bg-cyan-800 text-white',
    btnIdle: isDark ? '!bg-transparent !border-2 !border-cyan-500/85 !text-cyan-300 cursor-not-allowed'
                    : '!bg-transparent !border-2 !border-cyan-600/85 !text-cyan-800 cursor-not-allowed',
    btnSecondary: isDark ? 'bg-zinc-700 hover:bg-zinc-600 text-zinc-200' : 'bg-gray-100 hover:bg-gray-200 text-gray-700',
    success: isDark ? 'bg-emerald-900/20 border-emerald-700 text-emerald-200' : 'bg-emerald-50 border-emerald-300 text-emerald-800',
    warning: isDark ? 'bg-amber-900/20 border-amber-700 text-amber-200' : 'bg-amber-50 border-amber-300 text-amber-800',
    danger: isDark ? 'bg-red-950/30 border-red-800 text-red-100' : 'bg-red-50 border-red-200 text-red-800',
    // Semantic section colors, specific to this tool's flow, beyond the
    // standard set — not a substitute for it.
    loop: isDark ? 'bg-amber-950/30 border-amber-800' : 'bg-amber-50 border-amber-200',
    real: isDark ? 'bg-emerald-950/30 border-emerald-800' : 'bg-emerald-50 border-emerald-200',
    unknown: isDark ? 'bg-sky-950/30 border-sky-800' : 'bg-sky-50 border-sky-200',
    decision: isDark ? 'bg-orange-950/30 border-orange-800' : 'bg-orange-50 border-orange-200',
    exitCard: isDark ? 'bg-cyan-950/30 border-cyan-700' : 'bg-cyan-50 border-cyan-300',
    rule: isDark ? 'bg-zinc-900 border-zinc-600' : 'bg-zinc-50 border-zinc-300',
  };
  c.textMuteded = c.textMuted;
  c.label = c.labelText;

  const linkStyle = isDark
    ? 'text-cyan-400 hover:text-cyan-300 underline underline-offset-2'
    : 'text-cyan-700 hover:text-cyan-800 underline underline-offset-2';

  const STATUS_COPY = {
    YES: { labelKey: 'sps_status_yes', icon: '→' },
    PARTLY: { labelKey: 'sps_status_partly', icon: '◐' },
    NOT_YET: { labelKey: 'sps_status_not_yet', icon: '⏱' },
    NO: { labelKey: 'sps_status_no', icon: '✓' },
  };
  const EXIT_LABEL_KEYS = { ACT: 'sps_exit_act', CAPTURE: 'sps_exit_capture', WAIT: 'sps_exit_wait', DISENGAGE: 'sps_exit_disengage' };

  const [thoughts, setThoughts] = useState('');
  const [actualEvent, setActualEvent] = useState('');
  const [showActualEvent, setShowActualEvent] = useState(false);
  const [showShift, setShowShift] = useState(false);
  const [shiftStep, setShiftStep] = useState(0);
  const [results, setResults] = useState(null);
  const [error, setError] = useState('');
  const resultsRef = useRef(null);

  const canSubmit = thoughts.trim().length > 0;
  const hasInput = !!(thoughts.trim() || actualEvent.trim() || results);

  const attentionSteps = [
    { title: t('sps_shift_step1_title'), body: t('sps_shift_step1_body') },
    { title: t('sps_shift_step2_title'), body: t('sps_shift_step2_body') },
    { title: t('sps_shift_step3_title'), body: t('sps_shift_step3_body') },
    { title: t('sps_shift_step4_title'), body: results ? t('sps_shift_step4_body_post') : t('sps_shift_step4_body_pre') },
  ];

  const handleReset = useCallback(() => {
    setThoughts(''); setActualEvent(''); setShowActualEvent(false);
    setShowShift(false); setShiftStep(0); setResults(null); setError('');
  }, []);

  const loadExample = useCallback(() => {
    const ex = pickExample('SpiralStopper', EXAMPLES);
    setThoughts(t(ex.thoughtsKey));
    setActualEvent(t(ex.actualEventKey));
    setShowActualEvent(true);
    setShowShift(false);
    setShiftStep(0);
    setResults(null);
    setError('');
  }, [t]);

  const handleSubmit = useCallback(async () => {
    if (!canSubmit || loading) return;
    setError('');
    setResults(null);
    try {
      const data = await callToolEndpoint('spiral-stopper', {
        thoughts: thoughts.trim(),
        actual_event: actualEvent.trim() || null,
        userLocale, userCurrency, userRegion,
      });
      if (data) {
        setResults(data);
        setShowShift(false);
        setShiftStep(0);
      }
    } catch (e) {
      setError(e?.message || t('sps_error_generic'));
    }
  }, [canSubmit, loading, thoughts, actualEvent, userLocale, userCurrency, userRegion, callToolEndpoint, t]);

  // Cmd/Ctrl+Enter submits from anywhere, only while the form is showing.
  useEffect(() => {
    const handler = (e) => {
      const tag = document.activeElement?.tagName;
      if (tag === 'SELECT') return;
      if (e.key === 'Enter' && (e.metaKey || e.ctrlKey) && !loading && !results) handleSubmit();
    };
    document.addEventListener('keydown', handler);
    return () => document.removeEventListener('keydown', handler);
  }, [loading, results, handleSubmit]);

  const buildText = useCallback(() => {
    if (!results || results.safety_redirect) return '';
    const lines = [t('sps_copy_header'), ''];
    if (results.loop_summary) lines.push(t('sps_copy_loop'), results.loop_summary, '');
    if (results.what_is_real?.length) {
      lines.push(t('sps_copy_real'));
      results.what_is_real.forEach(x => lines.push(`• ${x}`));
      lines.push('');
    }
    if (results.what_is_unknown?.length) {
      lines.push(t('sps_copy_unknown'));
      results.what_is_unknown.forEach(x => lines.push(`• ${x}`));
      lines.push('');
    }
    if (results.solvability) {
      lines.push(t('sps_copy_solvability'), results.solvability.headline || results.solvability.status, results.solvability.explanation || '', '');
    }
    if (results.exit) {
      lines.push(t('sps_copy_exit'), results.exit.action || '');
      if (results.exit.why) lines.push(results.exit.why);
      if (results.exit.done_when) lines.push(`${t('sps_copy_done_when')} ${results.exit.done_when}`);
      lines.push('');
    }
    if (results.stopping_rule) lines.push(t('sps_copy_stopping_rule'), results.stopping_rule, '');
    lines.push(BRAND);
    return lines.join('\n');
  }, [results, t]);

  useRegisterActions(results ? buildText() : '', tool?.title);

  useEffect(() => {
    if (results) {
      setTimeout(() => {
        resultsRef.current?.scrollIntoView({ behavior: 'smooth', block: 'start' });
        revealSection(resultsRef.current);
      }, 80);
    }
  }, [results]);

  const status = results?.solvability?.status ? STATUS_COPY[results.solvability.status] : null;
  const exitLabelKey = results?.exit?.kind ? EXIT_LABEL_KEYS[results.exit.kind] : null;

  return (
    <div className={`space-y-4 ${c.text}`}>
      <div className={`${c.card} border ${c.border} rounded-xl shadow-sm px-5 pt-3 pb-5`}>
        <div className="flex items-start justify-between gap-3">
          <div>
            <p className={`text-base ${c.textSecondary}`}>
              <span className="me-2 text-lg">{tool?.icon ?? '🌀'}</span>{toolTagline(tool?.tagline ?? t('sps_tagline'))}
            </p>
            <button onClick={loadExample} disabled={loading} style={{ backgroundColor: (tool?.headerColor ?? '#67e8f9') + '80' }} className="mt-2 px-4 py-2 rounded-full text-sm font-semibold border border-black/25 text-zinc-900 shadow-sm hover:brightness-105 hover:shadow transition disabled:opacity-40 whitespace-nowrap">✨ {t('try_example')}</button>
          </div>
          {hasInput && (
            <button onClick={handleReset} className={`${c.btnSecondary} px-3 py-1.5 rounded-lg text-xs font-bold whitespace-nowrap`}>
              ↺ {t('start_over')}
            </button>
          )}
        </div>
      </div>

      {error && <div className={`${c.danger} border rounded-xl p-4 text-sm`}>⚠️ {error}</div>}

      {!results && (
        <div className={`${c.card} border ${c.border} rounded-xl shadow-sm p-5 space-y-4`}>
          <div>
            <label className={`block font-bold text-sm ${c.text}`}>{t('sps_thoughts_label')} <span className={c.required}>*</span></label>
            <p className={`text-xs ${c.textSecondary} mt-1 mb-2`}>{t('sps_thoughts_hint')}</p>
            <textarea
              value={thoughts}
              onChange={e => setThoughts(e.target.value)}
              rows={6}
              autoFocus
              placeholder={t('sps_thoughts_ph')}
              className={`w-full p-3 border rounded-lg text-sm ${c.input}`}
            />
          </div>

          {!showActualEvent ? (
            <button onClick={() => setShowActualEvent(true)} className={`text-sm font-semibold ${c.accentTxt} hover:underline`}>
              ＋ {t('sps_add_actual_event')} <span className={`font-normal ${c.textMuted}`}>{t('sps_optional')}</span>
            </button>
          ) : (
            <div>
              <label className={`block text-sm font-bold ${c.text}`}>{t('sps_actual_event_label')} <span className={`font-normal ${c.textMuted}`}>{t('sps_optional')}</span></label>
              <p className={`text-xs ${c.textSecondary} mt-1 mb-2`}>{t('sps_actual_event_hint')}</p>
              <input
                value={actualEvent}
                onChange={e => setActualEvent(e.target.value)}
                placeholder={t('sps_actual_event_ph')}
                className={`w-full p-3 border rounded-lg text-sm ${c.input}`}
              />
            </div>
          )}

          <div className="flex flex-col sm:flex-row gap-2">
            <button title={t('cmd_enter')} onClick={handleSubmit} disabled={loading || !canSubmit}
              className={`relative flex-1 py-3.5 rounded-xl font-semibold text-base flex items-center justify-center gap-2 ${!canSubmit ? c.btnIdle : c.btnPrimary}`}>
              {loading
                ? <><span className="inline-block animate-spin">{tool?.icon ?? '🌀'}</span> {t('sps_processing')}</>
                : <><span>{tool?.icon ?? '🌀'}</span> {t('sps_submit')}</>}
              {!loading && canSubmit && (
                <kbd aria-hidden="true"
                  className="hidden sm:flex items-center absolute end-3 top-1/2 -translate-y-1/2 px-1.5 py-0.5 rounded border border-white/30 bg-white/15 text-[10px] font-bold tracking-wide">
                  ⌘↵
                </kbd>
              )}
            </button>
            <button onClick={() => { setShowShift(v => !v); setShiftStep(0); }} className={`${c.btnSecondary} px-4 py-3.5 rounded-xl text-sm font-semibold`}>
              {t('sps_shift_attention_btn')}
            </button>
          </div>

          {showShift && (
            <AttentionShift steps={attentionSteps} step={shiftStep}
              onNext={() => setShiftStep(s => s + 1)}
              onDone={() => { setShowShift(false); setShiftStep(0); }}
              doneLabel={t('sps_shift_back_pre')} c={c} t={t} />
          )}

          <p className={`text-xs ${c.textMuted} text-center`}>{t('sps_safety_footer')}</p>
          <p className={`text-xs text-center ${c.textMuted}`}>
            {t('sps_xref_crash_q')} <a href="/BeforeTheCrash" className={linkStyle}>{t('sps_xref_crash')}</a>
          </p>
        </div>
      )}

      {results && (results.safety_redirect ? (
        <div ref={resultsRef} className={`${c.danger} border rounded-xl p-5`}>
          <h3 className="font-bold mb-2">{t('sps_safety_redirect_title')}</h3>
          <p className="text-sm">{results?.message || t('sps_crisis')}</p>
        </div>
      ) : (
        <div data-copy-results ref={resultsRef} className="scroll-mt-24 space-y-4">
          {results?.loop_summary && (
            <section className={`${c.loop} border rounded-xl p-5`}>
              <p className={`text-xs font-bold tracking-wide ${c.textMuted}`}>{t('sps_loop_title').toUpperCase()}</p>
              <p className={`text-lg font-semibold leading-snug ${c.text} mt-2`}>{results.loop_summary}</p>
            </section>
          )}

          {results?.what_is_real?.length > 0 && (
            <section className={`${c.real} border rounded-xl p-5`}>
              <h3 className={`font-bold text-sm ${c.text}`}>✓ {t('sps_real_title').toUpperCase()}</h3>
              <div className="mt-3 space-y-2">
                {results?.what_is_real.map((x, i) => <p key={i} className={`text-sm ${c.text}`}>• {x}</p>)}
              </div>
            </section>
          )}

          {results?.what_is_unknown?.length > 0 && (
            <section className={`${c.unknown} border rounded-xl p-5`}>
              <h3 className={`font-bold text-sm ${c.text}`}>? {t('sps_unknown_title').toUpperCase()}</h3>
              <div className="mt-3 space-y-2">
                {results?.what_is_unknown.map((x, i) => <p key={i} className={`text-sm ${c.text}`}>• {x}</p>)}
              </div>
            </section>
          )}

          {results?.solvability && (
            <section className={`${c.decision} border rounded-xl p-5`}>
              <p className={`text-xs font-bold tracking-wide ${c.textMuted}`}>{t('sps_solvability_title').toUpperCase()}</p>
              <h3 className={`text-base font-bold ${c.text} mt-2`}>{status?.icon} {results.solvability.headline || (status ? t(status.labelKey) : results.solvability.status)}</h3>
              {results?.solvability.explanation && <p className={`text-sm ${c.textSecondary} mt-2`}>{results.solvability.explanation}</p>}
            </section>
          )}

          {results?.exit && (
            <section className={`${c.exitCard} border-2 rounded-xl p-5`}>
              <p className={`text-xs font-bold tracking-wide ${c.textMuted}`}>{exitLabelKey ? t(exitLabelKey).toUpperCase() : t('sps_exit_title').toUpperCase()}</p>
              <p className={`text-xl font-bold leading-snug ${c.text} mt-2`}>{results.exit.action}</p>
              {results?.exit.why && <p className={`text-sm ${c.textSecondary} mt-3`}>{results.exit.why}</p>}
              {results?.exit.done_when && (
                <div className={`${c.card} border ${c.border} rounded-lg p-3 mt-4`}>
                  <span className={`text-xs font-bold ${c.textMuted}`}>{t('sps_done_when_label').toUpperCase()} </span>
                  <span className={`text-sm ${c.text}`}>{results.exit.done_when}</span>
                </div>
              )}
            </section>
          )}

          {results?.stopping_rule && (
            <section className={`${c.rule} border rounded-xl p-5`}>
              <p className={`text-xs font-bold tracking-wide ${c.textMuted}`}>{t('sps_stopping_rule_title').toUpperCase()}</p>
              <p className={`text-lg font-bold ${c.text} mt-2`}>{results.stopping_rule}</p>
            </section>
          )}

          <div className="flex flex-col sm:flex-row gap-2 pt-1">
            <button onClick={() => { setShowShift(v => !v); setShiftStep(0); }} className={`${c.btnSecondary} flex-1 px-4 py-2.5 rounded-lg text-sm font-bold`}>
              {t('sps_shift_still_looping_btn')}
            </button>
            <button onClick={() => handleReset()} className={`${c.btnSecondary} flex-1 px-4 py-2.5 rounded-lg text-sm font-bold`}>{t('sps_try_another')}</button>
          </div>

          {showShift && (
            <AttentionShift steps={attentionSteps} step={shiftStep}
              onNext={() => setShiftStep(s => s + 1)}
              onDone={() => { setShowShift(false); setShiftStep(0); }}
              doneLabel={t('sps_shift_back_post')} c={c} t={t} />
          )}

          <p className={`text-xs ${c.textMuted} text-center pt-1`}>
            {t('sps_xref_crash_q')} <a href="/BeforeTheCrash" className={linkStyle}>{t('sps_xref_crash')}</a>
          </p>
        </div>
      ))}
    </div>
  );
};

SpiralStopper.displayName = 'SpiralStopper';
export default SpiralStopper;
