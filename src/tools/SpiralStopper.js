import React, { useState, useEffect, useCallback, useRef } from 'react';
import { useClaudeAPI } from '../hooks/useClaudeAPI';
import { useTheme } from '../hooks/useTheme';
import { useRegisterActions } from '../components/ActionBarContext';
import { useTranslation } from '../i18n/useTranslation';
import { pickExample } from '../utils/exampleRotation';
import { revealSection } from '../utils/revealSection';
import { toolTagline } from '../utils/toolTagline';

const BRAND = '\n\n— Generated by DeftBrain · deftbrain.com';

// Five, rotated: a work mistake, a comparison spiral, a medical-results
// wait, a friendship worry, and a social-awkwardness replay — different
// enough triggers that the pattern (fact vs. prediction vs. unknown) reads
// as general, not tied to one kind of worry.
const EXAMPLES = [
  { thoughtsKey: 'sps_ex1_thoughts', actualEventKey: 'sps_ex1_actual' },
  { thoughtsKey: 'sps_ex2_thoughts', actualEventKey: 'sps_ex2_actual' },
  { thoughtsKey: 'sps_ex3_thoughts', actualEventKey: 'sps_ex3_actual' },
  { thoughtsKey: 'sps_ex4_thoughts', actualEventKey: 'sps_ex4_actual' },
  { thoughtsKey: 'sps_ex5_thoughts', actualEventKey: 'sps_ex5_actual' },
];

const SpiralStopper = ({ tool }) => {
  const { callToolEndpoint, loading, userLocale, userCurrency, userRegion } = useClaudeAPI();
  const { isDark } = useTheme();
  const { t } = useTranslation();

  const c = {
    card:          isDark ? 'bg-zinc-800' : 'bg-white',
    cardAlt:       isDark ? 'bg-zinc-700/50' : 'bg-slate-50',
    input:         isDark ? 'bg-zinc-900 border-zinc-600 text-zinc-100 placeholder-zinc-400 focus:border-cyan-500 focus:ring-cyan-500/20' : 'bg-white border-gray-300 text-gray-900 placeholder-gray-400 focus:border-cyan-500 focus:ring-cyan-100',
    text:          isDark ? 'text-zinc-50' : 'text-gray-900',
    textSecondary: isDark ? 'text-zinc-300' : 'text-gray-600',
    textMuted:     isDark ? 'text-zinc-400' : 'text-gray-500',
    labelText:     isDark ? 'text-zinc-200' : 'text-gray-700',
    required:      isDark ? 'text-amber-400' : 'text-amber-700',
    accentTxt:     isDark ? 'text-cyan-400' : 'text-cyan-600',
    btnPrimary:    isDark ? 'bg-cyan-600 hover:bg-cyan-500 text-white' : 'bg-cyan-600 hover:bg-cyan-700 text-white',
    btnIdle:       isDark ? '!bg-transparent !border-2 !border-cyan-500/85 !text-cyan-300 cursor-not-allowed'
                          : '!bg-transparent !border-2 !border-cyan-600/85 !text-cyan-800 cursor-not-allowed',
    btnSecondary:  isDark ? 'bg-zinc-700 hover:bg-zinc-600 text-zinc-200' : 'bg-gray-100 hover:bg-gray-200 text-gray-700',
    border:        isDark ? 'border-zinc-700' : 'border-gray-200',
    danger:        isDark ? 'bg-red-950/30 border-red-800 text-red-200' : 'bg-red-50 border-red-200 text-red-800',
    success:       isDark ? 'bg-emerald-900/20 border-emerald-700 text-emerald-200' : 'bg-emerald-50 border-emerald-300 text-emerald-800',
    warning:       isDark ? 'bg-amber-900/20 border-amber-700 text-amber-200' : 'bg-amber-50 border-amber-300 text-amber-800',
    // Semantic section colors, specific to this tool's three-way split —
    // beyond the standard set, not a substitute for it.
    fact:          isDark ? 'bg-emerald-950/30 border-emerald-800' : 'bg-emerald-50 border-emerald-200',
    story:         isDark ? 'bg-amber-950/30 border-amber-800' : 'bg-amber-50 border-amber-200',
    unknown:       isDark ? 'bg-sky-950/30 border-sky-800' : 'bg-sky-50 border-sky-200',
    anchorBg:      isDark ? 'bg-cyan-950/30 border-cyan-700' : 'bg-cyan-50 border-cyan-300',
  };
  c.textMuteded = c.textMuted;
  c.label = c.labelText;

  const linkStyle = isDark
    ? 'text-cyan-400 hover:text-cyan-300 underline underline-offset-2'
    : 'text-cyan-700 hover:text-cyan-800 underline underline-offset-2';

  // ── State ──
  const [thoughts, setThoughts] = useState('');
  const [actualEvent, setActualEvent] = useState('');
  const [showActualEvent, setShowActualEvent] = useState(false);
  const [showGrounding, setShowGrounding] = useState(false);
  const [results, setResults] = useState(null);
  const [error, setError] = useState('');
  const resultsRef = useRef(null);

  const canSubmit = thoughts.trim().length > 0;
  const hasInput = !!(thoughts.trim() || actualEvent.trim() || results);

  const statusLabel = (status) => {
    if (status === 'PREDICTION') return t('sps_status_prediction');
    if (status === 'CONCLUSION') return t('sps_status_conclusion');
    return t('sps_status_interpretation');
  };

  const handleReset = useCallback(() => {
    setThoughts(''); setActualEvent(''); setShowActualEvent(false); setShowGrounding(false);
    setResults(null); setError('');
  }, []);

  const loadExample = useCallback(() => {
    const ex = pickExample('SpiralStopper', EXAMPLES);
    setThoughts(t(ex.thoughtsKey));
    setActualEvent(t(ex.actualEventKey));
    setShowActualEvent(true);
    setShowGrounding(false);
    setResults(null);
    setError('');
  }, [t]);

  const handleSubmit = useCallback(async () => {
    if (!canSubmit || loading) return;
    setError(''); setResults(null);
    try {
      const data = await callToolEndpoint('spiral-stopper', {
        thoughts: thoughts.trim(),
        actual_event: actualEvent.trim() || undefined,
        userLocale, userCurrency, userRegion,
      });
      setResults(data);
    } catch (e) { setError(e.message || t('sps_error_generic')); }
  }, [canSubmit, loading, thoughts, actualEvent, callToolEndpoint, userLocale, userCurrency, userRegion, t]);

  // Cmd/Ctrl+Enter submits from anywhere
  useEffect(() => {
    const handler = (e) => {
      const tag = document.activeElement?.tagName;
      if (tag === 'SELECT') return;
      if (e.key === 'Enter' && (e.metaKey || e.ctrlKey) && !loading) handleSubmit();
    };
    document.addEventListener('keydown', handler);
    return () => document.removeEventListener('keydown', handler);
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [loading, handleSubmit]);

  const buildText = useCallback(() => {
    if (!results || results.safety_redirect) return '';
    const lines = [t('sps_copy_header'), ''];
    if (results.what_happened?.length) {
      lines.push(t('sps_copy_what_happened'));
      results.what_happened.forEach(x => lines.push(`• ${x}`));
      lines.push('');
    }
    if (results.what_the_spiral_added?.length) {
      lines.push(t('sps_copy_spiral_added'));
      results.what_the_spiral_added.forEach(x => {
        lines.push(`• ${x.thought}`);
        if (x.grounded_version) lines.push(`  → ${x.grounded_version}`);
      });
      lines.push('');
    }
    if (results.what_is_unknown?.length) {
      lines.push(t('sps_copy_unknown'));
      results.what_is_unknown.forEach(x => lines.push(`• ${x}`));
      lines.push('');
    }
    if (results.anchor) lines.push(t('sps_copy_anchor'), results.anchor, '');
    if (results.next_move?.available && results.next_move.action) {
      lines.push(t('sps_copy_next_move'), results.next_move.action, '');
    }
    if (results.after_this) lines.push(results.after_this, '');
    lines.push(BRAND);
    return lines.join('\n');
  }, [results, t]);

  useRegisterActions(results ? buildText() : '', tool?.title);

  useEffect(() => {
    if (!results) return;
    const timer = setTimeout(() => revealSection(resultsRef.current), 100);
    return () => clearTimeout(timer);
  }, [results]);

  return (
    <div className={`space-y-4 ${c.text}`}>

      {/* Input card */}
      <div className={`${c.card} border ${c.border} rounded-xl p-6`}>
        <div className={`mb-5 pb-4 border-b ${c.border}`}>
          <div className="flex items-start justify-between gap-3">
            <div>
              {/* PF-30 — the wrapper already prints the name as the page <h1>. */}
              <p className={`text-base ${c.textSecondary}`}>
                <span className="me-2 text-lg">{tool?.icon ?? '🌀'}</span>{toolTagline(tool?.tagline ?? t('sps_tagline'))}
              </p>
              <button onClick={loadExample} disabled={loading} style={{ backgroundColor: (tool?.headerColor ?? '#67e8f9') + '80' }} className="mt-2 px-4 py-2 rounded-full text-sm font-semibold border border-black/25 text-zinc-900 shadow-sm hover:brightness-105 hover:shadow transition disabled:opacity-40 whitespace-nowrap">✨ {t('try_example')}</button>
            </div>
            <div className="flex items-center gap-2 flex-shrink-0">
              {hasInput && (
                <button onClick={handleReset} className={`${c.btnSecondary} px-3 py-1.5 rounded-lg text-xs font-bold`}>
                  ↺ {t('start_over')}
                </button>
              )}
            </div>
          </div>
        </div>

        {!results && (
          <div className="space-y-4">
            <div>
              <label className={`block text-sm font-semibold mb-1.5 ${c.text}`}>
                {t('sps_thoughts_label')} <span className={c.required}>*</span>
              </label>
              <p className={`text-xs mb-2 ${c.textMuted}`}>{t('sps_thoughts_hint')}</p>
              <textarea value={thoughts} onChange={e => setThoughts(e.target.value)}
                onKeyDown={e => { if (e.key === 'Enter' && (e.metaKey || e.ctrlKey) && !loading && canSubmit) { e.preventDefault(); handleSubmit(); } }}
                placeholder={t('sps_thoughts_ph')}
                rows={6} autoFocus
                className={`w-full px-4 py-3 rounded-xl border text-sm resize-none ${c.input}`} />
            </div>

            {!showActualEvent ? (
              <button onClick={() => setShowActualEvent(true)} className={`text-sm font-semibold ${c.accentTxt} hover:underline`}>
                ＋ {t('sps_add_actual_event')} <span className={`font-normal ${c.textMuted}`}>{t('sps_optional')}</span>
              </button>
            ) : (
              <div>
                <label className={`block text-sm font-semibold mb-1.5 ${c.text}`}>
                  {t('sps_actual_event_label')} <span className={`font-normal ${c.textMuted}`}>{t('sps_optional')}</span>
                </label>
                <p className={`text-xs mb-2 ${c.textMuted}`}>{t('sps_actual_event_hint')}</p>
                <input value={actualEvent} onChange={e => setActualEvent(e.target.value)}
                  placeholder={t('sps_actual_event_ph')}
                  className={`w-full px-4 py-3 rounded-xl border text-sm ${c.input}`} />
              </div>
            )}

            {error && <div className={`p-3 rounded-xl border text-sm ${c.danger}`}><span className="me-1">⚠️</span>{error}</div>}

            <div className="flex flex-col sm:flex-row gap-2">
              <button title={t('cmd_enter')} onClick={handleSubmit} disabled={loading || !canSubmit}
                className={`relative flex-1 py-3 rounded-xl font-bold min-h-[48px] flex items-center justify-center gap-2 ${!canSubmit ? c.btnIdle : c.btnPrimary}`}>
                {loading
                  ? <><span className="inline-block animate-spin">{tool?.icon ?? '🌀'}</span> {t('sps_processing')}</>
                  : <><span>{tool?.icon ?? '🌀'}</span> {t('sps_submit')}</>}
                {!loading && (
                  <kbd aria-hidden="true"
                    className="hidden sm:flex items-center absolute end-3 top-1/2 -translate-y-1/2 px-1.5 py-0.5 rounded border border-white/30 bg-white/15 text-[10px] font-bold tracking-wide">
                    ⌘↵
                  </kbd>
                )}
              </button>
              <button onClick={() => setShowGrounding(v => !v)} className={`${c.btnSecondary} px-4 py-3 rounded-xl text-sm font-semibold`}>
                {t('sps_ground_me')}
              </button>
            </div>

            {showGrounding && (
              <div className={`${c.cardAlt} border ${c.border} rounded-xl p-4 space-y-2`}>
                <p className={`font-semibold text-sm ${c.text}`}>{t('sps_ground_title')}</p>
                <p className={`text-sm ${c.textSecondary}`}>1. {t('sps_ground_step1')}</p>
                <p className={`text-sm ${c.textSecondary}`}>2. {t('sps_ground_step2')}</p>
                <p className={`text-sm ${c.textSecondary}`}>3. {t('sps_ground_step3')}</p>
                <p className={`text-xs ${c.textMuted}`}>{t('sps_ground_footer')}</p>
              </div>
            )}

            <p className={`text-xs text-center ${c.textMuted}`}>{t('sps_safety_footer')}</p>

            <p className={`text-xs text-center ${c.textMuted}`}>
              {t('sps_xref_crash_q')} <a href="/BeforeTheCrash" className={linkStyle}>{t('sps_xref_crash')}</a>
            </p>
          </div>
        )}
      </div>

      {/* Results — safety redirect and the ordinary breakdown are two
          branches of one results block (not separate top-level conditionals)
          so the tool page's results region is unambiguous. */}
      {results && (results?.safety_redirect ? (
        <div ref={resultsRef} className={`${c.danger} border rounded-xl p-5`}>
          <p className="font-bold mb-2">{t('sps_safety_redirect_title')}</p>
          <p className="text-sm">{results?.message || t('sps_crisis')}</p>
        </div>
      ) : (
        <div className="space-y-4">
          <div data-copy-results ref={resultsRef} data-results-anchor className="scroll-mt-24" />

          {results?.what_happened?.length > 0 && (
            <div className={`rounded-xl border p-5 ${c.fact}`}>
              <p className={`text-xs font-bold uppercase tracking-widest ${c.text}`}>✓ {t('sps_what_happened_title')}</p>
              <div className="mt-3 space-y-2">
                {results?.what_happened.map((x, i) => <p key={i} className={`text-sm ${c.text}`}>• {x}</p>)}
              </div>
            </div>
          )}

          {results?.what_the_spiral_added?.length > 0 && (
            <div className={`rounded-xl border p-5 ${c.story}`}>
              <p className={`text-xs font-bold uppercase tracking-widest ${c.text}`}>🌀 {t('sps_spiral_added_title')}</p>
              <div className="mt-3 space-y-4">
                {results?.what_the_spiral_added.map((x, i) => (
                  <div key={i}>
                    <div className="flex items-start gap-2 flex-wrap">
                      <span className={`text-[10px] font-bold tracking-wide px-2 py-1 rounded-full border ${c.border} ${c.textMuted}`}>{statusLabel(x.status)}</span>
                      <p className={`text-sm font-semibold ${c.text}`}>{x.thought}</p>
                    </div>
                    {x.grounded_version && <p className={`text-sm mt-2 ms-1 ${c.textSecondary}`}>→ {x.grounded_version}</p>}
                  </div>
                ))}
              </div>
            </div>
          )}

          {results?.what_is_unknown?.length > 0 && (
            <div className={`rounded-xl border p-5 ${c.unknown}`}>
              <p className={`text-xs font-bold uppercase tracking-widest ${c.text}`}>? {t('sps_unknown_title')}</p>
              <div className="mt-3 space-y-2">
                {results?.what_is_unknown.map((x, i) => <p key={i} className={`text-sm ${c.text}`}>• {x}</p>)}
              </div>
            </div>
          )}

          {results?.anchor && (
            <div className={`rounded-xl border-2 p-5 ${c.anchorBg}`}>
              <p className={`text-xs font-bold uppercase tracking-widest ${c.textMuted}`}>{t('sps_anchor_title')}</p>
              <p className={`mt-2 text-xl font-bold leading-snug ${c.text}`}>{results?.anchor}</p>
            </div>
          )}

          {results?.next_move?.available && results?.next_move.action && (
            <div className={`${c.card} border ${c.border} rounded-xl p-5`}>
              <p className={`text-xs font-bold uppercase tracking-widest ${c.textMuted}`}>→ {t('sps_next_move_title')}</p>
              <p className={`mt-2 text-base font-semibold ${c.text}`}>{results?.next_move.action}</p>
              {results?.next_move.why && <p className={`mt-2 text-sm ${c.textSecondary}`}>{results?.next_move.why}</p>}
            </div>
          )}

          {results?.after_this && (
            <p className={`text-sm text-center px-4 ${c.textSecondary}`}>{results?.after_this}</p>
          )}

          <div className="flex flex-wrap gap-2 justify-center">
            <button onClick={() => handleReset()} className={`${c.btnSecondary} px-4 py-2 rounded-lg text-sm font-bold`}>{t('sps_try_another')}</button>
          </div>

          <p className={`text-xs text-center ${c.textMuted}`}>
            {t('sps_xref_crash_q')} <a href="/BeforeTheCrash" className={linkStyle}>{t('sps_xref_crash')}</a>
          </p>
        </div>
      ))}
    </div>
  );
};

SpiralStopper.displayName = 'SpiralStopper';
export default SpiralStopper;
