// ═══ Input consistency check (client-side, pre-submit) ═══
// Deliberately narrow: this only flags a HIGH-CONFIDENCE literal mismatch
// between an explicit count-in-a-timeframe or onset phrase in the free-text
// description and the Duration/Frequency selections — the exact failure
// shape the backend's input-integrity pass was written to catch (see
// backend/routes/pet-weirdness-decoder.js). It never tries to reconcile the
// conflict itself: the caller shows it and offers "use what I wrote" /
// "change the selections," nothing automatic in between. False negatives
// (a real conflict this misses) are fine — this is a lightweight nudge, not
// a parser. False positives are not, so every signal here requires an
// explicit, literal phrase, not an inference.
const FREQUENCY_RATE_TIER = {
  'Rare (once a week or less)': 'low',
  Occasionally: 'low',
  'Once or twice a day': 'mid',
  'Multiple times daily': 'high',
  Constant: 'high',
};
const NUMBER_WORDS = { once: 1, one: 1, twice: 2, two: 2, couple: 2, three: 3, four: 4, five: 5, six: 6, seven: 7, 'a few': 3, several: 4 };

// Returns { field, textKind, ... } rather than a rendered sentence — the
// phrase has to be localized, and this module has no i18n access, so the
// component turns this into text via conflictTextPhrase() below.
function detectFieldConflict(behaviorText, duration, frequency) {
  const text = (behaviorText || '').toLowerCase();

  // Signal 1 — an explicit "N times today/this week/last week/this month"
  // count phrase vs. the Frequency selection's implied rate.
  const countMatch = text.match(/\b(once|twice|a few|several|couple|one|two|three|four|five|six|seven|\d+)\s+times?\b[^.!?]{0,25}?\b(today|this week|past week|last week|this month)\b/);
  if (countMatch) {
    const n = NUMBER_WORDS[countMatch[1]] ?? parseInt(countMatch[1], 10);
    const isWeekOrMonth = /week|month/.test(countMatch[2]);
    const impliedTier = isWeekOrMonth ? (n >= 14 ? 'high' : 'low') : (n >= 3 ? 'high' : 'mid');
    const selectedTier = FREQUENCY_RATE_TIER[frequency];
    if (selectedTier && ((impliedTier === 'low' && selectedTier === 'high') || (impliedTier === 'high' && selectedTier === 'low'))) {
      return { field: 'frequency', textKind: 'count', n, timeframeKey: countMatch[2].replace(/\s+/g, '_') };
    }
  }

  // Signal 2 — an explicit onset phrase ("just started") vs. an established-
  // pattern Duration, or the reverse ("for weeks/months/always") vs. "Just
  // started (today)."
  if (/\b(just started|started today|started this morning|first time (this|today)|never (happened|done this) before)\b/.test(text)
      && (duration === 'Weeks' || duration === 'Months' || duration === 'As long as I can remember')) {
    return { field: 'duration', textKind: 'just_started' };
  }
  if (/\b(for weeks|for months|several weeks|several months|always done (this|that)|as long as (i've|i have) had (him|her|them|it))\b/.test(text)
      && duration === 'Just started (today)') {
    return { field: 'duration', textKind: 'long_running' };
  }

  return null;
}

