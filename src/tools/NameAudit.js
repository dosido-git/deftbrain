        lines.push(cand.best_quality ? t('nau_copy_best', { value: cand.best_quality }) : '');
        lines.push(cand.biggest_risk ? t('nau_copy_risk', { value: cand.biggest_risk }) : '');
        lines.push(cand.fit_for_context || '');
        lines.push('');
