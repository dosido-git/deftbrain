  // Nine pills across the top of a form asking "what kind of bill is it?" are
  // eight answers to questions nobody has asked yet. They are follow-up
  // actions, and they now appear as such, under the answer. The full row still
  // renders on every other view, or there is no way back.
  const renderNav = () => (
    <div className="flex flex-wrap gap-1.5 mb-5">
      {[
        { key: 'rescue', label: `🧾 ${t('br_nav_rescue')}` },
        { key: 'quick', label: `⚡ ${t('br_nav_quick')}` },
        { key: 'triage', label: `📊 ${t('br_nav_triage')}` },
        { key: 'rehearse', label: `🎭 ${t('br_nav_rehearse')}` },
        { key: 'letters', label: `✉️ ${t('br_nav_letters')}` },
        { key: 'tracker', label: `📋 ${t('br_nav_tracker')}${savedPlans.length ? ` (${savedPlans.length})` : ''}` },
        { key: 'log', label: `📞 ${t('br_nav_log')}${callLogs.length ? ` (${callLogs.length})` : ''}` },
        { key: 'calendar', label: `📅 ${t('br_nav_calendar')}` },
        { key: 'victories', label: `🏆 ${t('br_nav_wins')}${victories.length ? ` (${totalSaved > 0 ? formatCurrency(totalSaved, userLocale, userCurrency) : victories.length})` : ''}` },
      ].map(tab => (
        <button key={tab.key} onClick={() => { setView(tab.key); setError(''); }}
          className={`px-3 py-1.5 rounded-lg text-xs font-bold border transition-colors min-h-[32px] ${
            view === tab.key ? c.pillActive : c.pillInactive
          }`}>{tab.label}</button>
      ))}
    </div>
  );

