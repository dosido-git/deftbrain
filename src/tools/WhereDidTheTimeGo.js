import React, { useState, useCallback, useRef, useEffect } from 'react';
import { useClaudeAPI } from '../hooks/useClaudeAPI';
import { useTheme } from '../hooks/useTheme';
import { useRegisterActions } from '../components/ActionBarContext';
import { usePersistentState } from '../hooks/usePersistentState';
import { useTranslation } from '../i18n/useTranslation';
import { pickExample } from '../utils/exampleRotation';
import { revealSection } from '../utils/revealSection';

const BRAND = '\n\n— Generated by DeftBrain · deftbrain.com';

// id stays stable (sent to backend + stored in copy text); labelKey resolves
// to the localized pill label at render time.
const TIMEFRAME_OPTIONS = [
  { id: 'today',             labelKey: 'wdttg_tf_today' },
  { id: 'yesterday',         labelKey: 'wdttg_tf_yesterday' },
  { id: 'this week',         labelKey: 'wdttg_tf_this_week' },
  { id: 'this past weekend', labelKey: 'wdttg_tf_weekend' },
];

const EXAMPLES = [
  {
    dayDescription: "Got up at 7:30, spent 30 min on phone in bed. Shower and breakfast ~45 min. Sat down to work at 9am. Had a 10am call that ran to 11:30. Tried to get back into a doc but kept checking Slack. Lunch 30 min at my desk. More Slack, a few emails, a 2pm call for an hour. Meant to deep-work 3-5 but it felt fragmented. Closed laptop at 6. Dinner, TV, scrolling. Bed midnight.",
    perceivedBreakdown: "I feel like I worked 8 solid hours but I honestly couldn't tell you what I produced",
    timeframe: 'today',
  },
  {
    dayDescription: "Woke up around 9 since I didn't set an alarm. Made coffee, sat on the porch for a while just thinking. Ran two errands — bank and pharmacy, maybe an hour total with driving. Napped for what I thought was 20 minutes but it was almost 2 hours. Cooked dinner, which took forever because I kept getting distracted. Watched three episodes of a show I don't even really like. In bed by 11 but scrolled until 1am.",
    perceivedBreakdown: "I feel like I did nothing all day, but I was also never actually sitting still doing nothing — every hour had something in it",
    timeframe: 'yesterday',
  },
  {
    dayDescription: "Worked Monday through Friday, roughly 9-6 each day, but at least two of those days had a 'wasted' afternoon where I was technically at my desk but not really working. Went to the gym twice instead of my usual four times. Had dinner with a friend Wednesday, cancelled plans Thursday because I was too tired. Weekend errands somehow ran over into Monday morning. Can't point to one big thing I accomplished outside of my actual job.",
    perceivedBreakdown: "I feel like the whole week disappeared and I have nothing to show for the parts that weren't work",
    timeframe: 'this week',
  },
  {
    dayDescription: "Saturday: slept in, meant to clean the apartment, ended up doing about 20% of it before getting distracted by a project I wasn't even planning to start. Went out for dinner with friends, out until 1am. Sunday: recovery day, didn't leave the house until 4pm, ran the one errand I needed to, meal-prepped for maybe an hour, rest was TV and dreading Monday.",
    perceivedBreakdown: "I feel like I need a weekend to recover from my weekend",
    timeframe: 'this past weekend',
  },
  {
    dayDescription: "Up at 6am with the kids, breakfast and getting everyone dressed took until 8. School drop-off and back by 9. Tried to do a work call from home but got interrupted twice by the daycare calling about the toddler's fever. Picked up my sick kid at 11, rest of the day was doctor's office, pharmacy, and comforting a cranky toddler. Managed maybe 40 minutes of actual work squeezed into naptime. Dinner, bath, bedtime routine took until 8pm. Collapsed on the couch after.",
    perceivedBreakdown: "I feel like I was busy every single second but got almost none of my actual job done",
    timeframe: 'today',
  },
];
const WhereDidTheTimeGo = ({ tool }) => {
  const { callToolEndpoint, loading, userLocale, userCurrency, userRegion } = useClaudeAPI();
  const { isDark } = useTheme();
  const { t } = useTranslation();
  // Localized label for the currently-selected timeframe (id stays stable).
  const timeframeLabel = (id) => {
    const opt = TIMEFRAME_OPTIONS.find(o => o.id === id);
    return opt ? t(opt.labelKey) : id;
  };
  const loadExample = () => {
    const ex = pickExample('WhereDidTheTimeGo', EXAMPLES);
    setDayDescription(ex.dayDescription);
    setPerceivedBreakdown(ex.perceivedBreakdown);
    setTimeframe(ex.timeframe);
  };

  const resultsRef = useRef(null);

  // ─── Colors: Crimson family (Me) ───
  const c = {
    card:              isDark ? 'bg-zinc-800' : 'bg-white',
    cardAlt:           isDark ? 'bg-zinc-700/50' : 'bg-slate-50',
    input:             isDark ? 'bg-zinc-900 border-zinc-600 text-zinc-100 placeholder-zinc-400 focus:border-cyan-500 focus:ring-cyan-500/20' : 'bg-white border-gray-300 text-gray-900 placeholder-gray-400 focus:border-cyan-500 focus:ring-cyan-100',
    text:              isDark ? 'text-zinc-50' : 'text-gray-900',
    textSecondary:     isDark ? 'text-zinc-300' : 'text-gray-600',
    textMuted:         isDark ? 'text-zinc-400' : 'text-gray-500',
    required:      isDark ? 'text-amber-400' : 'text-amber-700',
    accentTxt:         isDark ? 'text-cyan-400' : 'text-cyan-600',
    btnPrimary:        isDark ? 'bg-cyan-600 hover:bg-cyan-500 text-white' : 'bg-cyan-600 hover:bg-cyan-700 text-white',
    // Waiting for input: an outline, not a smudge. Empty fill keeps "filled"
    // meaning "ready"; the border and label carry the visibility. Important
    // modifiers because tools carry their own border/text utilities on the
    // submit and Tailwind resolves conflicts by stylesheet order, not class
    // order. See the PF-13 exception in audit/audit_v2-3-2.py.
    btnIdle:       isDark ? '!bg-transparent !border-2 !border-cyan-500/85 !text-cyan-300 cursor-not-allowed'
                          : '!bg-transparent !border-2 !border-cyan-600/85 !text-cyan-800 cursor-not-allowed',
    btnSecondary:      isDark ? 'bg-zinc-700 hover:bg-zinc-600 text-zinc-200' : 'bg-gray-100 hover:bg-gray-200 text-gray-700',
    border:            isDark ? 'border-zinc-700' : 'border-gray-200',
    success:           isDark ? 'bg-emerald-900/20 border-emerald-600 text-emerald-300' : 'bg-emerald-50 border-emerald-600 text-emerald-700',
    warning:           isDark ? 'bg-amber-900/20 border-amber-700 text-amber-200' : 'bg-amber-100 border-amber-300 text-amber-800',
    danger:            isDark ? 'bg-red-900/20 border-red-700 text-red-200' : 'bg-red-100 border-red-200 text-red-800',
    pillActive:        isDark ? 'border-cyan-500 bg-cyan-900/30 text-cyan-200' : 'border-cyan-600 bg-cyan-100 text-cyan-900',
    pillInactive:      isDark ? 'border-zinc-600 text-zinc-400 hover:border-zinc-500' : 'border-gray-300 text-gray-500 hover:border-gray-400',
    // Category panel tints — Crimson family (Me)
    panelTint:         isDark ? 'bg-[#7a2e2e]/30' : 'bg-[#f5eaea]',
    panelTintBorder:   isDark ? 'border-[#9a4040]' : 'border-[#d4a0a0]',
    // Gold AI insight — all tools
    panelInsight:       isDark ? 'bg-[#93541f]/25' : 'bg-[#fdf4e8]',
    panelInsightBorder: isDark ? 'border-[#c8872e]' : 'border-[#e8c98a]',
    // Tool-specific
    goldText:          isDark ? 'text-amber-300' : 'text-amber-700',
    labelText:         isDark ? 'text-zinc-200' : 'text-gray-700',
  };
  c.textMuteded = c.textMuted;
  c.label = c.labelText;

  // Icon fallback uses Unicode escape so the literal hourglass glyph never
  // appears in source — audit S0 forbids the hourglass-flow emoji as a
  // hardcoded loading spinner, but tools.js legitimately uses it as this
  // tool's icon. Resolves the S0 / S0f conflict.
  const ICON_FALLBACK = '\u23F3';

  // ─── State ───
  const [dayDescription, setDayDescription] = useState('');
  const [perceivedBreakdown, setPerceivedBreakdown] = useState('');
  const [timeframe, setTimeframe] = useState('today');
  const [results, setResults] = usePersistentState('wheredidthetimego-result-v2', null);
  const [error, setError] = useState('');
  // Recent Sessions stores the full result (not a truncated preview: field) so
  // a click can restore the complete reconstruction and original input, and
  // so the label shown is the model's neutral session_label, never a raw
  // fragment of what the user typed.
  const [sessionHistory, setSessionHistory] = usePersistentState('wheredidthetimego-history-v2', []);

  // ─── Handlers ───
  const handleSubmit = useCallback(async () => {
    if (!dayDescription.trim()) return;
    setError('');
    setResults(null);

    try {
      const res = await callToolEndpoint('where-did-the-time-go', {
        dayDescription: dayDescription.trim(),
        perceivedBreakdown: perceivedBreakdown.trim() || undefined,
        timeframe,
        userLocale, userCurrency, userRegion,
      });
      setResults(res);
      setSessionHistory(prev => [{
        id: Date.now(), date: new Date().toISOString(),
        timeframe, dayDescription: dayDescription.trim(), perceivedBreakdown: perceivedBreakdown.trim(), results: res,
      }, ...prev].slice(0, 6));
    } catch (err) {
      setError(err.message || t('wdttg_error'));
    } }, [dayDescription, perceivedBreakdown, timeframe, callToolEndpoint, setResults, setSessionHistory, userLocale, userCurrency, userRegion, t]);

  const handleReset = () => {
    setDayDescription('');
    setPerceivedBreakdown('');
    setResults(null);
    setError('');
  };

  const restoreSession = (entry) => {
    setDayDescription(entry.dayDescription || '');
    setPerceivedBreakdown(entry.perceivedBreakdown || '');
    setTimeframe(entry.timeframe || 'today');
    setResults(entry.results || null);
  };

  // ─── Keyboard: SELECT-only guard, ref pattern ───
  const handleSubmitRef = useRef(null);
  const canSubmitRef = useRef(false);
  handleSubmitRef.current = handleSubmit;
  canSubmitRef.current = !loading;

  useEffect(() => {
    const handler = (e) => {
      const tag = document.activeElement?.tagName;
      if (tag === 'SELECT') return;
      if (e.key === 'Enter' && (e.metaKey || e.ctrlKey) && !loading && canSubmitRef.current) {
        e.preventDefault();
        handleSubmitRef.current?.();
      }
    };
    document.addEventListener('keydown', handler);
    return () => document.removeEventListener('keydown', handler);
  }, [loading]);

  // ─── Scroll to results ───
  useEffect(() => {
    if (!results) return;
    const timer = setTimeout(() => revealSection(resultsRef.current), 250);
    return () => clearTimeout(timer);
  }, [results]);

  // ─── Build copy text ───
  const buildFullText = useCallback(() => {
    if (!results) return '';
    const r = results;
    let txt = `${t('wdttg_copy_header')}\n${t('wdttg_copy_timeframe')} ${timeframeLabel(timeframe)}\n\n`;

    if (r.the_day_you_described?.length) {
      txt += `━━ ${t('wdttg_copy_the_day')} ━━\n\n`;
      r.the_day_you_described.forEach(b => {
        txt += `${b.time} — ${b.note}\n`;
      });
      txt += '\n';
    } if (r.what_stands_out?.length) {
      txt += `━━ ${t('wdttg_copy_stands_out')} ━━\n\n`;
      r.what_stands_out.forEach(o => { txt += `${o}\n`; });
      txt += '\n';
    } if (r.the_biggest_mismatch) {
      txt += `━━ ${t('wdttg_copy_biggest_mismatch')} ━━\n${r.the_biggest_mismatch}\n\n`;
    } if (r.whats_still_unclear) {
      txt += `━━ ${t('wdttg_copy_still_unclear')} ━━\n${r.whats_still_unclear}\n\n`;
    } if (r.try_this_next_time) {
      txt += `━━ ${t('wdttg_copy_try_this')} ━━\n${r.try_this_next_time}\n\n`;
    }

    txt += BRAND;
    return txt;
  // timeframeLabel is a stable closure over t; t covers its localization.
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [results, timeframe, t]);

  // Register export content with wrapper ActionBar
  useRegisterActions(buildFullText(), tool?.title || 'Where Did the Time Go?');

  // ─── Render ───
  return (<div className={`space-y-4 ${c.text}`}>

        {/* Header — always rendered so the one reset button survives into the
            results phase (PF-16: exactly one reset, never two). */}
        <div className={`${c.card} ${c.border} border rounded-2xl p-6 shadow-sm ${!results ? 'space-y-5' : ''}`}>
          <div className={`${!results ? 'mb-4 pb-3 border-b' : 'pb-3 border-b'} ${c.border}`}>
            <div className="flex items-start justify-between gap-3">
              <div>
                {/* PF-30 — the wrapper already prints the name as the page <h1>. */}
                <p className={`text-base ${c.textSecondary}`}>
                  <span className="me-2 text-xl">{tool?.icon}</span>{tool?.tagline ?? t('wdttg_tagline')}
                </p>
                {!results && (
                  <button onClick={loadExample} disabled={loading} style={{ backgroundColor: (tool?.headerColor ?? '#888888') + '80' }} className="mt-2 px-4 py-2 rounded-full text-sm font-semibold border border-black/25 text-zinc-900 shadow-sm hover:brightness-105 hover:shadow transition disabled:opacity-40 whitespace-nowrap">✨ {t('try_example')}</button>
                )}
              </div>
              {/* PF-16: the tool's one reset, on the title row, from the first keystroke. */}
              {(results || dayDescription.trim() || perceivedBreakdown.trim()) ? (
                <button onClick={handleReset} className={`${c.btnSecondary} px-3 py-1.5 rounded-lg text-xs font-semibold flex-shrink-0 whitespace-nowrap`}>
                  ↺ {t('start_over')}
                </button>
              ) : null}
            </div>
          </div>

          {/* Form */} {!results && (<div className="space-y-5">
            {/* Timeframe */} <div className="space-y-2">
              <label className={`text-sm font-semibold ${c.text}`}>{t('wdttg_timeframe')}</label>
              <div className="flex gap-2">
                {TIMEFRAME_OPTIONS.map(opt => (<button
                    key={opt.id} onClick={() => setTimeframe(opt.id)} className={`flex-1 ${timeframe === opt.id ? c.pillActive : c.pillInactive} border rounded-xl py-2 text-sm font-medium text-center transition-all duration-150`} >
                    {t(opt.labelKey)} </button>
                ))} </div>
            </div>

            {/* Day description */} <div className="space-y-2">
              <label className={`text-sm font-semibold ${c.text}`}>
                <span className="me-1.5">📋</span> {t('wdttg_day_q', { tf: timeframeLabel(timeframe) })} <span className={c.required}>*</span>
              </label>
              <textarea
                value={dayDescription} onChange={(e) => setDayDescription(e.target.value)} placeholder={t('wdttg_day_ph')} rows={5} maxLength={1000} className={`w-full px-4 py-3 rounded-xl text-sm ${c.input} ${c.border} border ${c.text} resize-y outline-none transition-colors`} />
            </div>

            {/* Felt discrepancy */} <div className="space-y-2">
              <label className={`text-sm font-semibold ${c.text}`}>
                <span className="me-1.5">🤔</span> {t('wdttg_perceived_q')} <span className={`font-normal ${c.textMuted}`}>{t('wdttg_perceived_hint')}</span>
              </label>
              <textarea
                value={perceivedBreakdown} onChange={(e) => setPerceivedBreakdown(e.target.value)} placeholder={t('wdttg_perceived_ph')}
                rows={2} maxLength={400} className={`w-full px-4 py-3 rounded-xl text-sm ${c.input} ${c.border} border ${c.text} resize-y outline-none transition-colors`} />
            </div>

            {/* Submit */} <button title={t('cmd_enter')}
              onClick={handleSubmit} disabled={loading || !dayDescription.trim()} className={`relative w-full ${loading || dayDescription.trim() ? c.btnPrimary : c.btnIdle} py-3 rounded-xl font-semibold text-sm shadow-md
                disabled:cursor-not-allowed transition-all duration-200 flex items-center justify-center gap-2`} >
              {loading ? (<>
                  <span className="inline-block animate-spin !text-white text-xl">{tool?.icon ?? ICON_FALLBACK}</span>
                  <span className="!text-white">{t('wdttg_tracing')}</span>
                </>
              ) : (<>
                  <span className="text-xl">{tool?.icon ?? ICON_FALLBACK}</span> {t('wdttg_submit')}
                </>
              )} {!loading && (
                             <kbd aria-hidden="true"
                               className="hidden sm:flex items-center absolute end-3 top-1/2 -translate-y-1/2 px-1.5 py-0.5 rounded border border-white/30 bg-white/15 text-[10px] font-bold tracking-wide">
                               ⌘↵
                             </kbd>
                           )}
                           </button>
          </div>
          )}
        </div>
        {/* Error */} {error && (<div className={`${c.danger} border rounded-xl p-4 text-sm flex items-center gap-2`}>
            <span>⚠️</span> {error} </div>
        )}

        {/* Results */} {results && (<div data-copy-results ref={resultsRef} data-results-anchor className="scroll-mt-24 space-y-5">

            {/* The day you described */} {results?.the_day_you_described?.length > 0 && (<div className={`${c.card} ${c.border} border rounded-2xl p-5`}>
                <h3 className={`font-bold ${c.text} flex items-center gap-2 mb-4`}>
                  <span>📊</span> {t('wdttg_the_day')}
                </h3>
                <div className="space-y-2">
                  {results?.the_day_you_described.map((b, i) => (<div key={i} className={`${c.cardAlt} ${c.border} border rounded-xl p-3 flex items-baseline gap-3`}>
                      <span className={`text-xs font-bold ${c.goldText} flex-shrink-0 whitespace-nowrap`}>{b.time}</span>
                      <span className={`text-sm ${c.text}`}>{b.note}</span>
                    </div>
                  ))} </div>
              </div>
            )} {/* What stands out */} {results?.what_stands_out?.length > 0 && (<div className={`${c.panelTint} border ${c.panelTintBorder} rounded-2xl p-5`}>
                <p className={`text-xs font-semibold uppercase tracking-wider ${c.goldText} mb-3 flex items-center gap-1.5`}>
                  <span>🔍</span> {t('wdttg_stands_out')}
                </p>
                <div className="space-y-2">
                  {results?.what_stands_out.map((o, i) => (<p key={i} className={`text-sm ${c.text} leading-relaxed`}>→ {o}</p>
                  ))} </div>
              </div>
            )} {/* The biggest mismatch */} {results?.the_biggest_mismatch && (<div className={`${c.cardAlt} ${c.border} border rounded-xl p-4`}>
                <p className={`text-xs font-semibold uppercase tracking-wider ${c.textMuted} mb-2`}>{t('wdttg_biggest_mismatch')}</p>
                <p className={`text-sm ${c.text} leading-relaxed`}>
                  {results?.the_biggest_mismatch} </p>
              </div>
            )} {/* What's still unclear */} {results?.whats_still_unclear && (<div className={`${c.cardAlt} ${c.border} border rounded-xl p-4`}>
                <p className={`text-xs font-semibold uppercase tracking-wider ${c.textMuted} mb-2 flex items-center gap-1.5`}>
                  <span>🌫️</span> {t('wdttg_still_unclear')}
                </p>
                <p className={`text-sm ${c.text} leading-relaxed`}>
                  {results?.whats_still_unclear} </p>
              </div>
            )} {/* Try this next time — Gold AI insight panel */} {results?.try_this_next_time && (<div className={`${c.panelInsight} border ${c.panelInsightBorder} rounded-2xl p-6`}>
                <p className={`text-xs font-semibold uppercase tracking-wider ${c.accentTxt} mb-3 text-center`}>
                  {t('wdttg_try_this')}
                </p>
                <p className={`text-sm ${c.text} text-center leading-relaxed`}>
                  {results?.try_this_next_time} </p>
              </div>
            )}
          </div>
        )} {/* History */} {sessionHistory.length > 0 && (<div className={`${c.cardAlt} border ${c.border} rounded-xl p-4`}>
            <p className={`text-xs font-bold ${c.textMuted} mb-2`}>📋 {t('wdttg_recent_sessions')}</p>
            <div className="space-y-1">
              {sessionHistory.map(s => (<button key={s.id} onClick={() => restoreSession(s)} className="w-full flex items-center justify-between text-start hover:opacity-80">
                  <span className="min-w-0">
                    <span className={`block text-xs ${c.textSecondary} truncate`}>{s.results?.session_label || t('wdttg_session')}</span>
                    {s.results?.session_tags?.length > 0 && (
                      <span className={`block text-[10px] ${c.textMuted} truncate`}>{s.results.session_tags.slice(0, 3).join(' · ')}</span>
                    )}
                  </span>
                  <span className={`text-xs ${c.textMuted} ms-2 flex-shrink-0`}>{new Date(s.date).toLocaleDateString()}</span>
                </button>
              ))} </div>
          </div>
        )}
    </div>
  );
};

WhereDidTheTimeGo.displayName = 'WhereDidTheTimeGo';
export default WhereDidTheTimeGo;
