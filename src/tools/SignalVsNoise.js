// Results saved before 2026-10-27 have Signal / Noise / Still worth verifying
// sections; they open in today's shape: a verdict and one assessment per claim.
function adaptResult(r) {
  if (!r || Array.isArray(r.claims) || !(r.the_signal || r.the_noise || r.still_worth_verifying)) return r;
  const claims = [
    ...(r.the_signal?.items || []).map(x => ({ claim: x.claim, assessment: 'supported', finding: x.basis, limitation: x.limits || null, source_ids: x.source_ids || [] })),
    ...(r.the_noise || []).map(x => ({ claim: x.claim, assessment: 'overstated', finding: x.what_the_evidence_supports_instead, limitation: x.what_went_wrong || null, source_ids: x.source_ids || [] })),
    ...(r.still_worth_verifying || []).map(x => ({ claim: x.question, assessment: 'unresolved', finding: x.why_it_matters, limitation: x.what_would_help || null, source_ids: x.source_ids || [] })),
  ].filter(x => x.claim && x.finding);
  return { ...r, verdict: r.framing, claims };
}

