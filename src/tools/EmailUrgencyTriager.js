function splitEmailBlocks(raw) {
  return String(raw || '')
    .split(/\n\s*---+\s*\n/g)
    .map(x => x.trim())
    .filter(Boolean);
}

function subjectFromBlock(block) {
  const subject = block.match(/^Subject:\s*(.+)$/im)?.[1]?.trim() || '';
  const from = block.match(/^From:\s*(.+)$/im)?.[1]?.trim() || '';
  return { subject, from };
}

function findOriginalBlock(raw, email) {
  const blocks = splitEmailBlocks(raw);
  const targetSubject = String(email?.email_subject || '').trim().toLowerCase();
  const targetFrom = String(email?.from || '').trim().toLowerCase();

  const exact = blocks.find(block => {
    const h = subjectFromBlock(block);
    return (
      (!targetSubject || h.subject.toLowerCase() === targetSubject) &&
      (!targetFrom || h.from.toLowerCase().includes(targetFrom) || targetFrom.includes(h.from.toLowerCase()))
    );
  });
  if (exact) return exact;

  const bySubject = blocks.find(block => {
    const h = subjectFromBlock(block);
    return targetSubject && h.subject.toLowerCase() === targetSubject;
  });
  return bySubject || '';
}

function normalizeTier(v) {
  const s = String(v || '').toLowerCase().replace(/\s+/g, '_');
  if (['now', 'today', 'urgent'].includes(s)) return 'now';
  if (['this_week', 'week'].includes(s)) return 'this_week';
  return 'optional';
}

