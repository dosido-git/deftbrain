import Caret from '../components/Caret';
import { CopyBtn } from '../components/ActionButtons';
import React, { useState, useCallback, useRef, useEffect } from 'react';
import { useRegisterActions } from '../components/ActionBarContext';
import { useClaudeAPI } from '../hooks/useClaudeAPI';
import { useTheme } from '../hooks/useTheme';
import { usePersistentState } from '../hooks/usePersistentState';
import { useTranslation } from '../i18n/useTranslation';
import { pickExample } from '../utils/exampleRotation';

const BRAND = '\n\n— Generated by DeftBrain · deftbrain.com';

// ════════════════════════════════════════════════════════════
// MAIN COMPONENT
// ════════════════════════════════════════════════════════════
const ColdOpenCraft = ({ tool }) => {
  const { callToolEndpoint, loading, userLocale, userCurrency, userRegion } = useClaudeAPI();
  const { isDark } = useTheme();
  const { t } = useTranslation();

  // Channel options (labels localized via t()).
  const CHANNELS = [
    { value: 'email',        label: t('coc_ch_email'),     emoji: '📧' },
    { value: 'linkedin',     label: t('coc_ch_linkedin'),  emoji: '💼' },
    { value: 'twitter_dm',   label: t('coc_ch_twitter'),   emoji: '🐦' },
    { value: 'instagram_dm', label: t('coc_ch_instagram'), emoji: '📸' },
    { value: 'text',         label: t('coc_ch_text'),      emoji: '💬' },
  ];



  const c = {
    card:          isDark ? 'bg-zinc-800' : 'bg-white',
    cardAlt:       isDark ? 'bg-zinc-700/50' : 'bg-slate-50',
    input:         isDark ? 'bg-zinc-900 border-zinc-600 text-zinc-100 placeholder-zinc-400 focus:border-cyan-500 focus:ring-cyan-500/20' : 'bg-white border-gray-300 text-gray-900 placeholder-gray-400 focus:border-cyan-500 focus:ring-cyan-100',
    text:          isDark ? 'text-zinc-50' : 'text-gray-900',
    textSecondary: isDark ? 'text-zinc-300' : 'text-gray-600',
    textMuted:     isDark ? 'text-zinc-400' : 'text-gray-500',
    required:      isDark ? 'text-amber-400' : 'text-amber-700',
    labelText:     isDark ? 'text-zinc-200' : 'text-gray-700',
    accentTxt:     isDark ? 'text-cyan-400' : 'text-cyan-600',
    btnPrimary:    isDark ? 'bg-cyan-600 hover:bg-cyan-500 text-white' : 'bg-cyan-600 hover:bg-cyan-700 text-white',
    // Waiting for input: an outline, not a smudge. Empty fill keeps "filled"
    // meaning "ready"; the border and label carry the visibility. Important
    // modifiers because tools carry their own border/text utilities on the
    // submit and Tailwind resolves conflicts by stylesheet order, not class
    // order. See the PF-13 exception in audit/audit_v2-3-2.py.
    btnIdle:       isDark ? '!bg-transparent !border-2 !border-cyan-500/85 !text-cyan-300 cursor-not-allowed'
                          : '!bg-transparent !border-2 !border-cyan-600/85 !text-cyan-800 cursor-not-allowed',
    btnSecondary:  isDark ? 'bg-zinc-700 hover:bg-zinc-600 text-zinc-200' : 'bg-gray-100 hover:bg-gray-200 text-gray-700',
    border:        isDark ? 'border-zinc-700' : 'border-gray-200',
    success:       isDark ? 'bg-emerald-900/20 border-emerald-700 text-emerald-200' : 'bg-emerald-50 border-emerald-300 text-emerald-800',
    warning:       isDark ? 'bg-amber-900/20 border-amber-700 text-amber-200' : 'bg-amber-50 border-amber-300 text-amber-800',
    danger:        isDark ? 'bg-red-900/20 border-red-700 text-red-200' : 'bg-red-50 border-red-200 text-red-800',
    pillActive:    isDark ? 'border-cyan-500 bg-cyan-900/30 text-cyan-200' : 'border-cyan-600 bg-cyan-100 text-cyan-900',
    pillInactive:  isDark ? 'border-zinc-600 text-zinc-400 hover:border-zinc-500' : 'border-gray-300 text-gray-500 hover:border-gray-400',
  };
  c.textMuteded = c.textMuted;
  c.label = c.labelText;

  // ── Persisted state ──

  const [error, setError] = useState('');
  const [who,             setWho]             = usePersistentState('cold-open-craft-who', '');
  const [why,             setWhy]             = usePersistentState('cold-open-craft-why', '');
  const [channel,         setChannel]         = usePersistentState('cold-open-craft-channel', 'email');
  const [whatYouKnow,     setWhatYouKnow]     = usePersistentState('cold-open-craft-know', '');
  const [yourBackground,  setYourBackground]  = usePersistentState('cold-open-craft-bg', '');
  const [results,         setResults]         = usePersistentState('cold-open-craft-results', null);
  const [sessionHistory,         setSessionHistory]         = usePersistentState('cold-open-craft-history', []);
  const resultsRef = useRef(null);

  // ── Document-level Ctrl+Enter submit ──
  useEffect(() => {
    const handler = (e) => {
      if ((e.ctrlKey || e.metaKey) && e.key === 'Enter') {
        e.preventDefault();
        if (!loading && who.trim() && why.trim()) generate();
      }
    };
    document.addEventListener('keydown', handler);
    return () => document.removeEventListener('keydown', handler);
  }); // eslint-disable-line react-hooks/exhaustive-deps

  // ── Actions ──
  const generate = useCallback(async () => {
    if (!who.trim() || !why.trim()) return;
    setError('');
    setResults(null);
    try {
      const data = await callToolEndpoint('cold-open-craft', {
        who: who.trim(),
        why: why.trim(),
        channel,
        whatYouKnow: whatYouKnow.trim() || null,
        yourBackground: yourBackground.trim() || null,
        userLocale, userCurrency, userRegion,
      });
      setResults(data);
      const entry = {
        id: Date.now(),
        timestamp: new Date().toISOString(),
        preview: who.trim().slice(0, 40),
        result: data,
      };
      setSessionHistory(prev => [entry, ...prev].slice(0, 6));
    } catch (err) {
      setError(err.message || t('coc_error'));
    }
  }, [who, why, channel, whatYouKnow, yourBackground, callToolEndpoint, userLocale, userCurrency, userRegion, t]); // eslint-disable-line react-hooks/exhaustive-deps

  const loadExample = useCallback(() => {
    const ex = pickExample('ColdOpenCraft', [
      { n: '',  channel: 'email' },
      { n: '2', channel: 'email' },
    ]);
    const k = f => `coc_ex${ex.n}_${f}`;
    setWho(t(k('who')));
    setWhy(t(k('why')));
    setChannel(ex.channel);
    setWhatYouKnow(t(k('know')));
    setYourBackground(t(k('bg')));
    setResults(null);
  }, [setWho, setWhy, setChannel, setWhatYouKnow, setYourBackground, setResults, t]);

  const handleReset = useCallback(() => {
    setWho(''); setWhy(''); setChannel('email'); setWhatYouKnow('');
    setYourBackground(''); setResults(null); setError('');
  }, []); // eslint-disable-line react-hooks/exhaustive-deps

  // ── Build copy text ──
  const buildFullText = useCallback(() => {
    if (!results) return '';
    const r = results;
    let text = `📬 ${t('coc_copy_header')}\n${t('coc_copy_reaching')} ${who}\n`;
    if (r.situation_read) text += `\n${r.situation_read}\n`;
    if (r.subject_line) text += `\n${t('coc_copy_subject')} ${r.subject_line}\n`;
    if (r.openers?.length) {
      r.openers.forEach(o => { text += `\n--- ${o.label} ---\n${o.message}\n`; });
    }
    if (r.before_you_send) text += `\n${t('coc_before_send')} ${r.before_you_send}\n`;
    if (r.follow_up?.message) {
      text += `\n${t('coc_copy_followup')}\n${r.follow_up.message}\n`;
      if (r.follow_up.timing) text += `${r.follow_up.timing}\n`;
    }
    return text + BRAND;
  }, [results, who, t]);

  useRegisterActions(buildFullText(), tool?.title || 'Cold Open Craft');


  const r = results;

  // ════════════════════════════════════════════════════════════
  // RENDER
  // ════════════════════════════════════════════════════════════
  return (
    <div className={`space-y-4 ${c.text}`}>

      {/* ── INPUT CARD ── */}
      <div className={`${c.card} border ${c.border} rounded-xl shadow-sm px-5 pt-2.5 pb-5`}>
        {/* Standard header */}
        <div className="mb-4 pb-3 border-b border-zinc-500">
          <div className="flex items-center justify-between">
            <div>
              {/* PF-30 — the wrapper already prints the name as the page <h1>. */}
              <p className={`text-base ${c.textSecondary}`}>
                <span className="me-2 text-lg">{tool?.icon ?? '📬'}</span>{t('coc_tagline')}
              </p>
              <button onClick={loadExample} disabled={loading} style={{ backgroundColor: (tool?.headerColor ?? '#888888') + '80' }} className="mt-2 px-4 py-2 rounded-full text-sm font-semibold border border-black/25 text-zinc-900 shadow-sm hover:brightness-105 hover:shadow transition disabled:opacity-40 whitespace-nowrap">✨ {t('try_example')}</button>
            </div>
            {(results || who.trim() || why.trim()) && (
              <button onClick={handleReset} className={`${c.btnSecondary} px-3 py-1.5 rounded-lg text-xs`}>
                ↺ {t('start_over')}
              </button>
            )}
          </div>
        </div>

        <div className="space-y-4">
          {/* Who */}
          <div>
            <label className={`text-sm font-bold ${c.text} block mb-1.5`}>
              {t('coc_who_label')} <span className={c.required}>*</span>
            </label>
            <input
              type="text"
              value={who}
              onChange={e => setWho(e.target.value)}
              placeholder={t('coc_who_ph')}
              className={`w-full px-4 py-3 border rounded-xl text-sm focus:outline-none transition-colors ${c.input}`}
            />
          </div>

          {/* Why */}
          <div>
            <label className={`text-sm font-bold ${c.text} block mb-1.5`}>
              {t('coc_why_label')} <span className={c.required}>*</span>
            </label>
            <textarea
              value={why}
              onChange={e => setWhy(e.target.value)}
              placeholder={t('coc_why_ph')}
              rows={2}
              className={`w-full px-4 py-3 border rounded-xl text-sm focus:outline-none transition-colors resize-none ${c.input}`}
            />
            <p className={`text-xs ${c.textMuteded} mt-1`}>{t('coc_ctrl_enter')}</p>
          </div>

          {/* Channel */}
          <div>
            <label className={`text-sm font-bold ${c.text} block mb-2`}>{t('coc_channel_label')}</label>
            <div className="grid grid-cols-2 sm:grid-cols-3 gap-2">
              {CHANNELS.map(ch => (
                <button
                  key={ch.value}
                  onClick={() => setChannel(ch.value)}
                  className={`w-full px-3 py-2.5 rounded-xl text-sm font-bold border transition-colors min-h-[44px] ${
                    channel === ch.value ? c.pillActive : c.pillInactive
                  }`}
                >
                  {ch.emoji} {ch.label}
                </button>
              ))}
            </div>
          </div>

          {/* What you know */}
          <div>
            <label className={`text-sm font-bold ${c.text} block mb-1.5`}>
              {t('coc_know_label')}{' '}
              <span className={`font-normal ${c.textMuteded}`}>{t('coc_know_note')}</span>
            </label>
            <input
              type="text"
              value={whatYouKnow}
              onChange={e => setWhatYouKnow(e.target.value)}
              placeholder={t('coc_know_ph')}
              className={`w-full px-4 py-3 border rounded-xl text-sm focus:outline-none transition-colors ${c.input}`}
            />
          </div>

          {/* What should they know about you — deliberately not "your
              background", which invites a CV and gives the model far more
              material than the opener can use well. */}
          <div>
            <label className={`text-sm font-bold ${c.text} block mb-1`}>
              {t('coc_bg_label')} <span className={`font-normal ${c.textMuteded}`}>{t('coc_bg_note')}</span>
            </label>
            <p className={`text-xs ${c.textMuteded} mb-1.5`}>{t('coc_bg_hint')}</p>
            <input
              type="text"
              value={yourBackground}
              onChange={e => setYourBackground(e.target.value)}
              placeholder={t('coc_bg_ph')}
              className={`w-full px-4 py-3 border rounded-xl text-sm focus:outline-none transition-colors ${c.input}`}
            />
          </div>


          {error && (
            <div className={`${c.danger} border rounded-xl p-4 flex items-start gap-3`}>
              <span className="flex-shrink-0">⚠️</span>
              <p className="text-sm">{error}</p>
            </div>
          )}

          {/* Submit */}
          <button title={t('cmd_enter')}
          onClick={generate}
          disabled={loading || !who.trim() || !why.trim()}
          className={`relative w-full ${(!who.trim() || !why.trim()) ? c.btnIdle : c.btnPrimary} disabled:cursor-not-allowed font-bold py-3 px-6 rounded-xl flex items-center justify-center gap-2 min-h-[48px] transition-colors`}
          >
          {loading
            ? <><span className="animate-spin inline-block">{tool?.icon ?? '📬'}</span> {t('coc_crafting')}</>
            : <><span>{tool?.icon ?? '📬'}</span> {t('coc_craft')}</>}
          {!loading && (
            <kbd aria-hidden="true"
              className="hidden sm:flex items-center absolute end-3 top-1/2 -translate-y-1/2 px-1.5 py-0.5 rounded border border-white/30 bg-white/15 text-[10px] font-bold tracking-wide">
              ⌘↵
            </kbd>
          )}
          </button>
        </div>
      </div>

      {/* ── HISTORY ── */}
      {/* Collapsed: it was the next major block under the form, competing with
          the thing the visitor came to do. */}
      {sessionHistory.length > 0 && !results && (
        <details className={`group ${c.card} rounded-xl border ${c.border} p-4`}>
          <summary className="cursor-pointer list-none [&::-webkit-details-marker]:hidden">
            <div className={`flex items-center gap-2 text-sm font-bold ${c.text}`}>
              🕐 {t('coc_recent')}
              <Caret groupOpen className="ms-auto" />
            </div>
          </summary>
          <div className="space-y-1.5 mt-3">
            {sessionHistory.map(entry => (
              <button
                key={entry.id}
                onClick={() => setResults(entry.result)}
                className={`w-full text-start px-3 py-2 rounded-lg ${c.btnSecondary} text-xs`}
              >
                <span className={c.textMuteded}>
                  {new Date(entry.timestamp).toLocaleDateString(undefined, { month: 'short', day: 'numeric', hour: 'numeric', minute: '2-digit' })}
                </span>
                <span className={`ms-2 ${c.text}`}>{entry.preview}…</span>
              </button>
            ))}
          </div>
        </details>
      )}

      {/* ════════════════════════════════════════════════════════
          RESULTS
          ════════════════════════════════════════════════════════ */}
      {results && (
        <div data-copy-results ref={resultsRef} className="space-y-4">

          {/* Situation read */}
          {r.situation_read && (
            <div className={`${c.card} border ${c.border} rounded-xl p-5`}>
              <p className={`text-xs font-bold uppercase tracking-wide ${c.textMuteded} mb-2`}>🎯 {t('coc_situation_read')}</p>
              <p className={`text-sm ${c.textSecondary} leading-relaxed`}>{r.situation_read}</p>
            </div>
          )}

          {/* Subject line */}
          {r.subject_line && (
            <div className={`${c.cardAlt} border ${c.border} rounded-xl p-4`}>
              <p className={`text-[10px] font-bold ${c.textMuteded} mb-0.5`}>{t('coc_subject_line')}</p>
              <p className={`text-sm font-bold ${c.text}`}>{r.subject_line}</p>
            </div>
          )}

          {/* Openers. Three messages, a descriptive title, a copy button.
              The badge, the rationale and the "best if" were three lines of
              commentary on top of every one-line deliverable. */}
          {r.openers?.length > 0 && (
            <div className="space-y-3">
              {r.openers.map((opener, idx) => (
                <div key={idx} className={`${c.card} border ${c.border} rounded-xl p-5`}>
                  <h4 className={`text-sm font-bold ${c.text} mb-2`}>{opener.label}</h4>
                  <div className={`${c.cardAlt} rounded-lg p-4`}>
                    <p className={`text-sm ${c.text} leading-relaxed whitespace-pre-line`}>{opener.message}</p>
                  </div>
                  <div className="mt-3">
                    <CopyBtn exact quiet label={t('coc_copy')}
                      content={[r.subject_line ? `${t('coc_subject_line')} ${r.subject_line}` : '', opener.message].filter(Boolean).join('\n\n') + BRAND} />
                  </div>
                </div>
              ))}
            </div>
          )}

          {/* One line, and only when there is something worth checking. */}
          {r.before_you_send && (
            <div className={`${c.cardAlt} border ${c.border} rounded-xl p-4`}>
              <p className={`text-xs ${c.textSecondary}`}>
                <span className="font-bold">{t('coc_before_send')}</span> {r.before_you_send}
              </p>
            </div>
          )}

          {/* Follow-up: a message they can send, and timing that does not
              pretend to know their recipient's calendar. */}
          {r.follow_up?.message && (
            <div className={`${c.card} border ${c.border} rounded-xl p-5`}>
              <h4 className={`text-sm font-bold ${c.text} mb-2`}>{t('coc_followup_plan')}</h4>
              <div className={`${c.cardAlt} rounded-lg p-4`}>
                <p className={`text-sm ${c.text} leading-relaxed whitespace-pre-line`}>{r.follow_up.message}</p>
              </div>
              {r.follow_up.timing && (
                <p className={`text-xs ${c.textMuteded} mt-2`}>{r.follow_up.timing}</p>
              )}
              <div className="mt-3">
                <CopyBtn exact quiet label={t('coc_copy')} content={r.follow_up.message + BRAND} />
              </div>
            </div>
          )}



          {/* AI disclaimer */}
          <p className={`text-xs text-center ${c.textMuteded}`}>
            {t('coc_disclaimer')}
          </p>

        </div>
      )}
    </div>
  );
};

ColdOpenCraft.displayName = 'ColdOpenCraft';
export default ColdOpenCraft;
