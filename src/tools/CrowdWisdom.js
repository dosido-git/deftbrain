import React, { useState, useEffect, useRef, useCallback } from 'react';
import Caret from '../components/Caret';
import { useTheme } from '../hooks/useTheme';
import { useClaudeAPI } from '../hooks/useClaudeAPI';
import { usePersistentState } from '../hooks/usePersistentState';
import { useRegisterActions } from '../components/ActionBarContext';
import { useTranslation } from '../i18n/useTranslation';
import { pickExample } from '../utils/exampleRotation';
import { revealSection } from '../utils/revealSection';

const BRAND = '\n\n— Generated by DeftBrain · deftbrain.com';

// Maps archetype emoji → c object key (approved color families only)
// Five distinct voice colors are a core function of this tool — documented exception
const ARCHETYPE_KEY = {
  '🔧': 'archetypePragmatist',
  '🎲': 'archetypeRisk',
  '🪞': 'archetypeRegret',
  '🕰️': 'archetypeWait',
  '🔄': 'archetypeContrarian',
};

const CrowdWisdom = ({ tool }) => {
  const { isDark } = useTheme();
  const { callToolEndpoint, loading, userLocale, userCurrency, userRegion } = useClaudeAPI();
  const { t } = useTranslation();

  // Example questions — localized seed text.
  const EXAMPLE_QUESTIONS = [
    { q: t('cw_ex1_q'), ctx: t('cw_ex1_ctx') },
    { q: t('cw_ex2_q'), ctx: t('cw_ex2_ctx') },
    { q: t('cw_ex3_q'), ctx: t('cw_ex3_ctx') },
    { q: t('cw_ex4_q'), ctx: t('cw_ex4_ctx') },
    { q: t('cw_ex5_q'), ctx: t('cw_ex5_ctx') },
  ];


  const c = {
    card:                isDark ? 'bg-zinc-800' : 'bg-white',
    cardAlt:             isDark ? 'bg-zinc-700/50' : 'bg-slate-50',
    input:               isDark ? 'bg-zinc-900 border-zinc-600 text-zinc-100 placeholder-zinc-400 focus:border-[#7fb3e0] focus:ring-[#7fb3e0]/20' : 'bg-white border-gray-300 text-gray-900 placeholder-gray-400 focus:border-[#142a43] focus:ring-[#142a43]/15',
    text:                isDark ? 'text-zinc-50' : 'text-gray-900',
    textSecondary:       isDark ? 'text-zinc-300' : 'text-gray-600',
    textMuted:           isDark ? 'text-zinc-400' : 'text-gray-500',
    labelText:           isDark ? 'text-zinc-200' : 'text-gray-700',
    accentTxt:           isDark ? 'text-[#7fb3e0]' : 'text-[#165b9a]',
    btnPrimary:          isDark ? 'bg-[#2f6fb0] hover:bg-[#3a7cc0] text-white' : 'bg-[#142a43] hover:bg-[#234568] text-white',
    // Waiting for input: an outline, not a smudge. Empty fill keeps "filled"
    // meaning "ready"; the border and label carry the visibility. Important
    // modifiers because tools carry their own border/text utilities on the
    // submit and Tailwind resolves conflicts by stylesheet order, not class
    // order. See the PF-13 exception in audit/audit_v2-3-2.py.
    btnIdle:       isDark ? '!bg-transparent !border-2 !border-[#7fb3e0]/85 !text-[#a9cdef] cursor-not-allowed' : '!bg-transparent !border-2 !border-[#142a43]/80 !text-[#142a43] cursor-not-allowed',
    btnSecondary:        isDark ? 'bg-zinc-700 hover:bg-zinc-600 text-zinc-200'
                                : 'bg-gray-100 hover:bg-gray-200 text-gray-700',
    border:              isDark ? 'border-zinc-700' : 'border-gray-200',
    success:             isDark ? 'bg-emerald-900/20 border-emerald-700 text-emerald-200'
                                : 'bg-emerald-50 border-emerald-300 text-emerald-800',
    warning:             isDark ? 'bg-amber-900/20 border-amber-700 text-amber-200'
                                : 'bg-amber-50 border-amber-300 text-amber-800',
    danger:              isDark ? 'bg-red-900/20 border-red-700 text-red-200'
                                : 'bg-red-50 border-red-200 text-red-800',
    infoBox:             isDark ? 'bg-sky-900/20 border-sky-700 text-sky-200'
                                : 'bg-sky-50 border-sky-200 text-sky-800',
    successBox:          isDark ? 'bg-emerald-900/20 border-emerald-700' : 'bg-emerald-50 border-emerald-300',
    successTxt:          isDark ? 'text-emerald-300' : 'text-emerald-800',
    warningBox:          isDark ? 'bg-amber-900/20 border-amber-700' : 'bg-amber-50 border-amber-300',
    warningTxt:          isDark ? 'text-amber-300' : 'text-amber-800',
    pillActive:          isDark ? 'border-[#7fb3e0] bg-[#1f2530] text-zinc-100' : 'border-[#142a43] bg-[#eef3f8] text-[#142a43]',
    pillInactive:        isDark ? 'border-zinc-600 text-zinc-400 hover:border-zinc-500'
                                : 'border-gray-300 text-gray-500 hover:border-gray-400',
    required:            isDark ? 'text-amber-400' : 'text-amber-700',
    // Bespoke — five distinct archetype voice colors (documented exception to color family limit)
    archetypePragmatist: isDark ? 'bg-zinc-800 border-zinc-600' : 'bg-slate-50 border-slate-300',
    archetypeRisk:       isDark ? 'bg-amber-900/20 border-amber-700' : 'bg-amber-50 border-amber-300',
    archetypeRegret:     isDark ? 'bg-red-900/20 border-red-700' : 'bg-red-50 border-red-200',
    archetypeWait:       isDark ? 'bg-sky-900/20 border-sky-700' : 'bg-sky-50 border-sky-200',
    archetypeContrarian: isDark ? 'bg-emerald-900/20 border-emerald-700' : 'bg-emerald-50 border-emerald-200',
    quoteInner:          isDark ? 'bg-zinc-700/60' : 'bg-slate-100',
    tensionBg:           isDark ? 'bg-amber-900/20 border-amber-700' : 'bg-amber-50 border-amber-300',
    tensionLabel:        isDark ? 'text-amber-400' : 'text-amber-700',
  };
  c.textMuteded = c.textMuted;
  c.label = c.labelText;

  const linkStyle = isDark ? 'text-[#7fb3e0] hover:text-[#a9cdef] underline underline-offset-2' : 'text-[#142a43] hover:text-[#142a43] underline underline-offset-2';


  // ─── State ───
  const [error, setError] = useState('');
  const [expanded, setExpanded] = useState({});

  const [question, setQuestion] = usePersistentState('crowd-wisdom-question', '');
  const [context, setContext] = usePersistentState('crowd-wisdom-context', '');
  const [results, setResults] = usePersistentState('crowd-wisdom-results', null);
  const [sessionHistory, setSessionHistory] = usePersistentState('crowd-wisdom-history', []);

  // ─── Refs ───
  const resultsRef = useRef(null);
  const handleRef = useRef(null);
  const canSubmitRef = useRef(false);

  // Scroll to results when they load
  useEffect(() => {
    if (results && resultsRef.current) {
      revealSection(resultsRef.current);
    }
  }, [results]);

  // Keyboard: Cmd/Ctrl+Enter to submit
  useEffect(() => {
    const handler = (e) => {
      if ((e.metaKey || e.ctrlKey) && e.key === 'Enter' && canSubmitRef.current)
        handleRef.current?.();
    };
    document.addEventListener('keydown', handler);
    return () => document.removeEventListener('keydown', handler);
  }, []);

  const toggle = (key) => setExpanded(p => ({ ...p, [key]: !p[key] }));

  const handleSubmit = async () => {
    if (!question.trim()) return;
    setError(''); setResults(null);
    try {
      const data = await callToolEndpoint('crowd-wisdom', {
        question: question.trim(),
        context: context.trim() || undefined,
        userLocale, userCurrency, userRegion,
      });
      setResults(data);
      setSessionHistory(p => [{
        // PF-25 exception: 40-char preview-text truncation; session history is capped at 6.
        preview: question.trim().slice(0, 40),
        question: question.trim(),
        context: context.trim(),
        result: data,
        date: new Date().toISOString(),
      }, ...p].slice(0, 6));
    } catch (e) {
      setError(e.message || t('cw_error'));
    }
  };

  const loadExample = () => {
    const ex = pickExample('CrowdWisdom', EXAMPLE_QUESTIONS);
    setQuestion(ex.q); setContext(ex.ctx); setResults(null); setError('');
  };

  const handleReset = () => {
    setResults(null); setQuestion(''); setContext(''); setExpanded({}); setError('');
  };

  const buildFullText = useCallback(() => {
    if (!results) return '';
    let out = `👥 ${t('cw_copy_header')}\n\n"${question}"\n\n`;
    if (results.question_reframed) out += `${t('cw_copy_deeper')} ${results.question_reframed}\n\n`;
    results.voices?.forEach(v => {
      out += `${v.emoji} ${v.archetype}\n${v.what_they_say}\n\n${t('cw_copy_uniquely')} ${v.the_truth_only_they_see}\n\n`;
    });
    if (results.the_tension) out += `━━ ${t('cw_copy_tension')} ━━\n${results.the_tension}\n\n`;
    if (results.the_question_nobody_asked) out += `${t('cw_copy_nobody')} ${results.the_question_nobody_asked}\n`;
    return out + BRAND;
  }, [results, question, t]);

  useRegisterActions(buildFullText(), tool?.title || 'Crowd Wisdom');

  handleRef.current = handleSubmit;
  canSubmitRef.current = !loading && !!question.trim();

  return (
    <div className={`space-y-4 ${c.text}`}>

      {/* Header card */}
      <div>
        <div>
          {/* Header — site style (2026-09-27): a pale band of the tool's color
              bleeding to the card edges, the ground the "Try an example" pill was
              made for (PF-17c). Screen only. */}
          <div
            data-print-hide
            className="-mx-4 -mt-4 sm:-mx-6 sm:-mt-6 lg:-mx-8 lg:-mt-8 px-4 sm:px-6 lg:px-8 pt-4 sm:pt-6 lg:pt-8 pb-5"
            style={/^#[0-9a-f]{6}$/i.test(tool?.headerColor || '') ? { background: `${tool.headerColor}${isDark ? '26' : '66'}` } : undefined}
          >
            <div>
            <div className="flex items-start justify-between gap-3">
              <div>
                {/* PF-30 — the wrapper already prints the name as the page <h1>. */}
              <p className={`text-[17px] leading-snug ${c.textSecondary}`}>
                <span className="me-2 text-xl">{tool?.icon ?? '👥'}</span>{t('cw_tagline')}
              </p>
                <button onClick={loadExample} disabled={loading} style={{ backgroundColor: (tool?.headerColor ?? '#888888') + '80' }} className="mt-2 px-4 py-2 rounded-full text-sm font-semibold border border-black/25 text-zinc-900 shadow-sm hover:brightness-105 hover:shadow transition disabled:opacity-40 whitespace-nowrap">✨ {t('try_example')}</button>
              </div>
              {(results || question.trim()) && (
                <button onClick={handleReset} className={`${c.btnSecondary} px-3 py-1.5 rounded-lg text-xs font-bold flex-shrink-0`}>
                  ↺ {t('start_over')}
                </button>
              )}
            </div>
          </div>
          </div>
        </div>
      </div>

      {/* Input card */}
      <div data-print-form {...(results ? { 'data-print-hide': '' } : {})} className={`border-t ${c.border} pt-5 space-y-4`}>
        <div className="pb-3 border-b border-zinc-500">
          <h3 className={`font-semibold text-sm ${c.text}`}>{tool?.icon ?? '👥'} {t('cw_your_question')}</h3>
          <p className={`text-xs ${c.textSecondary}`}>{t('cw_subtitle')}</p>
        </div>

        <div>
          <label className={`block text-sm font-semibold mb-1.5 ${c.labelText}`}>
            {t('cw_question_label')} <span className={c.required}>*</span>
          </label>
          <textarea
            value={question}
            onChange={e => setQuestion(e.target.value)}
            placeholder={t('cw_question_ph')}
            rows={3}
            maxLength={500}
            className={`w-full px-4 py-3 rounded-xl border text-sm resize-none ${c.input}`}
          />
        </div>

        <div>
          <label className={`block text-sm font-semibold mb-1.5 ${c.labelText}`}>
            {t('cw_context_label')} <span className={`font-normal ${c.textMuted}`}>{t('cw_context_hint')}</span>
          </label>
          <textarea
            value={context}
            onChange={e => setContext(e.target.value)}
            placeholder={t('cw_context_ph')}
            rows={2}
            maxLength={300}
            className={`w-full px-4 py-3 rounded-xl border text-sm resize-none ${c.input}`}
          />
        </div>

        {error && (
          <div className={`p-3 rounded-xl border text-sm ${c.danger}`}>
            <span className="me-1">⚠️</span>{error}
          </div>
        )}

        <div>
          <button title={t('cmd_enter')}
            onClick={handleSubmit}
            disabled={loading || !question.trim()}
            className={`relative w-full py-3 rounded-xl font-bold ${(!question.trim()) ? c.btnIdle : c.btnPrimary}`}
          >
            {loading
              ? <><span className="animate-spin inline-block me-2 text-xl">{tool?.icon ?? '👥'}</span>{t('cw_gathering')}</>
              : <><span className="me-1 text-xl">{tool?.icon ?? '👥'}</span>{t('cw_ask')}</>}
          {!loading && (
            <kbd aria-hidden="true"
              className="hidden sm:flex items-center absolute end-3 top-1/2 -translate-y-1/2 px-1.5 py-0.5 rounded border border-white/30 bg-white/15 text-[10px] font-bold tracking-wide">
              ⌘↵
            </kbd>
          )}
          </button>
        </div>
        <p className={`text-xs text-center ${c.textMuted}`}>{t('cw_submit_hint')}</p>
      </div>

      {/* History panel */}
      {sessionHistory.length > 0 && !results && (
        <div className={`rounded-xl border p-4 space-y-2 ${c.card} ${c.border}`}>
          <p className={`text-[15px] font-semibold ${c.labelText}`}>{t('cw_recent')}</p>
          {sessionHistory.map((h, i) => (
            <button
              key={i}
              onClick={() => { setQuestion(h.question); setContext(h.context); setResults(h.result); setExpanded({}); setError(''); }}
              className={`w-full text-start px-3 py-2 rounded-lg text-xs ${c.cardAlt} ${c.textSecondary} hover:opacity-80`}
            >
              {h.preview}{h.preview?.length >= 40 ? '…' : ''}
            </button>
          ))}
        </div>
      )}

      {/* Results */}
      {results && (
        <div data-copy-results ref={resultsRef} className="scroll-mt-24 space-y-4">

          {/* Question header */}
          <div className={`rounded-xl border p-5 ${c.card} ${c.border}`}>
            <p className={`text-[15px] font-semibold mb-1 ${c.labelText}`}>{t('cw_the_question')}</p>
            <p className={`text-base font-semibold ${c.text}`}>"{question}"</p>
            {results.question_reframed && (
              <p className={`text-sm mt-2 italic ${c.textSecondary}`}>
                {t('cw_deeper')} {results.question_reframed}
              </p>
            )}
          </div>

          {/* Five voices */}
          {results.voices?.map((voice, i) => {
            const isOpen = expanded[i];
            const cardKey = ARCHETYPE_KEY[voice.emoji] || 'archetypeContrarian';
            return (
              <div key={i} className={`rounded-xl overflow-hidden border ${c[cardKey]}`}>
                <button data-print-heading aria-expanded={!!(isOpen)} onClick={() => toggle(i)} className="w-full text-start p-5">
                  <div className="flex items-start justify-between gap-3">
                    <div className="flex items-center gap-3">
                      <span className="text-2xl">{voice.emoji}</span>
                      <div>
                        <p className={`font-bold ${c.text}`}>{voice.archetype}</p>
                        <p className={`text-xs mt-0.5 ${c.textMuted}`}>{voice.profile}</p>
                      </div>
                    </div>
                    <span data-print-hide><Caret open={isOpen} className="flex-shrink-0" /></span>
                  </div>
                  {!isOpen && (
                    <p data-print-hide className={`text-sm mt-3 leading-relaxed line-clamp-2 ${c.textSecondary}`}>
                      {voice.what_they_say}
                    </p>
                  )}
                </button>
                {(
                  <div data-sec-body hidden={!(isOpen)} className={`px-5 pb-5 space-y-3 border-t ${c.border}`}>
                    <div className="pt-3">
                      <p className={`text-[15px] font-semibold mb-1 ${c.labelText}`}>{t('cw_what_they_say')}</p>
                      <p className={`text-sm leading-relaxed ${c.text}`}>{voice.what_they_say}</p>
                    </div>
                    {voice.core_belief && (
                      <p className={`text-[13px] ${c.textMuted} italic`}><span className="font-semibold not-italic">{t('cw_core_belief')}</span> {voice.core_belief}</p>
                    )}
                    <div className={`p-3 rounded-xl ${c.quoteInner}`}>
                      <p className={`text-[15px] font-semibold mb-1 ${c.labelText}`}>🔦 {t('cw_only_see')}</p>
                      <p className={`text-sm ${c.textSecondary}`}>{voice.the_truth_only_they_see}</p>
                    </div>
                    <div className={`text-[13px] ${c.textMuted} italic`}>
                      <span className="font-semibold not-italic">{t('cw_blind_spot')}</span> {voice.the_thing_they_might_miss}
                    </div>
                  </div>
                )}
              </div>
            );
          })}

          {/* Tension + closing question */}
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
            {results.the_tension && (
              <div className={`rounded-xl border p-4 ${c.tensionBg}`}>
                <p className={`text-[13px] font-boldr mb-2 ${c.tensionLabel}`}>⚡ {t('cw_tension')}</p>
                <p className={`text-sm ${c.textSecondary}`}>{results.the_tension}</p>
              </div>
            )}
            {results.the_question_nobody_asked && (
              <div className={`rounded-xl border p-4 ${c.card} ${c.border}`}>
                <p className={`text-[15px] font-semibold mb-2 ${c.labelText}`}>❓ {t('cw_nobody_asked')}</p>
                <p className={`text-sm italic ${c.textSecondary}`}>{results.the_question_nobody_asked}</p>
              </div>
            )}
          </div>

          {/* AI disclaimer */}
          <p className={`text-xs text-center italic ${c.textMuted}`}>
            {t('cw_disclaimer')}
          </p>

          {/* Post-result cross-refs */}
          <div data-print-hide className={`${c.cardAlt} border ${c.border} rounded-xl p-4`}>
            <p className={`text-[13px] font-bold ${c.textMuted} mb-2`}>🔗 {t('cw_related')}</p>
            <div className="flex flex-wrap gap-3">
              <a href="/DecisionCoach" className={`text-xs ${linkStyle}`}>🎯 {t('cw_decision_coach')}</a>
              <a href="/BeliefStressTest" className={`text-xs ${linkStyle}`}>🧪 {t('cw_belief')}</a>
            </div>
          </div>
        </div>
      )}
    </div>
  );
};

CrowdWisdom.displayName = 'CrowdWisdom';
export default CrowdWisdom;
