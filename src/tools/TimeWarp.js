import React, { useState, useCallback, useEffect, useRef } from 'react';
import { useClaudeAPI } from '../hooks/useClaudeAPI';
import { useTheme } from '../hooks/useTheme';
import { usePersistentState } from '../hooks/usePersistentState';
import { useRegisterActions } from '../components/ActionBarContext';
import { useTranslation } from '../i18n/useTranslation';
import { pickExample } from '../utils/exampleRotation';
import { useScrollToSection } from '../hooks/useScrollToSection';

const BRAND = '\n\n— Generated by DeftBrain · deftbrain.com';

// ════════════════════════════════════════════════════════════
// CONSTANTS
// ════════════════════════════════════════════════════════════
// Ground-up redesign (2026-09-14): Time Warp no longer picks a format —
// the model chooses whatever form makes the collision funniest. History
// facts, era context, and the "Best Moment" callout are gone too; see
// backend/routes/time-warp.js PERSONALITY for the product reasoning
// ("Time Warp is not a history tool. History is the playground.").
//
// modern: invariant brand name OR a key (modernKey) for generic terms.
// period is always localized via periodKey. The combo `modern`/`period`
// VALUES sent to the backend use the localized display strings.
const QUICK_COMBOS = [
  { modern: 'TikTok', periodKey: 'tw_period_victorian', icon: '🎭' },
  { modern: 'Uber', periodKey: 'tw_period_1920s_ny', icon: '🚕' },
  { modernKey: 'tw_combo_dating_apps', periodKey: 'tw_period_medieval_eu', icon: '💘' },
  { modernKey: 'tw_combo_roomba', periodKey: 'tw_period_ancient_rome', icon: '🏛️' },
  { modernKey: 'tw_combo_wifi', periodKey: 'tw_period_wild_west', icon: '🤠' },
  { modern: 'Instagram', periodKey: 'tw_period_renaissance', icon: '🎨' },
  { modern: 'Amazon Prime', periodKey: 'tw_period_silk_road', icon: '🐪' },
  { modernKey: 'tw_combo_podcasts', periodKey: 'tw_period_ancient_greece', icon: '🏺' },
];

// Examples aren't translated (precedent: seed/default input text, not a UI
// label) — they're typed straight into the free-text fields.
const EXAMPLES = [
  { modernThing: 'Online dating apps', historicalPeriod: 'Medieval Europe' },
  { modernThing: 'Zoom meetings', historicalPeriod: 'Victorian England' },
  { modernThing: 'Airbnb', historicalPeriod: '1920s New York' },
  { modernThing: 'a corporate performance review', historicalPeriod: 'a pirate ship' },
  { modernThing: 'LinkedIn', historicalPeriod: 'Renaissance Florence' },
];

const TimeWarp = ({ tool }) => {
  const { callToolEndpoint, loading, userLocale, userCurrency, userRegion } = useClaudeAPI();
  const { isDark } = useTheme();
  const { t } = useTranslation();

  const c = {
    card:          isDark ? 'bg-zinc-800' : 'bg-white',
    cardAlt:       isDark ? 'bg-zinc-700/50' : 'bg-slate-50',
    input:         isDark ? 'bg-zinc-900 border-zinc-600 text-zinc-100 placeholder:text-zinc-400 focus:border-cyan-500 focus:ring-cyan-500/20' : 'bg-white border-gray-300 text-gray-900 placeholder:text-gray-400 focus:border-cyan-500 focus:ring-cyan-100',
    text:          isDark ? 'text-zinc-50' : 'text-gray-900',
    textSecondary: isDark ? 'text-zinc-300' : 'text-gray-600',
    textMuted:     isDark ? 'text-zinc-400' : 'text-gray-500',
    required:      isDark ? 'text-amber-400' : 'text-amber-700',
    labelText:     isDark ? 'text-zinc-200' : 'text-gray-700',
    accentTxt:     isDark ? 'text-amber-400' : 'text-amber-700',
    accentBox:     isDark ? 'bg-amber-900/20 border-amber-700' : 'bg-amber-50 border-amber-300',
    btnPrimary:    isDark ? 'bg-cyan-600 hover:bg-cyan-500 text-white' : 'bg-cyan-600 hover:bg-cyan-700 text-white',
    // Waiting for input: an outline, not a smudge. Empty fill keeps "filled"
    // meaning "ready"; the border and label carry the visibility. Important
    // modifiers because tools carry their own border/text utilities on the
    // submit and Tailwind resolves conflicts by stylesheet order, not class
    // order. See the PF-13 exception in audit/audit_v2-3-2.py.
    btnIdle:       isDark ? '!bg-transparent !border-2 !border-cyan-500/85 !text-cyan-300 cursor-not-allowed'
                          : '!bg-transparent !border-2 !border-cyan-600/85 !text-cyan-800 cursor-not-allowed',
    btnSecondary:  isDark ? 'bg-zinc-700 hover:bg-zinc-600 text-zinc-100' : 'bg-gray-100 hover:bg-gray-200 text-gray-700',
    border:        isDark ? 'border-zinc-700' : 'border-gray-200',
    danger:        isDark ? 'bg-red-900/20 border-red-700 text-red-200' : 'bg-red-50 border-red-200 text-red-800',
    success:       isDark ? 'bg-emerald-900/20 border-emerald-700 text-emerald-200' : 'bg-emerald-50 border-emerald-300 text-emerald-800',
    warning:       isDark ? 'bg-amber-900/20 border-amber-700 text-amber-200' : 'bg-amber-50 border-amber-300 text-amber-800',
    quoteBg:       isDark ? 'bg-zinc-900/60' : 'bg-slate-50',
  };
  c.label = c.labelText;
  c.textMuteded = c.textMuted;

  const linkStyle = isDark
    ? 'text-cyan-400 hover:text-cyan-300 underline underline-offset-2'
    : 'text-cyan-700 hover:text-cyan-800 underline underline-offset-2';

  // ── State ──
  // -v2 keys: a v1 result has era_context/historical_footnotes/
  // anachronism_alert/flip_it/fiction_note, none of which this renderer
  // reads, and lacks warp_insight/next_collision, which it does. Restoring
  // a v1 result here would render a title and body with everything below
  // it silently missing. New keys so old saved sessions don't surface at
  // all rather than surfacing broken.
  const [modernThing, setModernThing] = useState('');
  const [historicalPeriod, setHistoricalPeriod] = useState('');
  const [results, setResults] = usePersistentState('time-warp-result-v2', null);
  const [sessionHistory, setSessionHistory] = usePersistentState('time-warp-history-v2', []);
  const [error, setError] = useState('');

  // ── API ──
  const loadExample = () => {
    const ex = pickExample('TimeWarp', EXAMPLES);
    setModernThing(ex.modernThing);
    setHistoricalPeriod(ex.historicalPeriod);
    setResults(null);
  };

  const applyCombo = (combo) => {
    setModernThing(combo.modernKey ? t(combo.modernKey) : combo.modern);
    setHistoricalPeriod(t(combo.periodKey));
    setResults(null);
  };

  const runWarp = useCallback(async (override = null) => {
    const nextModern = override?.modernThing ?? modernThing;
    const nextPeriod = override?.historicalPeriod ?? historicalPeriod;
    if (!nextModern.trim() && !nextPeriod.trim()) return;

    if (override) {
      setModernThing(nextModern);
      setHistoricalPeriod(nextPeriod);
    }

    setError('');
    setResults(null);

    try {
      const data = await callToolEndpoint('time-warp', {
        modernThing: nextModern.trim(),
        historicalPeriod: nextPeriod.trim(),
        seed: Date.now(),
        userLocale,
        userCurrency,
        userRegion,
      });

      setResults(data);
      // Full input + full result, not a truncated preview: this is what
      // lets a history card actually be reopened instead of just logged.
      // See openSession() below.
      setSessionHistory(prev => [{
        id: 'tw_' + Date.now(),
        date: new Date().toISOString(),
        title: data?.title || `${nextModern} × ${nextPeriod}`,
        modernThing: nextModern.trim(),
        historicalPeriod: nextPeriod.trim(),
        insight: data?.warp_insight || '',
        result: data,
      }, ...prev].slice(0, 6));
    } catch (err) {
      setError(err.message || t('tw_error'));
    }
  }, [modernThing, historicalPeriod, callToolEndpoint, userLocale, userCurrency, userRegion, t, setResults, setSessionHistory]);

  // Reopens a past warp exactly as it was — no re-call.
  const openSession = (session) => {
    setModernThing(session.modernThing || '');
    setHistoricalPeriod(session.historicalPeriod || '');
    setResults(session.result || null);
    setError('');
  };

  const runNext = () => {
    const next = results?.next_collision;
    if (!next) return;
    runWarp({
      modernThing: next.modernThing || '',
      historicalPeriod: next.historicalPeriod || '',
    });
  };

  // ── Copy text builder ──
  const buildFullText = useCallback(() => {
    if (!results) return '';
    const lines = [`⏰ ${results.title || t('tw_copy_header')}`, ''];
    if (results.main_content) lines.push(results.main_content, '');
    if (results.warp_insight) lines.push(`🌀 ${t('tw_the_warp')}`, results.warp_insight, '');
    if (results.next_collision) {
      lines.push(
        `↪️ ${t('tw_one_more')}`,
        `${results.next_collision.modernThing} × ${results.next_collision.historicalPeriod}`,
        results.next_collision.teaser || '',
        ''
      );
    }
    lines.push(`🎭 ${t('tw_fiction_note')}`);
    return lines.join('\n') + BRAND;
  }, [results, t]);

  useRegisterActions(buildFullText(), tool?.title);

  // Reveal the answer when it arrives: frame the tool if its header fits,
  // otherwise put the answer on top. Focus moves either way.
  const revealRef = useRef(null);
  useScrollToSection(revealRef, results);

  useEffect(() => {
    const handler = (e) => {
      if ((e.metaKey || e.ctrlKey) && e.key === 'Enter') {
        if (modernThing.trim() || historicalPeriod.trim()) runWarp();
      }
    };
    document.addEventListener('keydown', handler);
    return () => document.removeEventListener('keydown', handler);
  }, [runWarp, modernThing, historicalPeriod]);

  // RENDER
  // ════════════════════════════════════════════════════════════
  return (
    <div className={`space-y-4 ${c.text}`}>
      {/* Input */}
      <div className={`${c.card} border rounded-xl px-5 pt-2.5 pb-5`}>
        <div className="mb-4 pb-3 border-b border-zinc-500">
          <div className="flex items-start justify-between gap-3">
            <div>
              {/* PF-30 — the wrapper already prints the name as the page <h1>. */}
              <p className={`text-base ${c.textSecondary}`}>
                <span className="me-2 text-lg">{tool?.icon ?? '⏰'}</span>{t('tw_tagline')}
              </p>
              <button onClick={loadExample} disabled={loading} style={{ backgroundColor: (tool?.headerColor ?? '#888888') + '80' }} className="mt-2 px-4 py-2 rounded-full text-sm font-semibold border border-black/25 text-zinc-900 shadow-sm hover:brightness-105 hover:shadow transition disabled:opacity-40 whitespace-nowrap">✨ {t('try_example')}</button>
            </div>
            {/* PF-16: the tool's one reset, on the title row, from the first keystroke. */}
            {(results || historicalPeriod.trim() || modernThing.trim()) ? (
              <button onClick={() => { setModernThing(''); setHistoricalPeriod(''); setResults(null); }} className={`${c.btnSecondary} px-3 py-1.5 rounded-lg text-xs font-semibold flex-shrink-0 whitespace-nowrap`}>
                {t('tw_new_warp')}
              </button>
            ) : null}
          </div>
        </div>

        {/* Quick combos */}
        <div className="mb-4">
          <div className="flex items-center justify-between mb-2">
            <label className={`text-[10px] font-bold ${c.labelText} uppercase`}>{t('tw_quick_combos')}</label>
            <button onClick={() => applyCombo(QUICK_COMBOS[Math.floor(Math.random() * QUICK_COMBOS.length)])}
              className={`${c.btnSecondary} px-2.5 py-1 rounded-lg text-[10px] font-bold`}>
              {t('tw_shuffle')}
            </button>
          </div>
          <div className="flex flex-wrap gap-1.5">
            {QUICK_COMBOS.map((combo, i) => (
              <button key={i} onClick={() => applyCombo(combo)}
                className={`${c.btnSecondary} px-2.5 py-1.5 rounded-lg text-[11px] font-medium min-h-[32px] flex items-center gap-1`}>
                <span>{combo.icon}</span> {combo.modernKey ? t(combo.modernKey) : combo.modern} × {t(combo.periodKey)}
              </button>
            ))}
          </div>
        </div>

        {/* Inputs */}
        <p className={`text-[10px] ${c.textMuted} mb-1.5`}>{t('tw_fill_hint')}</p>
        <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 mb-5">
          <div>
            <label className={`text-xs font-bold ${c.labelText} block mb-1.5`}>{t('tw_modern_label')} <span className={c.required}>*</span></label>
            <input type="text" value={modernThing} onChange={e => setModernThing(e.target.value)}
              placeholder={t('tw_modern_ph')}
              className={`w-full px-3 py-2.5 border rounded-lg text-sm ${c.input} outline-none focus:ring-2`} />
          </div>
          <div>
            <label className={`text-xs font-bold ${c.labelText} block mb-1.5`}>{t('tw_period_label')} <span className={c.required}>*</span></label>
            <input type="text" value={historicalPeriod} onChange={e => setHistoricalPeriod(e.target.value)}
              placeholder={t('tw_period_ph')}
              className={`w-full px-3 py-2.5 border rounded-lg text-sm ${c.input} outline-none focus:ring-2`} />
          </div>
        </div>

        <p className={`text-[11px] ${c.textMuted} mb-2 text-center`}>
          {t('tw_xref')} <a href="/WrongAnswersOnly" className={linkStyle}>🎭 {t('tw_xref_wao')}</a> {t('tw_xref_desc')}
        </p>

        <button title={t('cmd_enter')} onClick={() => runWarp()} disabled={(!modernThing.trim() && !historicalPeriod.trim()) || loading}
          className={`relative w-full ${(!modernThing.trim() && !historicalPeriod.trim()) ? c.btnIdle : c.btnPrimary} font-bold py-3 rounded-lg flex items-center justify-center gap-2 min-h-[48px]`}>
          {loading
            ? <><span className="inline-block animate-spin">{tool?.icon ?? '⏰'}</span> {t('tw_warping')}</>
            : <><span>{tool?.icon ?? '⏰'}</span> {t('tw_warp_it')}</>}
          {!loading && (
            <kbd aria-hidden="true"
              className="hidden sm:flex items-center absolute end-3 top-1/2 -translate-y-1/2 px-1.5 py-0.5 rounded border border-white/30 bg-white/15 text-[10px] font-bold tracking-wide">
              ⌘↵
            </kbd>
          )}
        </button>
      </div>

      {/* Error */}
      {error && (
        <div className={`${c.danger} border rounded-lg p-4 flex items-start gap-3`}>
          <span>⚠️</span><p className="text-sm">{error}</p>
        </div>
      )}

      {/* Results */}
      {results && (
        <div ref={revealRef} className="scroll-mt-24 space-y-4">
          {results?.title && (
            <div className={`${c.accentBox} border-2 rounded-xl p-5 text-center`}>
              <span className="text-3xl block mb-2">⏰</span>
              <p className={`text-lg font-black ${c.text}`}>{results.title}</p>
            </div>
          )}

          {results?.main_content && (
            <div className={`${c.card} border ${c.border} rounded-xl p-5`}>
              <p className={`text-sm ${c.textSecondary} whitespace-pre-line leading-relaxed`}>{results.main_content}</p>
            </div>
          )}

          {results?.warp_insight && (
            <div className={`${c.quoteBg} border ${c.border} rounded-xl p-5`}>
              <p className={`text-[10px] font-black ${c.accentTxt} uppercase tracking-widest mb-2`}>🌀 {t('tw_the_warp')}</p>
              <p className={`text-sm ${c.textSecondary} leading-relaxed`}>{results.warp_insight}</p>
            </div>
          )}

          {/* Fixed interface copy, not model-generated: this note can't
              overreach into certifying the piece as researched because
              nothing in it is generated per-request. */}
          {results?.main_content && (
            <p className={`text-[11px] ${c.textMuted} italic px-1`}>
              🎭 {t('tw_fiction_note')}
            </p>
          )}

          {results?.next_collision && (
            <button
              onClick={runNext}
              disabled={loading}
              className={`w-full text-start ${c.cardAlt} border ${c.border} rounded-xl p-4 hover:brightness-105 transition disabled:opacity-40`}
            >
              <p className={`text-[10px] font-black ${c.accentTxt} uppercase tracking-widest mb-1`}>↪️ {t('tw_one_more')}</p>
              <p className={`text-sm font-bold ${c.text}`}>
                {results.next_collision.modernThing} × {results.next_collision.historicalPeriod}
              </p>
              {results.next_collision.teaser && (
                <p className={`text-xs ${c.textMuted} mt-1 italic`}>{results.next_collision.teaser}</p>
              )}
            </button>
          )}

          <button onClick={() => runWarp()} disabled={loading}
            className={`w-full ${c.btnSecondary} disabled:opacity-40 font-bold py-3 rounded-lg min-h-[44px]`}>
            {t('tw_same_combo')}
          </button>

          {/* One quiet link, not a "Next step" box: Warp → The Warp →
              One More? → Same Combo → Recent Warps is the loop; a boxed
              navigation section here duplicates the site's own Related
              Tools section right below and interrupts that loop. */}
          <p className={`text-[11px] ${c.textMuted} text-center`}>
            <a href="/WhichLife" className={linkStyle}>🤔 {t('tw_link_whatif')}</a>
          </p>
        </div>
      )}

      {/* Recent warps — each card reopens the complete past session (no
          re-call). */}
      {sessionHistory.length > 0 && (() => {
        const validSessions = sessionHistory.filter(s => s.result);
        if (!validSessions.length) return null;
        return (
          <div className={`${c.cardAlt} border ${c.border} rounded-xl p-4 mt-4`}>
            <p className={`text-xs font-bold ${c.textMuted} mb-2`}>📋 {t('tw_recent')}</p>
            <div className="space-y-1.5">
              {validSessions.map(s => (
                <button
                  key={s.id}
                  onClick={() => openSession(s)}
                  className={`w-full text-start ${c.card} border ${c.border} rounded-lg px-3 py-2.5 hover:brightness-105 transition`}
                >
                  <p className={`text-xs font-semibold ${c.text} truncate`}>{s.title}</p>
                  <p className={`text-[10px] ${c.textMuted} mt-0.5 truncate`}>
                    {s.modernThing} × {s.historicalPeriod}
                  </p>
                  {s.insight && (
                    <p className={`text-[10px] ${c.textMuted} mt-1 line-clamp-2`}>{s.insight}</p>
                  )}
                </button>
              ))}
            </div>
          </div>
        );
      })()}
    </div>
  );
};

TimeWarp.displayName = 'TimeWarp';
export default TimeWarp;
