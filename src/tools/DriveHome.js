  const [conditions, setConditions] = useState([]);
  const [road, setRoad] = useState('');
  const [driverState, setDriverState] = useState('');
  const [concern, setConcern] = useState('');
  const [session, setSession] = usePersistentState('drive-home-v2-session', null);
  // A pre-drive call is about the next few minutes. A verdict older than an
  // hour and a half is not advice about tonight, so it does not come back on
  // reload wearing the authority of a fresh one.
