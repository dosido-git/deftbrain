  const canSubmitRef = useRef(false);
  canSubmitRef.current = canAssess && !loading;
  const assessRef = useRef(assess);
  assessRef.current = assess;
  useEffect(() => {
    const handler = (e) => {
      if (e.key === 'Enter' && (e.metaKey || e.ctrlKey) && canSubmitRef.current) assessRef.current?.();
    };
    document.addEventListener('keydown', handler);
    return () => document.removeEventListener('keydown', handler);
  }, []);

  // ══════════════════════════════════════════
  // EXAMPLE / RESET
  // ══════════════════════════════════════════
  const loadExample = useCallback(() => {
    const ex = pickExample('DriveHome', EXAMPLES);
    setFrom(ex.from);
    setTo(ex.to);
    setMinutes(ex.minutes);
    setTime(ex.time);
    setConditions(ex.conditions);
    setRoad(ex.road);
    setDriverState(ex.state);
    setConcern(ex.concern);
    setResult(null);
    setError('');
  }, []);

  const handleReset = useCallback(() => {
    setFrom(''); setTo(''); setMinutes(''); setTime(''); setConditions([]);
    setRoad(''); setDriverState(''); setConcern(''); setResult(null); setError('');
    setShowCheckin(false); setCheckinMinutes(''); setArrived(false);
    setLocationUrl(''); setLocationNote(''); setTimerEnd(null);
  }, [setTimerEnd]);

