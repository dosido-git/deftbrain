const list = v => (Array.isArray(v) ? v.filter(Boolean) : v ? [String(v)] : []);

// PF-2 — accept the aliases the model reaches for when it drifts off schema.
function normalize(raw = {}) {
  const r = String(raw.recommendation || raw.drive_recommendation || raw.verdict || '');
  const recommendation = /do.?not|don't|stop|unsafe|avoid/i.test(r)
    ? 'do_not_drive'
    : /go|proceed|reasonable/i.test(r)
    ? 'go'
    : 'pause';
  return {
    recommendation,
    headline: raw.headline || raw.recommendation_text || '',
    summary: raw.summary || raw.assessment || raw.overview || '',
    main_concern: raw.main_concern || raw.biggest_concern || null,
    factors_harder: [...list(raw.factors_harder), ...list(raw.risk_factors), ...list(raw.watch_out_for)],
    factors_in_favor: [...list(raw.factors_in_favor), ...list(raw.protective_factors)],
    before_you_decide: raw.before_you_decide || raw.decision_boundary || null,
    safer_options: [...list(raw.safer_options), ...list(raw.alternatives)],
    prep_checklist: [...list(raw.prep_checklist), ...list(raw.checklist), ...list(raw.pre_drive_checklist)],
    watch_for: [...list(raw.watch_for), ...list(raw.watch_items)],
    limits: [...list(raw.limits), ...list(raw.limitations)],
  };
}

const fmtClock = (ms) => {
  const s = Math.max(0, Math.ceil(ms / 1000));
  return `${Math.floor(s / 60)}:${String(s % 60).padStart(2, '0')}`;
};

