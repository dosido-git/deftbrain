import React, { useState, useEffect, useRef, useCallback } from 'react';
import Caret from '../components/Caret';
import { useClaudeAPI } from '../hooks/useClaudeAPI';
import { useTheme } from '../hooks/useTheme';
import { usePersistentState } from '../hooks/usePersistentState';
import { useRegisterActions } from '../components/ActionBarContext';
import { useTranslation } from '../i18n/useTranslation';
import { pickExample } from '../utils/exampleRotation';
import { revealSection } from '../utils/revealSection';

const BRAND = '\n\n— Generated by DeftBrain · deftbrain.com';

// "Have you already done anything?" — the architectural addition of the V2
// rewrite. v1 generated `what_to_do` from the message alone, with no idea
// whether the visitor had merely received it or already handed over a
// password; the backend's WHAT THE VISITOR ALREADY DID section branches
// specifically on these codes (see backend/routes/scam-radar.js).
const INTERACTION_OPTIONS = [
  { id: 'none',            labelKey: 'scam_int_none' },
  { id: 'clicked_link',    labelKey: 'scam_int_clicked' },
  { id: 'replied',         labelKey: 'scam_int_replied' },
  { id: 'downloaded_file', labelKey: 'scam_int_downloaded' },
  { id: 'entered_password',labelKey: 'scam_int_password' },
  { id: 'shared_info',     labelKey: 'scam_int_shared_info' },
  { id: 'sent_money',      labelKey: 'scam_int_sent_money' },
  { id: 'other',           labelKey: 'scam_int_other' },
];

const EXAMPLES = [
  {
  messageText: `Subject: URGENT: Your account has been suspended — verify now

Dear Valued Customer,

We have detected unusual activity on your account. Your access has been temporarily suspended for your protection.

To restore full access, you must verify your identity within 24 HOURS or your account will be permanently deleted.

Click here to verify: http://secure-paypa1-verify.com/restore

You will need to provide:
• Full name and date of birth
• Credit card number and CVV
• Social Security Number

This is an automated security alert. Failure to respond will result in permanent account closure and potential legal action.

PayPal Security Team
© PayPal Inc. All Rights Reserved`,
  senderContext: 'From: security@paypa1-alerts.net',
  interactionStatus: 'none',
},
  {
  messageText: `Hi David! Sorry for the late reply, this is Wenjing from the tennis club. Is this still your number?

[after reply]

Oh I'm so sorry, wrong number! But you seem nice. I'm new to the area, I moved here from Singapore last year for work. Do you live nearby?

[three days of friendly conversation later]

My uncle works in commodities and he's been helping me with a gold trading account. I made 2,400 last month just following his signals. I'm not trying to sell you anything, I just think you'd be good at it. I can show you the platform if you're curious, no pressure at all.`,
  senderContext: '',
  interactionStatus: 'none',
},
];

function ScamRadar({ tool }) {
  const { callToolEndpoint, loading, userLocale, userCurrency, userRegion } = useClaudeAPI();
  const { isDark } = useTheme();
  const { t } = useTranslation();

  const c = {
    card:          isDark ? 'bg-zinc-800' : 'bg-white',
    cardAlt:       isDark ? 'bg-zinc-700/50' : 'bg-slate-50',
    input:         isDark ? 'bg-zinc-900 border-zinc-600 text-zinc-100 placeholder-zinc-400 focus:border-cyan-500 focus:ring-cyan-500/20'
                          : 'bg-white border-gray-300 text-gray-900 placeholder-gray-400 focus:border-cyan-500 focus:ring-cyan-100',
    text:          isDark ? 'text-zinc-50' : 'text-gray-900',
    textSecondary: isDark ? 'text-zinc-300' : 'text-gray-600',
    textMuted:     isDark ? 'text-zinc-400' : 'text-gray-500',
    labelText:     isDark ? 'text-zinc-200' : 'text-gray-700',
    accentTxt:     isDark ? 'text-cyan-400' : 'text-cyan-600',
    btnPrimary:    isDark ? 'bg-cyan-600 hover:bg-cyan-500 text-white'
                          : 'bg-cyan-600 hover:bg-cyan-700 text-white',
    btnIdle:       isDark ? '!bg-transparent !border-2 !border-cyan-500/85 !text-cyan-300 cursor-not-allowed'
                          : '!bg-transparent !border-2 !border-cyan-600/85 !text-cyan-800 cursor-not-allowed',
    btnSecondary:  isDark ? 'bg-zinc-700 hover:bg-zinc-600 text-zinc-200'
                          : 'bg-gray-100 hover:bg-gray-200 text-gray-700',
    border:        isDark ? 'border-zinc-700' : 'border-gray-200',
    success:       isDark ? 'bg-emerald-900/20 border-emerald-700 text-emerald-200'
                          : 'bg-emerald-50 border-emerald-300 text-emerald-800',
    warning:       isDark ? 'bg-amber-900/20 border-amber-700 text-amber-200'
                          : 'bg-amber-50 border-amber-300 text-amber-800',
    danger:        isDark ? 'bg-red-900/20 border-red-700 text-red-200'
                          : 'bg-red-50 border-red-200 text-red-800',
    // Neutral — used for the two verdicts that must NOT read as reassurance
    // (NO_CLEAR_SCAM_SIGNS explicitly is not "verified safe"; NOT_ENOUGH_TO_TELL
    // is not a finding at all). Deliberately not the old green "LIKELY SAFE"
    // treatment — a checkmark-green banner would visually contradict the
    // prompt's own "does NOT mean verified" framing.
    neutral:       isDark ? 'bg-slate-800/60 border-slate-500' : 'bg-slate-100 border-slate-300',
    neutralTxt:    isDark ? 'text-slate-200' : 'text-slate-700',
    successTxt:    isDark ? 'text-emerald-300' : 'text-emerald-800',
    warningTxt:    isDark ? 'text-amber-300' : 'text-amber-800',
    required:      isDark ? 'text-amber-400' : 'text-amber-700',
  };
  c.textMuteded = c.textMuted;
  c.label = c.labelText;

  const linkStyle = isDark
    ? 'text-cyan-400 hover:text-cyan-300 underline underline-offset-2'
    : 'text-cyan-700 hover:text-cyan-800 underline underline-offset-2';

  const [messageText, setMessageText]       = useState('');
  const [senderContext, setSenderContext]   = useState('');
  const [interactionStatus, setInteractionStatus] = useState('none');
  const [interactionOther, setInteractionOther]   = useState('');
  const [results, setResults]               = usePersistentState('scamradar-results-v2', null);
  const [sessionHistory, setSessionHistory] = usePersistentState('scamradar-history-v2', []);
  const [error, setError]                   = useState('');

  const resultsRef    = useRef(null);
  const handleScanRef = useRef(null);
  const canSubmitRef  = useRef(false);

  const canSubmit = !!messageText.trim();

  const handleReset = useCallback(() => {
    setResults(null);
    setError('');
    setMessageText('');
    setSenderContext('');
    setInteractionStatus('none');
    setInteractionOther('');
  }, [setResults]);

  const loadExample = useCallback(() => {
    const ex = pickExample('ScamRadar', EXAMPLES);
    setMessageText(ex.messageText);
    setSenderContext(ex.senderContext || '');
    setInteractionStatus(ex.interactionStatus || 'none');
    setInteractionOther('');
    setResults(null);
    setError('');
  }, [setResults]);

  const handleScan = useCallback(async () => {
    if (!canSubmit || loading) return;
    setError('');
    setResults(null);

    try {
      const parsed = await callToolEndpoint('scam-radar/stream', {
        messageText,
        senderContext,
        interactionStatus,
        interactionOther: interactionStatus === 'other' ? interactionOther : '',
        userLocale,
        userCurrency,
        userRegion,
      });
      const entry = { ...parsed, messageText, senderContext };
      setResults(entry);
      // PF-25 exception: 80 is a message-preview length; history itself is capped at 10 lookups.
      setSessionHistory(prev => [{ verdict: parsed.verdict, scam_pattern: parsed.scam_pattern?.label, verdict_explanation: parsed.verdict_explanation, preview: (messageText.slice(0, 80) + (messageText.length > 80 ? '…' : '')), ts: Date.now() }, ...prev].slice(0, 10));
    } catch (err) {
      setError(err.message || t('scam_error'));
    }
  }, [canSubmit, loading, messageText, senderContext, interactionStatus, interactionOther, callToolEndpoint, setResults, setSessionHistory, userLocale, userCurrency, userRegion, t]);

  handleScanRef.current = handleScan;
  canSubmitRef.current  = canSubmit;

  const buildFullText = useCallback(() => {
    if (!results) return '';
    const lines = [t('scam_copy_header'), ''];
    lines.push(`${t('scam_copy_verdict')} ${t(`scam_verdict_${results.verdict?.toLowerCase()}`)}`);
    if (results.verdict_explanation) lines.push(`\n${results.verdict_explanation}`);
    if (results.what_to_do_now?.length) {
      lines.push(`\n${t('scam_what_to_do_now')}`);
      results.what_to_do_now.forEach((a, i) => lines.push(`${i + 1}. ${a}`));
    }
    if (results.why_concerning?.length) {
      lines.push(`\n${t('scam_why_concerning')}`);
      results.why_concerning.forEach(f => lines.push(`• ${f.observation} ${f.why_it_matters ? '— ' + f.why_it_matters : ''}`));
    }
    if (results.how_to_verify?.length) {
      lines.push(`\n${t('scam_how_to_verify')}`);
      results.how_to_verify.forEach(a => lines.push(`• ${a.action} ${a.reason ? '— ' + a.reason : ''}`));
    }
    if (results.if_you_already_interacted?.relevant && results.if_you_already_interacted.guidance?.length) {
      lines.push(`\n${t('scam_if_interacted')}`);
      results.if_you_already_interacted.guidance.forEach(a => lines.push(`• ${a}`));
    }
    if (results.what_doesnt_settle_it?.length) {
      lines.push(`\n${t('scam_doesnt_settle')}`);
      results.what_doesnt_settle_it.forEach(a => lines.push(`• ${a}`));
    }
    if (results.avoid?.length) {
      lines.push(`\n${t('scam_avoid')}`);
      results.avoid.forEach(a => lines.push(`• ${a}`));
    }
    if (results.scam_pattern?.label) {
      lines.push(`\n${t('scam_more_pattern')}: ${results.scam_pattern.label}`);
      if (results.scam_pattern.explanation) lines.push(results.scam_pattern.explanation);
    }
    if (results.important_unknowns?.length) {
      lines.push(`\n${t('scam_unknowns')}`);
      results.important_unknowns.forEach(a => lines.push(`• ${a}`));
    }
    if (results.senderContext) lines.push(`\n${t('scam_copy_sender')} ${results.senderContext}`);
    lines.push(BRAND);
    return lines.join('\n');
  }, [results, t]);

  useRegisterActions(buildFullText(), tool?.title || 'ScamRadar');

  useEffect(() => {
    if (!results || !resultsRef.current) return;
    const timer = setTimeout(() => revealSection(resultsRef.current), 200);
    return () => clearTimeout(timer);
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [results]);

  useEffect(() => {
    const handler = (e) => {
      const tag = document.activeElement?.tagName;
      if (tag === 'SELECT') return;
      if (e.key === 'Enter' && (e.metaKey || e.ctrlKey) && !loading && canSubmitRef.current)
        handleScanRef.current?.();
    };
    document.addEventListener('keydown', handler);
    return () => document.removeEventListener('keydown', handler);
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [loading]);

  // ── Verdict styling ──
  // NO_CLEAR_SCAM_SIGNS and NOT_ENOUGH_TO_TELL both get the neutral
  // treatment, not success-green — neither one is a finding of safety.
  const verdictConfig = results ? {
    LIKELY_SCAM:         { bg: c.danger,  txt: isDark ? 'text-red-200' : 'text-red-800',     icon: '🚨' },
    VERIFY_FIRST:        { bg: c.warning, txt: c.warningTxt,                                  icon: '⚠️' },
    NO_CLEAR_SCAM_SIGNS: { bg: c.neutral, txt: c.neutralTxt,                                  icon: '🔍' },
    NOT_ENOUGH_TO_TELL:  { bg: c.neutral, txt: c.neutralTxt,                                  icon: '❓' },
  }[results.verdict] ?? { bg: c.neutral, txt: c.neutralTxt, icon: '❔' } : null;

  const historyIcon = (v) => v === 'LIKELY_SCAM' ? '🚨' : v === 'VERIFY_FIRST' ? '⚠️' : v === 'NOT_ENOUGH_TO_TELL' ? '❓' : '🔍';
  const historyColor = (v) => v === 'LIKELY_SCAM'
    ? (isDark ? 'text-red-400' : 'text-red-600')
    : v === 'VERIFY_FIRST'
      ? (isDark ? 'text-amber-400' : 'text-amber-600')
      : (isDark ? 'text-slate-300' : 'text-slate-600');

  // ── Render helpers ──
  const renderHeaderRow = () => (
    <div className="pb-3 border-b border-zinc-500">
      <div className="flex items-start justify-between gap-3">
        <div>
          {/* PF-30 — the wrapper already prints the name as the page <h1>. */}
          <p className={`text-base ${c.textSecondary}`}>
            <span className="me-2 text-lg">{tool?.icon ?? '🎣'}</span>{t('scam_tagline')}
          </p>
          {!results && (
            <button onClick={loadExample} disabled={loading} style={{ backgroundColor: (tool?.headerColor ?? '#888888') + '80' }} className="mt-2 px-4 py-2 rounded-full text-sm font-semibold border border-black/25 text-zinc-900 shadow-sm hover:brightness-105 hover:shadow transition disabled:opacity-40 whitespace-nowrap">✨ {t('try_example')}</button>
          )}
        </div>
        {/* PF-16: the tool's one reset, on the title row, from the first keystroke. */}
        {(results || messageText.trim() || senderContext.trim()) ? (
          <button onClick={handleReset} className={`${c.btnSecondary} px-3 py-1.5 rounded-lg text-xs font-semibold flex-shrink-0 whitespace-nowrap`}>
            ↺ {t('scam_scan_another')}
          </button>
        ) : null}
      </div>
    </div>
  );

  const renderInput = () => (
    <div className={`${c.card} border ${c.border} rounded-xl shadow-sm px-5 pt-2.5 pb-5 space-y-4`}>
      {renderHeaderRow()}

      {/* Message text — no message-type taxonomy to fill in first. The
          visitor is already pasting the actual material; a scam pattern is
          identified from content, not from a category the visitor picked. */}
      <div>
        <label className={`block text-sm font-medium ${c.labelText} mb-1`}>
          {t('scam_msg_content')} <span className={c.required}>*</span>
        </label>
        <textarea
          value={messageText}
          onChange={e => setMessageText(e.target.value)}
          placeholder={t('scam_msg_ph')}
          rows={8}
          className={`w-full px-3 py-2.5 border rounded-xl text-sm resize-y focus:outline-none focus:ring-2 ${c.input}`}
        />
      </div>

      {/* Sender context */}
      <div>
        <label className={`block text-sm font-medium ${c.labelText} mb-1`}>{t('scam_sender_label')} <span className={`text-xs font-normal ${c.textMuted}`}>{t('scam_sender_optional')}</span></label>
        <input
          type="text"
          value={senderContext}
          onChange={e => setSenderContext(e.target.value)}
          placeholder={t('scam_sender_ph')}
          className={`w-full px-3 py-2 border rounded-xl text-sm focus:outline-none focus:ring-2 ${c.input}`}
        />
      </div>

      {/* Have you already done anything? — the architectural addition.
          A single-select radio list, not pills: these are mutually
          exclusive states of fact about what the visitor already did, not a
          preference to toggle. */}
      <div>
        <label className={`block text-sm font-medium ${c.labelText} mb-2`}>{t('scam_interaction_label')} <span className={`text-xs font-normal ${c.textMuted}`}>{t('scam_sender_optional')}</span></label>
        <div className="space-y-1.5">
          {INTERACTION_OPTIONS.map(opt => (
            <label key={opt.id} className={`flex items-center gap-2 text-sm ${c.textSecondary} cursor-pointer`}>
              <input
                type="radio"
                name="scam-interaction"
                checked={interactionStatus === opt.id}
                onChange={() => setInteractionStatus(opt.id)}
                className="accent-cyan-600"
              />
              {t(opt.labelKey)}
            </label>
          ))}
        </div>
        {interactionStatus === 'other' && (
          <input
            type="text"
            value={interactionOther}
            onChange={e => setInteractionOther(e.target.value)}
            placeholder={t('scam_int_other_ph')}
            className={`mt-2 w-full px-3 py-2 border rounded-xl text-sm focus:outline-none focus:ring-2 ${c.input}`}
          />
        )}
      </div>

      {error && <p className={`text-sm ${c.danger} border rounded-lg px-3 py-2`}>{error}</p>}

      {/* Pre-result cross-ref */}
      <p className={`text-xs ${c.textMuted}`}>
        {t('scam_xref_pre')} <a href="/FakeReviewDetective" className={linkStyle}>🕵️ {t('scam_fakereview')}</a>.
      </p>

      <button title={t('cmd_enter')}
        onClick={handleScan}
        disabled={!canSubmit || loading}
        className={`relative w-full ${(!canSubmit) ? c.btnIdle : c.btnPrimary} font-bold py-3 rounded-lg flex items-center justify-center gap-2 min-h-[48px]`}
      >
        {loading
          ? <><span className="inline-block animate-spin">{tool?.icon ?? '🎣'}</span> {t('scam_scanning')}</>
          : <><span className="me-1">{tool?.icon ?? '🎣'}</span> {t('scam_scan_btn')}</>}
      {!loading && (
        <kbd aria-hidden="true"
          className="hidden sm:flex items-center absolute end-3 top-1/2 -translate-y-1/2 px-1.5 py-0.5 rounded border border-white/30 bg-white/15 text-[10px] font-bold tracking-wide">
          ⌘↵
        </kbd>
      )}
      </button>

      {/* History panel */}
      {sessionHistory.length > 0 && (
        <div className={`${c.cardAlt} border ${c.border} rounded-xl p-4`}>
          <div className="flex items-center justify-between mb-3">
            <p className={`text-xs font-bold ${c.textMuted} uppercase tracking-wide`}>🕓 {t('scam_recent')}</p>
            <button onClick={() => setSessionHistory([])} className={`text-xs ${c.textMuted} hover:${c.accentTxt}`}>{t('scam_clear')}</button>
          </div>
          <ul className="space-y-2">
            {sessionHistory.map((h, i) => (
              <li key={i} className={`text-xs ${c.textSecondary} flex items-start gap-2`}>
                <span className="flex-shrink-0">{historyIcon(h.verdict)}</span>
                <span>
                  <span className={`font-bold ${historyColor(h.verdict)}`}>{t(`scam_verdict_${h.verdict?.toLowerCase()}`)}</span>
                  {h.scam_pattern ? <span className={c.textMuted}> · {h.scam_pattern}</span> : null}
                  <span className={`block ${c.textMuted} mt-0.5`}>{h.preview}</span>
                </span>
              </li>
            ))}
          </ul>
        </div>
      )}
    </div>
  );

  const renderResults = () => {
    if (!results || !verdictConfig) return null;
    const interacted = results.if_you_already_interacted;

    return (
      <div className="scroll-mt-24 space-y-4" ref={resultsRef}>

        {/* Recap of the analyzed message — anchors persisted results on revisits */}
        {results.messageText && (
          <div className={`${c.cardAlt} border ${c.border} rounded-xl p-4`}>
            <p className={`text-xs font-semibold uppercase tracking-wide mb-1.5 ${c.textMuted}`}>📝 {t('scam_your_situation')}</p>
            <p className={`text-sm ${c.textSecondary}`}>{results.messageText.slice(0, 200)}{results.messageText.length > 200 ? '…' : ''}</p>
            {results.senderContext && <p className={`text-xs mt-1.5 ${c.textMuted}`}>{results.senderContext}</p>}
          </div>
        )}

        {/* THE READ — verdict + explanation, no numeric confidence */}
        <div className={`border-2 rounded-xl p-5 ${verdictConfig.bg}`}>
          <p className={`text-[10px] font-bold uppercase tracking-widest mb-2 ${verdictConfig.txt} opacity-70`}>{t('scam_the_read')}</p>
          <div className="flex items-center gap-3 mb-2">
            <span className="text-3xl">{verdictConfig.icon}</span>
            <span className={`text-2xl font-black tracking-tight ${verdictConfig.txt}`}>{t(`scam_verdict_${results.verdict?.toLowerCase()}`)}</span>
          </div>
          {results.verdict_explanation && <p className={`text-sm font-medium ${verdictConfig.txt}`}>{results.verdict_explanation}</p>}
        </div>

        {/* Safety disclaimer — automated guidance, not financial/legal advice */}
        <p className={`text-[11px] ${c.textMuted} px-1`}>ⓘ {t('scam_disclaimer')}</p>

        {/* WHAT TO DO RIGHT NOW — comes immediately after the read, not after
            a pattern explainer and a full flags checklist. */}
        {results?.what_to_do_now?.length > 0 && (
          <div className={`${c.card} border ${c.border} rounded-xl p-4`}>
            <p className={`text-xs font-bold ${c.textMuted} uppercase tracking-wide mb-3`}>✅ {t('scam_what_to_do_now')}</p>
            <ul className="space-y-2">
              {results?.what_to_do_now.map((a, i) => (
                <li key={i} className={`text-sm ${c.textSecondary}`}>
                  <span className={`font-bold ${c.successTxt}`}>{i + 1}.</span> {a}
                </li>
              ))}
            </ul>
          </div>
        )}

        {/* WHY THIS LOOKS CONCERNING — observation + why it matters, at most
            a handful of items, never a mandatory 8. */}
        {results?.why_concerning?.length > 0 && (
          <div className={`${c.card} border ${c.border} rounded-xl p-4`}>
            <p className={`text-xs font-bold ${c.textMuted} uppercase tracking-wide mb-3`}>🚩 {t('scam_why_concerning')}</p>
            <ul className="space-y-3">
              {results?.why_concerning.map((f, i) => (
                <li key={i} className={`text-sm ${c.danger} border rounded-lg px-3 py-2`}>
                  <p className={c.text}>{f.observation}</p>
                  {f.why_it_matters && <p className={`text-xs mt-1 ${c.textMuted}`}>{f.why_it_matters}</p>}
                </li>
              ))}
            </ul>
          </div>
        )}

        {/* HOW TO VERIFY IT */}
        {results?.how_to_verify?.length > 0 && (
          <div className={`${c.card} border ${c.border} rounded-xl p-4`}>
            <p className={`text-xs font-bold ${c.textMuted} uppercase tracking-wide mb-3`}>🔎 {t('scam_how_to_verify')}</p>
            <ul className="space-y-2">
              {results?.how_to_verify.map((a, i) => (
                <li key={i} className={`text-sm ${c.textSecondary}`}>
                  <span className={`font-bold ${c.accentTxt}`}>•</span> {a.action}
                  {a.reason && <span className={`block text-xs mt-0.5 ${c.textMuted}`}>{a.reason}</span>}
                </li>
              ))}
            </ul>
          </div>
        )}

        {/* IF YOU ALREADY INTERACTED — only when relevant */}
        {interacted?.relevant && interacted.guidance?.length > 0 && (
          <div className={`border rounded-xl p-4 ${c.warning}`}>
            <p className={`text-xs font-bold uppercase tracking-wide mb-3 ${c.warningTxt}`}>⚠️ {t('scam_if_interacted')}</p>
            <ul className="space-y-2">
              {interacted.guidance.map((a, i) => (
                <li key={i} className={`text-sm ${c.warningTxt}`}>• {a}</li>
              ))}
            </ul>
          </div>
        )}

        {/* WHAT DOESN'T SETTLE IT — a caution, never reassurance */}
        {results?.what_doesnt_settle_it?.length > 0 && (
          <div className={`${c.card} border ${c.border} rounded-xl p-4`}>
            <p className={`text-xs font-bold ${c.textMuted} uppercase tracking-wide mb-3`}>🧩 {t('scam_doesnt_settle')}</p>
            <ul className="space-y-2">
              {results?.what_doesnt_settle_it.map((f, i) => (
                <li key={i} className={`text-sm ${c.textSecondary}`}>• {f}</li>
              ))}
            </ul>
          </div>
        )}

        {/* AVOID */}
        {results?.avoid?.length > 0 && (
          <div className={`${c.card} border ${c.border} rounded-xl p-4`}>
            <p className={`text-xs font-bold ${c.textMuted} uppercase tracking-wide mb-3`}>🚫 {t('scam_avoid')}</p>
            <ul className="space-y-2">
              {results?.avoid.map((a, i) => (
                <li key={i} className={`text-sm ${c.textSecondary}`}>
                  <span className={`font-bold ${isDark ? 'text-red-400' : 'text-red-600'}`}>✗</span> {a}
                </li>
              ))}
            </ul>
          </div>
        )}

        {/* MORE ABOUT THIS PATTERN — collapsed. Taxonomy is supporting
            material, not the headline; important_unknowns lives here too,
            since both are "for context, not for the first screen." */}
        {(results?.scam_pattern?.label || results?.important_unknowns?.length > 0) && (
          <details className={`${c.cardAlt} border ${c.border} rounded-xl p-4 group`}>
            <summary className="cursor-pointer list-none [&::-webkit-details-marker]:hidden flex items-center justify-between">
              <span className={`text-xs font-bold ${c.textMuted} uppercase tracking-wide`}>🎣 {t('scam_more_pattern')}</span>
              <Caret groupOpen />
            </summary>
            <div className="mt-3 space-y-3">
              {results?.scam_pattern?.label && (
                <div>
                  <p className={`text-sm font-semibold ${c.text}`}>{results?.scam_pattern.label}</p>
                  {results?.scam_pattern.explanation && <p className={`text-sm mt-1 ${c.textSecondary}`}>{results?.scam_pattern.explanation}</p>}
                </div>
              )}
              {results?.important_unknowns?.length > 0 && (
                <div>
                  <p className={`text-xs font-bold ${c.textMuted} uppercase tracking-wide mb-1.5`}>{t('scam_unknowns')}</p>
                  <ul className="space-y-1">
                    {results?.important_unknowns.map((u, i) => (
                      <li key={i} className={`text-sm ${c.textSecondary}`}>• {u}</li>
                    ))}
                  </ul>
                </div>
              )}
            </div>
          </details>
        )}

        {/* Post-result cross-refs */}
        <div className={`${c.cardAlt} border ${c.border} rounded-xl p-4`}>
          <p className={`text-[10px] font-bold ${c.textMuted} uppercase mb-2`}>🔗 {t('scam_related')}</p>
          <div className="flex flex-wrap gap-3">
            <a href="/ComplaintEscalationWriter" className={`text-xs ${linkStyle}`}>📨 {t('scam_complaint')}</a>
            <a href="/MagicMouth" className={`text-xs ${linkStyle}`}>🪄 {t('scam_magicmouth')}</a>
            <a href="/FakeReviewDetective" className={`text-xs ${linkStyle}`}>🕵️ {t('scam_fakereview')}</a>
          </div>
        </div>
      </div>
    );
  };

  return (
    <div className={`space-y-4 ${c.text}`}>
      {!results && <p className={`text-xs ${c.textMuted} px-1`}>{t('scam_top_hint')} <a href="/FakeReviewDetective" className={linkStyle}>🕵️ {t('scam_fakereview')}</a>.</p>}
      {!results && renderInput()}
      {results ? (
        <div className={`${c.card} border ${c.border} rounded-xl shadow-sm px-5 pt-2.5 pb-5`}>
          {renderHeaderRow()}
        </div>
      ) : null}
      {results && renderResults()}
    </div>
  );
}

ScamRadar.displayName = 'ScamRadar';
export default ScamRadar;
