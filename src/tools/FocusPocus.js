import React, { useCallback, useEffect, useMemo, useRef, useState } from 'react';
import { useClaudeAPI } from '../hooks/useClaudeAPI';
import { useTheme } from '../hooks/useTheme';
import { usePersistentState } from '../hooks/usePersistentState';
import { useRegisterActions } from '../components/ActionBarContext';
import { useTranslation } from '../i18n/useTranslation';
import { pickExample } from '../utils/exampleRotation';

const BRAND = '\n\n— Generated by DeftBrain · deftbrain.com';
const DURATIONS = [15, 25, 45, 60];

const EXAMPLES = [
  { task: 'Finish the Q3 budget proposal', enough: 'Draft the headline numbers and the headcount section', minutes: 45 },
  { task: 'Sort out the tax paperwork', enough: '', minutes: 25 },
  { task: 'Reply to the messages I have been avoiding', enough: 'Answer the three that have been open longest', minutes: 15 },
];

// mm:ss from a millisecond gap. Never from an accumulated counter — the tool
// this replaced added elapsed time to a stored total on every reload, which is
// how it once displayed a 42,521-minute session.
const clock = (ms) => {
  const sec = Math.max(0, Math.floor(ms / 1000));
  const h = Math.floor(sec / 3600);
  const m = Math.floor((sec % 3600) / 60);
  const s = sec % 60;
  const mm = String(m).padStart(2, '0');
  const ss = String(s).padStart(2, '0');
  return h > 0 ? `${h}:${mm}:${ss}` : `${m}:${ss}`;
};

// Defined at module scope, NOT inside the component. A component declared inside
// another is a new type on every render, so React unmounts and remounts its
// whole subtree — which drops focus out of the text field after a character or
// two, and the browser's find-as-you-type grabs the rest (owner, 2026-08-26).
const Card = ({ c, children, className = '' }) => (
  <section className={`rounded-xl border ${c.border} ${c.card} p-4 md:p-5 shadow-sm ${className}`}>{children}</section>
);

const FocusPocus = ({ tool }) => {
  const { callToolEndpoint, loading } = useClaudeAPI();
  const { isDark } = useTheme();
  const { t } = useTranslation();

  const c = {
    card:          isDark ? 'bg-zinc-800' : 'bg-white',
    cardAlt:       isDark ? 'bg-zinc-700/45' : 'bg-slate-50',
    text:          isDark ? 'text-zinc-50' : 'text-gray-900',
    textSecondary: isDark ? 'text-zinc-300' : 'text-gray-600',
    textMuted:     isDark ? 'text-zinc-400' : 'text-gray-500',
    labelText:     isDark ? 'text-zinc-200' : 'text-gray-700',
    required:      isDark ? 'text-amber-400' : 'text-amber-700',
    border:        isDark ? 'border-zinc-700' : 'border-gray-200',
    input:         isDark ? 'bg-zinc-900 border-zinc-600 text-zinc-100 placeholder-zinc-400' : 'bg-white border-gray-300 text-gray-900 placeholder-gray-400',
    btnPrimary:    isDark ? 'bg-cyan-600 hover:bg-cyan-500 text-white' : 'bg-cyan-600 hover:bg-cyan-700 text-white',
    btnSecondary:  isDark ? 'bg-zinc-700 hover:bg-zinc-600 text-zinc-200' : 'bg-gray-100 hover:bg-gray-200 text-gray-700',
    success:       isDark ? 'bg-emerald-900/20 border-emerald-700 text-emerald-100' : 'bg-emerald-50 border-emerald-300 text-emerald-900',
    warning:       isDark ? 'bg-amber-900/20 border-amber-700 text-amber-100' : 'bg-amber-50 border-amber-300 text-amber-900',
    danger:        isDark ? 'bg-red-900/25 border-red-600 text-red-100' : 'bg-red-50 border-red-300 text-red-900',
    infoBox:       isDark ? 'bg-cyan-900/20 border-cyan-700 text-cyan-100' : 'bg-cyan-50 border-cyan-200 text-cyan-900',
    pillActive:    isDark ? 'border-cyan-500 bg-cyan-900/30 text-cyan-100' : 'border-cyan-600 bg-cyan-100 text-cyan-900',
    pillInactive:  isDark ? 'border-zinc-600 text-zinc-300 hover:border-zinc-500' : 'border-gray-300 text-gray-600 hover:border-gray-400',
    // PF-13 exception — an outline while the form is empty, not a grey smudge.
    btnIdle:       isDark ? '!bg-transparent !border-2 !border-cyan-500/85 !text-cyan-300 cursor-not-allowed'
                          : '!bg-transparent !border-2 !border-cyan-600/85 !text-cyan-800 cursor-not-allowed',
  };
  c.textMuteded = c.textMuted;
  c.label = c.labelText;

  const linkStyle = isDark
    ? 'text-cyan-400 hover:text-cyan-300 underline underline-offset-2'
    : 'text-cyan-700 hover:text-cyan-800 underline underline-offset-2';

  // ── State (all useState before any usePersistentState — PF-11/PF-14) ──
  const [task, setTask] = useState('');
  const [enough, setEnough] = useState('');
  const [minutes, setMinutes] = useState(25);
  const [customMinutes, setCustomMinutes] = useState('');
  const [nudge, setNudge] = useState('');
  const [remaining, setRemaining] = useState('');
  const [reviewChoice, setReviewChoice] = useState('');
  // The suggestion waits for a yes. Nothing starts on a target the person has
  // not seen (owner, 2026-08-26).
  const [suggested, setSuggested] = useState('');
  const [error, setError] = useState('');
  const [tick, setTick] = useState(0);

  // The session survives a refresh here AND on the server; whichever remembers
  // it, the other is rebuilt from it.
  const [session, setSession] = usePersistentState('focus-pocus-v2-session', null);

  const activeMinutes = useMemo(() => {
    const raw = customMinutes ? Number(customMinutes) : minutes;
    return Number.isFinite(raw) && raw >= 1 && raw <= 240 ? raw : 25;
  }, [minutes, customMinutes]);

  // ── The countdown is local; the server is the authority ──────────────
  // Polling once a second would spend the whole rate-limit budget in twelve
  // seconds. endsAt is an absolute timestamp, so the browser can count down on
  // its own and only ask the server when something actually changes.
  useEffect(() => {
    if (session?.status !== 'running') return undefined;
    const id = setInterval(() => setTick(n => n + 1), 1000);
    return () => clearInterval(id);
  }, [session?.status]);

  // The finished session is what this tool returns; the audit's result-block
  // rules key on this name, and here it is genuinely the same thing.
  const results = session?.status === 'done' ? session : null;
  const remainingMs = session ? Math.max(0, session.endsAt - Date.now()) : 0;
  const overtimeMs = session ? Math.max(0, Date.now() - session.endsAt) : 0;
  const overtime = session?.status === 'running' && overtimeMs > 0;
  const extensionsLeft = session ? session.extensionsLeft ?? 0 : 3;

  const call = useCallback(async (endpoint, payload) => {
    setError('');
    try {
      return await callToolEndpoint(endpoint, payload);
    } catch (e) {
      setError(e?.message || t('fpo_err_generic'));
      return null;
    }
  }, [callToolEndpoint, t]);

  // One sync on mount: the browser may have been closed for a week.
  const syncedRef = useRef(false);
  useEffect(() => {
    if (syncedRef.current || !session?.id || session.status === 'done') return;
    syncedRef.current = true;
    (async () => {
      const fresh = await call('focus-pocus/session', { action: 'sync', id: session.id, local: session });
      if (fresh?.id) setSession(fresh); else setSession(null);
    })();
    // eslint-disable-line react-hooks/exhaustive-deps
  }, []); // eslint-disable-line react-hooks/exhaustive-deps

  // Time-up is a state change, so it is the server's to make.
  const timeUpRef = useRef(false);
  useEffect(() => {
    if (session?.status !== 'running' || remainingMs > 0 || timeUpRef.current) return;
    timeUpRef.current = true;
    (async () => {
      const fresh = await call('focus-pocus/session', { action: 'time-up', id: session.id });
      if (fresh?.id) setSession(fresh);
    })();
  }, [session?.status, remainingMs, session?.id, call, setSession]);

  // ══════════════════════════════════════════
  // ACTIONS
  // ══════════════════════════════════════════
  const makeConcrete = async () => {
    if (!task.trim()) { setError(t('fpo_err_task')); return; }
    const data = await call('focus-pocus', { action: 'prepare', task: task.trim(), enough: enough.trim(), minutes: activeMinutes });
    if (data?.target) setSuggested(data.target);
  };

  const begin = async (target) => {
    const data = await call('focus-pocus/session', {
      action: 'start', task: task.trim(), target, minutes: activeMinutes,
    });
    if (data?.id) { timeUpRef.current = false; setNudge(''); setSuggested(''); setSession(data); }
  };

  // The target used to fall back to the task itself, so "Sort out the tax
  // paperwork" became its own stopping point — the one thing this tool exists
  // to prevent. Nothing starts without a real target now: if what they wrote is
  // blank or vague, the model proposes one and they approve it first.
  const startSession = async () => {
    if (!task.trim()) { setError(t('fpo_err_task')); return; }
    const typed = enough.trim();
    const data = await call('focus-pocus', { action: 'prepare', task: task.trim(), enough: typed, minutes: activeMinutes });
    if (!data) return;
    if (typed && data.wasVague === false) return begin(typed);   // theirs was already usable
    if (data.target) return setSuggested(data.target);
    if (typed) return begin(typed);                              // model gave nothing; theirs beats the task
    setError(t('fpo_err_task'));
  };

  const extend = async () => {
    const data = await call('focus-pocus/session', { action: 'extend', id: session.id });
    if (data?.id) { timeUpRef.current = false; setSession(data); }
  };

  const getUnstuck = async () => {
    const data = await call('focus-pocus', { action: 'stuck', id: session.id });
    if (data?.nudge) setNudge(data.nudge);
  };

  const finishEarly = async () => {
    const data = await call('focus-pocus/session', { action: 'finish-early', id: session.id });
    if (data?.id) setSession(data);
  };

  const submitReview = async (result) => {
    const data = await call('focus-pocus', { action: 'review', id: session.id, result, remaining: remaining.trim() });
    if (data?.id) setSession(data);
  };

  const loadExample = useCallback(() => {
    const ex = pickExample('FocusPocus', EXAMPLES);
    setTask(ex.task); setEnough(ex.enough); setMinutes(ex.minutes); setCustomMinutes('');
    setError('');
  }, []);

  // The header's reset and the done screen's button do the same work, but the
  // done screen's is a primary action closing a finished session — PF-16 counts
  // reset buttons, and there is exactly one.
  const startAnother = useCallback(() => { handleResetRef.current?.(); }, []);
  const handleResetRef = useRef(null);

  const handleReset = useCallback(async () => {
    if (session?.id) await callToolEndpoint('focus-pocus/session', { action: 'discard', id: session.id }).catch(() => {});
    timeUpRef.current = false;
    setSession(null); setTask(''); setEnough(''); setMinutes(25); setCustomMinutes('');
    setNudge(''); setRemaining(''); setReviewChoice(''); setSuggested(''); setError('');
  }, [session, callToolEndpoint, setSession]);
  handleResetRef.current = handleReset;

  // PF-31 — the chip only goes on a button whose shortcut exists.
  const canStartRef = useRef(false);
  canStartRef.current = !!task.trim() && !loading && !session;
  const startRef = useRef(null);
  startRef.current = startSession;
  useEffect(() => {
    const handler = (e) => {
      if (e.key === 'Enter' && (e.metaKey || e.ctrlKey) && canStartRef.current) startRef.current?.();
    };
    document.addEventListener('keydown', handler);
    return () => document.removeEventListener('keydown', handler);
  }, []);

  const buildFullText = useCallback(() => {
    if (!session) return '';
    const L = [`${tool?.icon ?? '🎩'} ${tool?.title || t('fpo_title')}`, ''];
    L.push(`${t('fpo_your_task')}: ${session.task}`);
    L.push(`${t('fpo_enough_label')}: ${session.target}`);
    L.push(`${t('fpo_planned')}: ${session.plannedMinutes} min`);
    if (session.extensionsUsed) L.push(`${t('fpo_extensions_used', { n: session.extensionsUsed })}`);
    if (session.breadcrumb) L.push(`\n${t('fpo_breadcrumb_label')}: ${session.breadcrumb}`);
    return L.join('\n') + BRAND;
  }, [session, tool, t]);

  useRegisterActions(buildFullText(), tool?.title || t('fpo_title'));


  const crossRef = (
    <p className={`text-center text-sm ${c.textMuted}`}>
      {t('fpo_xref_q')}{' '}
      <a href="/FocusSoundArchitect" className={linkStyle}>🎧 {t('fpo_xref_sound')}</a>
    </p>
  );

  // ══════════════════════════════════════════
  // RENDER
  // ══════════════════════════════════════════
  return (
    <div className={`space-y-4 ${c.text}`} data-tick={tick}>
      {/* ── PF-30 header ── */}
      <div className={`${c.card} border ${c.border} rounded-xl shadow-sm px-5 pt-2.5 pb-5`}>
        <div className="flex items-start justify-between gap-3">
          <div className="flex-1 min-w-0">
            {/* PF-30 — the wrapper already prints the name as the page <h1>. */}
            <p className={`text-base ${c.textSecondary}`}>
              <span className="me-2 text-lg">{tool?.icon ?? '🎩'}</span>{t('fpo_hero')}
            </p>
            {!session && (
              <button onClick={loadExample} disabled={loading}
                style={{ backgroundColor: (tool?.headerColor ?? '#888888') + '80' }}
                className="mt-2 px-4 py-2 rounded-full text-sm font-semibold border border-black/25 text-zinc-900 shadow-sm hover:brightness-105 hover:shadow transition disabled:opacity-40 whitespace-nowrap">
                ✨ {t('try_example')}
              </button>
            )}
          </div>
          {(session || task.trim()) ? (
            <button onClick={handleReset}
              className={`shrink-0 px-3 py-2 rounded-lg text-sm font-bold min-h-[40px] ${c.btnSecondary}`}>
              ↺ {t('start_over')}
            </button>
          ) : null}
        </div>
      </div>

      {error && <div className={`rounded-xl border p-4 text-sm ${c.danger}`}>{error}</div>}

      {/* ── SETUP ── */}
      {!session && (
        <>
          <Card c={c}>
            <label className="block">
              <span className={`text-sm font-semibold ${c.label}`}>{t('fpo_task_label')} <span className={c.required}>*</span></span>
              <input className={`mt-1 w-full rounded-lg border p-3 ${c.input}`} value={task}
                onChange={e => setTask(e.target.value)} placeholder={t('fpo_task_ph')} />
            </label>

            <div className="mt-4">
              <p className={`text-sm font-semibold ${c.label}`}>{t('fpo_how_long')}</p>
              <div className="mt-2 flex flex-wrap gap-2">
                {DURATIONS.map(n => (
                  <button key={n} type="button"
                    aria-pressed={!customMinutes && minutes === n}
                    onClick={() => { setMinutes(n); setCustomMinutes(''); }}
                    className={`min-h-[44px] rounded-lg border px-3 py-2 text-sm font-semibold ${!customMinutes && minutes === n ? c.pillActive : c.pillInactive}`}>
                    {t('fpo_minutes', { n })}
                  </button>
                ))}
                <input type="number" min="1" max="240" inputMode="numeric" aria-label={t('fpo_custom_aria')}
                  className={`w-28 rounded-lg border px-3 py-2 ${c.input}`} value={customMinutes}
                  onChange={e => setCustomMinutes(e.target.value)} placeholder={t('fpo_custom_ph')} />
              </div>
            </div>

            <label className="mt-4 block">
              <span className={`text-sm font-semibold ${c.label}`}>{t('fpo_enough_q')}</span>
              <textarea rows={3} className={`mt-1 w-full rounded-lg border p-3 ${c.input}`} value={enough}
                onChange={e => setEnough(e.target.value)} placeholder={t('fpo_enough_ph')} />
            </label>
            <button type="button" onClick={makeConcrete} disabled={loading || !task.trim()}
              className={`mt-2 text-sm font-semibold ${linkStyle} disabled:opacity-40`}>
              ✨ {t('fpo_make_concrete')}
            </button>

            <div className={`mt-4 rounded-lg border ${c.border} ${c.cardAlt} p-3`}>
              <p className={`text-sm font-semibold ${c.label}`}>{t('fpo_not_fill_title')}</p>
              <p className={`mt-1 text-sm ${c.textMuted}`}>{t('fpo_not_fill_body')}</p>
            </div>
          </Card>

          {suggested && (
            <Card c={c} className={c.infoBox}>
              <p className="text-xs font-bold uppercase">{t('fpo_suggested_label')}</p>
              <p className="mt-1 text-sm font-semibold">{suggested}</p>
              <div className="mt-3 flex flex-wrap gap-2">
                <button type="button" onClick={() => begin(suggested)} disabled={loading}
                  className={`min-h-[44px] rounded-lg px-4 py-2 text-sm font-bold ${c.btnPrimary}`}>{t('fpo_use_this')}</button>
                <button type="button" onClick={() => { setEnough(suggested); setSuggested(''); }}
                  className={`min-h-[44px] rounded-lg px-4 py-2 text-sm font-semibold ${c.btnSecondary}`}>{t('fpo_edit')}</button>
              </div>
            </Card>
          )}

          <button type="button" onClick={startSession} disabled={!task.trim() || loading} title={t('fpo_cmd_enter')}
            className={`relative min-h-[48px] w-full rounded-xl px-4 py-3 font-bold transition whitespace-nowrap ${task.trim() && !loading ? c.btnPrimary : c.btnIdle}`}>
            {loading
              ? <><span className="inline-block animate-spin">{tool?.icon ?? '🎩'}</span> <span>{t('fpo_starting')}</span></>
              : <><span>{tool?.icon ?? '🎩'}</span> <span>{t('fpo_start')}</span></>}
            {!loading && (
              <kbd aria-hidden="true" className="hidden sm:flex items-center absolute end-3 top-1/2 -translate-y-1/2 px-1.5 py-0.5 rounded border border-white/30 bg-white/15 text-[10px] font-bold tracking-wide">⌘↵</kbd>
            )}
          </button>

          {crossRef}
        </>
      )}

      {/* ── RUNNING ── */}
      {session?.status === 'running' && (
        <>
          <section className={`rounded-xl border-2 p-5 text-center ${overtime ? c.danger : c.infoBox}`}>
            <p className="text-xs font-bold uppercase tracking-wide">{overtime ? t('fpo_overtime') : t('fpo_focusing')}</p>
            <p className="mt-1 text-5xl font-bold tabular-nums">{overtime ? `+${clock(overtimeMs)}` : clock(remainingMs)}</p>
          </section>

          <Card c={c}>
            <p className={`text-xs font-bold uppercase ${c.textMuted}`}>{t('fpo_your_task')}</p>
            <p className={`mt-1 font-semibold ${c.text}`}>{session.task}</p>
            <p className={`mt-3 text-xs font-bold uppercase ${c.textMuted}`}>{t('fpo_enough_label')}</p>
            <p className={`mt-1 text-sm ${c.textSecondary}`}>{session.target}</p>
          </Card>

          {!overtime ? (
            <div className="flex flex-wrap gap-2">
              <button type="button" onClick={getUnstuck} disabled={loading}
                className={`min-h-[44px] flex-1 rounded-lg px-3 py-2 text-sm font-semibold ${c.btnSecondary}`}>{t('fpo_stuck')}</button>
              <button type="button" onClick={finishEarly} disabled={loading}
                className={`min-h-[44px] flex-1 rounded-lg px-3 py-2 text-sm font-semibold ${c.btnSecondary}`}>{t('fpo_finished_early')}</button>
            </div>
          ) : (
            <Card c={c} className={c.danger}>
              <p className="font-bold">{t('fpo_stop_title')}</p>
              <p className="mt-1 text-sm">{t('fpo_stop_body')}</p>
              <div className="mt-3 flex flex-wrap gap-2">
                <button type="button" onClick={finishEarly}
                  className={`min-h-[48px] flex-1 rounded-lg px-4 py-2 font-bold ${c.btnPrimary}`}>{tool?.icon ?? '🎩'} {t('fpo_take_break')}</button>
                <button type="button" onClick={extend} disabled={extensionsLeft <= 0 || loading}
                  className={`min-h-[44px] rounded-lg px-3 py-2 text-sm font-semibold ${extensionsLeft > 0 ? c.btnSecondary : c.btnIdle}`}>
                  {extensionsLeft > 0 ? t('fpo_five_more', { n: extensionsLeft }) : t('fpo_no_extensions')}
                </button>
              </div>
            </Card>
          )}

          {nudge && (
            <Card c={c} className={c.warning}>
              <p className="text-xs font-bold uppercase">{t('fpo_smallest_move')}</p>
              <p className="mt-1 text-sm">{nudge}</p>
            </Card>
          )}
        </>
      )}

      {/* ── REVIEW ── */}
      {session?.status === 'review' && (
        <>
          <Card c={c}>
            <p className={`text-lg font-bold ${c.text}`}>{t('fpo_time_up')}</p>
            <p className={`mt-2 text-sm ${c.textSecondary}`}>{session.target}</p>
            <div className="mt-4 grid gap-2 sm:grid-cols-3">
              {[['yes', 'fpo_yes', 'fpo_yes_sub'], ['almost', 'fpo_almost', 'fpo_almost_sub'], ['stuck', 'fpo_got_stuck', 'fpo_got_stuck_sub']].map(([k, label, sub]) => (
                <button key={k} type="button" aria-pressed={reviewChoice === k}
                  onClick={() => { setReviewChoice(k); if (k === 'yes') submitReview('yes'); }}
                  disabled={loading}
                  className={`min-h-[64px] rounded-lg border px-3 py-2 text-start ${reviewChoice === k ? c.pillActive : c.pillInactive}`}>
                  <span className="block text-sm font-bold">{t(label)}</span>
                  <span className={`block text-xs ${c.textMuted}`}>{t(sub)}</span>
                </button>
              ))}
            </div>

            {(reviewChoice === 'almost' || reviewChoice === 'stuck') && (
              <div className="mt-4">
                <label className="block">
                  <span className={`text-sm font-semibold ${c.label}`}>{t('fpo_what_remains')}</span>
                  <textarea rows={3} className={`mt-1 w-full rounded-lg border p-3 ${c.input}`} value={remaining}
                    onChange={e => setRemaining(e.target.value)} placeholder={t('fpo_what_remains_ph')} />
                </label>
                <button type="button" onClick={() => submitReview(reviewChoice)} disabled={loading}
                  className={`mt-3 min-h-[48px] w-full rounded-xl px-4 py-3 font-bold ${c.btnPrimary}`}>
                  {loading
                    ? <><span className="inline-block animate-spin">{tool?.icon ?? '🎩'}</span> <span>{t('fpo_saving')}</span></>
                    : <span>{t('fpo_leave_breadcrumb')}</span>}
                </button>
              </div>
            )}
          </Card>
          {crossRef}
        </>
      )}

      {/* ── DONE — this is the tool's result ── */}
      {results && (
        <>
          <Card c={c} className={results.completed === 'yes' ? c.success : c.infoBox}>
            <p className="text-lg font-bold">{session.completed === 'yes' ? t('fpo_done_title') : t('fpo_breadcrumb_title')}</p>
            {results.completed === 'yes'
              ? <p className="mt-2 text-sm">{t('fpo_done_body')}</p>
              : <>
                  <p className={`mt-2 text-xs font-bold uppercase ${c.textMuted}`}>{t('fpo_breadcrumb_label')}</p>
                  <p className="mt-1 text-sm font-semibold">{results.breadcrumb}</p>
                  <p className="mt-3 text-sm">{t('fpo_breadcrumb_body')}</p>
                </>}
          </Card>
          <button type="button" onClick={startAnother}
            className={`min-h-[48px] w-full rounded-xl px-4 py-3 font-bold ${c.btnPrimary}`}>{t('fpo_take_break')}</button>
          {/* Written out rather than reusing the shared crossRef: S5.5 counts the
              link itself, and a variable defined above the results block puts
              every href on the wrong side of it. */}
          <p className={`text-center text-sm ${c.textMuted}`}>
            {t('fpo_xref_q')}{' '}
            <a href="/FocusSoundArchitect" className={linkStyle}>🎧 {t('fpo_xref_sound')}</a>
          </p>
        </>
      )}
    </div>
  );
};

FocusPocus.displayName = 'FocusPocus';
export default FocusPocus;
