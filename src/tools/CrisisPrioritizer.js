import React, { useCallback, useEffect, useMemo, useRef, useState } from 'react';
import { useClaudeAPI } from '../hooks/useClaudeAPI';
import { useTheme } from '../hooks/useTheme';
import { usePersistentState } from '../hooks/usePersistentState';
import { useRegisterActions } from '../components/ActionBarContext';
import { useTranslation } from '../i18n/useTranslation';
import { pickExample } from '../utils/exampleRotation';
import { tools } from '../data/tools';

const BRAND = '\n\n— Generated by DeftBrain · deftbrain.com';

// One line of the headline for the recent-plans card.
const previewOf = (headline = '') => headline.slice(0, 80);

const blankTask = () => ({ task: '', deadline: '', who_waiting: '', consequence: '', depends_on: '', context: '' });

function Button({ children, onClick, disabled, primary = false, className = '', c }) {
  return <button type="button" onClick={onClick} disabled={disabled}
    className={`min-h-[44px] rounded-lg border ${c.border} px-4 py-2 text-sm font-semibold disabled:opacity-40 ${primary ? `shadow-sm ${c.btnPrimary}` : c.btnSecondary} ${className}`}>{children}</button>;
}
function Field({ label, children, hint, c }) {
  return <label className="block"><span className={`text-sm font-semibold ${c.label}`}>{label}</span>{hint && <span className={`block text-xs mt-0.5 ${c.textMuted}`}>{hint}</span>}<div className="mt-1">{children}</div></label>;
}
function Card({ title, children, className = '', c }) {
  return <section className={`rounded-xl border ${c.border} ${c.card} p-4 md:p-5 ${className}`}><h3 className={`font-bold mb-3 ${c.text}`}>{title}</h3>{children}</section>;
}
function Item({ title, why, action, meta, startLabel, c }) {
  return <div className={`rounded-lg border ${c.border} ${c.cardAlt} p-3`}>
    <p className={`font-semibold ${c.text}`}>{title}</p>
    {why && <p className={`text-sm mt-1 ${c.textSecondary}`}>{why}</p>}
    {action && <p className={`text-sm mt-2 ${c.textSecondary}`}><strong>{startLabel}</strong> {action}</p>}
    {meta && <p className={`text-xs mt-2 ${c.textMuted}`}>{meta}</p>}
  </div>;
}
function taskPayload(t) {
  return {
    task: t.task.trim(),
    deadline: t.deadline.trim() || null,
    who_waiting: t.who_waiting.trim() || null,
    consequence: t.consequence.trim() || null,
    depends_on: t.depends_on.trim() || null,
    context: t.context.trim() || null,
  };
}

export default function CrisisPrioritizer() {
  const { callToolEndpoint, loading } = useClaudeAPI();
  const { isDark } = useTheme();
  const { t } = useTranslation();
  const tool = tools.find(x => x.id === 'CrisisPrioritizer');

  // PF-14: the palette is defined before any state.
  const c = {
    text:          isDark ? 'text-zinc-100' : 'text-gray-900',
    textSecondary: isDark ? 'text-zinc-300' : 'text-gray-700',
    textMuted:     isDark ? 'text-zinc-400' : 'text-gray-500',
    labelText:     isDark ? 'text-zinc-200' : 'text-gray-800',
    card:          isDark ? 'bg-zinc-800' : 'bg-white',
    cardAlt:       isDark ? 'bg-zinc-700/40' : 'bg-slate-50',
    soft:          isDark ? 'bg-zinc-900/50' : 'bg-gray-50',
    border:        isDark ? 'border-zinc-700' : 'border-gray-200',
    input:         isDark ? 'bg-zinc-900 border-zinc-600 text-zinc-100' : 'bg-white border-gray-300 text-gray-900',
    btnPrimary:    isDark ? 'bg-cyan-600 hover:bg-cyan-500 text-white' : 'bg-cyan-600 hover:bg-cyan-700 text-white',
    btnSecondary:  isDark ? 'bg-zinc-700 hover:bg-zinc-600 text-zinc-200' : 'bg-gray-100 hover:bg-gray-200 text-gray-700',
    required:      isDark ? 'text-amber-400' : 'text-amber-700',
    danger:        isDark ? 'bg-red-900/20 border-red-700 text-red-200' : 'bg-red-50 border-red-300 text-red-800',
    success:       isDark ? 'bg-emerald-900/20 border-emerald-700 text-emerald-200' : 'bg-emerald-50 border-emerald-300 text-emerald-800',
    warning:       isDark ? 'bg-amber-900/20 border-amber-700 text-amber-200' : 'bg-amber-50 border-amber-300 text-amber-800',
  };
  c.label = c.labelText;          // PF-2
  c.textMuteded = c.textMuted;    // PF-2
  const linkStyle = isDark ? 'text-cyan-400 hover:text-cyan-300 underline' : 'text-cyan-700 hover:text-cyan-900 underline';

  const [tasks, setTasks] = useState([blankTask(), blankTask(), blankTask()]);
  const [dumpText, setDumpText] = useState('');
  const [showDump, setShowDump] = useState(false);
  const [showDetails, setShowDetails] = useState(false);
  const [hours, setHours] = useState('');
  const [energy, setEnergy] = useState('');
  const [context, setContext] = useState('');
  const [subResult, setSubResult] = useState(null);
  const [panel, setPanel] = useState(null);
  const [selectedTask, setSelectedTask] = useState('');
  const [delegateTo, setDelegateTo] = useState('');
  const [period, setPeriod] = useState('this_week');
  const [doneTasks, setDoneTasks] = useState([]);
  const submitRef = useRef(null);
  const canSubmitRef = useRef(false);

  const [result, setResult] = usePersistentState('crisis-prioritizer-v2-result', null);
  const [journal, setJournal] = usePersistentState('crisis-prioritizer-v2-journal', []);

  const cleanTasks = useMemo(() => tasks.filter(x => x.task.trim()).map(taskPayload), [tasks]);
  const allRanked = useMemo(() => result ? [
    ...(result.do_first || []), ...(result.do_next || []), ...(result.can_probably_wait || []),
    ...(result.need_one_fact || [])
  ].map(x => x.task).filter(Boolean) : [], [result]);

  const reset = () => {
    setTasks([blankTask(), blankTask(), blankTask()]);
    setDumpText(''); setHours(''); setEnergy(''); setContext('');
    setResult(null); setSubResult(null); setPanel(null); setSelectedTask(''); setDoneTasks([]);
  };

  const buildFullText = useCallback(() => {
    if (!result?.headline) return '';
    const lines = [`${tool?.icon ?? '🚨'} ${t('cp2_result_title')}`, '', result.headline, ''];
    const section = (label, rows, why) => {
      if (!rows?.length) return;
      lines.push(label);
      rows.forEach(x => {
        lines.push(`• ${x.task}`);
        if (why(x)) lines.push(`  ${why(x)}`);
        if (x.next_action) lines.push(`  ${t('cp2_start')} ${x.next_action}`);
      });
      lines.push('');
    };
    section(t('cp2_do_first'), result.do_first, x => x.why_now);
    section(t('cp2_do_next'), result.do_next, x => x.why_next);
    section(t('cp2_can_wait'), result.can_probably_wait, x => x.why);
    section(t('cp2_need_fact'), result.need_one_fact, x => x.question);
    if (result.capacity_fit?.summary) lines.push(result.capacity_fit.summary, '');
    return lines.join('\n').trim() + BRAND;
  }, [result, tool, t]);

  useRegisterActions(buildFullText(), tool?.title || 'Crisis Prioritizer');

  useEffect(() => {
    const handler = (e) => {
      if (e.target.tagName === 'SELECT') return;
      if ((e.ctrlKey || e.metaKey) && e.key === 'Enter') {
        e.preventDefault();
        if (canSubmitRef.current) submitRef.current?.();
      }
    };
    document.addEventListener('keydown', handler);
    return () => document.removeEventListener('keydown', handler);
  }, []);

  const updateTask = (i, key, value) => setTasks(prev => prev.map((x, n) => n === i ? { ...x, [key]: value } : x));
  const addTask = () => setTasks(prev => [...prev, blankTask()]);
  const removeTask = i => setTasks(prev => prev.filter((_, n) => n !== i));

  const loadExample = () => {
    const ex = pickExample('CrisisPrioritizer', [
      {
        tasks: [
          { task: 'Send the Q3 numbers to Dana', deadline: 'Friday', who_waiting: 'Dana', consequence: '', depends_on: '', context: '' },
          { task: 'Reply to the landlord about the lease renewal', deadline: '', who_waiting: 'landlord', consequence: '', depends_on: '', context: '' },
          { task: 'Renew the car registration', deadline: '', who_waiting: '', consequence: '', depends_on: '', context: '' },
          { task: 'Book a dentist appointment', deadline: '', who_waiting: '', consequence: '', depends_on: '', context: '' },
        ],
        hours: 'about 2 hours', energy: 'low',
        context: 'Two of these have been on the list for a fortnight.',
      },
      {
        tasks: [
          { task: 'Finish the grant application', deadline: 'the 30th', who_waiting: '', consequence: 'the round closes', depends_on: 'budget numbers from Priya', context: '' },
          { task: 'Get the budget numbers from Priya', deadline: '', who_waiting: '', consequence: '', depends_on: '', context: '' },
          { task: 'Cancel the old storage unit', deadline: '', who_waiting: '', consequence: '', depends_on: '', context: '' },
        ],
        hours: 'about 4 hours', energy: 'okay',
        context: 'Priya is away until Wednesday.',
      },
    ]);
    setTasks(ex.tasks.map(x => ({ ...blankTask(), ...x })));
    setHours(ex.hours); setEnergy(ex.energy); setContext(ex.context);
    setShowDetails(true); setShowDump(false);
    setResult(null); setSubResult(null); setPanel(null);
  };

  const extractDump = async () => {
    if (!dumpText.trim()) return;
    const data = await callToolEndpoint('crisis-prioritizer', { action: 'quick-dump', text: dumpText.trim() });
    if (data?.tasks) {
      setTasks(data.tasks.map(x => ({
        task: x.task || '', deadline: x.deadline || '', who_waiting: x.who_waiting || '',
        consequence: x.consequence || '', depends_on: x.depends_on || '', context: ''
      })));
      if (data.context_notes?.length) setContext(data.context_notes.join('\n'));
      setShowDump(false);
    }
  };

  const generate = async () => {
    if (!cleanTasks.length) return;
    const data = await callToolEndpoint('crisis-prioritizer', {
      action: 'generate', tasks: cleanTasks, energy_level: energy || null,
      hours_available: hours || null, context: context.trim() || null
    });
    setResult(data); setSubResult(null); setPanel(null); setDoneTasks([]);
    if (data?.headline) {
      // Exception to the cap of 6: the backend's history-patterns action reads
      // up to 20 sessions, and recurrence across fewer than that is not a
      // pattern — it is a coincidence with a sample size.
      setJournal(prev => [{
        at: new Date().toISOString(),
        preview: previewOf(data.headline),
        tasks: cleanTasks,
        result: data,
      }, ...prev].slice(0, 20));
    }
  };

  const oneThing = async () => {
    const data = await callToolEndpoint('crisis-prioritizer', {
      action: 'just-one-thing', tasks: cleanTasks, energy_level: energy || null,
      hours_available: hours || null, context: context.trim() || null
    });
    setSubResult({ type: 'one', data }); setPanel('result');
  };

  const splitTask = async () => {
    if (!selectedTask) return;
    const data = await callToolEndpoint('crisis-prioritizer', {
      action: 'split-task', task: selectedTask, context: context.trim() || null, energy_level: energy || null
    });
    setSubResult({ type: 'split', data }); setPanel('result');
  };

  const delegate = async () => {
    if (!selectedTask) return;
    const data = await callToolEndpoint('crisis-prioritizer', {
      action: 'delegate', task: selectedTask, delegateTo: delegateTo.trim() || null, context: context.trim() || null
    });
    setSubResult({ type: 'delegate', data }); setPanel('result');
  };

  const schedule = async () => {
    const priorities = (result?.do_first || []).concat(result?.do_next || []).map(x => ({ task: x.task, deadline: x.deadline || null }));
    const data = await callToolEndpoint('crisis-prioritizer', {
      action: 'time-block', priorities, hours_available: hours || null, energy_level: energy || null
    });
    setSubResult({ type: 'schedule', data }); setPanel('result');
  };

  const planPeriod = async () => {
    const data = await callToolEndpoint('crisis-prioritizer', {
      action: 'plan-period', tasks: cleanTasks, period, hours_available: hours || null,
      energy_level: energy || null, constraints: context.trim() || null
    });
    setSubResult({ type: 'period', data }); setPanel('result');
  };

  // Which tasks are done is a list the visitor already has on screen — it is
  // chosen by ticking it, not typed into a browser prompt() as semicolons.
  const retriage = async () => {
    const remaining = cleanTasks.filter(x => !doneTasks.includes(x.task));
    if (!remaining.length) return;
    const data = await callToolEndpoint('crisis-prioritizer', {
      action: 're-triage', completedTasks: doneTasks, remainingTasks: remaining,
      energy_level: energy || null, hours_remaining: hours || null
    });
    if (data) { setResult(data); setSubResult(null); setPanel(null); }
  };

  submitRef.current = generate;
  canSubmitRef.current = !result && !loading && cleanTasks.length > 0;

  const spinner = <span className="animate-spin inline-block me-1">{tool?.icon ?? '🚨'}</span>;

  return <div className={`space-y-5 ${c.text}`}>
    {/* ── Unified header card: icon + tagline + Try an example + reset ── */}
    <div className={`${c.card} border ${c.border} rounded-xl shadow-sm px-5 pt-2.5 pb-5`}>
      <div className="flex items-start justify-between gap-3">
        <div className="flex-1 min-w-0">
          {/* PF-30 — the wrapper already prints the name as the page <h1>. */}
          <p className={`text-base ${c.textSecondary}`}>
            <span className="me-2 text-lg">{tool?.icon ?? '🚨'}</span>{t('cp2_tagline')}
          </p>
          {/* PF-17c */}
          <button onClick={loadExample} disabled={loading} style={{ backgroundColor: (tool?.headerColor ?? '#888888') + '80' }}
            className="mt-2 px-4 py-2 rounded-full text-sm font-semibold border border-black/25 text-zinc-900 shadow-sm hover:brightness-105 hover:shadow transition disabled:opacity-40 whitespace-nowrap">
            ✨ {t('try_example')}
          </button>
        </div>
        {(result || cleanTasks.length || dumpText.trim()) ? (
          <button onClick={reset} className={`shrink-0 px-3 py-2 rounded-lg text-sm font-bold min-h-[40px] ${c.btnSecondary}`}>
            ↺ {t('start_over')}
          </button>
        ) : null}
      </div>
    </div>

    {!result ? <>
      <Card c={c} title={t('cp2_input_title')}>
        <p className={`text-sm mb-4 ${c.textMuted}`}>{t('cp2_input_sub')}</p>

        <div className="flex flex-wrap gap-2 mb-4">
          <Button c={c} onClick={() => setShowDump(!showDump)}>🧠 {showDump ? t('cp2_use_list') : t('cp2_paste_dump')}</Button>
          <Button c={c} onClick={() => setShowDetails(!showDetails)}>{showDetails ? t('cp2_hide_details') : t('cp2_show_details')}</Button>
        </div>

        {showDump ? <div className="space-y-3">
          <textarea className={`w-full rounded-lg border p-3 text-base ${c.input}`} rows={8}
            value={dumpText} onChange={e => setDumpText(e.target.value)}
            placeholder={t('cp2_dump_ph')} />
          <Button c={c} primary onClick={extractDump} disabled={loading || !dumpText.trim()}>{loading ? <>{spinner}{t('cp2_sorting')}</> : t('cp2_dump_cta')}</Button>
        </div> : <div className="space-y-3">
          {tasks.map((x, i) => <div key={i} className={`rounded-lg border ${c.border} p-3 ${c.soft}`}>
            <div className="flex gap-2">
              <input className={`flex-1 rounded-lg border p-3 text-base ${c.input}`} value={x.task}
                onChange={e => updateTask(i, 'task', e.target.value)} placeholder={t('cp2_task_ph', { n: i + 1 })} />
              {tasks.length > 1 && <Button c={c} onClick={() => removeTask(i)}>×</Button>}
            </div>
            {showDetails && <div className="grid md:grid-cols-2 gap-2 mt-3">
              <input className={`rounded-lg border p-2 ${c.input}`} value={x.deadline} onChange={e => updateTask(i, 'deadline', e.target.value)} placeholder={t('cp2_ph_deadline')} />
              <input className={`rounded-lg border p-2 ${c.input}`} value={x.who_waiting} onChange={e => updateTask(i, 'who_waiting', e.target.value)} placeholder={t('cp2_ph_waiting')} />
              <input className={`rounded-lg border p-2 ${c.input}`} value={x.consequence} onChange={e => updateTask(i, 'consequence', e.target.value)} placeholder={t('cp2_ph_consequence')} />
              <input className={`rounded-lg border p-2 ${c.input}`} value={x.depends_on} onChange={e => updateTask(i, 'depends_on', e.target.value)} placeholder={t('cp2_ph_depends')} />
            </div>}
          </div>)}
          <Button c={c} onClick={addTask}>+ {t('cp2_add_another')}</Button>
        </div>}
      </Card>

      <Card c={c} title={t('cp2_today_title')}>
        <div className="grid md:grid-cols-2 gap-4">
          <Field c={c} label={t('cp2_time_label')} hint={t('cp2_time_hint')}>
            <select className={`w-full rounded-lg border p-3 ${c.input}`} value={hours} onChange={e => setHours(e.target.value)}>
              <option value="">{t('cp2_time_none')}</option>
              <option value="about 1 hour">{t('cp2_time_1')}</option>
              <option value="about 2 hours">{t('cp2_time_2')}</option>
              <option value="about 4 hours">{t('cp2_time_4')}</option>
              <option value="most of the day">{t('cp2_time_day')}</option>
            </select>
          </Field>
          <Field c={c} label={t('cp2_energy_label')} hint={t('cp2_energy_hint')}>
            <select className={`w-full rounded-lg border p-3 ${c.input}`} value={energy} onChange={e => setEnergy(e.target.value)}>
              <option value="">{t('cp2_energy_none')}</option>
              <option value="running on fumes">{t('cp2_energy_fumes')}</option>
              <option value="low">{t('cp2_energy_low')}</option>
              <option value="okay">{t('cp2_energy_okay')}</option>
              <option value="good">{t('cp2_energy_good')}</option>
            </select>
          </Field>
        </div>
        <Field c={c} label={t('cp2_context_label')} hint={t('cp2_context_hint')}>
          <textarea className={`w-full rounded-lg border p-3 text-base ${c.input}`} rows={3} value={context} onChange={e => setContext(e.target.value)} />
        </Field>
      </Card>

      <div className="grid sm:grid-cols-2 gap-2">
        <Button c={c} primary className="w-full" onClick={generate} disabled={loading || !cleanTasks.length}>
          {loading ? <>{spinner}{t('cp2_prioritizing')}</> : <>{t('cp2_prioritize_cta')} <span className="opacity-60 text-xs ms-1">⌘↵</span></>}
        </Button>
        <Button c={c} className="w-full" onClick={oneThing} disabled={loading || !cleanTasks.length}>🎯 {t('cp2_one_cta')}</Button>
      </div>

      {!!journal.length && <Card c={c} title={t('cp2_recent_title', { n: journal.length })}>
        <div className="space-y-2">
          {journal.slice(0, 6).map((entry, i) => (
            <button key={i} type="button" onClick={() => { setResult(entry.result); setSubResult(null); setPanel(null); }}
              className={`w-full text-start rounded-lg border ${c.border} ${c.cardAlt} p-3`}>
              <span className={`block text-sm ${c.text}`}>{entry.preview}</span>
              <span className={`block text-xs mt-1 ${c.textMuted}`}>{new Date(entry.at).toLocaleDateString()}</span>
            </button>
          ))}
        </div>
      </Card>}

      <p className={`text-xs text-center px-4 ${c.textMuted}`}>
        {t('cp2_xref_pre')} <a href="/BrainDumpBuddy" className={linkStyle}>🧠 {t('cp2_xref_bdb')}</a>
      </p>
    </> : <>
      <Card c={c} title={t('cp2_result_title')}>
        <p className={`text-lg font-semibold ${c.text}`}>{result.headline}</p>
        {result.capacity_fit?.summary && <p className={`text-sm mt-2 ${c.textMuted}`}>{result.capacity_fit.summary}</p>}
        {result.capacity_fit?.if_it_does_not_fit && <p className={`text-sm mt-2 ${c.textSecondary}`}>{result.capacity_fit.if_it_does_not_fit}</p>}
      </Card>

      {!!result.do_first?.length && <Card c={c} title={t('cp2_do_first')}>
        <div className="space-y-2">{result.do_first.map((x, i) => <Item key={i} c={c} startLabel={t('cp2_start')} title={x.task} why={x.why_now} action={x.next_action}
          meta={[x.deadline && t('cp2_meta_deadline', { v: x.deadline }), x.who_waiting && t('cp2_meta_waiting', { v: x.who_waiting })].filter(Boolean).join(' · ')} />)}</div>
      </Card>}

      {!!result.do_next?.length && <Card c={c} title={t('cp2_do_next')}>
        <div className="space-y-2">{result.do_next.map((x, i) => <Item key={i} c={c} startLabel={t('cp2_start')} title={x.task} why={x.why_next} action={x.next_action}
          meta={x.deadline ? t('cp2_meta_deadline', { v: x.deadline }) : null} />)}</div>
      </Card>}

      {!!result.can_probably_wait?.length && <Card c={c} title={t('cp2_can_wait')}>
        <div className="space-y-2">{result.can_probably_wait.map((x, i) => <Item key={i} c={c} startLabel={t('cp2_start')} title={x.task} why={x.why}
          meta={x.revisit ? t('cp2_meta_revisit', { v: x.revisit }) : null} />)}</div>
      </Card>}

      {!!result.need_one_fact?.length && <Card c={c} title={t('cp2_need_fact')}>
        <p className={`text-sm mb-3 ${c.textMuted}`}>{t('cp2_need_fact_sub')}</p>
        <div className="space-y-2">{result.need_one_fact.map((x, i) => <Item key={i} c={c} startLabel={t('cp2_start')} title={x.task} why={x.question} meta={x.why_it_matters} />)}</div>
      </Card>}

      {result.just_one_thing && <Card c={c} title={t('cp2_just_one_title')}>
        {result.just_one_thing.task
          ? <Item c={c} startLabel={t('cp2_start')} title={result.just_one_thing.task} action={result.just_one_thing.first_action} why={result.just_one_thing.why} />
          : <p className={c.textSecondary}>{result.just_one_thing.why}</p>}
      </Card>}

      <Card c={c} title={t('cp2_more_title')}>
        <div className="grid sm:grid-cols-2 lg:grid-cols-3 gap-2">
          <Button c={c} onClick={() => { setPanel('split'); setSubResult(null); }}>{t('cp2_btn_split')}</Button>
          <Button c={c} onClick={schedule} disabled={loading || !(result.do_first?.length || result.do_next?.length)}>{t('cp2_btn_schedule')}</Button>
          <Button c={c} onClick={() => { setPanel('delegate'); setSubResult(null); }}>{t('cp2_btn_delegate')}</Button>
          <Button c={c} onClick={() => { setPanel('progress'); setSubResult(null); }} disabled={loading}>{t('cp2_btn_progress')}</Button>
          <Button c={c} onClick={() => { setPanel('period'); setSubResult(null); }}>{t('cp2_btn_period')}</Button>
          <Button c={c} onClick={oneThing} disabled={loading}>{t('cp2_btn_one')}</Button>
        </div>
      </Card>

      {(panel === 'split' || panel === 'delegate') && <Card c={c} title={panel === 'split' ? t('cp2_split_title') : t('cp2_delegate_title')}>
        <select className={`w-full rounded-lg border p-3 ${c.input}`} value={selectedTask} onChange={e => setSelectedTask(e.target.value)}>
          <option value="">{t('cp2_choose_task')}</option>{allRanked.map((x, i) => <option key={i} value={x}>{x}</option>)}
        </select>
        {panel === 'delegate' && <input className={`w-full rounded-lg border p-3 mt-3 ${c.input}`} value={delegateTo} onChange={e => setDelegateTo(e.target.value)} placeholder={t('cp2_delegate_to_ph')} />}
        <Button c={c} primary className="mt-3" onClick={panel === 'split' ? splitTask : delegate} disabled={loading || !selectedTask}>
          {loading ? <>{spinner}{t('cp2_working')}</> : panel === 'split' ? t('cp2_split_cta') : t('cp2_delegate_cta')}
        </Button>
      </Card>}

      {panel === 'progress' && <Card c={c} title={t('cp2_progress_title')}>
        <p className={`text-sm mb-3 ${c.textMuted}`}>{t('cp2_progress_sub')}</p>
        <div className="space-y-2">
          {allRanked.map((x, i) => (
            <label key={i} className={`flex items-start gap-3 rounded-lg border ${c.border} ${c.cardAlt} p-3 cursor-pointer`}>
              <input type="checkbox" className="mt-0.5 h-5 w-5 shrink-0" checked={doneTasks.includes(x)}
                onChange={() => setDoneTasks(prev => prev.includes(x) ? prev.filter(d => d !== x) : [...prev, x])} />
              <span className={`text-sm ${c.text}`}>{x}</span>
            </label>
          ))}
        </div>
        <Button c={c} primary className="mt-3" onClick={retriage} disabled={loading || !doneTasks.length || doneTasks.length === allRanked.length}>
          {loading ? <>{spinner}{t('cp2_working')}</> : t('cp2_progress_cta')}
        </Button>
      </Card>}

      {panel === 'period' && <Card c={c} title={t('cp2_period_title')}>
        <select className={`w-full rounded-lg border p-3 ${c.input}`} value={period} onChange={e => setPeriod(e.target.value)}>
          <option value="this_week">{t('cp2_period_week')}</option><option value="few_weeks">{t('cp2_period_weeks')}</option>
        </select>
        <Button c={c} primary className="mt-3" onClick={planPeriod} disabled={loading}>{loading ? <>{spinner}{t('cp2_planning')}</> : t('cp2_period_cta')}</Button>
      </Card>}

      {subResult && <SubResult result={subResult} c={c} t={t} />}

      <div className="flex flex-wrap gap-2">
        <Button c={c} onClick={() => { setResult(null); setSubResult(null); setPanel(null); }}>← {t('cp2_edit_tasks')}</Button>
      </div>

      {result && (
        <div className={`${c.cardAlt} border ${c.border} rounded-xl p-3 text-center`}>
          <p className={`text-xs ${c.textMuted}`}>
            {t('cp2_xref_post')}{' '}
            <a href="/BatchFlow" className={linkStyle}>🧺 {t('cp2_xref_batch')}</a>{' · '}
            <a href="/PEP" className={linkStyle}>✨ {t('cp2_xref_pep')}</a>
          </p>
        </div>
      )}
    </>}
  </div>;
}

function SubResult({ result, c, t }) {
  const { type, data } = result;
  if (!data) return null;
  if (type === 'one') return <Card c={c} title={t('cp2_just_one_title')}>
    {data.task
      ? <Item c={c} startLabel={t('cp2_start')} title={data.task} action={data.first_action} why={data.why} meta={data.after_this ? t('cp2_meta_after', { v: data.after_this }) : null} />
      : <Item c={c} startLabel={t('cp2_start')} title={t('cp2_need_fact')} why={data.need_one_fact} meta={data.why} />}
  </Card>;
  if (type === 'split') return <Card c={c} title={t('cp2_split_result_title')}>
    <p className={`mb-3 ${c.textSecondary}`}>{data.summary}</p>
    <div className="space-y-2">{(data.steps || []).map((x, i) => <Item key={i} c={c} startLabel={t('cp2_start')} title={`${i + 1}. ${x.step}`} meta={[x.rough_time, x.depends_on && t('cp2_after_step', { v: x.depends_on }), x.can_delegate === 'true' && t('cp2_could_delegate')].filter(Boolean).join(' · ')} />)}</div>
    {data.smallest_start && <p className={`mt-3 ${c.textSecondary}`}><strong>{t('cp2_smallest_start')}</strong> {data.smallest_start}</p>}
  </Card>;
  if (type === 'delegate') return <Card c={c} title={t('cp2_delegate_result_title')}>
    {data.subject_line && <p className={`text-sm mb-2 ${c.textSecondary}`}><strong>{t('cp2_subject')}</strong> {data.subject_line}</p>}
    <div className={`rounded-lg border ${c.border} p-3 whitespace-pre-wrap ${c.soft}`}>{data.message}</div>
    {data.missing_detail && <p className={`text-xs mt-2 ${c.textMuted}`}>{t('cp2_before_sending')} {data.missing_detail}</p>}
  </Card>;
  if (type === 'schedule') return <Card c={c} title={t('cp2_schedule_title')}>
    <p className={`mb-3 ${c.textSecondary}`}>{data.summary}</p>
    <div className="space-y-2">{(data.blocks || []).map((x, i) => <Item key={i} c={c} startLabel={t('cp2_start')} title={x.task} meta={[x.start && x.end ? `${x.start}–${x.end}` : null, x.rough_minutes ? t('cp2_rough_min', { n: x.rough_minutes }) : null, x.note].filter(Boolean).join(' · ')} />)}</div>
    {!!data.not_scheduled?.length && <p className={`mt-3 text-sm ${c.textSecondary}`}><strong>{t('cp2_not_scheduled')}</strong> {data.not_scheduled.join('; ')}</p>}
    {data.adjustment_rule && <p className={`text-sm mt-2 ${c.textMuted}`}>{data.adjustment_rule}</p>}
  </Card>;
  if (type === 'period') return <Card c={c} title={t('cp2_period_result_title')}>
    <p className={`mb-3 ${c.textSecondary}`}>{data.headline}</p>
    <div className="space-y-2">{(data.periods || []).map((x, i) => <div key={i} className={`rounded-lg border ${c.border} ${c.cardAlt} p-3`}><p className={`font-semibold ${c.text}`}>{x.label}: {x.focus}</p><ul className={`list-disc ps-5 text-sm mt-2 ${c.textSecondary}`}>{(x.tasks || []).map((task, j) => <li key={j}>{task}</li>)}</ul>{x.rough_load && <p className={`text-xs mt-2 ${c.textMuted}`}>{x.rough_load}</p>}</div>)}</div>
    {!!data.need_one_fact?.length && <p className={`mt-3 text-sm ${c.textSecondary}`}><strong>{t('cp2_need_fact')}:</strong> {data.need_one_fact.map(x => `${x.task}: ${x.question}`).join(' · ')}</p>}
    {data.capacity_note && <p className={`text-sm mt-2 ${c.textMuted}`}>{data.capacity_note}</p>}
  </Card>;
  return null;
}

