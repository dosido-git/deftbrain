import React, { useState, useCallback, useRef, useEffect } from 'react';
import { useClaudeAPI } from '../hooks/useClaudeAPI';
import { useTheme } from '../hooks/useTheme';
import { useRegisterActions } from '../components/ActionBarContext';
import { usePersistentState } from '../hooks/usePersistentState';
import { useTranslation } from '../i18n/useTranslation';
import { pickExample } from '../utils/exampleRotation';
import { revealSection } from '../utils/revealSection';

const BRAND = '\n\n— Generated by DeftBrain · deftbrain.com';

// ════════════════════════════════════════════════════════════
// CONSTANTS
// ════════════════════════════════════════════════════════════
const SOURCE_TYPES = [
  { value: 'texts', labelKey: 'wmv_src_texts', icon: '💬' },
  { value: 'emails', labelKey: 'wmv_src_emails', icon: '📧' },
  { value: 'social', labelKey: 'wmv_src_social', icon: '📱' },
  { value: 'dating', labelKey: 'wmv_src_dating', icon: '💘' },
  { value: 'work-slack', labelKey: 'wmv_src_work', icon: '💼' },
  { value: 'other', labelKey: 'wmv_src_other', icon: '✍️' },
];

// ════════════════════════════════════════════════════════════
// COMPONENT
// ════════════════════════════════════════════════════════════
const EXAMPLES = [
  {
    samples: `lmao okay so I tried the new ramen place and it was... aggressively fine? like nothing bad happened but nothing happened. the broth was doing its best.

anyway running 20 min late to your thing tonight, sorry in advance, I'll bring snacks as tribute

also did you see that email from Derek. classic Derek behavior. we need to discuss

also also I found a dog on my walk and his name was apparently Gerald which is extremely correct for him`,
    sourceType: 'texts',
  },
  {
    samples: `Per my earlier communication, I wanted to follow up on the outstanding deliverable we discussed. Moving forward, I think it would be beneficial to align on expectations to ensure we're all rowing in the same direction. Please advise at your earliest convenience.`,
    sourceType: 'emails',
  },
  {
    samples: `just a girl who forgot she had a dentist appointment and found out the hard way 💀

living for this random Tuesday sunset though, no context needed

reminder that you're allowed to cancel plans and it doesn't make you a bad person, it makes you tired

okay but why did nobody tell me oat milk in coffee changes EVERYTHING`,
    sourceType: 'social',
  },
  {
    samples: `Hey! I saw you like hiking, do you have a favorite trail around here?

Also I have to ask about the photo with the golden retriever, is that yours or a very lucky encounter

No pressure to answer both, just genuinely curious about the trail one lol`,
    sourceType: 'dating',
  },
  {
    samples: `quick q — did anyone else's build break this morning or is it just me

nvm found it, someone pushed straight to main again lol

anyway standup moved to 10:15, calendar invite incoming

also does anyone want the extra donuts in the kitchen, they will not last past noon otherwise`,
    sourceType: 'work-slack',
  },
];
const WhatsMyVibe = ({ tool }) => {
  const { callToolEndpoint, loading, userLocale, userCurrency, userRegion } = useClaudeAPI();
  const { isDark } = useTheme();
  const { t } = useTranslation();

  const c = {
    card:              isDark ? 'bg-zinc-800' : 'bg-white',
    cardAlt:           isDark ? 'bg-zinc-700/50' : 'bg-slate-50',
    input:             isDark ? 'bg-zinc-900 border-zinc-600 text-zinc-100 placeholder-zinc-400 focus:border-cyan-500 focus:ring-cyan-500/20' : 'bg-white border-gray-300 text-gray-900 placeholder-gray-400 focus:border-cyan-500 focus:ring-cyan-100',
    text:              isDark ? 'text-zinc-50' : 'text-gray-900',
    textSecondary:     isDark ? 'text-zinc-300' : 'text-gray-600',
    textMuted:         isDark ? 'text-zinc-400' : 'text-gray-500',
    required:      isDark ? 'text-amber-400' : 'text-amber-700',
    accentTxt:         isDark ? 'text-cyan-400' : 'text-cyan-600',
    btnPrimary:        isDark ? 'bg-cyan-600 hover:bg-cyan-500 text-white' : 'bg-cyan-600 hover:bg-cyan-700 text-white',
    // Waiting for input: an outline, not a smudge. Empty fill keeps "filled"
    // meaning "ready"; the border and label carry the visibility. Important
    // modifiers because tools carry their own border/text utilities on the
    // submit and Tailwind resolves conflicts by stylesheet order, not class
    // order. See the PF-13 exception in audit/audit_v2-3-2.py.
    btnIdle:       isDark ? '!bg-transparent !border-2 !border-cyan-500/85 !text-cyan-300 cursor-not-allowed'
                          : '!bg-transparent !border-2 !border-cyan-600/85 !text-cyan-800 cursor-not-allowed',
    btnSecondary:      isDark ? 'bg-zinc-700 hover:bg-zinc-600 text-zinc-200' : 'bg-gray-100 hover:bg-gray-200 text-gray-700',
    border:            isDark ? 'border-zinc-700' : 'border-gray-200',
    success:           isDark ? 'bg-emerald-900/20 border-emerald-600 text-emerald-300' : 'bg-emerald-50 border-emerald-600 text-emerald-700',
    warning:           isDark ? 'bg-amber-900/20 border-amber-500 text-amber-300' : 'bg-amber-50 border-amber-500 text-amber-700',
    danger:            isDark ? 'bg-red-900/20 border-red-700 text-red-200' : 'bg-red-100 border-red-200 text-red-800',
    pillActive:        isDark ? 'border-cyan-500 bg-cyan-900/30 text-cyan-200' : 'border-cyan-600 bg-cyan-100 text-cyan-900',
    pillInactive:      isDark ? 'border-zinc-600 text-zinc-400 hover:border-zinc-500' : 'border-gray-300 text-gray-500 hover:border-gray-400',
    // Category panel tints — Crimson family (Read the Room)
    // Gold AI insight — all tools
    // Tool-specific
    labelText:         isDark ? 'text-zinc-200' : 'text-gray-700',
    quoteBg:           isDark ? 'bg-zinc-700/40' : 'bg-[#f3efe8]',
    infoBox:           isDark ? 'bg-[#7a2e2e]/30 border-[#9a4040]' : 'bg-[#f5eaea] border-[#d4a0a0]',
    vibe:              isDark ? 'bg-[#7a2e2e]/30 border-[#9a4040]' : 'bg-[#f5eaea] border-[#d4a0a0]',
  };
  c.textMuteded = c.textMuted;
  c.label = c.labelText;

  const linkStyle = isDark
    ? 'text-cyan-400 hover:text-cyan-300 underline underline-offset-2'
    : 'text-cyan-700 hover:text-cyan-800 underline underline-offset-2';

  // ── State ──
  const [samples, setSamples] = useState('');
  const [sourceType, setSourceType] = useState('texts');
  const [results, setResults] = usePersistentState('whatsmyvibe-result-v2', null);
  const [error, setError] = useState('');
  const loadExample = () => {
    const ex = pickExample('WhatsMyVibe', EXAMPLES);
    setSamples(ex.samples);
    setSourceType(ex.sourceType);
  };

  const resultsRef = useRef(null);
  // Recent Vibes stores the full result (not a truncated preview: field) so a
  // click can restore the complete analysis and original input, not just
  // reopen a raw snippet of what was pasted.
  const [sessionHistory, setSessionHistory] = usePersistentState('whatsmyvibe-history-v2', []);

  const restoreSession = (entry) => {
    setSamples(entry.samples || '');
    setSourceType(entry.sourceType || 'texts');
    setResults(entry.results || null);
  };

  // ── API ──
  const runVibe = useCallback(async () => {
    if (!samples.trim()) return;
    setError('');
    setResults(null);
    try {
      const data = await callToolEndpoint('whats-my-vibe', {
        samples: samples.trim(),
        sourceType,
        userLocale, userCurrency, userRegion,
      });
      setResults(data);
      setSessionHistory(prev => [{
        id: Date.now(), date: new Date().toISOString(),
        sourceType, samples: samples.trim(), results: data,
      }, ...prev].slice(0, 6));
    } catch (err) {
      setError(err.message || t('wmv_error'));
    } }, [samples, sourceType, callToolEndpoint, setResults, setSessionHistory, userLocale, userCurrency, userRegion, t]);

  // ── Build text ──
  const buildFullText = useCallback(() => {
    if (!results) return '';
    const lines = [`✨ ${t('wmv_copy_header')}`, ''];
    if (results?.vibe_title) lines.push(`🏷️ ${results?.vibe_title}`);
    if (results?.vibe_summary) lines.push(results?.vibe_summary, '');
    if (results?.what_you_do?.length) {
      lines.push(t('wmv_copy_what_you_do'));
      results?.what_you_do?.forEach(q => lines.push(`  → ${q}`));
      lines.push('');
    }
    if (results?.how_it_can_land?.length) {
      lines.push(t('wmv_copy_how_it_can_land'));
      results?.how_it_can_land?.forEach(q => lines.push(`  → ${q}`));
      lines.push('');
    }
    if (results?.signature_moves?.length) {
      lines.push(t('wmv_copy_quirks'));
      results?.signature_moves?.forEach(q => lines.push(`  → ${q}`));
      lines.push('');
    }
    if (results?.easy_to_misread) lines.push(t('wmv_copy_easy_misread'), results?.easy_to_misread, '');
    if (results?.vibe_one_line) lines.push(`💬 ${results?.vibe_one_line}`);
    lines.push(BRAND);
    return lines.join('\n');
  }, [results, t]);

  // Register export content with wrapper ActionBar
  useRegisterActions(buildFullText(), tool?.title || "What's My Vibe");

  // ── Global keyboard handler ──
  // ── Keyboard: SELECT-only guard, ref pattern ──
  const runVibeRef = useRef(null);
  const canSubmitRef = useRef(false);
  runVibeRef.current = runVibe;
  canSubmitRef.current = !!samples.trim() && !loading;

  useEffect(() => {
    const handler = (e) => {
      const tag = document.activeElement?.tagName;
      if (tag === 'SELECT') return;
      if (e.key === 'Enter' && (e.metaKey || e.ctrlKey) && !loading && canSubmitRef.current) {
        e.preventDefault();
        runVibeRef.current?.();
      }
    };
    document.addEventListener('keydown', handler);
    return () => document.removeEventListener('keydown', handler);
  }, [loading]);

  // ── Scroll to results ──
  useEffect(() => {
    if (!results) return;
    const timer = setTimeout(() => revealSection(resultsRef.current), 200);
    return () => clearTimeout(timer);
  }, [results]);

  // Word count + label
  const wordCount = samples.split(/\s+/).filter(Boolean).length;
  const wordQuality = wordCount < 30 ? t('wmv_words_more') : wordCount < 80 ? t('wmv_words_good') : t('wmv_words_great');

  // ════════════════════════════════════════════════════════════
  // RENDER
  // ════════════════════════════════════════════════════════════
  return (<div className={`space-y-4 ${c.text}`}>
      {/* ── Input ── */} <div className={`${c.card} border rounded-xl p-5`}>
        <div className={`mb-4 pb-3 border-b ${c.border}`}>
          <div className="flex items-start justify-between gap-3">
            <div>
              {/* PF-30: the wrapper already prints the name as the page <h1>. */}
              <p className={`text-sm ${c.textSecondary}`}><span className="me-2">{tool?.icon ?? '✨'}</span>{tool?.tagline}</p>
              <button onClick={loadExample} disabled={loading} style={{ backgroundColor: (tool?.headerColor ?? '#888888') + '80' }} className="mt-2 px-4 py-2 rounded-full text-sm font-semibold border border-black/25 text-zinc-900 shadow-sm hover:brightness-105 hover:shadow transition disabled:opacity-40 whitespace-nowrap">✨ {t('try_example')}</button>
            </div>
            {/* PF-16: the tool's one reset, on the title row, from the first keystroke. */}
            {(results || samples.trim()) ? (
              <button onClick={() => { setResults(null); setSamples(''); }} className={`${c.btnSecondary} px-3 py-1.5 rounded-lg text-xs font-semibold flex-shrink-0 whitespace-nowrap`}>
                🔄 {t('wmv_check_another')}
              </button>
            ) : null}
          </div>
        </div>

        {/* Source type */} <div className="mb-4">
          <p className={`text-[10px] font-bold ${c.labelText} uppercase mb-2`}>{t('wmv_src_label')}</p>
          <div className="flex flex-wrap gap-1.5">
            {SOURCE_TYPES.map(s => (<button
                key={s.value} onClick={() => setSourceType(s.value)} className={`px-3 py-1.5 rounded-lg text-xs font-bold border transition-colors min-h-[36px] flex items-center gap-1.5 ${
                  sourceType === s.value ? c.pillActive : c.pillInactive
                }`} >
                <span>{s.icon}</span> {t(s.labelKey)} </button>
            ))} </div>
        </div>

        {/* Samples */} <div className="mb-5">
          <label className={`text-sm font-bold ${c.labelText} block mb-1.5`}>{t('wmv_samples_label')} <span className={c.required}>*</span></label>
          <textarea
            value={samples} onChange={e => setSamples(e.target.value)} placeholder={t('wmv_samples_ph')} rows={8} className={`w-full px-3 py-2.5 border rounded-lg text-sm ${c.input} outline-none focus:ring-2 resize-y`} />
          <p className={`text-[10px] ${c.textMuted} mt-1`}>
            {samples.length > 0 ? `${wordCount} ${t('wmv_words')} — ${wordQuality}` : t('wmv_hint_empty')} </p>
        </div>

        <button title={t('cmd_enter')}
          onClick={runVibe} disabled={!samples.trim() || loading} className={`relative w-full ${(!samples.trim()) ? c.btnIdle : c.btnPrimary} font-bold py-3 rounded-lg flex items-center justify-center gap-2 min-h-[48px]`} >
          {loading
            ? <><span className="inline-block animate-spin">{tool?.icon ?? '✨'}</span> {t('wmv_reading')}</>
            : <><span>{tool?.icon ?? '✨'}</span> {t('wmv_check')}</>} {!loading && (
          <kbd aria-hidden="true"
            className="hidden sm:flex items-center absolute end-3 top-1/2 -translate-y-1/2 px-1.5 py-0.5 rounded border border-white/30 bg-white/15 text-[10px] font-bold tracking-wide">
            ⌘↵
          </kbd>
        )}
        </button>
      </div>

      {/* ── Error ── */} {error && (<div className={`${c.danger} border rounded-lg p-4 flex items-start gap-3`}>
          <span className="flex-shrink-0">⚠️</span>
          <p className="text-sm">{error}</p>
        </div>
      )} {/* ── Results ── */} {results && (<div className="space-y-4">
          <div data-copy-results ref={resultsRef} data-results-anchor  className="scroll-mt-24"/>

          {/* Vibe title */} {results?.vibe_title && (<div className={`${c.vibe} border-2 rounded-xl p-6 text-center`}>
              <span className="text-4xl block mb-3">✨</span>
              <p className={`text-2xl font-black ${c.text} mb-2`}>{results?.vibe_title}</p>
              {results?.vibe_summary && <p className={`text-sm ${c.textSecondary} max-w-md mx-auto`}>{results?.vibe_summary}</p>} </div>
          )} {/* What you do */} {results?.what_you_do?.length > 0 && (<div className={`${c.card} border rounded-xl p-4`}>
              <h3 className={`text-sm font-bold ${c.text} mb-3`}>✏️ {t('wmv_what_you_do')}</h3>
              <div className="space-y-2">
                {results?.what_you_do?.map((q, i) => (<p key={i} className={`text-xs ${c.textSecondary} p-2.5 rounded-lg ${c.quoteBg}`}>→ {q}</p>
                ))} </div>
            </div>
          )} {/* How it can land */} {results?.how_it_can_land?.length > 0 && (<div className={`${c.card} border rounded-xl p-4`}>
              <h3 className={`text-sm font-bold ${c.text} mb-3`}>👀 {t('wmv_how_it_can_land')}</h3>
              <div className="space-y-2">
                {results?.how_it_can_land?.map((q, i) => (<p key={i} className={`text-xs ${c.textSecondary} p-2.5 rounded-lg ${c.quoteBg}`}>→ {q}</p>
                ))} </div>
            </div>
          )} {/* Signature moves */} {results?.signature_moves?.length > 0 && (<div className={`${c.card} border rounded-xl p-4`}>
              <h3 className={`text-sm font-bold ${c.text} mb-3`}>🔍 {t('wmv_quirks')}</h3>
              <div className="space-y-2">
                {results?.signature_moves?.map((q, i) => (<p key={i} className={`text-xs ${c.textSecondary} p-2.5 rounded-lg ${c.quoteBg}`}>→ {q}</p>
                ))} </div>
            </div>
          )} {/* Easy to misread */} {results?.easy_to_misread && (<div className={`${c.infoBox} border rounded-xl p-4`}>
              <p className={`text-[10px] font-bold ${c.accentTxt} uppercase mb-1`}>🤔 {t('wmv_easy_misread')}</p>
              <p className={`text-sm ${c.text}`}>{results?.easy_to_misread}</p>
            </div>
          )} {/* Vibe in one line */} {results?.vibe_one_line && (<div className={`${c.card} border rounded-xl p-4`}>
              <p className={`text-[10px] font-bold ${c.labelText} uppercase mb-1`}>📸 {t('wmv_shareline')}</p>
              <p className={`text-sm font-bold ${c.text}`}>{results?.vibe_one_line}</p>
            </div>
          )}

          {/* Post-result cross-ref — the only one; RelatedLinks already auto-surfaces
              tag/category matches below, and DecoderRing is its top pick for this tool,
              so this points at TruthBomb instead to avoid duplicating that block. */}
          <p className={`text-xs ${c.textMuted} text-center`}>
            <a href="/TruthBomb" className={linkStyle}>💣 {t('wmv_truthbomb_link')}</a>
          </p>
        </div>
      )} {/* eslint-disable-next-line no-restricted-globals */} {sessionHistory.length > 0 && (<div className={`${c.cardAlt} border ${c.border} rounded-xl p-4 mt-4`}>
          <p className={`text-xs font-bold ${c.textMuted} mb-2`}>📋 {t('wmv_recent')}</p>
          <div className="space-y-1">
            {/* eslint-disable-next-line no-restricted-globals */} {sessionHistory.map(s => (<button key={s.id} onClick={() => restoreSession(s)} className="w-full flex items-center justify-between text-start hover:opacity-80">
                <span className="min-w-0">
                  <span className={`block text-xs ${c.textSecondary} truncate`}>
                    {t(SOURCE_TYPES.find(x => x.value === s.sourceType)?.labelKey) || t('wmv_session')} — {s.results?.vibe_title || t('wmv_session')}
                  </span>
                  {s.results?.pattern_tags?.length > 0 && (
                    <span className={`block text-[10px] ${c.textMuted} truncate`}>{s.results.pattern_tags.slice(0, 3).join(' · ')}</span>
                  )}
                </span>
                <span className={`text-xs ${c.textMuted} ms-2 flex-shrink-0`}>{new Date(s.date).toLocaleDateString()}</span>
              </button>
            ))} </div>
        </div>
      )}
    </div>
  );
};

WhatsMyVibe.displayName = 'WhatsMyVibe';
export default WhatsMyVibe;
