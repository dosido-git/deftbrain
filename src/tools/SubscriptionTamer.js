import React, { useCallback, useEffect, useMemo, useState } from 'react';
import { useClaudeAPI } from '../hooks/useClaudeAPI';
import { useTheme } from '../hooks/useTheme';
import { usePersistentState } from '../hooks/usePersistentState';
import { useRegisterActions } from '../components/ActionBarContext';
import { useTranslation } from '../i18n/useTranslation';
import { pickExample } from '../utils/exampleRotation';
import { toolTagline } from '../utils/toolTagline';
import { formatCurrency, currencySymbol } from '../utils/formatLocale';

const BRAND = '\n\n— Generated by DeftBrain · deftbrain.com';
const STORE_KEY = 'subscription-tamer-v2-subs';
// Follow-through layer (2026-09-12): what the visitor decided to do about
// each reviewed subscription, keyed by the same subscription id as `subs` —
// separate persisted key since it's a genuinely new data shape, not a
// migration of the existing one.
const DECISIONS_KEY = 'subscription-tamer-v2-decisions';
const MAX_SUBS = 40;

const USAGE = [
  { value: 'a_lot', labelKey: 'sut_usage_a_lot' },
  { value: 'sometimes', labelKey: 'sut_usage_sometimes' },
  { value: 'barely', labelKey: 'sut_usage_barely' },
  { value: 'forgot', labelKey: 'sut_usage_forgot' },
  { value: 'not_sure', labelKey: 'sut_usage_not_sure' },
];

const CYCLES = [
  { value: 'monthly', labelKey: 'sut_cycle_monthly' },
  { value: 'yearly', labelKey: 'sut_cycle_yearly' },
  { value: 'weekly', labelKey: 'sut_cycle_weekly' },
];

let nextId = Date.now();
const blankSub = (overrides = {}) => ({
  id: String(nextId++),
  name: '',
  cost: '',
  cycle: 'monthly',
  usage: '',
  context: '',
  ...overrides,
});

// Five rotated scenarios, spanning all three review buckets: an obvious
// start_here (forgot/barely), a clear probably_leave_alone (a_lot with
// context), and a genuinely uncertain take_another_look (sometimes/not_sure).
const EXAMPLES = [
  [
    { nameKey: 'sut_ex1_sub1_name', cost: '17.99', cycle: 'monthly', usage: 'barely' },
    { nameKey: 'sut_ex1_sub2_name', cost: '11.99', cycle: 'monthly', usage: 'a_lot', contextKey: 'sut_ex1_sub2_context' },
    { nameKey: 'sut_ex1_sub3_name', cost: '40', cycle: 'monthly', usage: 'forgot' },
  ],
  [
    { nameKey: 'sut_ex2_sub1_name', cost: '9.99', cycle: 'monthly', usage: 'barely' },
    { nameKey: 'sut_ex2_sub2_name', cost: '89', cycle: 'monthly', usage: 'sometimes', contextKey: 'sut_ex2_sub2_context' },
    { nameKey: 'sut_ex2_sub3_name', cost: '25', cycle: 'yearly', usage: 'forgot' },
  ],
  [
    { nameKey: 'sut_ex3_sub1_name', cost: '6.99', cycle: 'monthly', usage: 'sometimes', contextKey: 'sut_ex3_sub1_context' },
    { nameKey: 'sut_ex3_sub2_name', cost: '99', cycle: 'yearly', usage: 'a_lot', contextKey: 'sut_ex3_sub2_context' },
    { nameKey: 'sut_ex3_sub3_name', cost: '4.99', cycle: 'monthly', usage: 'not_sure' },
  ],
  [
    { nameKey: 'sut_ex4_sub1_name', cost: '19.99', cycle: 'monthly', usage: 'forgot' },
    { nameKey: 'sut_ex4_sub2_name', cost: '4.99', cycle: 'monthly', usage: 'a_lot', contextKey: 'sut_ex4_sub2_context' },
    { nameKey: 'sut_ex4_sub3_name', cost: '12', cycle: 'monthly', usage: 'sometimes', contextKey: 'sut_ex4_sub3_context' },
  ],
  [
    { nameKey: 'sut_ex5_sub1_name', cost: '14.99', cycle: 'monthly', usage: 'a_lot', contextKey: 'sut_ex5_sub1_context' },
    { nameKey: 'sut_ex5_sub2_name', cost: '2.99', cycle: 'monthly', usage: 'not_sure' },
    { nameKey: 'sut_ex5_sub3_name', cost: '69.99', cycle: 'yearly', usage: 'barely', contextKey: 'sut_ex5_sub3_context' },
  ],
];

function monthlyEquivalent(cost, cycle) {
  const c = Number(cost) || 0;
  if (cycle === 'yearly') return c / 12;
  if (cycle === 'weekly') return c * 52 / 12;
  return c;
}

const SubscriptionTamer = ({ tool }) => {
  const { callToolEndpoint, loading, userLocale, userCurrency } = useClaudeAPI();
  const { isDark } = useTheme();
  const { t } = useTranslation();
  const sym = currencySymbol(userLocale, userCurrency);
  const fmt = (v) => formatCurrency(v, userLocale, userCurrency);

  const c = {
    card: isDark ? 'bg-zinc-800' : 'bg-white',
    cardAlt: isDark ? 'bg-zinc-900/55' : 'bg-slate-50',
    text: isDark ? 'text-zinc-50' : 'text-slate-900',
    textSecondary: isDark ? 'text-zinc-300' : 'text-slate-600',
    textMuted: isDark ? 'text-zinc-400' : 'text-slate-500',
    labelText: isDark ? 'text-zinc-200' : 'text-slate-700',
    required: isDark ? 'text-amber-400' : 'text-amber-700',
    input: isDark
      ? 'bg-zinc-900 border-zinc-600 text-zinc-50 placeholder:text-zinc-500'
      : 'bg-white border-slate-300 text-slate-900 placeholder:text-slate-400',
    btnPrimary: isDark ? 'bg-cyan-600 hover:bg-cyan-500 text-white' : 'bg-cyan-700 hover:bg-cyan-800 text-white',
    btnIdle: isDark ? '!bg-transparent !border-2 !border-cyan-500/85 !text-cyan-300 cursor-not-allowed'
                    : '!bg-transparent !border-2 !border-cyan-600/85 !text-cyan-800 cursor-not-allowed',
    btnSecondary: isDark ? 'bg-zinc-700 hover:bg-zinc-600 text-zinc-100' : 'bg-slate-100 hover:bg-slate-200 text-slate-800',
    border: isDark ? 'border-zinc-700' : 'border-slate-200',
    pillActive: isDark ? 'border-cyan-500 bg-cyan-900/30 text-cyan-200' : 'border-cyan-600 bg-cyan-100 text-cyan-900',
    pillInactive: isDark ? 'border-zinc-600 text-zinc-400 hover:border-zinc-500' : 'border-slate-300 text-slate-600 hover:border-slate-400',
    danger: isDark ? 'bg-red-900/20 border-red-700 text-red-200' : 'bg-red-50 border-red-200 text-red-800',
    success: isDark ? 'bg-emerald-900/20 border-emerald-700 text-emerald-200' : 'bg-emerald-50 border-emerald-300 text-emerald-800',
    warning: isDark ? 'bg-amber-900/20 border-amber-700 text-amber-200' : 'bg-amber-50 border-amber-300 text-amber-800',
    startHere: isDark ? 'bg-amber-950/30 border-amber-800/60' : 'bg-amber-50 border-amber-200',
    takeLook: isDark ? 'bg-sky-950/25 border-sky-800/50' : 'bg-sky-50 border-sky-200',
    leaveAlone: isDark ? 'bg-emerald-950/20 border-emerald-800/50' : 'bg-emerald-50 border-emerald-200',
  };
  c.textMuteded = c.textMuted;
  c.label = c.labelText;

  const linkStyle = isDark
    ? 'text-cyan-400 hover:text-cyan-300 underline underline-offset-2'
    : 'text-cyan-700 hover:text-cyan-800 underline underline-offset-2';

  const [result, setResult] = useState(null);
  const [error, setError] = useState('');
  const [showStatement, setShowStatement] = useState(false);
  const [statement, setStatement] = useState('');
  const [candidates, setCandidates] = useState([]);
  const [scanning, setScanning] = useState(false);
  const [subs, setSubs] = usePersistentState(STORE_KEY, [blankSub()]);
  const [decisions, setDecisions] = usePersistentState(DECISIONS_KEY, {});

  const handleReset = useCallback(() => {
    setSubs([blankSub()]);
    setResult(null);
    setDecisions({});
    setStatement('');
    setCandidates([]);
    setError('');
  }, [setSubs, setDecisions]);

  const loadExample = useCallback(() => {
    const scenario = pickExample('SubscriptionTamer', EXAMPLES);
    setSubs(scenario.map(item => blankSub({
      name: t(item.nameKey),
      cost: item.cost,
      cycle: item.cycle,
      usage: item.usage,
      context: item.contextKey ? t(item.contextKey) : '',
    })));
    setResult(null);
    setDecisions({});
    setError('');
  }, [t, setSubs, setDecisions]);

  const buildText = useCallback(() => {
    if (!result) return '';
    return [
      t('sut_copy_header'),
      '',
      `${t('sut_copy_monthly')}: ${fmt(result.totals?.monthly)}`,
      `${t('sut_copy_annual')}: ${fmt(result.totals?.annual)}`,
      '',
      ...((result.items || []).map(x => `${x.name}: ${x.bucket.replaceAll('_', ' ')} — ${x.reason}`)),
      BRAND,
    ].join('\n');
  }, [result, t, fmt]);
  useRegisterActions(result ? buildText() : '', tool?.title);

  const updateSub = (id, patch) => {
    setSubs(prev => prev.map(s => s.id === id ? { ...s, ...patch } : s));
    // Edited entries mean the prior review no longer applies to whatever was
    // decided from it — clear a stale decision rather than let it survive.
    setDecisions(prev => {
      if (!(id in prev)) return prev;
      const next = { ...prev };
      delete next[id];
      return next;
    });
    setResult(null);
  };

  const addSub = () => setSubs(prev => [...prev.slice(0, MAX_SUBS - 1), blankSub()]);
  const removeSub = id => {
    setSubs(prev => {
      const next = prev.filter(s => s.id !== id);
      return next.length ? next : [blankSub()];
    });
    setResult(null);
  };

  const validSubs = useMemo(() => subs.filter(s => s.name.trim() && Number(s.cost) >= 0 && s.usage), [subs]);
  const hasDraft = !!(subs.some(s => s.name.trim() || s.cost || s.usage || s.context.trim()) || result);

  const analyze = useCallback(async () => {
    setError('');
    if (!validSubs.length) {
      setError(t('sut_error_need_sub'));
      return;
    }
    try {
      const data = await callToolEndpoint('subscription-tamer', {
        action: 'analyze',
        currency: sym,
        subscriptions: validSubs.map(s => ({
          id: s.id,
          name: s.name.trim(),
          cost: Number(s.cost),
          cycle: s.cycle,
          usage: s.usage,
          context: s.context.trim(),
        })),
      });
      setResult(data);
    } catch (e) {
      setError(e?.message || t('sut_error_generic'));
    }
  }, [validSubs, sym, callToolEndpoint, t]);

  // Cmd/Ctrl+Enter submits the review from anywhere on the form.
  useEffect(() => {
    const handler = (e) => {
      const tag = document.activeElement?.tagName;
      if (tag === 'SELECT') return;
      if (e.key === 'Enter' && (e.metaKey || e.ctrlKey) && !loading && validSubs.length && !result) analyze();
    };
    document.addEventListener('keydown', handler);
    return () => document.removeEventListener('keydown', handler);
  }, [loading, validSubs.length, result, analyze]);

  const scanStatement = async () => {
    setError('');
    if (!statement.trim()) return setError(t('sut_error_need_statement'));
    setScanning(true);
    try {
      const data = await callToolEndpoint('subscription-tamer', {
        action: 'parse',
        statement,
        currency: sym,
      });
      setCandidates(data?.candidates || []);
    } catch (e) {
      setError(e?.message || t('sut_error_generic'));
    } finally {
      setScanning(false);
    }
  };

  const addCandidate = candidate => {
    setSubs(prev => [
      ...prev.filter(s => s.name.trim()),
      blankSub({
        name: candidate.display_name || candidate.merchant_text || '',
        cost: candidate.amount ?? '',
        cycle: candidate.cycle && candidate.cycle !== 'unknown' ? candidate.cycle : 'monthly',
        usage: '',
        context: candidate.why_flagged || '',
      }),
    ]);
  };

  const groups = useMemo(() => {
    const items = result?.items || [];
    return {
      start_here: items.filter(x => x.bucket === 'start_here'),
      take_another_look: items.filter(x => x.bucket === 'take_another_look'),
      probably_leave_alone: items.filter(x => x.bucket === 'probably_leave_alone'),
    };
  }, [result]);

  // Follow-through: what the visitor actually decided about each reviewed
  // subscription. Keep/Cancel/Decide later, plus a completed checkbox on
  // Cancel — the review only becomes useful if something happens after it.
  const decisionStats = useMemo(() => {
    const items = result?.items || [];
    const decided = items.filter(item => decisions[item.id]?.choice);
    const cancel = decided.filter(item => decisions[item.id]?.choice === 'cancel');
    const keep = decided.filter(item => decisions[item.id]?.choice === 'keep');
    const later = decided.filter(item => decisions[item.id]?.choice === 'later');
    const completed = cancel.filter(item => decisions[item.id]?.completed);
    const sumMonthly = list => list.reduce((sum, item) => sum + monthlyEquivalent(item.cost, item.cycle), 0);
    return {
      reviewed: decided.length,
      cancel: cancel.length,
      keep: keep.length,
      later: later.length,
      plannedMonthly: sumMonthly(cancel),
      completedMonthly: sumMonthly(completed),
      completed: completed.length,
    };
  }, [result, decisions]);

  const setDecision = (id, choice) => {
    setDecisions(prev => ({
      ...prev,
      [id]: { ...(prev[id] || {}), choice, completed: choice === 'cancel' ? !!prev[id]?.completed : false },
    }));
  };

  const setLaterNote = (id, note) => setDecisions(prev => ({
    ...prev, [id]: { ...(prev[id] || {}), choice: 'later', note },
  }));

  const toggleCompleted = id => setDecisions(prev => ({
    ...prev, [id]: { ...(prev[id] || {}), choice: 'cancel', completed: !prev[id]?.completed },
  }));

  const usageLabel = (value) => {
    const found = USAGE.find(x => x.value === value);
    return found ? t(found.labelKey) : value;
  };

  // Compact table: two lines per subscription instead of a padded card, so a
  // list of many subscriptions doesn't turn into a long scroll. Line 1 is the
  // scannable row (name, price/cycle/usage, decision); line 2 is the same
  // reason + question prose the card version showed, just without its own
  // border/box around it.
  const renderGroup = (titleKey, subtitleKey, items, className) => {
    if (!items?.length) return null;
    return (
      <section className={`border rounded-2xl overflow-hidden ${className}`}>
        <div className="p-4 sm:p-5 pb-3">
          <h3 className={`text-sm font-black tracking-wide uppercase ${c.text}`}>{t(titleKey)}</h3>
          <p className={`mt-1 text-sm ${c.textSecondary}`}>{t(subtitleKey)}</p>
        </div>
        <div className={`divide-y ${c.border}`}>
          {items.map(item => {
            const choice = decisions[item.id]?.choice;
            return (
              <div key={item.id} className="px-4 sm:px-5 py-3">
                {/* Line 1: name, price/cycle/usage, decision */}
                <div className="flex items-start justify-between gap-3 flex-wrap">
                  <div className="min-w-0 flex items-baseline gap-2 flex-wrap">
                    <span className={`font-bold ${c.text}`}>{item.name}</span>
                    <span className={`text-xs whitespace-nowrap ${c.textMuted}`}>
                      {fmt(item.cost)}/{t(CYCLES.find(x => x.value === item.cycle)?.labelKey || 'sut_cycle_monthly')} · {usageLabel(item.usage)}
                    </span>
                  </div>
                  <div className="flex items-center gap-1.5 shrink-0">
                    {[
                      ['keep', 'sut_decision_keep'],
                      ['cancel', 'sut_decision_cancel'],
                      ['later', 'sut_decision_later'],
                    ].map(([value, labelKey]) => (
                      <button
                        key={value}
                        type="button"
                        onClick={() => setDecision(item.id, value)}
                        className={`rounded-full border px-2.5 py-1 text-xs font-semibold transition-colors ${choice === value ? c.pillActive : c.pillInactive}`}
                      >{t(labelKey)}</button>
                    ))}
                  </div>
                </div>
                {/* Line 2: reason + the one question, as prose */}
                <p className={`mt-1 text-xs leading-5 ${c.textSecondary}`}>
                  {item.reason}
                  {item.question && (
                    <> <span className={c.textMuted}>·</span> <span className={`font-semibold ${c.text}`}>{t('sut_before_you_decide')}</span> {item.question}</>
                  )}
                </p>
                {choice === 'later' && (
                  <input
                    value={decisions[item.id]?.note || ''}
                    onChange={e => setLaterNote(item.id, e.target.value)}
                    placeholder={t('sut_decision_later_ph')}
                    className={`mt-2 w-full rounded-lg border px-2.5 py-1.5 text-xs ${c.input}`}
                  />
                )}
                {choice === 'cancel' && (
                  <label className={`mt-2 inline-flex items-center gap-2 text-xs ${c.textSecondary}`}>
                    <input type="checkbox" checked={!!decisions[item.id]?.completed} onChange={() => toggleCompleted(item.id)} />
                    {t('sut_decision_canceled_it')}
                  </label>
                )}
              </div>
            );
          })}
        </div>
      </section>
    );
  };

  return (
    <div className={`space-y-4 ${c.text}`}>
      <div className={`border rounded-2xl p-5 ${c.card} ${c.border}`}>
        <div className="flex items-start justify-between gap-4">
          <div>
            {/* PF-30 — the wrapper already prints the name as the page <h1>. */}
            <p className={`text-base ${c.textSecondary}`}>
              <span className="me-2 text-lg">{tool?.icon ?? '⚔️'}</span>{toolTagline(tool?.tagline ?? t('sut_tagline'))}
            </p>
            <button onClick={loadExample} disabled={loading} style={{ backgroundColor: (tool?.headerColor ?? '#888888') + '80' }} className="mt-2 px-4 py-2 rounded-full text-sm font-semibold border border-black/25 text-zinc-900 shadow-sm hover:brightness-105 hover:shadow transition disabled:opacity-40 whitespace-nowrap">✨ {t('try_example')}</button>
          </div>
          {hasDraft && (
            <button onClick={handleReset} className={`shrink-0 rounded-lg px-3 py-2 text-sm font-semibold ${c.btnSecondary}`}>↺ {t('start_over')}</button>
          )}
        </div>
      </div>

      {!result && (
        <section className={`border rounded-2xl p-4 sm:p-5 ${c.card} ${c.border}`}>
          <div className="flex flex-wrap items-center justify-between gap-3">
            <div>
              <h2 className={`font-bold ${c.text}`}>{t('sut_your_subs_title')}</h2>
              <p className={`text-sm mt-1 ${c.textMuted}`}>{t('sut_your_subs_hint')}</p>
            </div>
            <button onClick={() => setShowStatement(v => !v)} className={`rounded-lg px-3 py-2 text-sm font-semibold ${c.btnSecondary}`}>{t('sut_import_statement_btn')}</button>
          </div>

          {showStatement && (
            <div className={`mt-4 rounded-xl border p-4 ${c.cardAlt} ${c.border}`}>
              <label className={`text-sm font-semibold ${c.text}`}>{t('sut_paste_label')} <span className={c.required}>*</span></label>
              <textarea
                value={statement}
                onChange={e => setStatement(e.target.value)}
                rows={5}
                placeholder={t('sut_paste_ph')}
                className={`mt-2 w-full rounded-xl border p-3 text-sm ${c.input}`}
              />
              <p className={`mt-2 text-xs ${c.textMuted}`}>{t('sut_paste_hint')}</p>
              <button onClick={scanStatement} disabled={scanning || !statement.trim()} className={`mt-3 rounded-lg px-4 py-2 text-sm font-bold ${c.btnPrimary} disabled:opacity-50`}>
                {scanning ? t('sut_finding_charges') : t('sut_find_charges_btn')}
              </button>
              {!!candidates.length && (
                <div className="mt-4 space-y-2">
                  {candidates.map((x, i) => (
                    <div key={`${x.merchant_text}-${i}`} className={`border rounded-lg p-3 ${c.card} ${c.border}`}>
                      <div className="flex flex-col sm:flex-row gap-2 sm:items-center sm:justify-between">
                        <div>
                          <div className={`font-semibold ${c.text}`}>{x.display_name || x.merchant_text}</div>
                          <div className={`text-xs mt-1 ${c.textMuted}`}>{x.amount != null ? fmt(x.amount) : t('sut_candidate_amount_unclear')} · {x.status || 'possible'}</div>
                          {x.why_flagged && <div className={`text-xs mt-1 ${c.textSecondary}`}>{x.why_flagged}</div>}
                        </div>
                        <button onClick={() => addCandidate(x)} className={`rounded-lg px-3 py-2 text-sm font-semibold ${c.btnSecondary}`}>{t('sut_candidate_add_btn')}</button>
                      </div>
                    </div>
                  ))}
                </div>
              )}
            </div>
          )}

          <div className="mt-5 space-y-4">
            {subs.map((sub, index) => (
              <div key={sub.id} className={`rounded-xl border p-4 ${c.cardAlt} ${c.border}`}>
                <div className="flex items-center justify-between gap-3 mb-3">
                  <div className={`text-xs font-black uppercase tracking-wide ${c.textMuted}`}>{t('sut_sub_label', { n: index + 1 })}</div>
                  <button onClick={() => removeSub(sub.id)} className={`text-sm ${c.textMuted}`} aria-label={t('sut_remove_aria')}>✕</button>
                </div>
                <div className="grid grid-cols-1 sm:grid-cols-12 gap-3">
                  <input
                    value={sub.name}
                    onChange={e => updateSub(sub.id, { name: e.target.value })}
                    placeholder={t('sut_name_ph')}
                    className={`sm:col-span-5 rounded-xl border px-3 py-2.5 ${c.input}`}
                  />
                  <input
                    type="number"
                    min="0"
                    step="0.01"
                    value={sub.cost}
                    onChange={e => updateSub(sub.id, { cost: e.target.value })}
                    placeholder={`${t('sut_price_ph')} (${sym})`}
                    className={`sm:col-span-3 rounded-xl border px-3 py-2.5 ${c.input}`}
                  />
                  <select value={sub.cycle} onChange={e => updateSub(sub.id, { cycle: e.target.value })} className={`sm:col-span-4 rounded-xl border px-3 py-2.5 ${c.input}`}>
                    {CYCLES.map(x => <option key={x.value} value={x.value}>{t(x.labelKey)}</option>)}
                  </select>
                </div>

                <div className="mt-4">
                  <div className={`text-sm font-semibold ${c.text}`}>{t('sut_usage_question')}</div>
                  <div className="mt-2 flex flex-wrap gap-2">
                    {USAGE.map(x => (
                      <button
                        key={x.value}
                        type="button"
                        onClick={() => updateSub(sub.id, { usage: x.value })}
                        className={`rounded-full border px-3 py-2 text-sm font-semibold transition-colors ${sub.usage === x.value ? c.pillActive : c.pillInactive}`}
                      >{t(x.labelKey)}</button>
                    ))}
                  </div>
                </div>

                <div className="mt-4">
                  <label className={`text-sm font-semibold ${c.text}`}>{t('sut_context_label')} <span className={`font-normal ${c.textMuted}`}>{t('sut_context_optional')}</span></label>
                  <textarea
                    value={sub.context}
                    onChange={e => updateSub(sub.id, { context: e.target.value })}
                    rows={2}
                    placeholder={t('sut_context_ph')}
                    className={`mt-2 w-full rounded-xl border px-3 py-2.5 text-sm ${c.input}`}
                  />
                </div>
              </div>
            ))}
          </div>

          <button onClick={addSub} disabled={subs.length >= MAX_SUBS} className={`mt-4 rounded-lg px-4 py-2 text-sm font-semibold ${c.btnSecondary} disabled:opacity-50`}>{t('sut_add_another_btn')}</button>
          {error && <div className={`mt-4 p-3 rounded-xl border text-sm ${c.danger}`}><span className="me-1">⚠️</span>{error}</div>}
          <button title={t('cmd_enter')} onClick={analyze} disabled={loading || !validSubs.length}
            className={`relative mt-5 w-full py-3 rounded-xl font-black flex items-center justify-center gap-2 ${!validSubs.length ? c.btnIdle : c.btnPrimary} disabled:opacity-50`}>
            {loading
              ? <><span className="inline-block animate-spin">{tool?.icon ?? '⚔️'}</span> {t('sut_processing')}</>
              : <><span>{tool?.icon ?? '⚔️'}</span> {t('sut_submit_btn')}</>}
            {!loading && validSubs.length > 0 && (
              <kbd aria-hidden="true"
                className="hidden sm:flex items-center absolute end-3 top-1/2 -translate-y-1/2 px-1.5 py-0.5 rounded border border-white/30 bg-white/15 text-[10px] font-bold tracking-wide">
                ⌘↵
              </kbd>
            )}
          </button>

          <p className={`mt-4 text-xs text-center ${c.textMuted}`}>
            {t('sut_xref_q')} <a href="/BillRescue" className={linkStyle}>{t('sut_xref')}</a>
          </p>
        </section>
      )}

      {result && (
        <>
          <div className={`border rounded-2xl p-5 ${c.card} ${c.border}`}>
            <div className={`text-sm font-black uppercase tracking-wide ${c.textMuted}`}>{t('sut_your_subs_title')}</div>
            <div className="mt-3 grid grid-cols-2 sm:grid-cols-3 gap-3">
              <div className={`rounded-xl border p-4 ${c.cardAlt} ${c.border}`}>
                <div className={`text-xs ${c.textMuted}`}>{t('sut_monthly_label')}</div>
                <div className={`text-2xl font-black mt-1 ${c.text}`}>{fmt(result.totals?.monthly)}</div>
              </div>
              <div className={`rounded-xl border p-4 ${c.cardAlt} ${c.border}`}>
                <div className={`text-xs ${c.textMuted}`}>{t('sut_annual_label')}</div>
                <div className={`text-2xl font-black mt-1 ${c.text}`}>{fmt(result.totals?.annual)}</div>
              </div>
              {/* Live: recalculates the moment a subscription is marked Cancel or Keep — this is
                  the number the old opt-in "What if I stopped this?" checkboxes used to require
                  manual selection to see. Now it just reflects the decisions already made. */}
              <div className={`rounded-xl border p-4 col-span-2 sm:col-span-1 ${c.startHere}`}>
                <div className={`text-xs font-semibold ${c.textMuted}`}>{t('sut_projected_monthly')}</div>
                <div className={`text-2xl font-black mt-1 ${c.text}`}>{fmt((result.totals?.monthly || 0) - decisionStats.plannedMonthly)}</div>
                {decisionStats.cancel > 0 && (
                  <div className={`text-xs mt-1 ${c.textSecondary}`}>{t('sut_projected_monthly_hint', { count: decisionStats.cancel })}</div>
                )}
              </div>
            </div>
            {result.summary && <p className={`mt-4 text-sm leading-6 ${c.textSecondary}`}>{result.summary}</p>}
          </div>

          {renderGroup('sut_start_here_title', 'sut_start_here_subtitle', groups.start_here, c.startHere)}
          {renderGroup('sut_take_another_look_title', 'sut_take_another_look_subtitle', groups.take_another_look, c.takeLook)}
          {renderGroup('sut_leave_alone_title', 'sut_leave_alone_subtitle', groups.probably_leave_alone, c.leaveAlone)}

          <div className={`border rounded-2xl p-5 ${c.card} ${c.border}`}>
            <div className={`text-sm font-black uppercase tracking-wide ${c.textMuted}`}>{t('sut_decisions_title')}</div>
            <div className="mt-3 grid grid-cols-2 sm:grid-cols-4 gap-3">
              <div className={`rounded-xl border p-3 ${c.cardAlt} ${c.border}`}>
                <div className={`text-xs ${c.textMuted}`}>{t('sut_decisions_reviewed')}</div>
                <div className={`text-xl font-black ${c.text}`}>{decisionStats.reviewed}/{result.items?.length || 0}</div>
              </div>
              <div className={`rounded-xl border p-3 ${c.cardAlt} ${c.border}`}>
                <div className={`text-xs ${c.textMuted}`}>{t('sut_decision_cancel')}</div>
                <div className={`text-xl font-black ${c.text}`}>{decisionStats.cancel}</div>
              </div>
              <div className={`rounded-xl border p-3 ${c.cardAlt} ${c.border}`}>
                <div className={`text-xs ${c.textMuted}`}>{t('sut_decision_keep')}</div>
                <div className={`text-xl font-black ${c.text}`}>{decisionStats.keep}</div>
              </div>
              <div className={`rounded-xl border p-3 ${c.cardAlt} ${c.border}`}>
                <div className={`text-xs ${c.textMuted}`}>{t('sut_decision_later')}</div>
                <div className={`text-xl font-black ${c.text}`}>{decisionStats.later}</div>
              </div>
            </div>
            <div className="mt-4 grid grid-cols-1 sm:grid-cols-2 gap-3">
              <div className={`rounded-xl border p-4 ${c.startHere}`}>
                <div className={`text-xs font-black ${c.textMuted}`}>{t('sut_planned_reduction')}</div>
                <div className={`mt-1 text-2xl font-black ${c.text}`}>{t('sut_per_month', { amount: fmt(decisionStats.plannedMonthly) })}</div>
                <div className={`text-sm ${c.textSecondary}`}>{t('sut_per_year_annualized', { amount: fmt(decisionStats.plannedMonthly * 12) })}</div>
              </div>
              <div className={`rounded-xl border p-4 ${c.leaveAlone}`}>
                <div className={`text-xs font-black ${c.textMuted}`}>{t('sut_actually_canceled')}</div>
                <div className={`mt-1 text-2xl font-black ${c.text}`}>{t('sut_per_month', { amount: fmt(decisionStats.completedMonthly) })}</div>
                <div className={`text-sm ${c.textSecondary}`}>{t('sut_per_year_annualized', { amount: fmt(decisionStats.completedMonthly * 12) })} · {t('sut_completed_suffix', { count: decisionStats.completed })}</div>
              </div>
            </div>
          </div>

          <p className={`text-xs text-center ${c.textMuted}`}>
            {t('sut_xref_q')} <a href="/BillRescue" className={linkStyle}>{t('sut_xref')}</a>
          </p>

          <div className="flex flex-wrap gap-3">
            <button onClick={() => setResult(null)} className={`rounded-xl px-4 py-2.5 font-semibold ${c.btnSecondary}`}>{t('sut_edit_subs_btn')}</button>
            <button onClick={() => handleReset()} className={`rounded-xl px-4 py-2.5 font-semibold ${c.btnSecondary}`}>{t('sut_new_review_btn')}</button>
          </div>
        </>
      )}
    </div>
  );
};

SubscriptionTamer.displayName = 'SubscriptionTamer';
export default SubscriptionTamer;
