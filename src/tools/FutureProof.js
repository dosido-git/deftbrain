import React, { useState, useEffect, useRef, useCallback } from 'react';
import { useClaudeAPI } from '../hooks/useClaudeAPI';
import { useTheme } from '../hooks/useTheme';
import { usePersistentState } from '../hooks/usePersistentState';
import { useRegisterActions } from '../components/ActionBarContext';
import { useTranslation } from '../i18n/useTranslation';
import { pickExample } from '../utils/exampleRotation';
import Caret from '../components/Caret';

const BRAND = '\n\n— Generated by DeftBrain · deftbrain.com';


// ─── Constants ───
// Subject types: value is sent to the backend; labelKey is localized at render.
const SUBJECT_TYPES = [
  { value: 'skill',      labelKey: 'fp_type_skill',      icon: '🛠️' },
  { value: 'career',     labelKey: 'fp_type_career',     icon: '💼' },
  { value: 'technology', labelKey: 'fp_type_technology', icon: '⚙️' },
  { value: 'investment', labelKey: 'fp_type_investment', icon: '📈' },
  { value: 'commitment', labelKey: 'fp_type_commitment', icon: '🤝' },
];

const TIMEFRAMES = [
  { value: '1 year',   labelKey: 'fp_tf_1y' },
  { value: '3 years',  labelKey: 'fp_tf_3y' },
  { value: '5 years',  labelKey: 'fp_tf_5y' },
  { value: '10 years', labelKey: 'fp_tf_10y' },
];

const EFFORT_KEYS = { low: 'fp_effort_low', medium: 'fp_effort_medium', high: 'fp_effort_high' };

// How well established a force is, said in words. The old ●●● read as a
// measurement of something; it was the model's own impression of its own
// impression, which is not a quantity and should not have looked like one.
const STATUS_KEYS = {
  observed_now: 'fp_status_observed',
  emerging:     'fp_status_emerging',
  plausible:    'fp_status_plausible',
};
// A card needs both halves. One without the other rendered as a titleless
// paragraph or a heading with nothing under it.
const usableForce = (x) => !!(x && String(x.force || '').trim() && String(x.explanation || '').trim());

const CERTAINTY_KEYS = { high: 'fp_certainty_high', moderate: 'fp_certainty_moderate', low: 'fp_certainty_low' };
const EXPOSURE_KEYS = {
  currently_susceptible:          'fp_exp_susceptible',
  increasingly_assisted:          'fp_exp_assisted',
  difficult_with_current_systems: 'fp_exp_difficult',
  could_become_exposed:           'fp_exp_could',
};

// ════════════════════════════════════════════════════════════
// COMPONENT
// ════════════════════════════════════════════════════════════
const FutureProof = ({ tool }) => {
  const { callToolEndpoint, loading, userLocale, userCurrency, userRegion } = useClaudeAPI();
  const { isDark } = useTheme();
  const { t } = useTranslation();

  const c = {
    card:          isDark ? 'bg-zinc-800' : 'bg-white',
    cardAlt:       isDark ? 'bg-zinc-700/50' : 'bg-slate-50',
    input:         isDark ? 'bg-zinc-900 border-zinc-600 text-zinc-100 placeholder-zinc-400 focus:border-cyan-500 focus:ring-cyan-500/20'
                          : 'bg-white border-gray-300 text-gray-900 placeholder-gray-400 focus:border-cyan-500 focus:ring-cyan-100',
    text:          isDark ? 'text-zinc-50' : 'text-gray-900',
    textSecondary: isDark ? 'text-zinc-300' : 'text-gray-600',
    textMuted:     isDark ? 'text-zinc-400' : 'text-gray-500',
    labelText:     isDark ? 'text-zinc-200' : 'text-gray-700',
    accentTxt:     isDark ? 'text-cyan-400' : 'text-cyan-600',
    btnPrimary:    isDark ? 'bg-cyan-600 hover:bg-cyan-500 text-white'
                          : 'bg-cyan-600 hover:bg-cyan-700 text-white',
    // Waiting for input: an outline, not a smudge. Empty fill keeps "filled"
    // meaning "ready"; the border and label carry the visibility. Important
    // modifiers because tools carry their own border/text utilities on the
    // submit and Tailwind resolves conflicts by stylesheet order, not class
    // order. See the PF-13 exception in audit/audit_v2-3-2.py.
    btnIdle:       isDark ? '!bg-transparent !border-2 !border-cyan-500/85 !text-cyan-300 cursor-not-allowed'
                          : '!bg-transparent !border-2 !border-cyan-600/85 !text-cyan-800 cursor-not-allowed',
    btnSecondary:  isDark ? 'bg-zinc-700 hover:bg-zinc-600 text-zinc-200'
                          : 'bg-gray-100 hover:bg-gray-200 text-gray-700',
    border:        isDark ? 'border-zinc-700' : 'border-gray-200',
    success:       isDark ? 'bg-emerald-900/20 border-emerald-700 text-emerald-200'
                          : 'bg-emerald-50 border-emerald-300 text-emerald-800',
    warning:       isDark ? 'bg-amber-900/20 border-amber-700 text-amber-200'
                          : 'bg-amber-50 border-amber-300 text-amber-800',
    danger:        isDark ? 'bg-red-900/20 border-red-700 text-red-200'
                          : 'bg-red-50 border-red-200 text-red-800',
    infoBox:       isDark ? 'bg-sky-900/20 border-sky-700 text-sky-200'
                          : 'bg-sky-50 border-sky-200 text-sky-800',
    pillActive:    isDark ? 'border-cyan-500 bg-cyan-900/30 text-cyan-200'
                          : 'border-cyan-600 bg-cyan-100 text-cyan-900',
    pillInactive:  isDark ? 'border-zinc-600 text-zinc-400 hover:border-zinc-500'
                          : 'border-gray-300 text-gray-500 hover:border-gray-400',
    required:      isDark ? 'text-amber-400' : 'text-amber-700',
  };
  c.textMuteded = c.textMuted;
  c.label = c.labelText;

  const linkStyle = isDark
    ? 'text-cyan-400 hover:text-cyan-300 underline underline-offset-2'
    : 'text-cyan-700 hover:text-cyan-800 underline underline-offset-2';

  const trajStyle = (traj) => {
    const map = {
      growing:           { bg: isDark ? 'bg-emerald-900/30 border-emerald-600' : 'bg-emerald-50 border-emerald-300', txt: isDark ? 'text-emerald-300' : 'text-emerald-800', dot: '🟢', label: t('fp_traj_growing') },
      stable:            { bg: isDark ? 'bg-cyan-900/30 border-cyan-600'       : 'bg-cyan-50 border-cyan-300',       txt: isDark ? 'text-cyan-300'    : 'text-cyan-800',    dot: '🔵', label: t('fp_traj_stable') },
      transforming:      { bg: isDark ? 'bg-amber-900/30 border-amber-600'     : 'bg-amber-50 border-amber-300',     txt: isDark ? 'text-amber-300'   : 'text-amber-800',   dot: '🟡', label: t('fp_traj_transforming') },
      declining:         { bg: isDark ? 'bg-red-900/30 border-red-600'         : 'bg-red-50 border-red-300',         txt: isDark ? 'text-red-300'     : 'text-red-800',     dot: '🔴', label: t('fp_traj_declining') },
      volatile:          { bg: isDark ? 'bg-orange-900/30 border-orange-600'   : 'bg-orange-50 border-orange-300',   txt: isDark ? 'text-orange-300'  : 'text-orange-800',  dot: '🟠', label: t('fp_traj_volatile') },
      context_dependent: { bg: isDark ? 'bg-cyan-900/30 border-cyan-600'   : 'bg-cyan-50 border-cyan-300',   txt: isDark ? 'text-cyan-300'  : 'text-cyan-800',  dot: '🟣', label: t('fp_traj_context') },
    };
    return map[traj] || map.context_dependent;
  };

  const autoStyle = (level) => {
    const map = {
      high:       { bg: isDark ? 'bg-red-900/20 border-red-700'         : 'bg-red-50 border-red-300',         txt: isDark ? 'text-red-300'     : 'text-red-800'     },
      medium:     { bg: isDark ? 'bg-amber-900/20 border-amber-700'     : 'bg-amber-50 border-amber-300',     txt: isDark ? 'text-amber-300'   : 'text-amber-800'   },
      low:        { bg: isDark ? 'bg-cyan-900/20 border-cyan-700'       : 'bg-cyan-50 border-cyan-300',       txt: isDark ? 'text-cyan-300'    : 'text-cyan-800'    },
      negligible: { bg: isDark ? 'bg-emerald-900/20 border-emerald-700' : 'bg-emerald-50 border-emerald-300', txt: isDark ? 'text-emerald-300' : 'text-emerald-800' },
    };
    return map[level] || map.medium;
  };

  // ─── State ───
  const [subject, setSubject] = useState('');
  const [subjectType, setSubjectType] = useState('');
  const [context, setContext] = useState('');
  const [timeframe, setTimeframe] = useState('5 years');
  const [results, setResults] = usePersistentState('futureproof-result', null);
  const [error, setError] = useState('');
  const [activeScenario, setActiveScenario] = useState('base_case');
  const [showBasis, setShowBasis] = useState(false);
  const [showAutomation, setShowAutomation] = useState(false);
  const [sessionHistory, setSessionHistory] = usePersistentState('futureproof-history', []);

  // ─── Refs ───
  const resultsRef = useRef(null);
  const handleSubmitRef = useRef(null);
  const canSubmitRef = useRef(false);

  canSubmitRef.current = !!subject.trim();

  // ─── Handlers ───
  const handleSubmit = async () => {
    if (!subject.trim()) return;
    setError('');
    setResults(null);
    setActiveScenario('base_case');
    try {
      const data = await callToolEndpoint('future-proof', {
        subject: subject.trim(),
        subjectType: subjectType || undefined,
        context: context.trim() || undefined,
        timeframe,
        userLocale,
        userCurrency,
        userRegion,
      });
      setResults(data);
      setSessionHistory(prev => [{
        id: Date.now(),
        date: new Date().toISOString(),
        preview: subject.trim().slice(0, 40),
        subject: subject.trim(),
        trajectory: data.trajectory,
        timestamp: new Date().toISOString(),
        result: data,
      }, ...(prev || [])].slice(0, 6));
    } catch (err) {
      setError(err.message || t('fp_error'));
    }
  };
  handleSubmitRef.current = handleSubmit;

  const loadExample = useCallback(() => {
    const ex = pickExample('FutureProof', [
      { subj: 'fp_ex_subject',  type: 'career',  ctx: 'fp_ex_context',  years: '5 years' },
      { subj: 'fp_ex2_subject', type: 'skill',   ctx: 'fp_ex2_context', years: '10 years' },
    ]);
    setSubject(t(ex.subj));
    setSubjectType(ex.type);
    setContext(t(ex.ctx));
    setTimeframe(ex.years);
    setResults(null);
  }, [setSubject, setSubjectType, setContext, setTimeframe, setResults, t]);

  const handleReset = () => {
    setSubject('');
    setSubjectType('');
    setContext('');
    setTimeframe('5 years');
    setResults(null);
    setError('');
    setActiveScenario('base_case');
  };

  // ─── Build full text ───
  const buildFullText = useCallback(() => {
    if (!results) return '';
    const r = results;
    const ts = trajStyle(r.trajectory);
    const lines = [
      `🔮 ${t('fp_copy_header')} — ${r.analysis_title || r.subject_as_understood || subject}`,
      r.the_question || '',
      `${t('fp_copy_trajectory')} ${r.trajectory_label || ts.label}`,
      `${t('fp_how_certain')}: ${r.certainty ? t(CERTAINTY_KEYS[r.certainty] || 'fp_certainty_moderate') : ''}${r.certainty_because ? ` — ${r.certainty_because}` : ''}`,
      '',
      `${t('fp_copy_pattern')}\n${r.the_pattern || ''}`,
    ];
    if (r.tailwinds?.length) {
      lines.push('', t('fp_copy_tailwinds'));
      r.tailwinds.forEach(tw => lines.push(`+ ${tw.force}: ${tw.explanation}${STATUS_KEYS[tw.status] ? ` [${t(STATUS_KEYS[tw.status])}]` : ''}`));
    }
    if (r.headwinds?.length) {
      lines.push('', t('fp_copy_headwinds'));
      r.headwinds.forEach(h => lines.push(`- ${h.force}: ${h.explanation}${h.timing ? ` (${h.timing})` : ''}`));
    }
    if (r.the_automation_question) {
      const aq = r.the_automation_question;
      lines.push('', `${t('fp_copy_automation')} ${EXPOSURE_KEYS[aq.exposure] ? t(EXPOSURE_KEYS[aq.exposure]) : ''}`, aq.net_effect || '');
    }
    if (r.the_pivot?.the_version_worth_pursuing) {
      lines.push('', t('fp_copy_version'), r.the_pivot.the_version_worth_pursuing);
    }
    if (r.scenarios) {
      lines.push('', t('fp_copy_scenarios'));
      [['bull_case', 'fp_copy_bull'], ['base_case', 'fp_copy_base'], ['bear_case', 'fp_copy_bear']].forEach(([k, lk]) => {
        const sc = r.scenarios[k];
        if (!sc) return;
        if (typeof sc === 'string') { lines.push(`${t(lk)} ${sc}`); return; }
        lines.push(`${t(lk)} ${t('fp_if_true')}: ${sc.if_true || ''}`);
        if (sc.then) lines.push(`   ${t('fp_then')}: ${sc.then}`);
        if (sc.for_you) lines.push(`   ${t('fp_for_you')}: ${sc.for_you}`);
      });
    }
    const synthesis = r.what_this_means_for_you || r.the_honest_take;
    if (synthesis)    lines.push('', t('fp_means_for_you'), synthesis);
    if (r.one_action) lines.push('', `${t('fp_copy_action')} ${r.one_action}`, r.one_action_why || '');
    const sa = r.sources_and_assumptions;
    if (sa && (sa.observed?.length || sa.inferred?.length || sa.assumed?.length)) {
      lines.push('', t('fp_basis'));
      [['observed', 'fp_basis_observed'], ['inferred', 'fp_basis_inferred'], ['assumed', 'fp_basis_assumed']].forEach(([k, lk]) => {
        if (sa[k]?.length) {
          lines.push(t(lk));
          sa[k].forEach(x => lines.push(typeof x === 'object' && x
            ? `  · ${x.claim}${[x.publisher, x.published].filter(Boolean).length ? ` (${[x.publisher, x.published].filter(Boolean).join(', ')})` : ''}${x.url ? ` ${x.url}` : ''}`
            : `  · ${x}`));
        }
      });
    }
    lines.push(BRAND);
    return lines.join('\n');
  }, [results, subject, t]);

  useRegisterActions(buildFullText(), tool?.title || 'Future Proof');

  // ─── Scroll useEffect ───
  useEffect(() => {
    if (!results || !resultsRef.current) return;
    const timer = setTimeout(() => resultsRef.current?.scrollIntoView({ behavior: 'smooth', block: 'start' }), 200);
    return () => clearTimeout(timer);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [results]);

  // ─── Keyboard useEffect ───
  useEffect(() => {
    const handler = (e) => {
      const tag = document.activeElement?.tagName;
      if (tag === 'SELECT') return;
      if (e.key === 'Enter' && (e.metaKey || e.ctrlKey) && !loading && canSubmitRef.current)
        handleSubmitRef.current?.();
    };
    document.addEventListener('keydown', handler);
    return () => document.removeEventListener('keydown', handler);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [loading]);

  // ════════════════════════════════════════════════════════════
  // RENDER
  // ════════════════════════════════════════════════════════════
  return (
    <div className={`space-y-4 ${c.text}`}>

      {/* Input card */}
      <div className={`${c.card} border ${c.border} rounded-xl shadow-sm px-5 pt-2.5 pb-5`}>
        <div className="pb-3 border-b border-zinc-500">
          <div className="flex items-start justify-between gap-3">
            <div>
              {/* PF-30 — the wrapper already prints the name as the page <h1>. */}
              <p className={`text-base ${c.textSecondary}`}>
                <span className="me-2 text-lg">{tool?.icon ?? '🔮'}</span>{t('fp_tagline')}
              </p>
              <button onClick={loadExample} disabled={loading} style={{ backgroundColor: (tool?.headerColor ?? '#888888') + '80' }} className="mt-2 px-4 py-2 rounded-full text-sm font-semibold border border-black/25 text-zinc-900 shadow-sm hover:brightness-105 hover:shadow transition disabled:opacity-40 whitespace-nowrap">✨ {t('try_example')}</button>
            </div>
            {(results || subject.trim()) && (
              <button onClick={handleReset} className={`${c.btnSecondary} px-3 py-1.5 rounded-lg text-xs font-bold flex-shrink-0`}>
                ↺ {t('start_over')}
              </button>
            )}
          </div>
        </div>

        <div className="mt-4 space-y-4">
          <div>
            <label className={`block text-sm font-medium ${c.labelText} mb-1`}>
              {t('fp_q_label')} <span className={c.required}>*</span>
            </label>
            <input
              type="text"
              value={subject}
              onChange={e => setSubject(e.target.value)}
              placeholder={t('fp_ph_subject')}
              maxLength={200}
              className={`w-full px-3 py-2.5 border rounded-lg text-sm ${c.input} outline-none focus:ring-2`}
            />
          </div>

          <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
            <div>
              <label className={`block text-sm font-medium ${c.labelText} mb-1.5`}>{t('fp_type_label')} <span className={`font-normal ${c.textMuted}`}>{t('fp_optional')}</span></label>
              <div className="flex flex-wrap gap-1.5">
                {SUBJECT_TYPES.map(st => (
                  <button key={st.value} onClick={() => setSubjectType(subjectType === st.value ? '' : st.value)}
                    className={`px-2.5 py-1.5 rounded-lg text-xs font-medium border transition-colors flex items-center gap-1 ${subjectType === st.value ? c.pillActive : c.pillInactive}`}>
                    <span>{st.icon}</span> {t(st.labelKey)}
                  </button>
                ))}
              </div>
            </div>
            <div>
              <label className={`block text-sm font-medium ${c.labelText} mb-1.5`}>{t('fp_horizon_label')}</label>
              <div className="flex flex-wrap gap-1.5">
                {TIMEFRAMES.map(tf => (
                  <button key={tf.value} onClick={() => setTimeframe(tf.value)}
                    className={`px-2.5 py-1.5 rounded-lg text-xs font-medium border transition-colors ${timeframe === tf.value ? c.pillActive : c.pillInactive}`}>
                    {t(tf.labelKey)}
                  </button>
                ))}
              </div>
            </div>
          </div>

          <div>
            <label className={`block text-sm font-medium ${c.labelText} mb-1`}>
              {t('fp_context_label')} <span className={`font-normal ${c.textMuted}`}>{t('fp_optional')}</span>
            </label>
            <textarea
              value={context}
              onChange={e => setContext(e.target.value)}
              placeholder={t('fp_ph_context')}
              rows={2}
              maxLength={400}
              className={`w-full px-3 py-2.5 border rounded-lg text-sm ${c.input} outline-none focus:ring-2 resize-none`}
            />
          </div>

          <button title={t('cmd_enter')} onClick={handleSubmit} disabled={!subject.trim() || loading}
          className={`relative w-full ${(!subject.trim()) ? c.btnIdle : c.btnPrimary} font-bold py-3 rounded-lg flex items-center justify-center gap-2 min-h-[48px]`}>
          {loading
            ? <><span className="inline-block animate-spin">{tool?.icon ?? '🔮'}</span> {t('fp_analyzing')}</>
            : <><span>{tool?.icon ?? '🔮'}</span> {t('fp_run')}</>}
          {!loading && (
            <kbd aria-hidden="true"
              className="hidden sm:flex items-center absolute end-3 top-1/2 -translate-y-1/2 px-1.5 py-0.5 rounded border border-white/30 bg-white/15 text-[10px] font-bold tracking-wide">
              ⌘↵
            </kbd>
          )}
          </button>

          {/* What the tool actually does, next to the button that does it.
              Secondary weight on purpose — this is a description, not a warning. */}
          <p className={`text-xs text-center ${c.textMuted} leading-relaxed`}>{t('fp_not_a_forecast')}</p>

          {/* Pre-result cross-ref */}
          <p className={`text-xs text-center ${c.textMuted}`}>
            {t('fp_xref_pre')}{' '}
            <a href="/LeverageLogic" className={linkStyle}>🎯 {t('fp_leverage_logic')}</a>{' '}
            {t('fp_xref_leverage_suffix')}
          </p>
        </div>
      </div>

      {error && (
        <div className={`${c.danger} border rounded-lg p-4 flex items-start gap-3`}>
          <span className="flex-shrink-0">⚠️</span>
          <p className="text-sm">{error}</p>
        </div>
      )}

      {results && (
        <div data-copy-results ref={resultsRef} className="space-y-4">

          {/* Trajectory banner */}
          {results?.trajectory && (() => {
            const ts = trajStyle(results?.trajectory);
            return (
              <div className={`${ts.bg} border-2 rounded-xl p-5`}>
                {/* A short label you can scan, then the question in sentence
                    case. The whole reframed question used to be set in tiny
                    uppercase, which is precise and close to unreadable. */}
                <p className={`text-[10px] font-bold uppercase tracking-wide ${c.textMuted} mb-1`}>
                  {results?.analysis_title || results?.subject_as_understood || subject} · {timeframe}
                </p>
                {results?.the_question && (
                  <p className={`text-sm ${ts.txt} mb-2 leading-relaxed`}>{results.the_question}</p>
                )}
                <p className={`text-xl font-bold ${ts.txt} mb-3`}>
                  {ts.dot} {results?.trajectory_label || ts.label}
                </p>

                {/* Certainty and its reason are one block. Split apart, the
                    reader sees "Moderate" with nothing under it and the reason
                    reads as the opening of the paragraph below. */}
                {results?.certainty && (
                  <div className={`mb-3 pt-3 border-t ${isDark ? 'border-white/15' : 'border-black/10'}`}>
                    <p className={`text-[9px] ${c.textMuted} uppercase tracking-wide`}>{t('fp_how_certain')}</p>
                    <p className={`text-sm font-bold ${ts.txt}`}>{t(CERTAINTY_KEYS[results.certainty] || 'fp_certainty_moderate')}</p>
                    {results?.certainty_because && (
                      <p className={`text-xs ${ts.txt} opacity-90 mt-1 leading-relaxed`}>{results.certainty_because}</p>
                    )}
                  </div>
                )}

                {results?.the_pattern && (
                  <p className={`text-sm ${ts.txt} leading-relaxed`}>{results?.the_pattern}</p>
                )}
              </div>
            );
          })()}

          {/* Tailwinds + Headwinds */}
          {(results?.tailwinds?.filter(usableForce).length > 0 || results?.headwinds?.filter(usableForce).length > 0) && (
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
              {results?.tailwinds?.filter(usableForce).length > 0 && (
                <div className={`${c.card} border ${c.border} rounded-xl p-4`}>
                  <p className={`text-[10px] font-bold uppercase ${c.textMuted} mb-3`}>🌬️ {t('fp_tailwinds')}</p>
                  <div className="space-y-3">
                    {results?.tailwinds?.filter(usableForce).map((tw, i) => (
                      <div key={i}>
                        <div className="flex items-center justify-between gap-2 mb-0.5">
                          <p className={`text-xs font-semibold ${c.text}`}>{tw.force}</p>
                          {STATUS_KEYS[tw.status] && (
                            <span className={`text-[9px] uppercase tracking-wide flex-shrink-0 ${c.textMuted}`}>{t(STATUS_KEYS[tw.status])}</span>
                          )}
                        </div>
                        <p className={`text-xs ${c.textSecondary}`}>{tw.explanation}</p>
                      </div>
                    ))}
                  </div>
                </div>
              )}
              {results?.headwinds?.filter(usableForce).length > 0 && (
                <div className={`${c.card} border ${c.border} rounded-xl p-4`}>
                  <p className={`text-[10px] font-bold uppercase ${c.textMuted} mb-3`}>⛈️ {t('fp_headwinds')}</p>
                  <div className="space-y-3">
                    {results?.headwinds?.filter(usableForce).map((h, i) => (
                      <div key={i}>
                        <div className="flex items-center justify-between gap-2 mb-0.5">
                          <p className={`text-xs font-semibold ${c.text}`}>{h.force}</p>
                          {STATUS_KEYS[h.status] && (
                            <span className={`text-[9px] uppercase tracking-wide flex-shrink-0 ${c.textMuted}`}>{t(STATUS_KEYS[h.status])}</span>
                          )}
                        </div>
                        <p className={`text-xs ${c.textSecondary}`}>{h.explanation}</p>
                        {h.timing && <p className={`text-[10px] mt-0.5 ${c.textMuted}`}>{h.timing}</p>}
                      </div>
                    ))}
                  </div>
                </div>
              )}
            </div>
          )}

          {/* Automation question */}
          {results?.the_automation_question && (() => {
            const aq = results?.the_automation_question;
            const central = aq.central_to_conclusion !== false;
            const as_ = autoStyle(aq.exposure === 'currently_susceptible' ? 'high'
              : aq.exposure === 'could_become_exposed' ? 'medium'
              : aq.exposure === 'increasingly_assisted' ? 'low' : 'negligible');
            return (
              <div className={`${as_.bg} border rounded-xl p-4`}>
                {/* Folded away when automation is not one of the things the
                    answer turns on. For a plumbing business the story is route
                    to market and succession; automation is a footnote, and a
                    footnote should not take a page. */}
                <button onClick={() => setShowAutomation(v => !v)}
                  aria-expanded={central || showAutomation} disabled={central}
                  className={`w-full flex items-center gap-2 mb-3 text-start ${central ? 'cursor-default' : ''}`}>
                  <p className={`text-[10px] font-bold uppercase ${c.textMuted}`}>🤖 {t('fp_automation_q')}</p>
                  {EXPOSURE_KEYS[aq.exposure] && (
                    <span className={`text-[10px] font-bold uppercase px-2 py-0.5 rounded-full border ${as_.bg} ${as_.txt}`}>
                      {t(EXPOSURE_KEYS[aq.exposure])}
                    </span>
                  )}
                  {!central && <span className="ms-auto"><Caret open={showAutomation} /></span>}
                </button>
                <div className={`space-y-2 ${central || showAutomation ? '' : 'hidden'}`}>
                  {aq.what_is_exposed && (
                    <div>
                      <p className={`text-[10px] font-semibold ${c.textMuted} mb-0.5`}>{t('fp_what_automated')}</p>
                      <p className={`text-xs ${c.textSecondary}`}>{aq.what_is_exposed}</p>
                    </div>
                  )}
                  {aq.what_is_not && (
                    <div>
                      <p className={`text-[10px] font-semibold ${c.textMuted} mb-0.5`}>{t('fp_what_doesnt')}</p>
                      <p className={`text-xs ${c.textSecondary}`}>{aq.what_is_not}</p>
                    </div>
                  )}
                  {aq.net_effect && (
                    <div className={`pt-2 border-t ${c.border}`}>
                      <p className={`text-xs font-medium ${as_.txt}`}>{aq.net_effect}</p>
                    </div>
                  )}
                </div>
              </div>
            );
          })()}

          {/* The pivot */}
          {results?.the_pivot && (
            <div className={`${c.card} border ${c.border} rounded-xl p-4`}>
              <p className={`text-[10px] font-bold uppercase ${c.textMuted} mb-3`}>🔀 {t('fp_adjacent_moves')}</p>
              {results?.the_pivot?.adjacent_moves?.length > 0 && (
                <div className="space-y-3 mb-4">
                  {results?.the_pivot?.adjacent_moves.map((move, i) => (
                    <div key={i} className={`${c.cardAlt} rounded-lg p-3`}>
                      <div className="flex items-start justify-between gap-2 mb-1">
                        <p className={`text-sm font-semibold ${c.text}`}>{move.move}</p>
                        {move.effort_required && (
                          <span className={`text-[9px] flex-shrink-0 ${c.textMuted}`}>{EFFORT_KEYS[move.effort_required] ? t(EFFORT_KEYS[move.effort_required]) : move.effort_required}</span>
                        )}
                      </div>
                      <p className={`text-xs ${c.textSecondary}`}>{move.why_resilient || move.why_it_changes_the_picture}</p>
                    </div>
                  ))}
                </div>
              )}
              {results?.the_pivot?.the_version_worth_pursuing && (
                <div className={`${c.infoBox} border rounded-lg p-3`}>
                  <p className={`text-[10px] font-bold uppercase mb-1`}>💡 {t('fp_version_worth')}</p>
                  <p className="text-xs leading-relaxed">{results?.the_pivot?.the_version_worth_pursuing}</p>
                </div>
              )}
            </div>
          )}

          {/* Scenarios */}
          {results?.scenarios && (
            <div className={`${c.card} border ${c.border} rounded-xl overflow-hidden`}>
              <div className={`flex border-b ${c.border}`}>
                {[
                  { key: 'bull_case', label: t('fp_scenario_bull'), icon: '🐂' },
                  { key: 'base_case', label: t('fp_scenario_base'), icon: '📊' },
                  { key: 'bear_case', label: t('fp_scenario_bear'), icon: '🐻' },
                ].map(s => (
                  <button key={s.key} onClick={() => setActiveScenario(s.key)}
                    className={`flex-1 flex items-center justify-center gap-1.5 px-4 py-3 text-sm font-semibold transition-all ${
                      activeScenario === s.key
                        ? (isDark ? 'bg-zinc-900 text-cyan-300 border-b-2 border-cyan-500' : 'bg-white text-cyan-700 border-b-2 border-cyan-600')
                        : (isDark ? 'text-zinc-400 hover:bg-zinc-700/50' : 'text-gray-500 hover:bg-gray-50')
                    }`}>
                    <span>{s.icon}</span>
                    <span className="hidden sm:inline">{s.label} {t('fp_scenario_case')}</span>
                    <span className="sm:hidden">{s.label}</span>
                  </button>
                ))}
              </div>
              <div className="p-5">
                {(() => {
                  const sc = results?.scenarios?.[activeScenario];
                  if (!sc) return <p className={`text-sm ${c.textSecondary}`}>—</p>;
                  // A scenario the tool cannot state conditionally is a forecast,
                  // so the old flat-string shape still renders rather than blanking.
                  if (typeof sc === 'string') return <p className={`text-sm ${c.textSecondary} leading-relaxed`}>{sc}</p>;
                  return (
                    <div className="space-y-3">
                      {sc.if_true && (
                        <div>
                          <p className={`text-[10px] font-bold uppercase ${c.textMuted} mb-0.5`}>{t('fp_if_true')}</p>
                          <p className={`text-sm ${c.text} leading-relaxed`}>{sc.if_true}</p>
                        </div>
                      )}
                      {sc.then && (
                        <div>
                          <p className={`text-[10px] font-bold uppercase ${c.textMuted} mb-0.5`}>{t('fp_then')}</p>
                          <p className={`text-sm ${c.textSecondary} leading-relaxed`}>{sc.then}</p>
                        </div>
                      )}
                      {sc.for_you && (
                        <div>
                          <p className={`text-[10px] font-bold uppercase ${c.textMuted} mb-0.5`}>{t('fp_for_you')}</p>
                          <p className={`text-sm ${c.textSecondary} leading-relaxed`}>{sc.for_you}</p>
                        </div>
                      )}
                    </div>
                  );
                })()}
              </div>
            </div>
          )}

          {/* Honest take */}
          {(results?.what_this_means_for_you || results?.the_honest_take) && (
            <div className={`${c.cardAlt} border ${c.border} rounded-xl p-5`}>
              <p className={`text-[10px] font-bold uppercase ${c.textMuted} mb-2`}>🧭 {t('fp_means_for_you')}</p>
              <p className={`text-sm ${c.text} leading-relaxed`}>{results?.what_this_means_for_you || results?.the_honest_take}</p>
            </div>
          )}

          {/* One action */}
          {results?.one_action && (
            <div className={`${c.success} border-2 rounded-xl p-5`}>
              <p className={`text-[10px] font-bold uppercase mb-2`}>⚡ {t('fp_one_action')}</p>
              <p className={`text-sm font-semibold leading-relaxed`}>{results?.one_action}</p>
              {results?.one_action_why && (
                <p className="text-xs mt-2 opacity-90 leading-relaxed">{results.one_action_why}</p>
              )}
            </div>
          )}

          {/* Sources & assumptions — closed by default. Someone who wants to
              check what the analysis rests on can; nobody else has to read it. */}
          {results?.sources_and_assumptions && (
            <div className={`${c.card} border ${c.border} rounded-xl`}>
              <button onClick={() => setShowBasis(v => !v)} aria-expanded={showBasis}
                className="w-full flex items-center justify-between gap-2 p-4 text-start">
                <span className={`text-[10px] font-bold uppercase ${c.textMuted}`}>🔍 {t('fp_basis')}</span>
                <Caret open={showBasis} />
              </button>
              {showBasis && (
                <div className={`px-4 pb-4 space-y-3 border-t ${c.border} pt-3`}>
                  {[['observed', 'fp_basis_observed'], ['inferred', 'fp_basis_inferred'], ['assumed', 'fp_basis_assumed']].map(([key, labelKey]) => {
                    const list = results.sources_and_assumptions[key];
                    if (!Array.isArray(list) || !list.length) return null;
                    return (
                      <div key={key}>
                        <p className={`text-[10px] font-bold uppercase ${c.textMuted} mb-1`}>{t(labelKey)}</p>
                        <ul className="space-y-1.5">
                          {list.map((item, i) => {
                            // Observed entries are records so a reader can go and
                            // check them; inferred and assumed stay plain strings.
                            const rec = item && typeof item === 'object' ? item : null;
                            const text = rec ? rec.claim : item;
                            const url = rec && typeof rec.url === 'string' && /^https?:\/\//i.test(rec.url) ? rec.url : null;
                            const meta = rec ? [rec.publisher, rec.published, rec.jurisdiction].filter(Boolean).join(' · ') : '';
                            return (
                              <li key={i} className={`text-xs ${c.textSecondary} flex gap-2`}>
                                <span aria-hidden="true" className={c.textMuted}>·</span>
                                <span>
                                  {text}
                                  {meta && <span className={`block mt-0.5 ${c.textMuted}`}>{meta}</span>}
                                  {url && (
                                    <a href={url} target="_blank" rel="noopener noreferrer nofollow"
                                      className={`block mt-0.5 break-all ${linkStyle}`}>{url}</a>
                                  )}
                                </span>
                              </li>
                            );
                          })}
                        </ul>
                      </div>
                    );
                  })}
                </div>
              )}
            </div>
          )}

          {/* Post-result cross-refs */}
          <div className={`${c.cardAlt} border ${c.border} rounded-xl p-4`}>
            <p className={`text-[10px] font-bold ${c.textMuted} uppercase mb-2`}>🔗 {t('fp_related')}</p>
            <div className="flex flex-wrap gap-3">
              <a href="/DecisionCoach" className={`text-xs ${linkStyle}`}>🧭 {t('fp_decision_coach')}</a>
              <a href="/LeverageLogic" className={`text-xs ${linkStyle}`}>🎯 {t('fp_leverage_logic')}</a>
            </div>
          </div>
        </div>
      )}

      {/* History */}
      {sessionHistory?.length > 0 && !results && (
        <div className={`${c.card} border ${c.border} rounded-xl p-4`}>
          <h3 className={`text-sm font-bold ${c.text}`}>🕐 {t('fp_recent')}</h3>
          <p className={`text-xs ${c.textMuted} mb-3`}>{t('fp_recent_hint')}</p>
          <div className="space-y-1.5">
            {sessionHistory.map(entry => {
              const ts = trajStyle(entry.trajectory);
              return (
                <button key={entry.id} onClick={() => setResults(entry.result)}
                  title={t('fp_reopen')}
                  className={`w-full text-start px-3 py-2 rounded-lg border ${c.border} ${c.btnSecondary} text-xs flex items-center gap-2 transition hover:-translate-y-0.5`}>
                  <span>{ts.dot}</span>
                  <span className={`${c.text} flex-1 truncate font-medium`}>{entry.subject}</span>
                  <span className={c.textMuted}>
                    {new Date(entry.timestamp).toLocaleDateString(undefined, { month: 'short', day: 'numeric' })}
                  </span>
                  <span aria-hidden="true" className={c.textMuted}>›</span>
                </button>
              );
            })}
          </div>
        </div>
      )}
    </div>
  );
};

FutureProof.displayName = 'FutureProof';
export default FutureProof;
