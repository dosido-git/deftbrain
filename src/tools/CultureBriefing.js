import React, { useState, useEffect, useRef, useCallback } from 'react';
import { useClaudeAPI } from '../hooks/useClaudeAPI';
import CheckNote, { checkStatusFor } from '../components/CheckNote';
import { useTheme } from '../hooks/useTheme';
import { usePersistentState } from '../hooks/usePersistentState';
import { useRegisterActions } from '../components/ActionBarContext';
import { useTranslation } from '../i18n/useTranslation';
import { pickExample } from '../utils/exampleRotation';
import { revealSection } from '../utils/revealSection';
import { schemeStyle } from '../data/toolSchemes';
import { SCHEME_C, FORM_PANEL, AnswerCard, ToolTopRow } from '../components/CategoryStyle';

const BRAND = '\n\n— Generated by DeftBrain · deftbrain.com';

const TRIP_PURPOSES = [
  { id: 'tourism',  labelKey: 'cb_purpose_tourism',  icon: '🏖️' },
  { id: 'business', labelKey: 'cb_purpose_business', icon: '💼' },
  { id: 'family',   labelKey: 'cb_purpose_family',   icon: '👨‍👩‍👧' },
  { id: 'living',   labelKey: 'cb_purpose_living',   icon: '🏠' },
  { id: 'study',    labelKey: 'cb_purpose_study',    icon: '📚' },
  { id: 'remote',   labelKey: 'cb_purpose_remote',   icon: '💻' },
];


// Five, rotated: business, family, tourism, a full relocation with family
// in tow, and a student exchange living with a host family — the purposes
// that change what "culture" even means to brief someone on.
const EXAMPLES = [
  {
  destination: 'Japan',
  tripPurpose: 'business',
  duration: '1 week',
  homeCountry: 'United States',
  region: 'Osaka',
  context: 'Vegetarian and don\u2019t drink alcohol; meeting a client\u2019s executive team',
},
  {
  destination: 'Nigeria',
  tripPurpose: 'family',
  duration: '2 weeks',
  homeCountry: 'United Kingdom',
  region: 'Lagos',
  context: "Meeting my partner's extended family for the first time, at a wedding. I don't speak Yoruba and I'm the only one who won't know anyone.",
},
  {
  destination: 'Italy',
  tripPurpose: 'tourism',
  duration: '10 days',
  homeCountry: 'Australia',
  region: 'Rome and the Amalfi Coast',
  context: 'First trip to Europe, travelling with two teenagers, budget-conscious.',
},
  {
  destination: 'South Korea',
  tripPurpose: 'living',
  duration: '1 year',
  homeCountry: 'Canada',
  region: 'Seoul',
  context: 'Relocating for a job. Bringing a spouse and a toddler. Renting an apartment, not staying in a hotel.',
},
  {
  destination: 'Germany',
  tripPurpose: 'study',
  duration: '1 semester',
  homeCountry: 'Brazil',
  region: 'Munich',
  context: 'Exchange student, living with a host family for the first time, do not speak German yet.',
},
];

// How strongly each item holds, from the source it rests on (set by the
// backend, never by the writer): a rule, a courtesy, something that varies,
// a thing to ask your host, something a source says can cause offence — or a
// law or safety matter, never labelled a courtesy.
const STRENGTH = { required: 'cb_s_required', common: 'cb_s_common', varies: 'cb_s_varies', ask: 'cb_s_ask', offence: 'cb_s_offence', law: 'cb_s_law', safety: 'cb_s_safety' };
const WARNING = new Set(['offence', 'law', 'safety']);

function CultureBriefing({ tool }) {
  const { callToolEndpointProgressive, cancelProgressive, loading, userLocale, userCurrency, userRegion } = useClaudeAPI();
  const { isDark } = useTheme();
  const { t } = useTranslation();

  const c = {
    card:          isDark ? 'bg-zinc-800' : 'bg-white',
    cardAlt:       isDark ? 'bg-zinc-700/50' : 'bg-slate-50',
    input:         isDark ? 'bg-zinc-900 border-zinc-600 text-zinc-100 placeholder-zinc-400 focus:border-[#7fb3e0] focus:ring-[#7fb3e0]/20' : 'bg-white border-gray-300 text-gray-900 placeholder-gray-400 focus:border-[#142a43] focus:ring-[#142a43]/15',
    text:          isDark ? 'text-zinc-50' : 'text-gray-900',
    textSecondary: isDark ? 'text-zinc-300' : 'text-gray-600',
    textMuted:     isDark ? 'text-zinc-400' : 'text-gray-500',
    labelText:     isDark ? 'text-zinc-200' : 'text-gray-700',
    accentTxt:     isDark ? 'text-[#7fb3e0]' : 'text-[#165b9a]',
    btnPrimary:    isDark ? 'bg-[#2f6fb0] hover:bg-[#3a7cc0] text-white' : 'bg-[#142a43] hover:bg-[#234568] text-white',
    // Waiting for input: an outline, not a smudge. Empty fill keeps "filled"
    // meaning "ready"; the border and label carry the visibility. Important
    // modifiers because tools carry their own border/text utilities on the
    // submit and Tailwind resolves conflicts by stylesheet order, not class
    // order. See the PF-13 exception in audit/audit_v2-3-2.py.
    btnIdle:       isDark ? '!bg-transparent !border-2 !border-[#7fb3e0]/85 !text-[#a9cdef] cursor-not-allowed' : '!bg-transparent !border-2 !border-[#142a43]/80 !text-[#142a43] cursor-not-allowed',
    btnSecondary:  isDark ? 'bg-zinc-700 hover:bg-zinc-600 text-zinc-200'
                          : 'bg-gray-100 hover:bg-gray-200 text-gray-700',
    border:        isDark ? 'border-zinc-700' : 'border-gray-200',
    pillActive:    isDark ? 'border-[#7fb3e0] bg-[#1f2530] text-zinc-100' : 'border-[#142a43] bg-[#eef3f8] text-[#142a43]',
    pillInactive:  isDark ? 'border-zinc-600 text-zinc-400 hover:border-zinc-500'
                          : 'border-gray-300 text-gray-500 hover:border-gray-400',
    required:      isDark ? 'text-amber-400' : 'text-amber-700',
    sectionHead:   '',
    danger:        isDark ? 'bg-red-900/20 border-red-700 text-red-200'
                          : 'bg-red-50 border-red-200 text-red-800',
    warning:       isDark ? 'bg-amber-900/20 border-amber-700 text-amber-200'
                          : 'bg-amber-50 border-amber-300 text-amber-800',
    success:       isDark ? 'bg-emerald-900/20 border-emerald-700 text-emerald-200'
                          : 'bg-emerald-50 border-emerald-300 text-emerald-800',
  };
  c.textMuteded = c.textMuted;
  c.label = c.labelText;

  // Category colours (src/data/toolSchemes.js, audit/CONVENTIONS.md
  // "Category-colour pages"): no traffic lights — what is widely observed
  // and what varies read as plain notes, only what is best avoided wears the
  // contrast colour.
  const sv = schemeStyle(tool, isDark);
  if (sv) Object.assign(c, SCHEME_C, {
    // Gray-500 is 4.4:1 on the envelope shade; one step darker passes.
    textMuted: isDark ? 'text-zinc-400' : 'text-gray-600',
    textMuteded: isDark ? 'text-zinc-400' : 'text-gray-600',
    success:  'bg-[var(--sc-card)] border-[var(--sc-line)] text-[var(--sc-strong)]',
    warning:  'bg-[var(--sc-envelope)] border-[var(--sc-line)] text-[var(--sc-strong)]',
    sectionHead: 'text-base font-bold text-[var(--sc-strong)]',
  });
  const head = sv ? c.sectionHead : `text-[13px] font-bold ${c.textMuted}`;

  const linkStyle = sv ? 'text-[var(--sc-accent)] hover:text-[var(--sc-strong)] underline underline-offset-2' : isDark ? 'text-[#7fb3e0] hover:text-[#a9cdef] underline underline-offset-2' : 'text-[#142a43] hover:text-[#142a43] underline underline-offset-2';
  const [checkStatus, setCheckStatus] = useState(null); // CheckNote: checking | done | fixed

  const [destination, setDestination]   = useState('');
  const [tripPurpose, setTripPurpose]   = useState('tourism');
  const [duration, setDuration]         = useState('');
  const [homeCountry, setHomeCountry]   = useState('');
  const [region, setRegion]             = useState('');
  const [context, setContext]           = useState('');
  const [results, setResults]           = usePersistentState('culturebriefing-results', null);
  const [sessionHistory, setSessionHistory]           = usePersistentState('culturebriefing-history', []);
  const [error, setError]               = useState('');
  const [activeSection, setActiveSection] = useState(null);

  const resultsRef    = useRef(null);
  const handleBriefRef = useRef(null);
  const canSubmitRef  = useRef(false);

  const canSubmit = destination.trim().length >= 2;

  const handleReset = useCallback(() => {
    cancelProgressive(); setCheckStatus(null);
    setResults(null);
    setError('');
    setDestination('');
    setDuration('');
    setHomeCountry('');
    setTripPurpose('tourism');
    setActiveSection(null);
  }, [setResults]); // eslint-disable-line react-hooks/exhaustive-deps

  const loadExample = useCallback(() => {
    const ex = pickExample('CultureBriefing', EXAMPLES);
    setDestination(ex.destination);
    setTripPurpose(ex.tripPurpose);
    setDuration(ex.duration);
    setHomeCountry(ex.homeCountry);
    setRegion(ex.region);
    setContext(ex.context);
    setResults(null);
    setError('');
  }, [setResults]);

  const handleBrief = useCallback(async () => {
    if (!canSubmit || loading) return;
    setError('');
    setResults(null); setCheckStatus(null);
    setActiveSection(null);

    try {
      // Progressive: the questions for this visit show in seconds; the
      // researched parts follow; checked after.
      let opened = false;
      const keep = d => ({ ...d, destination: destination.trim(), tripPurpose });
      const parsed = await callToolEndpointProgressive('culture-briefing', {
        destination: destination.trim(),
        tripPurpose,
        duration: duration.trim() || null,
        homeCountry: homeCountry.trim() || null,
        region: region.trim() || null,
        context: context.trim() || null,
        userLocale,
        userCurrency,
        userRegion,
      }, {
        onDraft: d => {
          setResults(keep(d)); setCheckStatus('checking');
          if (!opened && d?.sections?.[0]?.id) { opened = true; setActiveSection(d.sections[0].id); }
        },
        onChecked: (d, changed) => { setResults(keep(d)); setCheckStatus(checkStatusFor(changed)); },
      });
      if (!parsed) return; // replaced by a newer run
      setResults(keep(parsed));
      // PF-25 exception: keeps the last 8 destination lookups for the history panel.
      setSessionHistory(prev => [{
        destination: destination.trim(),
        tripPurpose,
        preview: destination.trim().slice(0, 40),
        ts: Date.now(),
      }, ...prev].slice(0, 8));
      if (!opened) setActiveSection(parsed?.sections?.[0]?.id ?? null);
    } catch (err) {
      setError(err.message || t('cb_error_generic'));
    }
  }, [canSubmit, loading, destination, tripPurpose, duration, homeCountry, region, context, callToolEndpointProgressive, setResults, setSessionHistory, userLocale, userCurrency, userRegion, t]);

  handleBriefRef.current = handleBrief;
  canSubmitRef.current   = canSubmit;

  const buildFullText = useCallback(() => {
    if (!results) return '';
    const lines = [`${t('cb_copy_header')} — ${results.destination?.toUpperCase()}`, ''];
    if (results.overview) lines.push(results.overview, '');
    if (results.visit?.length) {
      lines.push(t('cb_visit_questions'));
      results.visit.forEach(q => lines.push(`  • ${q.question}`));
      lines.push('');
    }
    if (results.essentials?.length) {
      lines.push(`${t('cb_essentials')}`);
      results.essentials.forEach(e => lines.push(`  • ${e.point}`));
    }
    results.for_your_needs?.forEach(n => lines.push(`\n${n.need}: ${n.plan}`));
    results.sections?.forEach(sec => {
      lines.push(`\n${sec.icon ?? '•'} ${sec.title}`);
      (sec.items || []).forEach(it => lines.push(`  • ${it.text}${STRENGTH[it.strength] ? ` (${t(STRENGTH[it.strength])})` : ''}`));
    });
    if (results.small_slips?.length) {
      lines.push(`\n${t('cb_small_slips_label')}`);
      results.small_slips.forEach(x => lines.push(`  • ${x.slip} — ${x.recovery}`));
    }
    if (results.sources?.length) {
      lines.push(`\n${t('cb_sources')}`);
      results.sources.forEach(src => lines.push(`  ${src.id} ${src.title ? `${src.title} — ` : ''}${src.publisher} — ${src.url}`));
    }
    lines.push(BRAND);
    return lines.join('\n');
  }, [results, t]);

  useRegisterActions(buildFullText(), tool?.title || 'CultureBriefing');

  useEffect(() => {
    if (!results || !resultsRef.current) return;
    const t = setTimeout(() => revealSection(resultsRef.current), 200);
    return () => clearTimeout(t);
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [results]);

  useEffect(() => {
    const handler = (e) => {
      if (e.key === 'Enter' && (e.metaKey || e.ctrlKey) && !loading && canSubmitRef.current)
        handleBriefRef.current?.();
    };
    document.addEventListener('keydown', handler);
    return () => document.removeEventListener('keydown', handler);
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [loading]);

  const activeData = results?.sections?.find(s => s.id === activeSection);
  // A briefing saved before the 2026-10-27 rebuild has a different shape.
  useEffect(() => { if (results && !Array.isArray(results.essentials)) setResults(null); }, [results, setResults]);

  // The row above the form. With a category scheme the wrapper carries the
  // tagline and the tool keeps one row: Try an example and the reset
  // (PF-16: the tool's one reset, on the title row next to the page's <h1>).
  const renderHeaderRow = () => {
    const resetBtn = (results || activeSection || destination.trim() || duration.trim() || homeCountry.trim()) ? (
      <button onClick={handleReset} className={`${c.btnSecondary} px-3 py-1.5 rounded-lg ${sv ? 'text-sm' : 'text-xs'} font-semibold flex-shrink-0 whitespace-nowrap`}>
        ↺ {t('cb_new_briefing')}
      </button>
    ) : null;
    if (sv) return <ToolTopRow onExample={loadExample} loading={loading}>{resetBtn}</ToolTopRow>;
    return (
      <div>
        {/* Header — site style (2026-09-27): a pale band of the tool's color
            bleeding to the card edges, the ground the "Try an example" pill was
            made for (PF-17c). Screen only. */}
        <div
          data-print-hide
          className="-mx-4 -mt-4 sm:-mx-6 sm:-mt-6 lg:-mx-8 lg:-mt-8 px-4 sm:px-6 lg:px-8 pt-4 sm:pt-6 lg:pt-8 pb-5"
          style={/^#[0-9a-f]{6}$/i.test(tool?.headerColor || '') ? { background: `${tool.headerColor}${isDark ? '26' : '66'}` } : undefined}
        >
          <div className="flex items-start justify-between">
          <div>
            <div className="flex items-start justify-between gap-3">
              <div>
                {/* PF-30 — the wrapper already prints the name as the page <h1>. */}
                <p className={`text-[17px] leading-snug ${c.textSecondary}`}>
                  <span className="me-2 text-xl">{tool?.icon ?? '🌍'}</span>{t('cb_tagline')}
                </p>
                <button onClick={loadExample} disabled={loading} style={{ backgroundColor: (tool?.headerColor ?? '#888888') + '80' }} className="mt-2 px-4 py-2 rounded-full text-sm font-semibold border border-black/25 text-zinc-900 shadow-sm hover:brightness-105 hover:shadow transition disabled:opacity-40 whitespace-nowrap">✨ {t('try_example')}</button>
              </div>
              {/* PF-16: the tool's one reset, on the title row, from the first keystroke. */}
              {resetBtn}
            </div>
          </div>
        </div>
        </div>
      </div>
    );
  };

  const renderInput = () => (
    <div className={sv ? `${FORM_PANEL} space-y-4` : `border-t ${c.border} pt-5 space-y-4`}>
      {/* Destination */}
      <div>
        <label className={`block text-sm font-medium ${c.labelText} mb-1`}>
          {t('cb_destination')} <span className={c.required}>*</span>
        </label>
        <input
          type="text"
          value={destination}
          onChange={e => setDestination(e.target.value)}
          placeholder={t('cb_destination_ph')}
          className={`w-full px-3 py-2.5 border rounded-xl text-sm focus:outline-none focus:ring-2 ${c.input}`}
        />
      </div>

      {/* Region / city */}
      <div>
        <label className={`block text-sm font-medium ${c.labelText} mb-1`}>
          {t('cb_region')} <span className={`text-xs font-normal ${c.textMuted}`}>({t('optional')})</span>
        </label>
        <input
          type="text"
          value={region}
          onChange={e => setRegion(e.target.value)}
          placeholder={t('cb_region_ph')}
          className={`w-full px-3 py-2 border rounded-xl text-sm focus:outline-none focus:ring-2 ${c.input}`}
        />
      </div>

      {/* Trip purpose */}
      <div>
        <label className={`block text-sm font-medium ${c.labelText} mb-2`}>{t('cb_trip_purpose')}</label>
        <div className="flex flex-wrap gap-2">
          {TRIP_PURPOSES.map(tp => (
            <button aria-pressed={tripPurpose === tp.id} key={tp.id} onClick={() => setTripPurpose(tp.id)}
              className={`px-3 py-1.5 rounded-lg border text-xs font-medium transition-colors ${tripPurpose === tp.id ? c.pillActive : c.pillInactive}`}>
              {sv && tripPurpose === tp.id && <span className="me-1">✓</span>}<span className="me-1">{tp.icon}</span>{t(tp.labelKey)}
            </button>
          ))}
        </div>
      </div>

      {/* Duration + Home country */}
      <div className="grid grid-cols-2 gap-3">
        <div>
          <label className={`block text-sm font-medium ${c.labelText} mb-1`}>
            {t('cb_duration')} <span className={`text-xs font-normal ${c.textMuted}`}>({t('optional')})</span>
          </label>
          <input
            type="text"
            value={duration}
            onChange={e => setDuration(e.target.value)}
            placeholder={t('cb_duration_ph')}
            className={`w-full px-3 py-2 border rounded-xl text-sm focus:outline-none focus:ring-2 ${c.input}`}
          />
        </div>
        <div>
          <label className={`block text-sm font-medium ${c.labelText} mb-1`}>
            {t('cb_home_country')} <span className={`text-xs font-normal ${c.textMuted}`}>({t('optional')})</span>
          </label>
          <input
            type="text"
            value={homeCountry}
            onChange={e => setHomeCountry(e.target.value)}
            placeholder={t('cb_home_country_ph')}
            className={`w-full px-3 py-2 border rounded-xl text-sm focus:outline-none focus:ring-2 ${c.input}`}
          />
        </div>
      </div>

      {/* Context / constraints */}
      <div>
        <label className={`block text-sm font-medium ${c.labelText} mb-1`}>
          {t('cb_context')} <span className={`text-xs font-normal ${c.textMuted}`}>({t('optional')})</span>
        </label>
        <p className={`text-[13px] ${c.textMuted} mb-1.5`}>{t('cb_context_ph')}</p>
        <textarea
          value={context}
          onChange={e => setContext(e.target.value)}
          placeholder={t('cb_context_ph')}
          rows={3}
          className={`w-full px-3 py-2 border rounded-xl text-sm focus:outline-none focus:ring-2 ${c.input}`}
        />
      </div>

      {error && <p className={`text-sm ${c.danger} border rounded-lg px-3 py-2`}>{error}</p>}


      <button title={t('cmd_enter')} onClick={handleBrief} disabled={!canSubmit || loading}
        className={`relative w-full ${(!canSubmit) ? c.btnIdle : c.btnPrimary} font-bold py-3 rounded-lg flex items-center justify-center gap-2 min-h-[48px]`}>
        {loading
          ? <><span className="inline-block animate-spin text-xl">{tool?.icon ?? '🌍'}</span> {t('cb_building')}</>
          : <><span className="me-1 text-xl">{tool?.icon ?? '🌍'}</span> {t('cb_get_briefing')}</>}
      {!loading && (
        <kbd aria-hidden="true"
          className="hidden sm:flex items-center absolute end-3 top-1/2 -translate-y-1/2 px-1.5 py-0.5 rounded border border-white/30 bg-white/15 text-[10px] font-bold tracking-wide">
          ⌘↵
        </kbd>
      )}
      </button>

      {sessionHistory.length > 0 && (
        <div className={`${c.cardAlt} border ${c.border} rounded-xl p-4`}>
          <div className="flex items-center justify-between mb-3">
            <p className={`text-[13px] font-bold ${c.textMuted}`}>🕓 {t('cb_recent_briefings')}</p>
            <button onClick={() => setSessionHistory([])} className={`text-[13px] ${c.textMuted}`}>{t('cb_clear')}</button>
          </div>
          <ul className="space-y-1.5">
            {sessionHistory.map((h, i) => {
              const purposeMeta = TRIP_PURPOSES.find(tp => tp.id === h.tripPurpose);
              return (
                <li key={i} className={`text-xs ${c.textSecondary} flex items-center gap-2`}>
                  <span>{purposeMeta?.icon ?? '🌍'}</span>
                  <span className="font-medium">{h.destination}</span>
                  <span className={c.textMuted}>· {purposeMeta ? t(purposeMeta.labelKey) : ''}</span>
                </li>
              );
            })}
          </ul>
        </div>
      )}
    </div>
  );

  const renderResults = () => {
    // Saved briefings from before 2026-10-27 have no essentials; they are
    // cleared on load (effect below), so render nothing for one meanwhile.
    if (!results || !Array.isArray(results.essentials)) return null;
    const purposeMeta = TRIP_PURPOSES.find(tp => tp.id === results.tripPurpose);
    const srcById = Object.fromEntries((results.sources || []).map(src => [src.id, src]));
    const Refs = ({ ids }) => {
      const srcs = [...new Set((ids || []).map(f => results.finding_sources?.[f]).filter(id => srcById[id]))];
      return srcs.length ? <span className={`ms-1 text-[12px] ${c.textMuted}`}>{srcs.map(id => <a key={id} href={srcById[id].url} target="_blank" rel="noopener noreferrer" className="underline underline-offset-2 me-1">{id}</a>)}</span> : null;
    };
    // No tag on a plain fact (how to pay, a transport ban): it is not a courtesy.
    const tag = (strength) => STRENGTH[strength] && (
      <span className={`ms-2 text-[12px] font-semibold px-1.5 py-0.5 rounded border whitespace-nowrap ${WARNING.has(strength) ? (sv ? 'border-[var(--sc-x-line)] text-[var(--sc-x-text)]' : c.danger) : (sv ? 'border-[var(--sc-line)] text-[var(--sc-accent)]' : `${c.border} ${c.textMuted}`)}`}>
        {t(STRENGTH[strength])}
      </span>
    );
    const SectionBody = ({ sec }) => (
      <ul className="space-y-2">
        {(sec.items || []).map((it, i) => (
          <li key={i} className={`text-sm leading-relaxed ${c.textSecondary}`}>{it.text}{tag(it.strength)}<Refs ids={it.finding_ids} /></li>
        ))}
      </ul>
    );

    const answer = (
      <div className="scroll-mt-24 space-y-5" ref={resultsRef}>
        <CheckNote status={checkStatus} className={c.textMuted} />

        <div>
          <p className={`text-2xl font-black ${c.text}`}>{results.destination}</p>
          <p className={`text-sm ${c.textMuted}`}>{purposeMeta?.icon} {purposeMeta ? t(purposeMeta.labelKey) : ''} {t('cb_briefing_suffix')}</p>
          {results.overview && <p className={`mt-2 text-sm ${c.textSecondary}`}>{results.overview}</p>}
        </div>

        {/* For this visit — leads (second review, 2026-10-27: the people
            being visited, not a national checklist, organise the briefing).
            The questions come first and need no research; the plans for the
            visitor's own needs follow once the research lands. */}
        {(results.visit?.length > 0 || results.for_your_needs?.length > 0) && (
          <div>
            <p className={`${head} mb-2`}>{t('cb_for_your_needs')}</p>
            {results.visit?.length > 0 && (
              <>
                <p className={`text-sm font-semibold mb-1.5 ${c.text}`}>{t('cb_visit_questions')}</p>
                <ul className="space-y-2 mb-3">
                  {results.visit.map((q, i) => (
                    <li key={i} className={`text-sm leading-relaxed ${c.textSecondary}`}>{q.question}{q.why ? <span className={c.textMuted}> — {q.why}</span> : null}</li>
                  ))}
                </ul>
              </>
            )}
            {results.for_your_needs?.length > 0 && (
              <ul className="space-y-2">
                {results.for_your_needs.map((n, i) => (
                  <li key={i} className={`text-sm leading-relaxed ${c.textSecondary}`}><span className={`font-semibold ${c.text}`}>{n.need}:</span> {n.plan}<Refs ids={n.finding_ids} /></li>
                ))}
              </ul>
            )}
          </div>
        )}

        {/* What matters most — the answer's key box (owner's review,
            2026-10-27: lead with the essentials, details after). */}
        {results.essentials.length > 0 && (
          <div data-keybox="" className={sv ? 'border-2 border-[var(--sc-accent)] bg-[var(--sc-card)] rounded-xl p-4 sm:p-5' : `${c.card} border-2 ${c.border} rounded-xl p-5`}>
            <p className={`${head} mb-2`}>{t('cb_essentials')}</p>
            <ol className="space-y-2 list-decimal ps-5">
              {results.essentials.map((e, i) => (
                <li key={i} className={`text-sm leading-relaxed ${c.text}`}>{e.point}<Refs ids={e.finding_ids} /></li>
              ))}
            </ol>
          </div>
        )}

        {results.sections?.length > 0 && (
          <div className={`border-t ${c.border} pt-5`}>
            <p data-print-hide className={`${head} mb-3`}>{t('cb_browse_topics')}</p>
            <div data-print-hide className="flex flex-wrap gap-2">
              {results.sections.map(sec => (
                <button aria-pressed={activeSection === sec.id} key={sec.id} onClick={() => setActiveSection(activeSection === sec.id ? null : sec.id)}
                  className={`px-3 py-1.5 rounded-lg border text-xs font-medium transition-colors ${activeSection === sec.id ? c.pillActive : c.pillInactive}`}>
                  {sv && activeSection === sec.id && <span className="me-1">✓</span>}<span className="me-1">{sec.icon}</span>{sec.title}
                </button>
              ))}
            </div>
            {activeData && (
              <div data-print-hide className={`mt-4 pt-4 border-t ${c.border}`}>
                <p className={`text-sm font-bold mb-2 ${c.text}`}>{activeData.icon} {activeData.title}</p>
                <SectionBody sec={activeData} />
              </div>
            )}
            {/* On paper every topic prints, one after another. */}
            <div className="hidden print:block">
              {results.sections.map(sec => (
                <div key={sec.id} className="mt-4 keep-together">
                  <p className={`text-sm font-bold mb-2 ${c.text}`}>{sec.icon} {sec.title}</p>
                  <SectionBody sec={sec} />
                </div>
              ))}
            </div>
          </div>
        )}

        {results.small_slips?.length > 0 && (
          <div className={`border-t ${c.border} pt-5`}>
            <p className={`${head} mb-2`}>{t('cb_small_slips_label')}</p>
            <ul className="space-y-2">
              {results.small_slips.map((x, i) => (
                <li key={i} className={`text-sm leading-relaxed ${c.textSecondary}`}>{x.slip} <span className={c.textMuted}>— {x.recovery}</span></li>
              ))}
            </ul>
          </div>
        )}

        {results.sources?.length > 0 && (
          <div className={`border-t ${c.border} pt-5`}>
            <p className={`${head} mb-2`}>{t('cb_sources')}</p>
            <ul className="space-y-1">
              {results.sources.map(src => (
                <li key={src.id} className={`text-[13px] ${c.textMuted}`}>
                  <span className="font-semibold me-1">{src.id}</span>
                  <a href={src.url} target="_blank" rel="noopener noreferrer" className={linkStyle}>{src.title || src.publisher}</a>{src.title ? ` · ${src.publisher}` : ''}{src.date ? ` · ${src.date}` : ''}
                </li>
              ))}
            </ul>
          </div>
        )}

        {/* Post-result cross-refs */}
        <div data-print-hide className={`${c.cardAlt} border ${c.border} rounded-xl p-4`}>
          <p className={`text-[13px] font-bold ${c.textMuted} mb-2`}>🔗 {t('cb_related_tools')}</p>
          <div className="flex flex-wrap gap-3">
            <a href="/LayoverMaximizer" className={`text-xs ${linkStyle}`}>✈️ {t('cb_layover')}</a>
            <a href="/MoneyDiplomat" className={`text-xs ${linkStyle}`}>💰 {t('cb_money_diplomat')}</a>
            <a href="/Mend" className={`text-xs ${linkStyle}`}>🙏 {t('cb_apology_calibrator')}</a>
          </div>
        </div>
      </div>
    );
    // With a category scheme the answer sits in the shared answer card.
    return sv ? <AnswerCard title={t('your_answer')}>{answer}</AnswerCard> : answer;
  };

  return (
    <div className={`space-y-4 ${c.text}`}>
      {renderHeaderRow()}
      {!results && renderInput()}
      {results && renderResults()}
    </div>
  );
}

