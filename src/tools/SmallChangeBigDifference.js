import React, { useState, useEffect, useRef } from 'react';
import Caret from '../components/Caret';
import { useTheme } from '../hooks/useTheme';
import { usePersistentState } from '../hooks/usePersistentState';
import { useClaudeAPI } from '../hooks/useClaudeAPI';
import { useRegisterActions } from '../components/ActionBarContext';
import { useTranslation } from '../i18n/useTranslation';
import { pickExample } from '../utils/exampleRotation';
import { useScrollToSection } from '../hooks/useScrollToSection';

const BRAND = '\n\n— Generated by DeftBrain · deftbrain.com';

// The four check-in outcomes are all "useful evidence," per the North Star —
// none of the four gets a red/negative treatment. See CHECK_IN_META below.
const CHECK_IN_STATUSES = ['helped', 'helped_a_little', 'not_really', 'not_tried'];

const SmallChangeBigDifference = ({ tool }) => {
  const { isDark } = useTheme();
  const { callToolEndpointStreaming, loading, userLocale, userCurrency, userRegion } = useClaudeAPI();
  const { t } = useTranslation();

  const EXAMPLES = [
    {
      routine: t('op_ex1_routine'),
      goals: t('op_ex1_goals'),
      pain: t('op_ex1_pain'),
    },
    {
      routine: t('op_ex2_routine'),
      goals: t('op_ex2_goals'),
      pain: t('op_ex2_pain'),
    },
  ];

  const c = {
    card:          isDark ? 'bg-zinc-800' : 'bg-white',
    cardAlt:       isDark ? 'bg-zinc-700/50' : 'bg-slate-50',
    input:         isDark ? 'bg-zinc-900 border-zinc-600 text-zinc-100 placeholder-zinc-400 focus:border-cyan-500 focus:ring-cyan-500/20' : 'bg-white border-gray-300 text-gray-900 placeholder-gray-400 focus:border-cyan-500 focus:ring-cyan-100',
    text:          isDark ? 'text-zinc-50' : 'text-gray-900',
    textSecondary: isDark ? 'text-zinc-300' : 'text-gray-600',
    textMuted:     isDark ? 'text-zinc-400' : 'text-gray-500',
    required:      isDark ? 'text-amber-400' : 'text-amber-700',
    labelText:     isDark ? 'text-zinc-200' : 'text-gray-700',
    accentTxt:     isDark ? 'text-cyan-400' : 'text-cyan-600',
    btnPrimary:    isDark ? 'bg-cyan-600 hover:bg-cyan-500 text-white' : 'bg-cyan-600 hover:bg-cyan-700 text-white',
    // Waiting for input: an outline, not a smudge. Empty fill keeps "filled"
    // meaning "ready"; the border and label carry the visibility. Important
    // modifiers because tools carry their own border/text utilities on the
    // submit and Tailwind resolves conflicts by stylesheet order, not class
    // order. See the PF-13 exception in audit/audit_v2-3-2.py.
    btnIdle:       isDark ? '!bg-transparent !border-2 !border-cyan-500/85 !text-cyan-300 cursor-not-allowed'
                          : '!bg-transparent !border-2 !border-cyan-600/85 !text-cyan-800 cursor-not-allowed',
    btnSecondary:  isDark ? 'bg-zinc-700 hover:bg-zinc-600 text-zinc-200' : 'bg-gray-100 hover:bg-gray-200 text-gray-700',
    border:        isDark ? 'border-zinc-700' : 'border-gray-200',
    success:       isDark ? 'bg-emerald-900/20 border-emerald-700 text-emerald-200' : 'bg-emerald-50 border-emerald-300 text-emerald-800',
    warning:       isDark ? 'bg-amber-900/20 border-amber-700 text-amber-200' : 'bg-amber-50 border-amber-300 text-amber-800',
    danger:        isDark ? 'bg-red-900/20 border-red-700 text-red-200' : 'bg-red-50 border-red-200 text-red-800',
    greenBg:       isDark ? 'bg-emerald-900/20 border-emerald-700' : 'bg-emerald-50 border-emerald-300',
    greenText:     isDark ? 'text-emerald-300' : 'text-emerald-800',
    navyBg:        isDark ? 'bg-sky-900/20 border-sky-700' : 'bg-sky-50 border-sky-300',
    navyText:      isDark ? 'text-sky-300' : 'text-sky-800',
    memoryBg:      isDark ? 'bg-cyan-900/20 border-cyan-700' : 'bg-cyan-50 border-cyan-300',
    memoryText:    isDark ? 'text-cyan-300' : 'text-cyan-800',
    pillActive:    isDark ? 'border-cyan-500 bg-cyan-900/30 text-cyan-200' : 'border-cyan-600 bg-cyan-100 text-cyan-900',
    pillInactive:  isDark ? 'border-zinc-600 text-zinc-400 hover:border-zinc-500' : 'border-gray-300 text-gray-500 hover:border-gray-400',
    histBg:        isDark ? 'bg-zinc-800 border-zinc-700' : 'bg-white border-gray-200',
    histCard:      isDark ? 'bg-zinc-700/50 border-zinc-600' : 'bg-slate-50 border-gray-200',
  };
  c.textMuteded = c.textMuted;
  c.label = c.labelText;

  const linkStyle = isDark
    ? 'text-cyan-400 hover:text-cyan-300 underline underline-offset-2'
    : 'text-cyan-700 hover:text-cyan-800 underline underline-offset-2';

  // Neutral on purpose — the North Star says all four outcomes are "useful
  // evidence," so nothing here reads as pass/fail. No red, no trophy.
  const CHECK_IN_META = {
    helped:            { emoji: '🟢', label: t('op_ci_helped') },
    helped_a_little:   { emoji: '🟡', label: t('op_ci_helped_a_little') },
    not_really:        { emoji: '⚪', label: t('op_ci_not_really') },
    not_tried:         { emoji: '⬜', label: t('op_ci_not_tried') },
  };
  const ROUTINE_AREA_LABEL = {
    Morning: t('op_area_morning'), Daytime: t('op_area_daytime'), Work: t('op_area_work'),
    Evening: t('op_area_evening'), Sleep: t('op_area_sleep'), Other: t('op_area_other'),
  };

  const [routine, setRoutine] = useState('');
  const [goals, setGoals] = useState('');
  const [painPoints, setPainPoints] = useState('');
  const [error, setError] = useState('');
  const [streamStage, setStreamStage] = useState('');
  // -v3: -v2 was the 2026-09-05 grounding rewrite's shape
  // (routine_diagnosis/the_one_change/the_year_from_now →
  // what_i_notice/change_to_try/why_not_start_elsewhere/what_to_watch_for).
  // -v3 is the same-day FULL LLM INSTRUCTIONS follow-up, which moved `math`
  // out of change_to_try into its own top-level {show, calculation, meaning}
  // object and turned why_not_start_elsewhere.alternatives from a string
  // into an array of {alternative, why_not_first} — a -v2 cached result
  // would crash calling .map() on that string.
  const [results, setResults] = usePersistentState('onepercenter-result-v3', null);
  // Recent Small Changes, added 2026-09-05. A NEW store, not a version bump
  // of `onepercenter-history` — the old key held only {id, date, preview}
  // and is deliberately left alone (read-only below) as the migration path:
  // real past entries are preserved and shown as legacy rows, never
  // fabricated into a fake recommendation/check-in.
  const [experiments, setExperiments] = usePersistentState('onepercenter-experiments', []);
  const [legacyHistory] = usePersistentState('onepercenter-history', []);
  const [showHistory, setShowHistory] = useState(false);
  const [showAllExperiments, setShowAllExperiments] = useState(false);
  const [checkingInId, setCheckingInId] = useState(null);
  const [draftStatus, setDraftStatus] = useState(null);
  const [draftReport, setDraftReport] = useState('');

  const getStreamStage = (text) => {
    if (text.includes('"what_to_watch_for"'))       return t('op_stage_watch');
    if (text.includes('"why_not_start_elsewhere"'))  return t('op_stage_alternatives');
    if (text.includes('"math"'))                     return t('op_stage_math');
    if (text.includes('"change_to_try"'))            return t('op_stage_change');
    if (text.includes('"what_i_notice"'))            return t('op_stage_notice');
    return t('op_stage_default');
  };

  // Reveal the answer when it arrives: frame the tool if its header fits,
  // otherwise put the answer on top. Focus moves either way.
  const revealRef = useRef(null);
  useScrollToSection(revealRef, results);

  // Relevance selection happens here, not on the backend (PF: the route
  // just formats whatever it's handed) — recent, REVIEWED experiments only.
  // An unreviewed one carries no outcome evidence (section 11 of the spec),
  // so it's never sent as history context.
  const relevantPreviousExperiments = () => experiments
    .filter(e => e.checkIn?.status && e.checkIn.status !== 'unreviewed')
    .slice(0, 3)
    .map(e => ({
      change: e.recommendation?.change || '',
      routineArea: e.experimentContext?.routineArea || '',
      checkInLabel: CHECK_IN_META[e.checkIn.status]?.label || e.checkIn.status,
      visitorReport: e.checkIn.visitorReport || '',
    }));

  const handleSubmit = async () => {
    if (!routine.trim()) return;
    setError(''); setResults(null); setStreamStage(t('op_stage_default'));
    const previousExperiments = relevantPreviousExperiments();
    callToolEndpointStreaming(
      'one-percenter',
      { routine: routine.trim(), goals: goals.trim() || undefined, painPoints: painPoints.trim() || undefined,
        previousExperiments: previousExperiments.length ? previousExperiments : undefined,
        userLocale, userCurrency, userRegion },
      {
        onChunk: (accumulated) => setStreamStage(getStreamStage(accumulated)),
        onDone: (finalText, serverParsed) => {
          setStreamStage('');
          try {
            let parsed = serverParsed;
            if (!parsed) {
              const start = finalText.indexOf('{');
              const end   = finalText.lastIndexOf('}');
              if (start === -1 || end === -1) throw new Error('No JSON object found in response');
              parsed = JSON.parse(finalText.slice(start, end + 1));
            }
            if (!parsed.what_i_notice || !parsed.change_to_try) {
              setError(t('op_err_analyze'));
            } else {
              setResults(parsed);
              // Auto-saved as "unreviewed" — the check-in prompt is never
              // shown as an interstitial here. It only ever surfaces later,
              // passively, as a row in Recent Small Changes below.
              const ch = parsed.change_to_try || {};
              setExperiments(prev => [{
                id: 'exp_' + Date.now(),
                createdAt: new Date().toISOString(),
                // PF-25 exception: 40-char preview-text truncation, same
                // convention as every other tool's history entry — this one
                // is a fallback display string, since the row itself
                // normally renders recommendation.change directly.
                preview: (ch.change || routine).trim().slice(0, 40),
                originalInput: { typicalDay: routine.trim(), improvementGoal: goals.trim(), offTrack: painPoints.trim() },
                recommendation: {
                  change: ch.change || '', whyThisOne: ch.why_this_one || '',
                  howToTryIt: ch.how_to_try_it || '', whatItMayChange: ch.what_it_may_change || '',
                },
                experimentContext: { routineArea: parsed.routine_area || 'Other' },
                checkIn: { status: 'unreviewed', visitorReport: '', reviewedAt: null },
                storedResult: parsed,
              }, ...prev].slice(0, 15));
            }
          } catch (e) {
            console.error('[SmallChangeBigDifference] JSON parse failed:', e.message);
            console.error('[SmallChangeBigDifference] Raw text (first 500):', finalText.slice(0, 500));
            setError(t('op_err_parse'));
          }
        },
        onError: (msg) => { setStreamStage(''); setError(msg || t('op_err_generic')); },
      }
    );
  };


  const handleRef = useRef(handleSubmit);
  useEffect(() => { handleRef.current = handleSubmit; });

  useEffect(() => {
    const handler = (e) => {
      const tag = document.activeElement?.tagName;
      if (tag === 'SELECT') return;
      if (e.key === 'Enter' && (e.metaKey || e.ctrlKey) && !loading) handleRef.current();
    };
    document.addEventListener('keydown', handler);
    return () => document.removeEventListener('keydown', handler);
  }, [loading]);

    const loadExample = () => {
    const ex = pickExample('SmallChangeBigDifference', EXAMPLES);
    setRoutine(ex.routine);
    setGoals(ex.goals || '');
    setPainPoints(ex.pain || '');
    setResults(null);
  };

  const viewExperiment = (exp) => {
    setRoutine(exp.originalInput?.typicalDay || '');
    setGoals(exp.originalInput?.improvementGoal || '');
    setPainPoints(exp.originalInput?.offTrack || '');
    setResults(exp.storedResult);
    setCheckingInId(null);
  };

  const openCheckIn = (expId) => {
    setCheckingInId(expId);
    setDraftStatus(null);
    setDraftReport('');
  };

  const saveCheckIn = () => {
    if (!draftStatus) return;
    setExperiments(prev => prev.map(e => e.id === checkingInId
      ? { ...e, checkIn: { status: draftStatus, visitorReport: draftReport.trim(), reviewedAt: new Date().toISOString() } }
      : e));
    setCheckingInId(null);
  };

  const removeExperiment = (expId) => {
    setExperiments(prev => prev.filter(e => e.id !== expId));
    if (checkingInId === expId) setCheckingInId(null);
  };

  const buildText = () => {
    if (!results) return '';
    const ch = results?.change_to_try;
    let out = `⚡ ${t('op_copy_header')}\n\n`;
    out += `${t('op_copy_notice')}\n${results?.what_i_notice?.pattern}\n\n`;
    out += `${t('op_copy_change')}\n${ch?.change}\n\n`;
    if (ch?.what_it_may_change) out += `${t('op_copy_mechanism')}\n${ch.what_it_may_change}\n\n`;
    if (results?.math?.show && results?.math?.calculation) out += `${t('op_copy_math')} ${results.math.calculation}\n\n`;
    out += `${t('op_copy_implement')}\n${ch?.how_to_try_it}\n\n`;
    if (results?.what_to_watch_for?.signs_it_may_be_helping?.length) {
      out += `${t('op_copy_watch')}\n`;
      results.what_to_watch_for.signs_it_may_be_helping.forEach(s => out += `  • ${s}\n`);
      out += '\n';
    }
    return out + BRAND;
  };

  useRegisterActions(buildText(), tool?.title || 'Small Change, Big Difference');

  // ═══ RENDER HELPERS ═══
  const CheckInForm = () => (
    <div className={`mt-3 pt-3 border-t ${c.border}`}>
      <p className={`text-xs font-bold uppercase tracking-wide mb-2 ${c.textMuteded}`}>{t('op_how_did_it_go')}</p>
      <div className="flex flex-wrap gap-1.5 mb-2">
        {CHECK_IN_STATUSES.map(s => (
          <button key={s} onClick={() => setDraftStatus(s)}
            className={`px-3 py-1.5 rounded-lg border text-xs font-semibold transition-all ${draftStatus === s ? c.pillActive : c.pillInactive}`}>
            {CHECK_IN_META[s].emoji} {CHECK_IN_META[s].label}
          </button>
        ))}
      </div>
      {draftStatus && (
        <>
          <input type="text" value={draftReport} onChange={e => setDraftReport(e.target.value)}
            placeholder={draftStatus === 'not_really' || draftStatus === 'not_tried' ? t('op_ci_ph_not_really') : t('op_ci_ph_helped')}
            className={`w-full px-3 py-2 rounded-lg border text-sm mb-2 ${c.input}`} />
          <div className="flex gap-2">
            <button onClick={saveCheckIn} className={`${c.btnPrimary} px-3 py-1.5 rounded-lg text-xs font-bold`}>{t('op_ci_save')}</button>
            <button onClick={() => setCheckingInId(null)} className={`${c.btnSecondary} px-3 py-1.5 rounded-lg text-xs font-bold`}>{t('op_ci_cancel')}</button>
          </div>
        </>
      )}
    </div>
  );

  const ExperimentRow = ({ exp }) => {
    const reviewed = exp.checkIn?.status && exp.checkIn.status !== 'unreviewed';
    const meta = reviewed ? CHECK_IN_META[exp.checkIn.status] : null;
    const dateStr = (() => { try { return new Date(exp.createdAt).toLocaleDateString(userLocale || undefined, { month: 'short', day: 'numeric' }); } catch { return ''; } })();
    return (
      <div className={`rounded-xl border ${c.histCard} p-3`}>
        <div className="flex items-start justify-between gap-2">
          <div className="flex-1 min-w-0">
            <p className={`text-sm font-semibold ${c.text} truncate`}>{exp.recommendation?.change || t('op_session')}</p>
            <p className={`text-xs ${c.textMuted} mt-0.5`}>
              {ROUTINE_AREA_LABEL[exp.experimentContext?.routineArea] || exp.experimentContext?.routineArea} · {dateStr}
            </p>
            {reviewed && (
              <p className={`text-xs mt-1 ${c.textSecondary}`}>
                {meta.emoji} {meta.label}
                {exp.checkIn.visitorReport && <span className="italic"> — "{exp.checkIn.visitorReport}"</span>}
              </p>
            )}
          </div>
          <div className="flex items-center gap-2 flex-shrink-0">
            {reviewed ? (
              <button onClick={() => viewExperiment(exp)} className={`text-xs font-bold ${linkStyle}`}>{t('op_view')} →</button>
            ) : (
              checkingInId !== exp.id && (
                <button onClick={() => openCheckIn(exp.id)} className={`text-xs font-bold ${linkStyle}`}>{t('op_how_did_it_go')} →</button>
              )
            )}
            <button onClick={() => removeExperiment(exp.id)} className={`text-xs ${c.textMuted} hover:${c.text}`} aria-label={t('op_remove')}>✕</button>
          </div>
        </div>
        {checkingInId === exp.id && <CheckInForm />}
      </div>
    );
  };

  return (
    <div className={`space-y-4 ${c.text}`}>

      <div className="max-w-2xl mx-auto">

        {/* Header */}
        <div className={`mb-4 pb-3 border-b ${c.border}`}>
          <div className="flex items-start justify-between gap-3">
            <div>
              {/* PF-30 — the wrapper already prints the name as the page <h1>. */}
              <p className={`text-base ${c.textSecondary}`}>
                <span className="me-2 text-lg">{tool?.icon ?? '⚡'}</span>{t('op_tagline')}
              </p>
              <button onClick={loadExample} disabled={loading} style={{ backgroundColor: (tool?.headerColor ?? '#888888') + '80' }} className="mt-2 px-4 py-2 rounded-full text-sm font-semibold border border-black/25 text-zinc-900 shadow-sm hover:brightness-105 hover:shadow transition disabled:opacity-40 whitespace-nowrap">✨ {t('try_example')}</button>
            </div>
            {(results || routine.trim()) && (
              <button onClick={() => { setResults(null); setRoutine(''); setGoals(''); setPainPoints(''); setError(''); }}
                className={`${c.btnSecondary} px-3 py-1.5 rounded-lg text-xs font-bold flex-shrink-0`}>
                ↺ {t('start_over')}
              </button>
            )}
          </div>
        </div>

        {/* Input */}
        {!results && (
          <div className={`rounded-2xl border p-6 shadow-sm space-y-4 ${c.card} ${c.border}`}>
            <p className={`text-xs ${c.textMuted}`}>
              {t('op_xref_intro')} <a href="/BrainDumpBuddy" className={linkStyle}>🧠 {t('op_braindump')}</a> {t('op_braindump_after')}
            </p>
            <div>
              <label className={`block text-sm font-semibold mb-1.5 ${c.text}`}>
                {t('op_routine_label')} <span className={c.required}>*</span>
              </label>
              <textarea value={routine} onChange={e => setRoutine(e.target.value)}
                placeholder={t('op_routine_ph')}
                rows={5} maxLength={800}
                className={`w-full px-4 py-3 rounded-xl border text-sm resize-none ${c.input} `} />
            </div>
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
              <div>
                <label className={`block text-sm font-semibold mb-1.5 ${c.text}`}>{t('op_goals_label')} <span className={`font-normal ${c.textMuteded}`}>({t('optional')})</span></label>
                <input type="text" value={goals} onChange={e => setGoals(e.target.value)}
                  placeholder={t('op_goals_ph')}
                  className={`w-full px-4 py-3 rounded-xl border text-sm ${c.input} `} />
              </div>
              <div>
                <label className={`block text-sm font-semibold mb-1.5 ${c.text}`}>{t('op_pain_label')} <span className={`font-normal ${c.textMuteded}`}>({t('optional')})</span></label>
                <input type="text" value={painPoints} onChange={e => setPainPoints(e.target.value)}
                  placeholder={t('op_pain_ph')}
                  className={`w-full px-4 py-3 rounded-xl border text-sm ${c.input} `} />
              </div>
            </div>

            {error && <div className={`p-3 rounded-xl border text-sm ${c.danger}`}><span className="me-1">⚠️</span>{error}</div>}

            <div>
              <button title={t('cmd_enter')} onClick={handleSubmit} disabled={loading || !routine.trim()}
                className={`relative w-full py-3 rounded-xl font-bold ${(!routine.trim()) ? c.btnIdle : c.btnPrimary}`}>
                {loading
                  ? <><span className="inline-block animate-spin">{tool?.icon ?? '⚡'}</span> {streamStage || t('op_stage_default')}</>
                  : <><span>{tool?.icon ?? '⚡'}</span> {t('op_submit')}</>}
              {!loading && (
                <kbd aria-hidden="true"
                  className="hidden sm:flex items-center absolute end-3 top-1/2 -translate-y-1/2 px-1.5 py-0.5 rounded border border-white/30 bg-white/15 text-[10px] font-bold tracking-wide">
                  ⌘↵
                </kbd>
              )}
              </button>
            </div>
          </div>
        )}

        {/* Results */}
        {results && (
          <div ref={revealRef} className="scroll-mt-24 space-y-4">

            {/* What I Notice */}
            {results?.what_i_notice && (
              <div className={`rounded-2xl border p-5 ${c.card} ${c.border}`}>
                <p className={`text-xs font-black uppercase tracking-widest mb-3 ${c.textMuteded}`}>🔎 {t('op_notice_label')}</p>
                {results?.what_i_notice?.pattern && (
                  <p className={`text-sm leading-relaxed mb-2 ${c.textSecondary}`}>{results?.what_i_notice?.pattern}</p>
                )}
                {results?.what_i_notice?.why_it_matters && (
                  <div>
                    <p className={`text-xs font-bold uppercase tracking-wider mb-1 ${c.textMuteded}`}>{t('op_why_it_matters_label')}</p>
                    <p className={`text-sm ${c.textMuted}`}>{results?.what_i_notice?.why_it_matters}</p>
                  </div>
                )}
              </div>
            )}

            {/* From your recent experiments — optional, only when it actually informed this recommendation */}
            {results?.previous_experiments?.used && results?.previous_experiments?.summary && (
              <div className={`rounded-xl border p-4 ${c.memoryBg}`}>
                <p className={`text-xs font-bold uppercase tracking-wide mb-1 ${c.memoryText}`}>🧪 {t('op_from_recent_experiments')}</p>
                <p className={`text-sm ${c.memoryText}`}>{results.previous_experiments.summary}</p>
                {results?.previous_experiments?.how_it_affected_this_choice && (
                  <div className="mt-2">
                    <p className={`text-xs font-bold uppercase tracking-wide mb-1 ${c.memoryText} opacity-80`}>{t('op_why_that_changed')}</p>
                    <p className={`text-sm ${c.memoryText}`}>{results.previous_experiments.how_it_affected_this_choice}</p>
                  </div>
                )}
              </div>
            )}

            {/* THE SMALL CHANGE — hero card */}
            {results?.change_to_try && (
              <div className={`rounded-2xl border-2 overflow-hidden ${isDark ? 'border-cyan-800 bg-zinc-800' : 'border-cyan-800 bg-white'}`}>
                <div style={{ background: isDark ? 'linear-gradient(135deg, #1e2a3a, #2c4a6e)' : 'linear-gradient(135deg, #2c4a6e, #4a6a8a)' }}
                  className="px-6 py-5">
                  <p className="text-xs font-black uppercase tracking-widest text-white/70 mb-2">⚡ {t('op_the_change_label')}</p>
                  <h2 className="text-xl font-black text-white leading-snug">{results?.change_to_try?.change}</h2>
                </div>

                <div className="px-6 py-5 space-y-4">
                  {results?.change_to_try?.why_this_one && (
                    <div>
                      <p className={`text-xs font-bold uppercase tracking-wider mb-1 ${c.textMuteded}`}>{t('op_why_this_one')}</p>
                      <p className={`text-sm leading-relaxed ${c.textSecondary}`}>{results?.change_to_try?.why_this_one}</p>
                    </div>
                  )}

                  {results?.change_to_try?.how_to_try_it && (
                    <div>
                      <p className={`text-xs font-bold uppercase tracking-wider mb-1 ${c.textMuteded}`}>✅ {t('op_how_implement')}</p>
                      <p className={`text-sm ${c.textSecondary}`}>{results?.change_to_try?.how_to_try_it}</p>
                    </div>
                  )}

                  {results?.change_to_try?.what_it_may_change && (
                    <div>
                      <p className={`text-xs font-bold uppercase tracking-wider mb-1 ${c.textMuteded}`}>⚙️ {t('op_what_it_may_change')}</p>
                      <p className={`text-sm leading-relaxed ${c.textSecondary}`}>{results?.change_to_try?.what_it_may_change}</p>
                    </div>
                  )}
                </div>
              </div>
            )}

            {/* The Math — its own section, shown only when math.show is true */}
            {results?.math?.show && (results?.math?.calculation || results?.math?.meaning) && (
              <div className={`p-4 rounded-xl border ${c.navyBg}`}>
                <p className={`text-xs font-bold uppercase tracking-wide mb-1 ${c.navyText}`}>📊 {t('op_the_math')}</p>
                {results?.math?.calculation && <p className={`text-sm font-mono font-semibold ${c.navyText}`}>{results.math.calculation}</p>}
                {results?.math?.meaning && <p className={`text-sm mt-1 ${c.navyText} opacity-90`}>{results.math.meaning}</p>}
              </div>
            )}

            {/* Why not start somewhere else — optional, up to 2 alternatives */}
            {results?.why_not_start_elsewhere?.show && results?.why_not_start_elsewhere?.alternatives?.length > 0 && (
              <div className={`rounded-2xl border p-5 ${c.card} ${c.border}`}>
                <p className={`text-xs font-bold uppercase tracking-wider mb-3 ${c.textMuteded}`}>🤔 {t('op_but_what_about')}</p>
                <div className="space-y-3">
                  {results.why_not_start_elsewhere.alternatives.map((alt, i) => (
                    <div key={i}>
                      {alt?.alternative && (
                        <p className={`text-sm mb-1 ${c.textSecondary}`}>
                          <span className={`font-semibold ${c.text}`}>{t('op_tempted_to')}</span> {alt.alternative}
                        </p>
                      )}
                      {alt?.why_not_first && (
                        <p className={`text-sm ${c.textSecondary}`}>
                          <span className={`font-semibold ${c.text}`}>{t('op_why_after')}</span> {alt.why_not_first}
                        </p>
                      )}
                    </div>
                  ))}
                </div>
              </div>
            )}

            {/* What to watch for */}
            {(results?.what_to_watch_for?.signs_it_may_be_helping?.length > 0 || results?.what_to_watch_for?.signs_to_rethink_it?.length > 0) && (
              <div className={`rounded-2xl border p-5 ${c.greenBg}`}>
                <p className={`text-xs font-black uppercase tracking-widest mb-3 ${c.greenText}`}>👀 {t('op_watch_for')}</p>
                {results?.what_to_watch_for?.signs_it_may_be_helping?.length > 0 && (
                  <div className="mb-3">
                    <p className={`text-xs font-bold uppercase tracking-wide mb-1 ${c.greenText}`}>{t('op_watch_helping')}</p>
                    <div className="space-y-1">
                      {results.what_to_watch_for.signs_it_may_be_helping.map((s, i) => (
                        <p key={i} className={`text-sm ${c.textSecondary}`}>• {s}</p>
                      ))}
                    </div>
                  </div>
                )}
                {results?.what_to_watch_for?.signs_to_rethink_it?.length > 0 && (
                  <div>
                    <p className={`text-xs font-bold uppercase tracking-wide mb-1 ${c.greenText}`}>{t('op_watch_rethink')}</p>
                    <div className="space-y-1">
                      {results.what_to_watch_for.signs_to_rethink_it.map((s, i) => (
                        <p key={i} className={`text-sm ${c.textSecondary}`}>• {s}</p>
                      ))}
                    </div>
                  </div>
                )}
              </div>
            )}

            {/* Cross-references */}
            <div className={`rounded-xl border p-4 ${c.cardAlt} ${c.border}`}>
              <p className={`text-xs font-semibold uppercase tracking-wide mb-3 ${c.textMuteded}`}>{t('op_related')}</p>
              <div className="flex flex-wrap gap-2">
                {[
                  { id: 'ChaosPilot', icon: '🎰', label: t('op_xref_chaospilot') },
                  { id: 'PreMortem', icon: '💀', label: t('op_xref_premortem') },
                  { id: 'FutureProof', icon: '🔮', label: t('op_xref_futureproof') },
                ].map(r => (
                  <a key={r.id} href={`/${r.id}`}
                    className={`px-3 py-1.5 rounded-lg text-xs font-medium transition-colors ${c.btnSecondary}`}>
                    {r.icon} {r.label}
                  </a>
                ))}
              </div>
            </div>
          </div>
        )}
      </div>

      {/* ─── Recent Small Changes — sits below the form/results either way, */}
      {/* never as an interstitial right after generating a new result. ─── */}
      {(experiments.length > 0 || legacyHistory.length > 0) ? (
        <div className={`p-4 rounded-xl border ${c.histBg}`}>
          <button onClick={() => setShowHistory(p => !p)} className="w-full flex items-center gap-2 text-start">
            <span>📋</span>
            <span className={`text-sm font-bold ${c.text} flex-1`}>{t('op_recent')}</span>
            <span className={`text-xs ${c.textMuted}`}>{experiments.length + legacyHistory.length}</span>
            <Caret open={showHistory} />
          </button>
          {showHistory && (
            <div className="mt-3 space-y-2">
              {(showAllExperiments ? experiments : experiments.slice(0, 3)).map(exp => (
                <ExperimentRow key={exp.id} exp={exp} />
              ))}
              {experiments.length > 3 && (
                <button onClick={() => setShowAllExperiments(p => !p)} className={`text-xs font-bold ${linkStyle}`}>
                  {showAllExperiments ? t('op_show_less') : t('op_view_all')}
                </button>
              )}
              {/* Legacy entries from before this feature — no fabricated
                  recommendation or check-in, per the migration rule. */}
              {legacyHistory.length > 0 && (
                <div className="space-y-1 pt-1">
                  {legacyHistory.map(s => (
                    <div key={s.id} className="flex items-center justify-between opacity-60">
                      <span className={`text-xs ${c.textSecondary} truncate`}>{s.preview || t('op_session')}</span>
                      <span className={`text-xs ${c.textMuted} ms-2`}>{new Date(s.date).toLocaleDateString()}</span>
                    </div>
                  ))}
                </div>
              )}
            </div>
          )}
        </div>
      ) : (
        <div className={`p-4 rounded-xl border ${c.histBg}`}>
          <p className={`text-sm ${c.textMuted}`}>📋 {t('op_recent')} — {t('op_empty_state')}</p>
        </div>
      )}
    </div>
  );
};

SmallChangeBigDifference.displayName = 'SmallChangeBigDifference';
export default SmallChangeBigDifference;
