const PlantRescue = ({ tool }) => {
  const { callToolEndpoint, loading, userLocale, userCurrency, userRegion } = useClaudeAPI();
  const { isDark } = useTheme();
  const { t } = useTranslation();

  const c = {
    card:          isDark ? 'bg-zinc-800' : 'bg-white',
    cardAlt:       isDark ? 'bg-zinc-700/50' : 'bg-slate-50',
    input:         isDark ? 'bg-zinc-900 border-zinc-600 text-zinc-100 placeholder-zinc-400 focus:border-cyan-500 focus:ring-cyan-500/20'
                          : 'bg-white border-gray-300 text-gray-900 placeholder-gray-400 focus:border-cyan-500 focus:ring-cyan-100',
    text:          isDark ? 'text-zinc-50' : 'text-gray-900',
    textSecondary: isDark ? 'text-zinc-300' : 'text-gray-600',
    textMuted:     isDark ? 'text-zinc-400' : 'text-gray-500',
    required:      isDark ? 'text-amber-400' : 'text-amber-700',
    labelText:     isDark ? 'text-zinc-200' : 'text-gray-700',
    accentTxt:     isDark ? 'text-cyan-400' : 'text-cyan-600',
    btnPrimary:    isDark ? 'bg-cyan-600 hover:bg-cyan-500 text-white'
                          : 'bg-cyan-600 hover:bg-cyan-700 text-white',
    btnIdle:       isDark ? '!bg-transparent !border-2 !border-cyan-500/85 !text-cyan-300 cursor-not-allowed'
                          : '!bg-transparent !border-2 !border-cyan-600/85 !text-cyan-800 cursor-not-allowed',
    btnSecondary:  isDark ? 'bg-zinc-700 hover:bg-zinc-600 text-zinc-200'
                          : 'bg-gray-100 hover:bg-gray-200 text-gray-700',
    border:        isDark ? 'border-zinc-700' : 'border-gray-200',
    success:       isDark ? 'bg-emerald-900/20 border-emerald-700 text-emerald-200'
                          : 'bg-emerald-50 border-emerald-300 text-emerald-800',
    warning:       isDark ? 'bg-amber-900/20 border-amber-700 text-amber-200'
                          : 'bg-amber-50 border-amber-300 text-amber-800',
    danger:        isDark ? 'bg-red-900/20 border-red-700 text-red-200'
                          : 'bg-red-50 border-red-200 text-red-800',
    pillActive:    isDark ? 'border-cyan-500 bg-cyan-900/30 text-cyan-200'
                          : 'border-cyan-600 bg-cyan-100 text-cyan-900',
    pillInactive:  isDark ? 'border-zinc-600 text-zinc-400 hover:border-zinc-500'
                          : 'border-gray-300 text-gray-500 hover:border-gray-400',
    critical:      isDark ? 'bg-red-900/20 border-red-700 text-red-200'       : 'bg-red-50 border-red-300 text-red-800',
    concerning:    isDark ? 'bg-amber-900/20 border-amber-700 text-amber-200' : 'bg-amber-50 border-amber-300 text-amber-800',
    minor:         isDark ? 'bg-sky-900/20 border-sky-700 text-sky-200'       : 'bg-sky-50 border-sky-200 text-sky-800',
    btnDanger:     isDark ? 'bg-red-700 hover:bg-red-600 text-white'          : 'bg-red-500 hover:bg-red-600 text-white',
  };
  c.label = c.labelText;
  c.textMuteded = c.textMuted;

  const linkStyle = isDark
    ? 'text-cyan-400 hover:text-cyan-300 underline underline-offset-2'
    : 'text-cyan-700 hover:text-cyan-800 underline underline-offset-2';

  const load = (k) => { try { const s = localStorage.getItem(k); return s ? JSON.parse(s) : null; } catch { return null; } };
  const save = (k, v) => { try { localStorage.setItem(k, JSON.stringify(v)); } catch {} };

  // ── State ──
  const [imagePreview, setImagePreview]         = useState(null);
  const [imageBase64, setImageBase64]           = useState(null);
  const [plantDescription, setPlantDescription] = useState('');
  const [lightLevel, setLightLevel]             = useState('');
  const [wateringMethod, setWateringMethod]     = useState('');
  const [wateringFreqText, setWateringFreqText] = useState('');
  const [hasDrainage, setHasDrainage]           = useState('');
  const [location, setLocation]                 = useState('');
  const [symptomDuration, setSymptomDuration]   = useState('');
  const [recentChanges, setRecentChanges]       = useState([]);
  const [uploading, setUploading]               = useState(false);
  const [hasPets, setHasPets]                   = useState(false);
  const [hasChildren, setHasChildren]           = useState(false);
  const [climateZone, setClimateZone]           = useState('');
  const [userLocation, setUserLocation]         = useState('');
  const [error, setError]                       = useState('');
  const [followUpQuestion, setFollowUpQuestion] = useState('');
  const [followUpAnswer, setFollowUpAnswer]     = useState('');
  const [followUpLoading, setFollowUpLoading]   = useState(false);
  const [mode, setMode]                         = useState('rescue');
  const [plantCollection, setPlantCollection]   = useState(() => load('plantCollection') || []);
  const [showCollection, setShowCollection]     = useState(false);
  const [plantName, setPlantName]               = useState('');
  const [activePlantId, setActivePlantId]       = useState(null);
  const [selectedSymptoms, setSelectedSymptoms] = useState([]);
  const [companionLoading, setCompanionLoading] = useState(false);
  const [companionResults, setCompanionResults] = useState(null);
  const [extraPhotos, setExtraPhotos]           = useState([null, null]);
  const [extraPreviews, setExtraPreviews]       = useState([null, null]);

  // Care mode's own fields — deliberately separate from Rescue's (lightLevel,
  // location) rather than shared, so Care's more granular light scale and
  // "what plant is it" question never leak into or get overwritten by
  // Rescue's simpler versions of the same idea.
  const [careSpecies, setCareSpecies]           = useState('');
  const [careWhereIsIt, setCareWhereIsIt]       = useState('');
  const [careLight, setCareLight]               = useState('');
  const [careHelpWith, setCareHelpWith]         = useState('');

  // ── Refs ──
  const fileInputRef     = useRef(null);
  const extraPhotoRef0   = useRef(null);
  const extraPhotoRef1   = useRef(null);
  const resultsRef       = useRef(null);
  const submitRef        = useRef(null);
  const canSubmitRef     = useRef(false);
  const collectionRef    = useRef(null);
  const formTopRef       = useRef(null);

  // ── Persistent state ──
  const [results, setResults] = usePersistentState('plantrescue-result', null);

  const extraPhotoRefs = [extraPhotoRef0, extraPhotoRef1];

  // Care mode needs to know what plant it's caring for — a photo alone
  // ("mainly to confirm identity if uncertain") doesn't substitute for that,
  // per the explicit spec. It's satisfied for free once careSpecies arrives
  // pre-filled from an Identify handoff or a My Plants "Check again."
  canSubmitRef.current = !loading && !uploading && (
    mode === 'identify' ? !!imageBase64 :
    mode === 'care' ? !!careSpecies.trim() :
    !!(imageBase64 || plantDescription.trim() || selectedSymptoms.length > 0)
  );

  // ── Image handling ──
  const processImage = async (file) => {
    if (!file || !file.type.startsWith('image/')) { setError(t('pr_err_upload_image')); return null; }
    setError('');
    try { return await compressImage(file, CompressionPresets.API_UPLOAD); }
    catch (err) { setError(err.message || t('pr_err_image_failed')); return null; }
  };
  const handleFileUpload = async (e) => {
    const f = e.target.files?.[0];
    if (f) { setUploading(true); const r = await processImage(f); if (r) { setImagePreview(r); setImageBase64(r); } setUploading(false); }
  };
  const handlePaste = async (e) => {
    const items = e.clipboardData?.items; if (!items) return;
    for (let i = 0; i < items.length; i++) {
      if (items[i].type.indexOf('image') !== -1) {
        setUploading(true); const r = await processImage(items[i].getAsFile());
        if (r) { setImagePreview(r); setImageBase64(r); } setUploading(false); break;
      }
    }
  };
  const handleRemoveImage = () => { setImagePreview(null); setImageBase64(null); if (fileInputRef.current) fileInputRef.current.value = ''; };
  const handleDragOver = (e) => e.preventDefault();
  const handleDrop = async (e) => {
    e.preventDefault(); const f = e.dataTransfer.files?.[0];
    if (f) { setUploading(true); const r = await processImage(f); if (r) { setImagePreview(r); setImageBase64(r); } setUploading(false); }
  };
  const handleExtraPhoto = async (idx, e) => {
    const f = e.target.files?.[0]; if (!f) return;
    const r = await processImage(f);
    if (r) { setExtraPhotos(p => { const n = [...p]; n[idx] = r; return n; }); setExtraPreviews(p => { const n = [...p]; n[idx] = r; return n; }); }
    if (extraPhotoRefs[idx]?.current) extraPhotoRefs[idx].current.value = '';
  };
  const handleRemoveExtra = (idx) => {
    setExtraPhotos(p => { const n = [...p]; n[idx] = null; return n; });
    setExtraPreviews(p => { const n = [...p]; n[idx] = null; return n; });
  };

  // ── Attention-level helpers (Rescue mode) ──
  const attentionStyles = (l) => ({ serious_damage_possible: c.critical, needs_attention: c.concerning, watch_and_check: c.minor, likely_minor: c.success }[l] || c.cardAlt);
  const attentionEmoji  = (l) => ATTENTION_META[l]?.icon || '🪴';
  const attentionLabel  = (l) => ({ serious_damage_possible: t('pr_attn_serious'), needs_attention: t('pr_attn_needs'), watch_and_check: t('pr_attn_watch'), likely_minor: t('pr_attn_minor') }[l] || l);
  const confidenceLabel = (l) => ({ high: t('pr_conf_high'), moderate: t('pr_conf_moderate'), low: t('pr_conf_low') }[l] || l);
  // Confidence describes the TOOL's own identification, not confidence in
  // something the visitor typed. A visitor-supplied identity the tool never
  // independently confirmed gets "Identity supplied by you" instead of a
  // high/moderate/low badge — shared by Rescue's plant_identification,
  // Care's plant, and Identify's identification_evidence.best_match.
  const identityBadge = (identitySource, confidence) => {
    if (identitySource === 'visitor_supplied') {
      return <span className={`text-xs px-2 py-1 rounded mt-2 inline-block ${isDark ? 'bg-zinc-700 text-zinc-300' : 'bg-gray-100 text-gray-600'}`}>{t('pr_identity_supplied')}</span>;
    }
    if (!confidence) return null;
    return (
      <span className={`text-xs px-2 py-1 rounded mt-2 inline-block ${confidence === 'high' ? 'bg-green-100 text-green-700' : confidence === 'moderate' ? 'bg-amber-100 text-amber-700' : 'bg-red-100 text-red-700'}`}>
        {confidenceLabel(confidence)}
      </span>
    );
  };

  // ── Symptom / duration / change / watering option definitions ──
  const symptomOptions = [
    { id: 'yellow_leaves', label: t('pr_sym_yellow_leaves') },
    { id: 'brown_tips',    label: t('pr_sym_brown_tips') },
    { id: 'drooping',      label: t('pr_sym_drooping') },
    { id: 'spots',         label: t('pr_sym_spots') },
    { id: 'mushy_stem',    label: t('pr_sym_mushy_stem') },
    { id: 'white_fuzz',    label: t('pr_sym_white_fuzz') },
    { id: 'tiny_bugs',     label: t('pr_sym_tiny_bugs') },
    { id: 'leggy',         label: t('pr_sym_leggy') },
    { id: 'no_growth',     label: t('pr_sym_no_growth') },
    { id: 'leaf_drop',     label: t('pr_sym_leaf_drop') },
    { id: 'crispy',        label: t('pr_sym_crispy') },
    { id: 'bad_smell',     label: t('pr_sym_bad_smell') },
  ];
  const toggleSymptom = (id) => setSelectedSymptoms(p => p.includes(id) ? p.filter(s => s !== id) : [...p, id]);

  const symptomDurationOptions = [
    { id: 'just_noticed',   label: t('pr_symdur_just_noticed') },
    { id: 'few_days',       label: t('pr_symdur_few_days') },
    { id: 'week_or_two',    label: t('pr_symdur_week_or_two') },
    { id: 'several_weeks',  label: t('pr_symdur_several_weeks') },
    { id: 'few_months',     label: t('pr_symdur_few_months') },
    { id: 'longer',         label: t('pr_symdur_longer') },
    { id: 'not_sure',       label: t('pr_symdur_not_sure') },
  ];

  const recentChangeOptions = [
    { id: 'moved',              label: t('pr_chg_moved') },
    { id: 'repotted',           label: t('pr_chg_repotted') },
    { id: 'watering_changed',   label: t('pr_chg_watering') },
    { id: 'light_changed',      label: t('pr_chg_light') },
    { id: 'fertilizer_changed', label: t('pr_chg_fertilizer') },
    { id: 'temperature_changed',label: t('pr_chg_temperature') },
    { id: 'pest_treatment',     label: t('pr_chg_pest') },
    { id: 'other',              label: t('pr_chg_other') },
    { id: 'nothing',            label: t('pr_chg_nothing') },
  ];
  const toggleRecentChange = (id) => setRecentChanges((prev) => {
    if (id === 'nothing') return prev.includes('nothing') ? [] : ['nothing'];
    const withoutNothing = prev.filter((x) => x !== 'nothing');
    return withoutNothing.includes(id) ? withoutNothing.filter((x) => x !== id) : [...withoutNothing, id];
  });

  const wateringMethodOptions = [
    { id: 'check_soil',   label: t('pr_watermethod_check_soil') },
    { id: 'schedule',     label: t('pr_watermethod_schedule') },
    { id: 'looks_thirsty',label: t('pr_watermethod_looks_thirsty') },
    { id: 'varies',       label: t('pr_watermethod_varies') },
  ];

  // ── Core handlers ──
  const priorObservationsForCurrent = plantCollection.find((p) => p.id === activePlantId)?.checks || [];

  const handleAnalyze = useCallback(async () => {
    if (mode === 'care' && !careSpecies.trim()) { setError(t('pr_err_care_species')); return; }
    if (mode !== 'care' && !imageBase64 && !plantDescription.trim() && selectedSymptoms.length === 0) { setError(t('pr_err_provide')); return; }
    setError(''); setResults(null); setFollowUpAnswer(''); setFollowUpQuestion(''); setCompanionResults(null);
    try {
      // Each mode sends ONLY its own fields — never whatever another mode's
      // form happened to leave in state. Rescue and Care share a look but
      // are genuinely separate questions (symptom triage vs. routine care),
      // and Identify is separate again (see the provenance fix above it).
      const shared = { mode, plantName: plantName.trim() || null, userLocale, userCurrency, userRegion };
      let payload;
      if (mode === 'identify') {
        payload = { ...shared, imageBase64 };
      } else if (mode === 'care') {
        payload = {
          ...shared, imageBase64,
          careSpecies: careSpecies.trim(), careWhereIsIt, careLight, careHelpWith,
          plantDescription: plantDescription.trim(),
          wateringMethod, wateringFreqText: wateringFreqText.trim(), hasDrainage,
          climateZone, userLocation: userLocation.trim(), hasPets, hasChildren,
          priorObservations: priorObservationsForCurrent,
        };
      } else {
        payload = {
          ...shared, imageBase64, extraPhotos: extraPhotos.filter(Boolean),
          plantDescription: plantDescription.trim(), symptoms: selectedSymptoms,
          symptomDuration, recentChanges,
          lightLevel, wateringMethod, wateringFreqText: wateringFreqText.trim(), hasDrainage,
          location, climateZone, userLocation: userLocation.trim(), hasPets, hasChildren,
          priorObservations: priorObservationsForCurrent,
        };
      }
      const data = await callToolEndpoint('plant-rescue', payload);
      setResults(data);
    } catch (err) { setError(err.message || t('pr_err_analysis')); }
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [imageBase64, extraPhotos, plantDescription, selectedSymptoms, symptomDuration, recentChanges, lightLevel,
      wateringMethod, wateringFreqText, hasDrainage, location, climateZone, userLocation, hasPets, hasChildren,
      careSpecies, careWhereIsIt, careLight, careHelpWith,
      mode, plantName, callToolEndpoint, userLocale, userCurrency, userRegion, priorObservationsForCurrent, t]);

  const loadExample = useCallback(() => {
    const ex = pickExample('PlantRescue', EXAMPLES);
    setMode(ex.mode);
    setPlantDescription(ex.plantDescription);
    setSelectedSymptoms(ex.symptoms || []);
    setSymptomDuration(ex.symptomDuration || '');
    setRecentChanges(ex.recentChanges || []);
    setLightLevel(ex.lightLevel);
    setWateringMethod(ex.wateringMethod || '');
    setWateringFreqText(ex.wateringFreqText || '');
    setHasDrainage(ex.hasDrainage || '');
    setLocation(ex.location);
    setHasPets(ex.hasPets);
    setHasChildren(ex.hasChildren);
  }, []);

  const handleFollowUp = async () => {
    if (!followUpQuestion.trim() || !results) return;
    setFollowUpLoading(true); setFollowUpAnswer('');
    try {
      const data = await callToolEndpoint('plant-rescue/followup', {
        question: followUpQuestion.trim(), originalDiagnosis: results, mode,
        plantDescription: plantDescription.trim(), imageBase64: imageBase64 || undefined,
        userLocale, userCurrency, userRegion
      });
      setFollowUpAnswer(data.answer || t('pr_no_answer'));
    } catch { setFollowUpAnswer(t('pr_err_followup')); }
    setFollowUpLoading(false);
  };

  const handleGetCompanions = async () => {
    if (plantCollection.length < 2) return;
    setCompanionLoading(true);
    try {
      const plants = plantCollection.map(p => ({
        name: p.name, species: p.species || p.commonName || 'Unknown',
        lightNeeds: p.lightNeeds || '', waterNeeds: p.waterNeeds || ''
      }));
      const data = await callToolEndpoint('plant-rescue/companions', { plants, climateZone, location, userLocale, userCurrency, userRegion });
      setCompanionResults(data);
    } catch { setError(t('pr_err_companion')); }
    setCompanionLoading(false);
  };

  const handleReset = () => {
    setImagePreview(null); setImageBase64(null); setPlantDescription(''); setLightLevel('');
    setWateringMethod(''); setWateringFreqText(''); setHasDrainage(''); setLocation('');
    setSymptomDuration(''); setRecentChanges([]); setHasPets(false);
    setHasChildren(false); setClimateZone(''); setUserLocation(''); setResults(null);
    setError(''); setFollowUpQuestion(''); setFollowUpAnswer(''); setSelectedSymptoms([]);
    setExtraPhotos([null, null]); setExtraPreviews([null, null]); setCompanionResults(null);
    setCareSpecies(''); setCareWhereIsIt(''); setCareLight(''); setCareHelpWith('');
    if (fileInputRef.current) fileInputRef.current.value = '';
  };

  // TAB SWITCH = NEW TASK. Rescue, Care, and Identify are separate questions
  // about (possibly) separate plants — clicking a different mode tab starts
  // that mode's form clean rather than carrying over whatever the previous
  // mode's form happened to hold. This does NOT touch My Plants / saved
  // history, only the transient form + result for the mode being left.
  // Contrast with the explicit handoffs below (handleShowCareFromIdentify,
  // handleCheckAgain), which deliberately DO carry specific information
  // forward because the visitor asked for that continuity.
  const handleModeTabClick = (newMode) => {
    if (newMode === mode) return;
    handleReset();
    setPlantName('');
    setActivePlantId(null);
    setMode(newMode);
  };

  // "My Plants" keeps WHAT WAS REPORTED and WHAT WAS SUGGESTED, never a
  // preserved AI conclusion — a saved check is observation, not a diagnosis
  // history. See PETWEIRDNESSDECODER-NOTES for the same discipline elsewhere.
  const handleSavePlant = () => {
    if (!results) return;
    const identity = mode === 'care' ? results?.plant : mode === 'identify' ? results?.identification_evidence?.best_match : results?.plant_identification;
    const name = plantName.trim() || identity?.name || identity?.common_name || identity?.best_match || t('pr_default_plant_name');
    const check = {
      date: new Date().toISOString(),
      // Symptoms are only ever collected (and shown) in Rescue mode — a
      // selection left over from an earlier Rescue session shouldn't leak
      // into what a Care or Identify save claims was "reported."
      reported: [plantDescription.trim(), mode === 'rescue' ? selectedSymptoms.map((s) => symptomOptions.find((o) => o.id === s)?.label).filter(Boolean).join(', ') : ''].filter(Boolean).join(' — '),
      suggestedChecks: mode === 'rescue' ? (results?.check_first || []).map((cf) => cf.check).join('; ') : '',
      attentionLevel: mode === 'rescue' ? results?.bottom_line?.attention_level : null,
    };
    setPlantCollection((prev) => {
      const existing = prev.find((p) => p.id === activePlantId);
      if (existing) {
        return prev.map((p) => p.id === activePlantId ? { ...p, checks: [check, ...(p.checks || [])].slice(0, 8) } : p);
      }
      const entry = {
        id: Date.now().toString(), name,
        species: identity?.scientific_name, commonName: identity?.name || identity?.common_name || identity?.best_match,
        lightNeeds: mode === 'care' ? results?.core_care?.light : '',
        waterNeeds: mode === 'care' ? results?.core_care?.watering : '',
        checks: [check],
      };
      setActivePlantId(entry.id);
      return [entry, ...prev].slice(0, 6);
    });
    // Open the list and move focus there — otherwise the only sign a save
    // did anything is the count in a header button the visitor isn't
    // looking at. Called directly (not left to the showCollection effect)
    // so this also fires when the list was already open and just gained
    // a new entry, not only on the closed -> open transition.
    setShowCollection(true);
    setTimeout(() => revealSection(collectionRef.current), 200);
  };
  const handleDeletePlant = (id) => { setPlantCollection(p => p.filter(pl => pl.id !== id)); if (activePlantId === id) setActivePlantId(null); };
  // An explicit handoff, not a tab switch: preload the stable information
  // belonging to THIS saved plant (its name), and clear everything else —
  // stale symptoms/photo/conditions from whatever was on screen before
  // clicking "Check again" must not silently become evidence about this
  // plant.
  const handleCheckAgain = (plant) => {
    handleReset();
    setPlantName(plant.name);
    setActivePlantId(plant.id);
    setShowCollection(false);
    setMode('rescue');
  };

  // Another explicit handoff: Identify already established what this plant
  // is, and the photo on screen is still of it — carry exactly those two
  // things into Care and nothing else (no Rescue symptom state could be
  // present anyway, since reaching Identify always goes through the
  // clean-form tab switch above, but this stays independent of that so it's
  // correct even if Identify is ever reached a different way).
  const handleShowCareFromIdentify = () => {
    const bestMatch = results?.identification_evidence?.best_match;
    if (!bestMatch) return;
    const identifiedName = bestMatch.common_name || bestMatch.scientific_name || '';
    const keepImage = imageBase64;
    const keepPreview = imagePreview;
    handleReset();
    setImageBase64(keepImage);
    setImagePreview(keepPreview);
    setCareSpecies(identifiedName);
    setMode('care');
  };

  // The empty "My Plants" state offers to add one rather than just saying
  // there's nothing there — this closes the panel and sends the visitor back
  // to the form, where a check's result carries its own "Save to My Plants"
  // button. There's no plant to jump to yet, so the form itself is the
  // closest useful "add one" target.
  const handleGoAddPlant = () => {
    setShowCollection(false);
    setTimeout(() => revealSection(formTopRef.current), 50);
  };

  // ── buildFullText ──
  const buildFullText = useCallback(() => {
    if (!results) return '';
    const l = [`🪴 ${mode === 'identify' ? t('pr_copy_id') : mode === 'care' ? t('pr_copy_care') : t('pr_copy_rescue')}`, '═'.repeat(40)];
    if (mode === 'rescue' && results?.plant_identification) {
      const pi = results.plant_identification;
      l.push('', `📷 ${pi.best_match || t('pr_unknown')}`, `  ${confidenceLabel(pi.confidence)}`);
    } else if (mode === 'care' && results?.plant) {
      l.push('', `📷 ${results.plant.name || t('pr_unknown')}`);
    } else if (mode === 'identify' && results?.identification_evidence) {
      const ev = results.identification_evidence;
      l.push('', `📷 ${ev.best_match?.common_name || t('pr_unknown')}`, `  ${confidenceLabel(ev.confidence)}`);
    }
    if (mode === 'rescue' && results?.bottom_line) {
      l.push('', `🚑 ${attentionLabel(results.bottom_line.attention_level)}`, `  ${results.bottom_line.summary || ''}`);
    }
    if (mode === 'rescue' && results?.possible_explanations?.length) {
      l.push('', t('pr_copy_could_explain')); results.possible_explanations.forEach((p) => l.push(`  • ${p.possibility}`));
    }
    if (mode === 'rescue' && results?.check_first?.length) {
      l.push('', t('pr_copy_check_first')); results.check_first.forEach((cfx) => l.push(`  • ${cfx.check}`));
    }
    if (mode === 'rescue' && results?.what_to_do_now?.length) {
      l.push('', t('pr_copy_action')); results.what_to_do_now.forEach((a) => l.push(`  • ${a.action}`));
    }
    if (mode === 'care' && results?.core_care) {
      const cc = results.core_care; l.push('', `🌿 ${t('pr_copy_care_head')}`);
      if (cc.watering) l.push(`  ${t('pr_copy_water')} ${cc.watering}`);
      if (cc.feeding) l.push(`  ${t('pr_copy_fertilize')} ${cc.feeding}`);
    }
    if (mode === 'identify' && results?.identification_evidence?.distinguishing_visible_features?.length) {
      l.push('', t('pr_copy_why_it_fits')); results.identification_evidence.distinguishing_visible_features.forEach((w) => l.push(`  • ${w}`));
    }
    if (followUpAnswer) l.push('', `${t('pr_copy_q')} ${followUpQuestion}`, `${t('pr_copy_a')} ${followUpAnswer}`);
    l.push(BRAND);
    return l.join('\n');
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [results, mode, followUpQuestion, followUpAnswer, t]);

  submitRef.current = handleAnalyze;

  useRegisterActions(buildFullText(), tool?.title || t('pr_title'));

  useEffect(() => {
    if (!results || !resultsRef.current) return;
    const timer = setTimeout(() => revealSection(resultsRef.current), 200);
    return () => clearTimeout(timer);
  }, [results]);

  // The My Plants panel renders below the entire input form — without this,
  // opening it from the header button (top of the page) changes nothing a
  // visitor can see without scrolling past everything else, which reads as
  // "clicking did nothing."
  useEffect(() => {
    if (!showCollection || !collectionRef.current) return;
    const timer = setTimeout(() => revealSection(collectionRef.current), 200);
    return () => clearTimeout(timer);
  }, [showCollection]);

  useEffect(() => {
    const handler = (e) => {
      const tag = document.activeElement?.tagName;
      if (tag === 'SELECT') return;
      if (e.key === 'Enter' && (e.metaKey || e.ctrlKey) && canSubmitRef.current)
        submitRef.current?.();
    };
    document.addEventListener('keydown', handler);
    return () => document.removeEventListener('keydown', handler);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  useEffect(() => { save('plantCollection', plantCollection); }, [plantCollection]);

  // ── Render ──
  return (
    <div className={`space-y-4 ${c.text}`}>

      {/* ── Main input card ── */}
      <div ref={formTopRef} className={`${c.card} border ${c.border} rounded-xl shadow-sm overflow-hidden`}>
        <div className="px-5 pt-2.5">
          <div className="pb-3 border-b border-zinc-500">
            <div className="flex items-end justify-between gap-3">
              <div>
                <p className={`text-base ${c.textSecondary}`}>
                  <span className="me-2 text-lg">{tool?.icon ?? '🪴'}</span>{tool?.tagline ?? t('pr_tagline')}
                </p>
                {/* This tool's headerColor is a deliberately dark navy (see
                    src/utils/headerGradient.js) — near-black text/border on
                    it reads fine blended with a light page but disappears
                    blended with a dark one, so both flip with isDark. Alpha
                    stays the standard '80' (PF-17b: the header pill regex
                    matches that literal). */}
                <button onClick={loadExample} disabled={loading} style={{ backgroundColor: (tool?.headerColor ?? '#888888') + '80' }} className={`mt-2 px-4 py-2 rounded-full text-sm font-semibold border ${isDark ? 'border-white/25 text-zinc-50' : 'border-black/25 text-zinc-900'} shadow-sm hover:brightness-105 hover:shadow transition disabled:opacity-40 whitespace-nowrap`}>✨ {t('try_example')}</button>
              </div>
              <div className="flex flex-col items-end gap-2 flex-shrink-0">
                {(results || plantDescription.trim() || imagePreview) && (
                  <button onClick={handleReset} className={`${c.btnSecondary} px-3 py-1.5 rounded-lg text-xs font-bold`}>
                    ↺ {t('start_over')}
                  </button>
                )}
                <button onClick={() => setShowCollection(!showCollection)}
                  className={`${c.btnSecondary} px-3 py-1.5 rounded text-xs`}>
                  🪴 {t('pr_my_plants')} ({plantCollection.length})
                </button>
              </div>
            </div>
          </div>
        </div>

        <div className="p-5 space-y-5">
          {/* Mode toggle */}
          <div className="flex gap-2">
            {[
              { key: 'rescue',   label: `🚑 ${t('pr_mode_rescue')}` },
              { key: 'care',     label: `🌱 ${t('pr_mode_care')}` },
              { key: 'identify', label: `🔍 ${t('pr_mode_identify')}` },
            ].map(m => (
              <button key={m.key} onClick={() => handleModeTabClick(m.key)}
                className={`flex-1 py-2.5 rounded-lg font-medium text-sm border transition-colors ${mode === m.key ? c.pillActive : c.pillInactive}`}>
                {m.label}
              </button>
            ))}
          </div>

          {/* Mode description */}
          <div className={`${c.cardAlt} border ${c.border} rounded-lg p-3`}>
            <p className={`text-sm ${c.textSecondary}`}>
              {mode === 'rescue'   ? t('pr_desc_rescue') :
               mode === 'care'     ? t('pr_desc_care') :
                                     t('pr_desc_identify')}
            </p>
          </div>

          {mode !== 'identify' && (
            <div>
              <label className={`block text-sm font-medium ${c.label} mb-1`}>{t('pr_plant_name')}</label>
              <input type="text" value={plantName} onChange={e => setPlantName(e.target.value)}
                placeholder={t('pr_plant_name_ph')}
                className={`w-full p-3 border rounded-lg ${c.input} outline-none focus:ring-2`} />
            </div>
          )}

          {/* What plant is it — Care mode's own identification input. Required
              unless it arrived already filled in from an Identify handoff or
              a My Plants "Check again" — the field being non-empty already
              satisfies that, no separate flag needed. */}
          {mode === 'care' && (
            <div>
              <label className={`block text-sm font-medium ${c.label} mb-1`}>{t('pr_care_species_label')} <span className={c.required}>*</span></label>
              <input type="text" value={careSpecies} onChange={e => setCareSpecies(e.target.value)}
                placeholder={t('pr_care_species_ph')}
                className={`w-full p-3 border rounded-lg ${c.input} outline-none focus:ring-2`} />
            </div>
          )}

          {/* Main photo */}
          <div>
            <label className={`block text-sm font-medium ${c.label} mb-2`}>
              {mode === 'rescue' ? t('pr_photo_rescue') : t('pr_photo_generic')}
              {mode === 'identify'
                ? <> <span className={c.required}>*</span></>
                : <> <span className={`font-normal ${c.textMuted}`}>{mode === 'care' ? t('pr_photo_hint_care') : t('pr_photo_hint_describe')}</span></>}
            </label>
            {!imagePreview ? (
              <div onDragOver={handleDragOver} onDrop={handleDrop} onPaste={handlePaste}
                className={`border-2 border-dashed rounded-lg p-6 text-center cursor-pointer ${isDark ? 'border-zinc-600 hover:border-zinc-400 bg-zinc-900/50' : 'border-gray-300 hover:border-gray-400 bg-white'}`}
                onClick={() => fileInputRef.current?.click()}>
                <input ref={fileInputRef} type="file" accept="image/*" onChange={handleFileUpload} className="hidden" />
                {uploading
                  ? <><span className="inline-block animate-spin">{tool?.icon ?? '🪴'}</span><p className={`text-sm ${c.text}`}>{t('pr_compressing')}</p></>
                  : <><span className="text-3xl block mb-2">📤</span><p className={`text-sm ${c.text}`}>{t('pr_upload_cta')}</p><p className={`text-xs ${c.textMuted}`}>{t('pr_upload_formats')}</p></>}
              </div>
            ) : (
              <div className="relative">
                <img src={imagePreview} alt={t('pr_alt_plant')} className="w-full max-h-48 object-contain rounded-lg border" />
                <button onClick={handleRemoveImage}
                  className={`absolute top-2 end-2 ${c.btnDanger} w-7 h-7 rounded-full flex items-center justify-center text-xs`}>✕</button>
              </div>
            )}
          </div>

          {/* Extra photos — rescue mode only */}
          {mode === 'rescue' && imagePreview && (
            <div className="grid grid-cols-2 gap-3">
              {[[t('pr_extra_closeup'), 0], [t('pr_extra_soil'), 1]].map(([label, idx]) => (
                <div key={idx}>
                  <label className={`block text-xs font-medium ${c.label} mb-1`}>{label}</label>
                  {!extraPreviews[idx] ? (
                    <div onClick={() => extraPhotoRefs[idx]?.current?.click()}
                      className={`border-2 border-dashed rounded-lg p-4 text-center cursor-pointer ${isDark ? 'border-zinc-600 hover:border-zinc-400' : 'border-gray-300 hover:border-gray-400'}`}>
                      <input ref={extraPhotoRefs[idx]} type="file" accept="image/*"
                        onChange={e => handleExtraPhoto(idx, e)} className="hidden" />
                      <span className="text-xl">📸</span><p className={`text-xs ${c.textMuted}`}>{t('pr_optional')}</p>
                    </div>
                  ) : (
                    <div className="relative">
                      <img src={extraPreviews[idx]} alt={t('pr_alt_extra', { n: idx + 1 })} className="w-full h-24 object-cover rounded-lg border" />
                      <button onClick={() => handleRemoveExtra(idx)}
                        className={`absolute top-1 end-1 ${c.btnDanger} w-5 h-5 rounded-full flex items-center justify-center text-xs`}>✕</button>
                    </div>
                  )}
                </div>
              ))}
            </div>
          )}

          {/* Symptom wizard — rescue only */}
          {mode === 'rescue' && (
            <div>
              <label className={`block text-sm font-medium ${c.label} mb-2`}>{t('pr_symptoms_label')} <span className={c.required}>*</span> <span className={`font-normal ${c.textMuted}`}>{t('pr_symptoms_hint')}</span></label>
              <div className="grid grid-cols-2 md:grid-cols-3 gap-2">
                {symptomOptions.map(s => (
                  <label key={s.id}
                    className={`p-2.5 rounded-lg border-2 cursor-pointer flex items-center gap-2 text-sm ${selectedSymptoms.includes(s.id) ? isDark ? 'border-cyan-500 bg-zinc-700' : 'border-cyan-600 bg-slate-50' : isDark ? 'border-zinc-700' : 'border-gray-200'}`}>
                    <input type="checkbox" checked={selectedSymptoms.includes(s.id)} onChange={() => toggleSymptom(s.id)} className="sr-only" />
                    <span>{CHANGE_CATEGORY_MAP[s.id]}</span>
                    <span className={selectedSymptoms.includes(s.id) ? 'font-bold' : ''}>{s.label}</span>
                  </label>
                ))}
              </div>
            </div>
          )}

          {/* Symptom duration — rescue only */}
          {mode === 'rescue' && (
            <div>
              <label className={`block text-sm font-medium ${c.label} mb-1`}>{t('pr_symdur_label')}</label>
              <select value={symptomDuration} onChange={(e) => setSymptomDuration(e.target.value)} className={`w-full p-2.5 border rounded-lg text-sm ${c.input}`}>
                <option value="">{t('pr_select')}</option>
                {symptomDurationOptions.map((o) => <option key={o.id} value={o.id}>{o.label}</option>)}
              </select>
            </div>
          )}

          {/* Recent changes — rescue only */}
          {mode === 'rescue' && (
            <div>
              <label className={`block text-sm font-medium ${c.label} mb-2`}>{t('pr_recent_changes_label')} <span className={`font-normal ${c.textMuted}`}>({t('pr_optional')})</span></label>
              <div className="grid grid-cols-2 md:grid-cols-3 gap-2">
                {recentChangeOptions.map((o) => (
                  <label key={o.id} className={`p-2 rounded-lg border-2 cursor-pointer flex items-center gap-2 text-xs ${recentChanges.includes(o.id) ? isDark ? 'border-cyan-500 bg-zinc-700' : 'border-cyan-600 bg-slate-50' : isDark ? 'border-zinc-700' : 'border-gray-200'}`}>
                    <input type="checkbox" checked={recentChanges.includes(o.id)} onChange={() => toggleRecentChange(o.id)} className="sr-only" />
                    <span className={recentChanges.includes(o.id) ? 'font-bold' : ''}>{o.label}</span>
                  </label>
                ))}
              </div>
            </div>
          )}

          {/* "Tell us a little more" — Rescue-only in this position; Care's
              equivalent ("anything else that matters?") sits after the
              conditions fields below, matching the user's Plant identity →
              Current conditions → Optional context ordering. */}
          {mode === 'rescue' && (
            <div>
              <div className="flex justify-between mb-1">
                <label className={`text-sm font-medium ${c.label}`}>{t('pr_details_label')} <span className={`font-normal ${c.textMuted}`}>({t('pr_optional')})</span></label>
              </div>
              <textarea value={plantDescription} onChange={e => setPlantDescription(e.target.value)}
                placeholder={t('pr_details_ph')}
                className={`w-full p-3 border rounded-lg ${c.input} outline-none focus:ring-2 resize-y`} rows={2} />
            </div>
          )}

          {/* Where / Light — Rescue and Care ask this the same conceptual
              question but with deliberately different option sets (Care's
              light scale is more granular, per the explicit Care redesign),
              so these are two separate field pairs, not a shared one. */}
          {mode === 'rescue' && (
            <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
              <div>
                <label className={`block text-xs font-medium ${c.label} mb-1`}>{t('pr_light')}</label>
                <select value={lightLevel} onChange={e => setLightLevel(e.target.value)} className={`w-full p-2.5 border rounded-lg text-sm ${c.input}`}>
                  <option value="">{t('pr_select')}</option>
                  <option value="full-sun">{t('pr_light_full')}</option>
                  <option value="partial-shade">{t('pr_light_partial')}</option>
                  <option value="low-light">{t('pr_light_low')}</option>
                </select>
              </div>
              <div>
                <label className={`block text-xs font-medium ${c.label} mb-1`}>{t('pr_location')}</label>
                <select value={location} onChange={e => setLocation(e.target.value)} className={`w-full p-2.5 border rounded-lg text-sm ${c.input}`}>
                  <option value="">{t('pr_select')}</option>
                  <option value="indoor">{t('pr_loc_indoor')}</option>
                  <option value="outdoor">{t('pr_loc_outdoor')}</option>
                  <option value="greenhouse">{t('pr_loc_greenhouse')}</option>
                </select>
              </div>
            </div>
          )}

          {mode === 'care' && (
            <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
              <div>
                <label className={`block text-xs font-medium ${c.label} mb-1`}>{t('pr_care_where_label')}</label>
                <select value={careWhereIsIt} onChange={e => setCareWhereIsIt(e.target.value)} className={`w-full p-2.5 border rounded-lg text-sm ${c.input}`}>
                  <option value="">{t('pr_select')}</option>
                  <option value="indoor">{t('pr_loc_indoor')}</option>
                  <option value="outdoor">{t('pr_loc_outdoor')}</option>
                  <option value="both">{t('pr_care_where_both')}</option>
                </select>
              </div>
              <div>
                <label className={`block text-xs font-medium ${c.label} mb-1`}>{t('pr_light')}</label>
                <select value={careLight} onChange={e => setCareLight(e.target.value)} className={`w-full p-2.5 border rounded-lg text-sm ${c.input}`}>
                  <option value="">{t('pr_select')}</option>
                  <option value="low">{t('pr_care_light_low')}</option>
                  <option value="medium">{t('pr_care_light_medium')}</option>
                  <option value="bright_indirect">{t('pr_care_light_bright_indirect')}</option>
                  <option value="some_direct">{t('pr_care_light_some_direct')}</option>
                  <option value="lots_direct">{t('pr_care_light_lots_direct')}</option>
                  <option value="not_sure">{t('pr_not_sure')}</option>
                </select>
              </div>
            </div>
          )}

          {mode !== 'identify' && (
            <>
              <div>
                <label className={`block text-xs font-medium ${c.label} mb-1`}>{t('pr_watermethod_label')}</label>
                <select value={wateringMethod} onChange={(e) => setWateringMethod(e.target.value)} className={`w-full p-2.5 border rounded-lg text-sm ${c.input} mb-2`}>
                  <option value="">{t('pr_select')}</option>
                  {wateringMethodOptions.map((o) => <option key={o.id} value={o.id}>{o.label}</option>)}
                </select>
                <input type="text" value={wateringFreqText} onChange={(e) => setWateringFreqText(e.target.value)}
                  placeholder={t('pr_watermethod_freq_ph')}
                  className={`w-full p-2.5 border rounded-lg text-sm ${c.input} outline-none focus:ring-2`} />
              </div>

              <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                <div>
                  <label className={`block text-xs font-medium ${c.label} mb-1`}>{t('pr_drainage_label')} <span className={`font-normal ${c.textMuted}`}>({t('pr_optional')})</span></label>
                  <select value={hasDrainage} onChange={(e) => setHasDrainage(e.target.value)} className={`w-full p-2.5 border rounded-lg text-sm ${c.input}`}>
                    <option value="">{t('pr_select')}</option>
                    <option value="yes">{t('pr_yes')}</option>
                    <option value="no">{t('pr_no')}</option>
                    <option value="not_sure">{t('pr_not_sure')}</option>
                  </select>
                </div>
                <div>
                  <label className={`block text-xs font-medium ${c.label} mb-1`}>{t('pr_climate')}</label>
                  <select value={climateZone} onChange={e => setClimateZone(e.target.value)} className={`w-full p-2.5 border rounded-lg text-sm ${c.input}`}>
                    <option value="">{t('pr_select')}</option>
                    <option value="tropical">{t('pr_climate_tropical')}</option>
                    <option value="subtropical">{t('pr_climate_subtropical')}</option>
                    <option value="temperate">{t('pr_climate_temperate')}</option>
                    <option value="cold">{t('pr_climate_cold')}</option>
                    <option value="arid">{t('pr_climate_arid')}</option>
                  </select>
                </div>
              </div>

              <div className="flex gap-4">
                <label className="flex items-center gap-2 cursor-pointer text-sm">
                  <input type="checkbox" checked={hasPets} onChange={e => setHasPets(e.target.checked)} className="w-4 h-4" /> {t('pr_pets')}
                </label>
                <label className="flex items-center gap-2 cursor-pointer text-sm">
                  <input type="checkbox" checked={hasChildren} onChange={e => setHasChildren(e.target.checked)} className="w-4 h-4" /> {t('pr_children')}
                </label>
              </div>
            </>
          )}

          {/* Care's "optional context" — deliberately last, after the
              conditions fields, matching the requested field ordering. */}
          {mode === 'care' && (
            <>
              <div>
                <label className={`block text-sm font-medium ${c.label} mb-1`}>{t('pr_care_notes_label')} <span className={`font-normal ${c.textMuted}`}>({t('pr_optional')})</span></label>
                <textarea value={plantDescription} onChange={e => setPlantDescription(e.target.value)}
                  placeholder={t('pr_care_notes_ph')}
                  className={`w-full p-3 border rounded-lg ${c.input} outline-none focus:ring-2 resize-y`} rows={2} />
              </div>
              <div>
                <label className={`block text-xs font-medium ${c.label} mb-1`}>{t('pr_care_help_label')} <span className={`font-normal ${c.textMuted}`}>({t('pr_optional')})</span></label>
                <select value={careHelpWith} onChange={e => setCareHelpWith(e.target.value)} className={`w-full p-2.5 border rounded-lg text-sm ${c.input}`}>
                  <option value="">{t('pr_select')}</option>
                  <option value="watering">{t('pr_care_help_watering')}</option>
                  <option value="light">{t('pr_care_help_light')}</option>
                  <option value="repotting">{t('pr_care_help_repotting')}</option>
                  <option value="feeding">{t('pr_care_help_feeding')}</option>
                  <option value="placement">{t('pr_care_help_placement')}</option>
                  <option value="general">{t('pr_care_help_general')}</option>
                </select>
              </div>
            </>
          )}

          <button title={t('cmd_enter')} onClick={() => handleAnalyze()}
          disabled={!canSubmitRef.current}
          className={`relative w-full ${!canSubmitRef.current ? c.btnIdle : c.btnPrimary} font-bold py-3 rounded-lg flex items-center justify-center gap-2 min-h-[48px]`}>
          {loading
            ? <><span className="inline-block animate-spin">{tool?.icon ?? '🪴'}</span> {t('pr_analyzing')}</>
            : <><span>{tool?.icon ?? '🪴'}</span> {mode === 'rescue' ? t('pr_btn_diagnose') : mode === 'identify' ? t('pr_btn_identify') : t('pr_btn_care')}</>}
          {!loading && (
            <kbd aria-hidden="true"
              className="hidden sm:flex items-center absolute end-3 top-1/2 -translate-y-1/2 px-1.5 py-0.5 rounded border border-white/30 bg-white/15 text-[10px] font-bold tracking-wide">
              ⌘↵
            </kbd>
          )}
          </button>

          <p className={`text-xs text-center ${c.textMuted}`}>
            {t('pr_xref_intro')} <a href="/BikeMedic" className={`text-xs ${linkStyle}`}>🚲 {t('pr_xref_bikemedic')}</a> {t('pr_xref_bikemedic_tail')}
          </p>

          {error && (
            <div className={`${c.critical} border rounded-lg p-4 flex items-start gap-3`}>
              <span>⚠️</span><p className="text-sm">{error}</p>
            </div>
          )}
        </div>
      </div>

      {/* ── Collection panel ── */}
      {showCollection && (
        <div ref={collectionRef} className={`${c.card} border ${c.border} rounded-xl p-5`}>
          <div className="flex items-center justify-between mb-3">
            <h3 className={`font-bold ${c.text}`}>🪴 {t('pr_my_plants')}</h3>
            {plantCollection.length >= 2 && (
              <button onClick={handleGetCompanions} disabled={companionLoading}
                className={`${c.btnSecondary} px-3 py-1.5 rounded text-xs disabled:opacity-40`}>
                {companionLoading ? <><span className="inline-block animate-spin">{tool?.icon ?? '🪴'}</span></> : t('pr_companion_check')}
              </button>
            )}
          </div>

          {plantCollection.length > 0 ? (
            <div className="space-y-2">
              {plantCollection.map(pl => (
                <div key={pl.id}
                  className={`p-3 rounded-lg border ${activePlantId === pl.id ? 'border-emerald-500' : isDark ? 'border-zinc-600' : 'border-gray-200'} ${isDark ? 'bg-zinc-700' : 'bg-white'}`}>
                  <div className="flex items-center justify-between gap-2">
                    <div className="min-w-0 flex-1">
                      <h4 className={`font-bold ${c.text} truncate`}>{pl.name}</h4>
                      <p className={`text-xs ${c.textMuted}`}>{pl.commonName || pl.species || t('pr_unknown')}</p>
                      {pl.checks?.[0] && <p className={`text-xs ${c.textSecondary} truncate`}>{new Date(pl.checks[0].date).toLocaleDateString()} — {pl.checks[0].reported?.slice(0, 60) || t('pr_no_description')}</p>}
                    </div>
                    <div className="flex items-center gap-2 flex-shrink-0">
                      <button onClick={() => handleCheckAgain(pl)} className={`${c.btnSecondary} px-2 py-1 rounded text-xs`}>{t('pr_check_again')}</button>
                      <button onClick={() => handleDeletePlant(pl.id)} className={`text-xs ${c.textMuted} hover:text-zinc-400`}>✕</button>
                    </div>
                  </div>
                </div>
              ))}
            </div>
          ) : (
            <div className="text-center py-2">
              <p className={`text-sm ${c.textMuted} mb-3`}>{t('pr_no_saved')}</p>
              <button onClick={handleGoAddPlant} className={`${c.btnPrimary} px-4 py-2 rounded-lg text-sm font-semibold`}>
                {t('pr_add_first_plant')}
              </button>
            </div>
          )}

          {/* Companion results — grouped by care-routine verdict, not physical
              proximity. "different_needs" means these plants shouldn't
              automatically share a routine, never that they can't be near
              each other. */}
          {companionResults && (
            <div className={`mt-4 p-4 rounded-lg border ${isDark ? 'bg-zinc-800 border-zinc-600' : 'bg-white border-gray-200'}`}>
              <h4 className={`font-bold mb-2 ${c.text}`}>{t('pr_companion_analysis')}</h4>
              {[
                { verdict: 'good_match', icon: '✅', label: t('pr_verdict_good_match') },
                { verdict: 'separate_care', icon: '🔸', label: t('pr_verdict_separate_care') },
                { verdict: 'different_needs', icon: '🔀', label: t('pr_verdict_different_needs') },
              ].map(({ verdict, icon, label }) => {
                const pairs = (companionResults.pairs || []).filter((p) => p.verdict === verdict);
                if (!pairs.length) return null;
                return (
                  <div key={verdict} className="space-y-2 mb-3">
                    <p className={`text-xs font-bold ${c.label}`}>{label}</p>
                    {pairs.map((g, i) => (
                      <div key={i} className={`p-2 rounded ${isDark ? 'bg-zinc-800' : 'bg-white'}`}>
                        <p className={`text-sm ${c.text}`}>{icon} {g.plants?.join(', ')}</p>
                        <p className={`text-xs ${c.textMuted}`}>{g.why}</p>
                      </div>
                    ))}
                  </div>
                );
              })}
              {companionResults.placement_principle && (
                <p className={`text-sm ${c.textSecondary} mt-2`}>💡 {companionResults.placement_principle}</p>
              )}
            </div>
          )}
        </div>
      )}

      {/* ── Results ── */}
      {results && (
        <div className="scroll-mt-24 space-y-4" ref={resultsRef}>

          <div className="flex justify-center">
            <button onClick={handleSavePlant} className={`${c.btnSecondary} px-4 py-2 rounded-lg text-sm`}>{t('pr_save_to_plants')}</button>
          </div>

          {/* ═══ RESCUE MODE ═══ */}
          {mode === 'rescue' && results?.bottom_line && (
            <>
              <div className={`${attentionStyles(results.bottom_line.attention_level)} border-s-4 rounded-e-lg p-6`}>
                <div className="flex items-center gap-3">
                  <span className="text-4xl">{attentionEmoji(results.bottom_line.attention_level)}</span>
                  <div>
                    <h3 className={`text-xl font-bold ${c.text}`}>{attentionLabel(results.bottom_line.attention_level)}</h3>
                  </div>
                </div>
                <p className={`text-sm mt-3 ${c.text}`}>{results.bottom_line.summary}</p>
              </div>

              {results?.plant_identification && (
                <div className={`${c.card} border ${c.border} rounded-xl p-5`}>
                  <h3 className={`font-bold mb-1 ${c.text}`}>{t('pr_identification')}</h3>
                  <p className={`text-lg font-bold ${c.text}`}>{results.plant_identification.best_match}</p>
                  {results.plant_identification.scientific_name && <p className={`text-sm italic ${c.textSecondary}`}>{results.plant_identification.scientific_name}</p>}
                  {identityBadge(results.plant_identification.identity_source, results.plant_identification.confidence)}
                  {results.plant_identification.why_it_fits && <p className={`text-sm mt-2 ${c.textSecondary}`}>{results.plant_identification.why_it_fits}</p>}
                  {results.plant_identification.alternatives?.filter((a) => a && a.trim()).length > 0 && (
                    <div className="mt-2">{results.plant_identification.alternatives.filter((a) => a && a.trim()).map((a, i) => <p key={i} className={`text-xs ${c.textMuted}`}>• {a}</p>)}</div>
                  )}
                </div>
              )}

              {results?.what_you_reported?.filter((r) => r && r.trim()).length > 0 && (
                <div className={`${c.card} border ${c.border} rounded-xl p-5`}>
                  <h3 className={`font-bold mb-2 ${c.text}`}>📋 {t('pr_what_you_reported')}</h3>
                  <ul className={`text-sm space-y-1 ${c.textSecondary}`}>{results.what_you_reported.filter((r) => r && r.trim()).map((r, i) => <li key={i}>• {r}</li>)}</ul>
                </div>
              )}

              {results?.possible_explanations?.length > 0 && (
                <div className={`${c.card} border ${c.border} rounded-xl p-5`}>
                  <h3 className={`font-bold ${c.text} mb-3`}>❓ {t('pr_could_explain')}</h3>
                  {results.possible_explanations.map((p, i) => (
                    <div key={i} className={`p-3 rounded-lg mb-2 ${isDark ? 'bg-zinc-700' : 'bg-amber-50'}`}>
                      <p className={`font-semibold ${c.text}`}>{p.possibility}</p>
                      {p.why_it_could_fit && <p className={`text-sm mt-1 ${c.textSecondary}`}>{p.why_it_could_fit}</p>}
                      {p.check && <p className={`text-xs mt-1 ${c.textMuted}`}>🔎 {p.check}</p>}
                    </div>
                  ))}
                </div>
              )}

              {results?.check_first?.length > 0 && (
                <div className={`${c.warning} border-s-4 rounded-e-lg p-5`}>
                  <h3 className="font-bold mb-2 flex items-center gap-2"><span>🔎</span> {t('pr_check_first')}</h3>
                  <div className="space-y-3">
                    {results.check_first.map((cfx, i) => (
                      <div key={i}>
                        <p className={`text-sm font-semibold ${c.text}`}>{cfx.check}</p>
                        {cfx.what_to_look_for && <p className={`text-xs ${c.textSecondary}`}>{cfx.what_to_look_for}</p>}
                        {cfx.if_yes && <p className={`text-xs ${c.textSecondary} mt-1`}>→ {t('pr_if_yes')}: {cfx.if_yes}</p>}
                        {cfx.if_no && <p className={`text-xs ${c.textSecondary}`}>→ {t('pr_if_no')}: {cfx.if_no}</p>}
                      </div>
                    ))}
                  </div>
                </div>
              )}

              {results?.what_to_do_now?.length > 0 && (
                <div className={`${c.card} border ${c.border} rounded-xl p-6`}>
                  <h3 className={`text-lg font-bold ${c.text} mb-3`}>✅ {t('pr_can_do_now')}</h3>
                  <div className="space-y-3">
                    {results.what_to_do_now.map((a, idx) => (
                      <div key={idx} className={`border-s-4 border-emerald-500 ${c.cardAlt} border rounded-e-lg p-4`}>
                        <h4 className={`font-bold ${c.text} mb-1`}>{a.action}</h4>
                        {a.why && <p className="text-sm"><strong>{t('pr_why_strong')}</strong> <span className={c.textSecondary}>{a.why}</span></p>}
                        {a.condition && <p className={`text-xs mt-1 ${c.textMuted}`}>{a.condition}</p>}
                      </div>
                    ))}
                  </div>
                </div>
              )}

              {results?.what_improvement_looks_like?.filter((x) => x && x.trim()).length > 0 && (
                <div className={`${c.success} border-s-4 rounded-e-lg p-5`}>
                  <h3 className="font-bold mb-2">🌱 {t('pr_improvement_looks_like')}</h3>
                  <ul className="text-sm space-y-1">{results.what_improvement_looks_like.filter((x) => x && x.trim()).map((x, i) => <li key={i}>• {x}</li>)}</ul>
                </div>
              )}

              {results?.safety?.show && (
                <div className={`${c.critical} border-4 rounded-xl p-6`}>
                  <h3 className={`text-lg font-bold mb-2 ${c.text}`}>⚠️ {t('pr_safety')}</h3>
                  {results.safety.who_or_what && <p className={`text-sm font-semibold ${c.text}`}>{results.safety.who_or_what}</p>}
                  <p className="text-sm mt-1">{results.safety.guidance}</p>
                </div>
              )}

              {results?.useful_next_photo && (
                <div className={`${c.cardAlt} border ${c.border} rounded-xl p-5`}>
                  <h3 className={`font-bold mb-1 ${c.text}`}>📷 {t('pr_useful_photo')}</h3>
                  <p className={`text-sm ${c.textSecondary}`}>{results.useful_next_photo}</p>
                </div>
              )}
            </>
          )}

          {/* ═══ CARE MODE ═══ */}
          {mode === 'care' && results?.core_care && (
            <>
              <div className={`${c.card} border ${c.border} rounded-xl shadow-sm p-6 text-center`}>
                <div className="text-6xl mb-3">🌿</div>
                <div className={`text-2xl font-black ${c.text}`}>{results?.plant?.name || t('pr_care_guide_title')}</div>
                {results?.plant?.scientific_name && <p className={`text-sm italic ${c.textSecondary}`}>{results.plant.scientific_name}</p>}
                {identityBadge(results?.plant?.identity_source, results?.plant?.confidence)}
              </div>

              <div className={`${c.card} ${c.success} border border-s-4 rounded-xl p-6`}>
                <h3 className={`text-lg font-bold mb-3 ${c.text}`}>{t('pr_care_schedule')}</h3>
                <div className="grid grid-cols-1 md:grid-cols-2 gap-3">
                  {results.core_care.light               && <div className={`p-3 rounded-lg ${isDark ? 'bg-zinc-800' : 'bg-white'}`}><p className="text-xs font-bold mb-1">{t('pr_cs_light')}</p><p className={`text-sm ${c.text}`}>{results.core_care.light}</p></div>}
                  {results.core_care.watering            && <div className={`p-3 rounded-lg ${isDark ? 'bg-zinc-800' : 'bg-white'}`}><p className="text-xs font-bold mb-1">{t('pr_cs_watering')}</p><p className={`text-sm ${c.text}`}>{results.core_care.watering}</p></div>}
                  {results.core_care.soil_and_drainage   && <div className={`p-3 rounded-lg ${isDark ? 'bg-zinc-800' : 'bg-white'}`}><p className="text-xs font-bold mb-1">{t('pr_cs_soil')}</p><p className={`text-sm ${c.text}`}>{results.core_care.soil_and_drainage}</p></div>}
                  {results.core_care.feeding             && <div className={`p-3 rounded-lg ${isDark ? 'bg-zinc-800' : 'bg-white'}`}><p className="text-xs font-bold mb-1">{t('pr_cs_fertilizing')}</p><p className={`text-sm ${c.text}`}>{results.core_care.feeding}</p></div>}
                  {results.core_care.temperature_and_humidity && <div className={`p-3 rounded-lg ${isDark ? 'bg-zinc-800' : 'bg-white'}`}><p className="text-xs font-bold mb-1">{t('pr_cs_temp_humidity')}</p><p className={`text-sm ${c.text}`}>{results.core_care.temperature_and_humidity}</p></div>}
                </div>
              </div>

              {results?.repot_when?.filter((x) => x && x.trim()).length > 0 && (
                <div className={`${c.card} border ${c.border} rounded-xl p-5`}>
                  <h3 className={`font-bold mb-2 ${c.text}`}>{t('pr_repot_when')}</h3>
                  <ul className={`text-sm space-y-1 ${c.textSecondary}`}>{results.repot_when.filter((x) => x && x.trim()).map((x, i) => <li key={i}>• {x}</li>)}</ul>
                </div>
              )}

              {results?.when_conditions_change?.length > 0 && (
                <div className={`${c.card} border ${c.border} rounded-xl p-5`}>
                  <h3 className={`font-bold mb-3 ${c.text}`}>{t('pr_when_conditions_change')}</h3>
                  <div className="space-y-2">
                    {results.when_conditions_change.map((w, i) => (
                      <div key={i} className={`p-3 rounded-lg ${c.cardAlt}`}>
                        <p className={`text-sm font-semibold ${c.text}`}>{w.condition}</p>
                        <p className={`text-sm ${c.textSecondary}`}>{w.adjustment}</p>
                      </div>
                    ))}
                  </div>
                </div>
              )}

              {results?.watch_for?.filter((x) => x && x.trim()).length > 0 && (
                <div className={`${c.warning} border-s-4 rounded-e-lg p-5`}>
                  <h3 className="font-bold mb-2 flex items-center gap-2"><span>👀</span> {t('pr_watch_for')}</h3>
                  <ul className="text-sm space-y-1">{results.watch_for.filter((x) => x && x.trim()).map((x, i) => <li key={i}>• {x}</li>)}</ul>
                </div>
              )}

              {results?.pet_child_safety?.show && (
                <div className={`${c.critical} border-4 rounded-xl p-6`}>
                  <h3 className={`text-lg font-bold mb-2 ${c.text}`}>⚠️ {t('pr_safety')}</h3>
                  <p className="text-sm">{results.pet_child_safety.guidance}</p>
                </div>
              )}
            </>
          )}

          {/* ═══ IDENTIFY MODE ═══ */}
          {/* Every section below reads from the single identification_evidence
              object the backend builds — none of them independently decide
              whether a photo exists (see IDENTIFY IMAGE CONSISTENCY). */}
          {mode === 'identify' && results?.identification_evidence && (
            <>
              <div className={`${c.card} border ${c.border} rounded-xl shadow-sm p-6 text-center`}>
                <div className="text-6xl mb-3">🔍</div>
                <div className={`text-2xl font-black ${c.text}`}>{results.identification_evidence.best_match?.common_name || t('pr_identified')}</div>
                {results.identification_evidence.best_match?.scientific_name && <p className={`text-sm italic ${c.textSecondary}`}>{results.identification_evidence.best_match.scientific_name}</p>}
                {identityBadge(results.identification_evidence.best_match?.identity_source, results.identification_evidence.confidence)}
              </div>

              {results.identification_evidence.current_image_observations?.filter((x) => x && x.trim()).length > 0 && (
                <div className={`${c.card} border ${c.border} rounded-xl p-5`}>
                  <h3 className={`font-bold mb-2 ${c.text}`}>{t('pr_image_observations')}</h3>
                  <ul className={`text-sm space-y-1 ${c.textSecondary}`}>{results.identification_evidence.current_image_observations.filter((x) => x && x.trim()).map((x, i) => <li key={i}>• {x}</li>)}</ul>
                </div>
              )}

              {results.identification_evidence.distinguishing_visible_features?.filter((x) => x && x.trim()).length > 0 && (
                <div className={`${c.card} border ${c.border} rounded-xl p-5`}>
                  <h3 className={`font-bold mb-2 ${c.text}`}>{t('pr_why_it_fits')}</h3>
                  <ul className={`text-sm space-y-1 ${c.textSecondary}`}>{results.identification_evidence.distinguishing_visible_features.filter((x) => x && x.trim()).map((x, i) => <li key={i}>• {x}</li>)}</ul>
                </div>
              )}

              {results.identification_evidence.plausible_alternatives?.length > 0 && (
                <div className={`${c.card} border ${c.border} rounded-xl p-5`}>
                  <h3 className={`font-bold mb-2 ${c.text}`}>{t('pr_could_also_be')}</h3>
                  {results.identification_evidence.plausible_alternatives.map((a, i) => (
                    <div key={i} className={`p-3 rounded-lg mb-2 ${isDark ? 'bg-zinc-700' : 'bg-amber-50'}`}>
                      <p className={`font-semibold ${c.text}`}>{a.name}</p>
                      {a.why_possible && <p className={`text-sm ${c.textSecondary}`}>{a.why_possible}</p>}
                      {a.how_to_distinguish && <p className={`text-xs ${c.textMuted}`}>🔎 {a.how_to_distinguish}</p>}
                    </div>
                  ))}
                </div>
              )}

              {results.identification_evidence.unresolved_identification_questions?.filter((x) => x && x.trim()).length > 0 && (
                <div className={`${c.cardAlt} border ${c.border} rounded-xl p-5`}>
                  <h3 className={`font-bold mb-2 ${c.text}`}>{t('pr_would_confirm')}</h3>
                  <ul className={`text-sm space-y-1 ${c.textSecondary}`}>{results.identification_evidence.unresolved_identification_questions.filter((x) => x && x.trim()).map((x, i) => <li key={i}>• {x}</li>)}</ul>
                </div>
              )}

              {results.safety_note?.show && (
                <div className={`${c.warning} border-s-4 rounded-e-lg p-5`}>
                  <h3 className="font-bold mb-2">⚠️ {t('pr_safety')}</h3>
                  <p className="text-sm">{results.safety_note.guidance}</p>
                </div>
              )}

              <div className="flex justify-center">
                <button onClick={handleShowCareFromIdentify} className={`${c.btnPrimary} px-4 py-2 rounded-lg text-sm font-semibold`}>{t('pr_show_care')} →</button>
              </div>
            </>
          )}

          {/* Follow-up */}
          <div className={`${c.card} border ${c.border} rounded-xl p-5`}>
            <h3 className={`font-bold mb-2 ${c.text}`}>{t('pr_followup')}</h3>
            <label htmlFor="pr-followup-q" className="sr-only">{t('pr_ask_followup_label')}</label>
            <div className="flex gap-2">
              <input id="pr-followup-q" type="text" value={followUpQuestion} onChange={e => setFollowUpQuestion(e.target.value)}
                onKeyDown={e => e.key === 'Enter' && handleFollowUp()}
                placeholder={t('pr_ask_anything_ph')}
                className={`flex-1 p-3 border rounded-lg ${c.input} outline-none focus:ring-2`} />
              <button onClick={handleFollowUp} disabled={followUpLoading || !followUpQuestion.trim()}
                className={`${c.btnPrimary} px-4 py-2 rounded disabled:opacity-40`}>
                {followUpLoading ? <span className="inline-block animate-spin">{tool?.icon ?? '🪴'}</span> : '❓'}
              </button>
            </div>
            {followUpAnswer && (
              <div className={`mt-3 p-4 rounded-lg ${c.cardAlt} border ${c.border}`}>
                <p className={`text-sm ${c.textSecondary} whitespace-pre-wrap`}>{followUpAnswer}</p>
              </div>
            )}
          </div>

          {/* Post-result cross-refs */}
          <div className={`${c.cardAlt} border ${c.border} rounded-xl p-4`}>
            <p className={`text-xs font-bold ${c.textMuted} uppercase tracking-wide mb-3`}>{t('pr_related')}</p>
            <div className="flex flex-wrap gap-3">
              <a href="/BikeMedic" className={`text-xs ${linkStyle}`}>🚲 {t('pr_xref_bikemedic')}</a>
              <a href="/DoctorVisitTranslator" className={`text-xs ${linkStyle}`}>🏥 {t('pr_xref_doctor')}</a>
            </div>
          </div>
        </div>
      )}
    </div>
  );
};

PlantRescue.displayName = 'PlantRescue';
export default PlantRescue;
