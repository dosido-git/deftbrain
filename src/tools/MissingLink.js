import React, { useState, useRef, useCallback, useEffect } from 'react';
import Caret from '../components/Caret';
import { useClaudeAPI } from '../hooks/useClaudeAPI';
import { useTheme } from '../hooks/useTheme';
import { usePersistentState } from '../hooks/usePersistentState';
import { useRegisterActions } from '../components/ActionBarContext';
import {} from '../components/ActionButtons'; // PrintBtn/ShareBtn available via ActionBar in wrapper
import { useTranslation } from '../i18n/useTranslation';
import { pickExample } from '../utils/exampleRotation';
import { revealSection } from '../utils/revealSection';
import { schemeStyle } from '../data/toolSchemes';
import { SCHEME_C, FORM_PANEL, AnswerCard, ToolTopRow } from '../components/CategoryStyle';

const BRAND = '\n\n— Generated by DeftBrain · deftbrain.com';

// ════════════════════════════════════════════════════════════
// MAIN
// ════════════════════════════════════════════════════════════
const MissingLink = ({ tool }) => {
  const { callToolEndpoint, callToolEndpointProgressive, cancelProgressive, loading, userLocale, userCurrency, userRegion } = useClaudeAPI();
  const { isDark } = useTheme();
  const { t } = useTranslation();

  const LEVELS = [
    { value: 'high_school', label: t('tg_lvl_hs') },
    { value: 'undergrad', label: t('tg_lvl_undergrad') },
    { value: 'grad', label: t('tg_lvl_grad') },
    { value: 'self_taught', label: t('tg_lvl_self') },
  ];

  const EXAMPLES = [
    { concept: t('tg_ex1'), subject: 'Calculus', level: 'undergrad' },
    { concept: t('tg_ex2'), subject: 'Computer Science', level: 'undergrad' },
    { concept: t('tg_ex3'), subject: 'Economics', level: 'high_school' },
    { concept: t('tg_ex4'), subject: 'Biology', level: 'undergrad' },
    { concept: t('tg_ex5'), subject: 'Statistics', level: 'undergrad' },
  ];

  const c = {
    card:          isDark ? 'bg-zinc-800' : 'bg-white',
    cardAlt:       isDark ? 'bg-zinc-700/50' : 'bg-slate-50',
    input:         isDark ? 'bg-zinc-900 border-zinc-600 text-zinc-100 placeholder-zinc-400 focus:border-[#7fb3e0] focus:ring-[#7fb3e0]/20' : 'bg-white border-gray-300 text-gray-900 placeholder-gray-400 focus:border-[#142a43] focus:ring-[#142a43]/15',
    text:          isDark ? 'text-zinc-50' : 'text-gray-900',
    textSecondary: isDark ? 'text-zinc-300' : 'text-gray-600',
    textMuted:     isDark ? 'text-zinc-400' : 'text-gray-500',
    labelText:     isDark ? 'text-zinc-200' : 'text-gray-700',
    btnPrimary:    isDark ? 'bg-[#2f6fb0] hover:bg-[#3a7cc0] text-white' : 'bg-[#142a43] hover:bg-[#234568] text-white',
    btnSecondary:  isDark ? 'bg-zinc-700 hover:bg-zinc-600 text-zinc-200'
                          : 'bg-gray-100 hover:bg-gray-200 text-gray-700',
    // Waiting for input: an outline, not a smudge. Empty fill keeps "filled"
    // meaning "ready"; the border and label carry the visibility. Important
    // modifiers because tools carry their own border/text utilities on the
    // submit and Tailwind resolves conflicts by stylesheet order, not class
    // order. See the PF-13 exception in audit/audit_v2-3-2.py.
    btnIdle:       isDark ? '!bg-transparent !border-2 !border-[#7fb3e0]/85 !text-[#a9cdef] cursor-not-allowed' : '!bg-transparent !border-2 !border-[#142a43]/80 !text-[#142a43] cursor-not-allowed',
    border:        isDark ? 'border-zinc-700' : 'border-gray-200',
    success:       isDark ? 'bg-emerald-900/20 border-emerald-700 text-emerald-200'
                          : 'bg-emerald-50 border-emerald-300 text-emerald-800',
    warning:       isDark ? 'bg-amber-900/20 border-amber-700 text-amber-200'
                          : 'bg-amber-50 border-amber-300 text-amber-800',
    danger:        isDark ? 'bg-red-900/20 border-red-700 text-red-200'
                          : 'bg-red-50 border-red-200 text-red-800',
    infoBox:       isDark ? 'bg-sky-900/20 border-sky-700' : 'bg-sky-50 border-sky-200',
    successBox:    isDark ? 'bg-emerald-900/20 border-emerald-700' : 'bg-emerald-50 border-emerald-300',
    successTxt:    isDark ? 'text-emerald-300' : 'text-emerald-800',
    warningBox:    isDark ? 'bg-amber-900/20 border-amber-700' : 'bg-amber-50 border-amber-300',
    warningTxt:    isDark ? 'text-amber-300' : 'text-amber-800',
    pillActive:    isDark ? 'border-[#7fb3e0] bg-[#1f2530] text-zinc-100' : 'border-[#142a43] bg-[#eef3f8] text-[#142a43]',
    pillInactive:  isDark ? 'border-zinc-600 text-zinc-400 hover:border-zinc-500'
                          : 'border-gray-300 text-gray-500 hover:border-gray-400',
    required:      isDark ? 'text-amber-400' : 'text-amber-700',
    // Tool-specific extras
    tipBg:         isDark ? 'bg-amber-900/20 border-amber-700' : 'bg-amber-50 border-amber-300',
    tipText:       isDark ? 'text-amber-300' : 'text-amber-800',
    histBg:        isDark ? 'bg-sky-900/20 border-sky-700/30' : 'bg-sky-50 border-sky-200',
    gapHigh:       isDark ? 'bg-red-900/20 border-red-700/50' : 'bg-red-50 border-red-300',
  };
  // Category colours (audit/CONVENTIONS.md "Category-colour pages"). Gap
  // likelihood reads contrast (high) / dark (medium) / medium shade (low)
  // instead of red / amber / green.
  const sv = schemeStyle(tool, isDark);
  if (sv) Object.assign(c, SCHEME_C, {
    infoBox:     'bg-[var(--sc-envelope)] border-[var(--sc-line)]',
    successBox:  'bg-[var(--sc-card)] border-[var(--sc-border,var(--sc-accent))]',
    successTxt:  'text-[var(--sc-strong)]',
    warningBox:  'bg-[var(--sc-card)] border-[var(--sc-x-line)]',
    warningTxt:  'text-[var(--sc-x-text)]',
    tipBg:       'bg-[var(--sc-envelope)] border-[var(--sc-line)]',
    tipText:     'text-[var(--sc-strong)]',
    histBg:      'bg-[var(--sc-envelope)] border-[var(--sc-line)]',
    gapHigh:     'bg-[var(--sc-card)] border-[var(--sc-x-line)]',
  });
  c.textMuteded = c.textMuted;
  c.label = c.labelText;

  const linkStyle = sv ? 'text-[var(--sc-accent)] hover:text-[var(--sc-strong)] underline underline-offset-2' : isDark ? 'text-[#7fb3e0] hover:text-[#a9cdef] underline underline-offset-2' : 'text-[#142a43] hover:text-[#142a43] underline underline-offset-2';

  // useState — all together first
  const [showHistory, setShowHistory] = useState(false);
  const [subject, setSubject] = useState('');
  const [showSubject, setShowSubject] = useState(false);
  const [whatIKnow, setWhatIKnow] = useState('');
  const [whereItBroke, setWhereItBroke] = useState('');
  const [level, setLevel] = useState('undergrad');
  const [digResults, setDigResults] = useState(null);
  const [showDeeper, setShowDeeper] = useState(false);
  const [digFocus, setDigFocus] = useState(null);
  const [digTarget, setDigTarget] = useState(null);
  const [error, setError] = useState('');
  // Which check answers are open, and the prerequisite list (owner's review,
  // 2026-10-27: the answer leads with the check; the list is optional detail).
  const [openAnswers, setOpenAnswers] = useState({});
  const [showChain, setShowChain] = useState(false);

  // useRef
  const resultsRef = useRef(null);
  const visualRef = useRef(null);
  const exampleRef = useRef(null);

  // usePersistentState — all together after useRef
  const [sessionHistory, setSessionHistory] = usePersistentState('the-gap-history', []);
  const [concept, setConcept] = usePersistentState('the-gap-concept', '');
  const [results, setResults] = usePersistentState('the-gap-results', null);

  // Once per answer, not on every progressive draft.
  const hasResults = Boolean(results);
  useEffect(() => {
    if (!hasResults) return;
    const timer = setTimeout(() => {
      revealSection(resultsRef.current);
    }, 200);
    return () => clearTimeout(timer);
  }, [hasResults]);

  useEffect(() => {
    const handler = (e) => {
      if (e.key !== 'Enter' || !(e.metaKey || e.ctrlKey)) return;
      const tag = document.activeElement?.tagName;
      if (tag === 'SELECT') return;
      if (!loading && concept.trim()) trace();
    };
    document.addEventListener('keydown', handler);
    return () => document.removeEventListener('keydown', handler);
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [loading, concept]);

  const trace = useCallback(async () => {
    if (!concept.trim()) { setError(t('tg_err_no_concept')); return; }
    setError(''); setResults(null); setDigResults(null); setDigTarget(null); setOpenAnswers({}); setShowChain(false);
    cancelProgressive();
    try {
      // Progressive (2026-10-18): the diagnosis shows first.
      const data = await callToolEndpointProgressive('the-gap', {
        concept: concept.trim(), subject: subject.trim() || null,
        whatIKnow: whatIKnow.trim() || null, whereItBroke: whereItBroke.trim() || null, level,
        userLocale, userCurrency, userRegion,
      }, { onDraft: d => setResults({ ...d, _concept: concept.trim() }) });
      if (!data) return; // replaced by a newer run
      setResults({ ...data, _concept: concept.trim() });
      const entry = { id: 'tg_' + Date.now(), date: new Date().toISOString(), concept: concept.trim(), subject: subject.trim(), likelyGap: data.likely_gap?.concept, preview: concept.trim().slice(0, 40) };
      setSessionHistory(prev => [entry, ...prev].slice(0, 6));
    } catch (err) { setError(err.message || t('tg_err_trace')); }
  }, [concept, subject, whatIKnow, whereItBroke, level, callToolEndpointProgressive, cancelProgressive, setSessionHistory, setResults, userLocale, userCurrency, userRegion, t]);

  // Take them to the part they asked for once it exists.
  useEffect(() => {
    if (!digResults || !digFocus) return;
    const target = digFocus === 'visual' ? visualRef.current : exampleRef.current;
    if (!target) return;
    revealSection(target);
  }, [digResults, digFocus]);

  const dig = useCallback(async (prerequisite, testResult) => {
    setDigTarget(prerequisite); setDigResults(null);
    try {
      const data = await callToolEndpoint('the-gap/dig', {
        originalConcept: concept.trim(), prerequisite, testResult: testResult || 'failed',
        userLocale, userCurrency, userRegion,
      });
      setDigResults(data);
    } catch (err) { setError(err.message || t('tg_err_dig')); }
  }, [concept, callToolEndpoint, userLocale, userCurrency, userRegion, t]);

  const handleReset = useCallback(() => {
    setConcept(''); setSubject(''); setWhatIKnow(''); setWhereItBroke('');
    setResults(null); setDigResults(null); setDigTarget(null); setError(''); setOpenAnswers({}); setShowChain(false);
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [setResults]);

  const loadExample = useCallback(() => {
    const ex = pickExample('MissingLink', EXAMPLES);
    setConcept(ex.concept); setSubject(''); setShowSubject(false); setLevel(ex.level);
    setResults(null); setDigResults(null); setError('');
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [setResults]);



  const buildCopy = useCallback(() => {
    if (!results) return '';
    const lines = [t('tg_copy_title'), '', `${t('tg_copy_struggling')} ${concept}`, ''];
    const gap = results?.likely_gap;
    if (gap) {
      lines.push(`${t(results?.basis === 'described' ? 'tg_most_likely' : 'tg_check_first')}: ${gap.concept}`);
      if (gap.why_check_this || gap.why_this_one) lines.push(gap.why_check_this || gap.why_this_one);
    }
    const check = results?.check;
    if (check?.example) {
      lines.push('', t('tg_check_title'), check.example, '');
      (check.questions || []).forEach((q, i) => lines.push(`${i + 1}. ${q.question}`, `   → ${q.answer}`));
    }
    const lesson = gap?.refresher;
    if (lesson) {
      lines.push('', t('tg_the_idea'), lesson.core_idea || '');
      const practice = lesson.practice;
      if (practice) lines.push('', typeof practice === 'string' ? practice : `${practice.task}\n${t('tg_how_to_check')} ${practice.how_to_check || ''}`);
    }
    lines.push('', BRAND);
    return lines.join('\n');
  }, [results, concept, t]);

  // Register export content with the wrapper's persistent ActionBar
  useRegisterActions(buildCopy(), tool?.title || 'Missing Link');

  const Pill = ({ active, onClick, children }) => (
    <button onClick={onClick} aria-pressed={active} className={'px-3 py-1.5 rounded-lg border text-[13px] font-semibold transition-all ' + (active ? c.pillActive : c.pillInactive)}>
      {active && <span className="me-1">✓</span>}{children}
    </button>
  );

  // ══════════════════════════════════════════
  // INPUT
  // ══════════════════════════════════════════
  // The title row, shared by both phases. It used to live only inside
  // renderInput, which unmounts the moment a result exists — so with the
  // output on screen there was no way to start over at all.
  // Site style (2026-09-27): a pale band of the tool's color bleeding to the
  // card edges, the ground the "Try an example" pill was made for (PF-17c).
  // With a category scheme the wrapper carries the tagline; the tool keeps one
  // row: Try an example and the reset (PF-16: the one reset).
  const renderHeaderRow = () => {
    const resetBtn = (hasInput) ? (
      <button onClick={handleReset} className={`${c.btnSecondary} px-3 py-1.5 rounded-lg ${sv ? 'text-sm' : 'text-xs'} font-semibold flex-shrink-0 whitespace-nowrap`}>
        {t('tg_start_over')}
      </button>
    ) : null;
    return sv ? <ToolTopRow onExample={loadExample} loading={loading}>{resetBtn}</ToolTopRow> : (
    <div
      data-print-hide
      className="-mx-4 -mt-4 sm:-mx-6 sm:-mt-6 lg:-mx-8 lg:-mt-8 px-4 sm:px-6 lg:px-8 pt-4 sm:pt-6 lg:pt-8 pb-5"
      style={/^#[0-9a-f]{6}$/i.test(tool?.headerColor || '') ? { background: `${tool.headerColor}${isDark ? '26' : '66'}` } : undefined}
    >
      <div className="flex items-start justify-between gap-3">
        <div>
          {/* PF-30 — the wrapper already prints the name as the page <h1>. */}
          <p className={`text-[17px] leading-snug ${c.textSecondary}`}>
            <span className="me-2 text-xl">{tool?.icon ?? '⛓️'}</span>{tool?.tagline ?? t('tg_tagline')}
          </p>
          {!results && (
            <button onClick={loadExample} disabled={loading} style={{ backgroundColor: (tool?.headerColor ?? '#888888') + '80' }} className="mt-2 px-4 py-2 rounded-full text-sm font-semibold border border-black/25 text-zinc-900 shadow-sm hover:brightness-105 hover:shadow transition disabled:opacity-40 whitespace-nowrap">✨ {t('try_example')}</button>
          )}
        </div>
        {/* PF-16: the tool's one reset, on the title row, from the first keystroke. */}
        {resetBtn}
      </div>
    </div>
  );
  };

  const renderInput = () => (
    <div data-print-form className={`space-y-4 ${sv ? FORM_PANEL : ''}`}>
      {renderHeaderRow()}

      <div>
        <label className={'text-base font-bold ' + c.text + ' mb-1 block'}>{t('tg_concept_label')} <span className={c.required}>*</span></label>
        <p className={'text-[13px] ' + c.textMuted + ' mb-3'}>{t('tg_concept_help')}</p>
        <input type="text" value={concept} onChange={e => setConcept(e.target.value)}
          placeholder={t('tg_concept_ph')}
          className={'w-full px-4 py-3 border-2 rounded-xl ' + c.input + ' outline-none focus:ring-2 text-sm'}
          onKeyDown={e => { if (e.key === 'Enter' && concept.trim()) trace(); }} />
      </div>

      <p className={'text-[13px] leading-relaxed ' + c.textSecondary}>{t('tg_reassure')}</p>

      <div className="grid grid-cols-2 gap-3">
        <div>
          <label className={'text-[15px] font-semibold ' + c.text + ' mb-1 block'}>{t('tg_subject_auto')}</label>
          {showSubject ? (
            <input type="text" value={subject} onChange={e => setSubject(e.target.value)}
              placeholder={t('tg_subject_ph')}
              className={'w-full px-3 py-2 rounded-xl border text-sm ' + c.input + ' outline-none'} />
          ) : (
            <button onClick={() => setShowSubject(true)} className={'text-xs font-semibold ' + linkStyle}>
              {t('tg_subject_set')}
            </button>
          )}
        </div>
        <div>
          <label className={'text-[15px] font-semibold ' + c.text + ' mb-2 block'}>{t('tg_level_label')}</label>
          <div className="flex flex-wrap gap-1">
            {LEVELS.map(l => <Pill key={l.value} active={level === l.value} onClick={() => setLevel(l.value)}>{l.label}</Pill>)}
          </div>
        </div>
      </div>
      <div>
        <label className={'text-[15px] font-semibold ' + c.text + ' mb-1 block'}>{t('tg_know_label')}</label>
        <input type="text" value={whatIKnow} onChange={e => setWhatIKnow(e.target.value)}
          placeholder={t('tg_know_ph')}
          className={'w-full px-3 py-2 rounded-xl border text-sm ' + c.input + ' outline-none'} />
      </div>
      <div>
        <label className={'text-[15px] font-semibold ' + c.text + ' mb-1 block'}>{t('tg_broke_label')}</label>
        <input type="text" value={whereItBroke} onChange={e => setWhereItBroke(e.target.value)}
          placeholder={t('tg_broke_ph')}
          className={'w-full px-3 py-2 rounded-xl border text-sm ' + c.input + ' outline-none'} />
      </div>


      <button title={t('cmd_enter')} onClick={trace} disabled={loading || !concept.trim()}
        className={'relative w-full py-4 rounded-2xl text-sm font-bold flex items-center justify-center gap-2 transition-all ' + (!concept.trim() ? c.btnIdle : c.btnPrimary)}>
        {loading ? <><span className="relative inline-block animate-spin text-xl">{tool?.icon ?? '⛓️'}</span> {t('tg_tracing')}</> : <><span className="me-1 text-xl">{tool?.icon ?? '⛓️'}</span> {t('tg_find_gap')}</>}
      {!loading && (
        <kbd aria-hidden="true"
          className="hidden sm:flex items-center absolute end-3 top-1/2 -translate-y-1/2 px-1.5 py-0.5 rounded border border-white/30 bg-white/15 text-[10px] font-bold tracking-wide">
          ⌘↵
        </kbd>
      )}
      </button>
      <p className={'text-xs text-center ' + c.textMuted}>{t('tg_ai_disclaimer')}</p>
      <p data-print-hide className={'text-[13px] ' + c.textMuted}>
        {t('tg_braindump_q')} <a href="/HeartOfTheMatter" className={linkStyle}>🎯 {t('tg_braindump_link')}</a> {t('tg_braindump_rest')}
      </p>
    </div>
  );

  // ══════════════════════════════════════════
  // RESULTS
  // ══════════════════════════════════════════
  const renderResults = () => {
    if (!results) return null;
    const chain = results?.prerequisite_chain || [];
    const gap = results?.likely_gap;
    const check = results?.check;
    const lesson = gap?.refresher;
    const practice = lesson?.practice;
    const described = results?.basis === 'described';
    const head = sv ? 'text-base font-bold text-[var(--sc-strong)]' : 'text-xs font-bold uppercase ' + c.textMuted;

    // Owner's review, 2026-10-27: a place to check (tentative unless they
    // described how they are stuck), one concrete check with a supplied
    // example, a short explanation, one practice task, then the optional
    // prerequisite list.
    const answer = (
      <div data-copy-results ref={resultsRef} className="scroll-mt-24 space-y-5 mt-4">
        {gap && (
          <div data-keybox="" className={'p-5 rounded-2xl border-2 ' + (sv ? 'bg-[var(--sc-card)] border-[var(--sc-border,var(--sc-accent))]' : c.gapHigh)}>
            <p className={'text-[13px] font-bold mb-1 ' + (sv ? 'text-[var(--sc-strong)]' : c.textMuted)}>🎯 {t(described ? 'tg_most_likely' : 'tg_check_first')}</p>
            <p className={'text-lg font-bold ' + c.text}>{gap.concept}</p>
            {(gap.why_check_this || gap.why_this_one) && <p className={'text-sm mt-1 ' + c.textSecondary}>{gap.why_check_this || gap.why_this_one}</p>}
            <p className={'text-[13px] mt-2 ' + c.textMuted}>{t(described ? 'tg_basis_described' : 'tg_basis_topic')}</p>
          </div>
        )}

        {check?.example && (
          <div>
            <p className={head + ' mb-1'}>{t('tg_check_title')}</p>
            <p className={'text-[13px] mb-2 ' + c.textMuted}>{t('tg_check_intro')}</p>
            <pre className={'text-[13px] leading-relaxed font-mono whitespace-pre-wrap break-words rounded-lg border p-3 ' + c.cardAlt + ' ' + c.border}>{check.example}</pre>
            <ol className="mt-3 space-y-3">
              {(check.questions || []).map((q, i) => (
                <li key={i} className="keep-together">
                  <p className={'text-sm font-semibold ' + c.text}>{i + 1}. {q.question}</p>
                  <button data-print-hide aria-expanded={!!openAnswers[i]} onClick={() => setOpenAnswers(p => ({ ...p, [i]: !p[i] }))}
                    className={'mt-1 text-xs font-bold flex items-center gap-1 ' + linkStyle}>
                    {t('tg_show_answer')} <Caret open={!!openAnswers[i]} />
                  </button>
                  {/* Printed open: the sheet carries its own answer key. */}
                  <div data-sec-body hidden={!openAnswers[i]} className={'mt-1 text-sm ' + c.textSecondary}>
                    <p>{q.answer}</p>
                    {q.if_missed && <p className={'text-[13px] mt-1 ' + c.textMuted}><span className="font-semibold">{t('tg_if_missed')}</span> {q.if_missed}</p>}
                  </div>
                </li>
              ))}
            </ol>
          </div>
        )}

        {lesson && (
          <div className="space-y-3">
            <p className={head}>{t('tg_the_idea')}</p>
            {lesson.core_idea && <p className={'text-sm leading-relaxed ' + c.text}>{lesson.core_idea}</p>}
            {lesson.common_confusion && (
              <p className={'text-[13px] ' + c.textSecondary}><span className="font-semibold">{t('tg_common_confusion')}</span> {lesson.common_confusion}</p>
            )}
          </div>
        )}

        {practice && (
          <div className="keep-together">
            <p className={head + ' mb-1'}>{t('tg_practice')}</p>
            {typeof practice === 'string'
              ? <p className={'text-sm ' + c.text}>{practice}</p>
              : <>
                  <p className={'text-sm ' + c.text}>{practice.task}</p>
                  {practice.how_to_check && <p className={'text-[13px] mt-1 ' + c.textSecondary}><span className="font-semibold">{t('tg_how_to_check')}</span> {practice.how_to_check}</p>}
                </>}
          </div>
        )}

        {results?.encouragement && (
          <p className={'keep-together text-sm ' + c.textSecondary}>{results.encouragement}</p>
        )}

        {gap && (
          <div data-print-hide>
            <button onClick={() => setShowDeeper(v => !v)} aria-expanded={showDeeper}
              className={'flex items-center gap-1.5 text-xs font-bold ' + linkStyle}>
              {t('tg_still_stuck')} <Caret open={showDeeper} />
            </button>
            {showDeeper && (
              <div className="mt-2 flex flex-col gap-1.5">
                <button onClick={() => { setDigFocus('visual'); dig(gap.concept, 'failed'); }}
                  className={'w-full py-2.5 rounded-xl text-xs font-bold text-start px-3 border ' + c.cardAlt}>
                  {t('tg_stuck_visual')}
                </button>
                <button onClick={() => { setDigFocus('example'); dig(gap.concept, 'failed'); }}
                  className={'w-full py-2.5 rounded-xl text-xs font-bold text-start px-3 border ' + c.cardAlt}>
                  {t('tg_stuck_example')}
                </button>
                <a href="/AnalogyEngine"
                  className={'w-full py-2.5 rounded-xl text-xs font-bold text-start px-3 border block ' + c.cardAlt}>
                  {t('tg_stuck_analogy')}
                </a>
                <button onClick={() => dig(gap.concept, 'failed')}
                  className={'w-full mt-1 py-3 rounded-xl text-xs font-bold flex items-center justify-center gap-1.5 ' + c.btnPrimary}>
                  <span>⛓️</span> {t('tg_deep_dive_btn')}
                </button>
              </div>
            )}
          </div>
        )}

        {/* The prerequisite list: optional detail, in the order worth checking. */}
        {chain.length > 0 && (
          <div className={'border-t ' + c.border}>
            <button data-print-heading aria-expanded={showChain} onClick={() => setShowChain(v => !v)}
              className="w-full py-4 flex items-center justify-between text-start min-h-[44px]">
              <span className={head}>{t('tg_other_checks')}</span>
              <span data-print-hide className={sv ? 'text-[var(--sc-accent)]' : ''}><Caret open={showChain} /></span>
            </button>
            <div data-sec-body hidden={!showChain} className="pb-4 space-y-3">
              {chain.map((node, idx) => (
                <div key={idx} className={'keep-together p-4 rounded-xl border ' + c.border}>
                  <p className={'text-sm font-bold ' + c.text}>{idx + 1}. {node.concept}</p>
                  <p className={'text-xs mt-0.5 ' + c.textSecondary}>{node.why_needed}</p>
                  {node.quick_test && (
                    <p className={'text-[13px] mt-2 ' + c.text}><span className="font-semibold">{t('tg_quick_test')}</span> {node.quick_test}</p>
                  )}
                  <div data-print-hide className="flex gap-1.5 mt-3">
                    <button onClick={() => dig(node.concept, 'failed')}
                      className={'flex-1 py-2 rounded-lg text-xs font-bold border ' + c.pillInactive}>
                      {t('tg_cant_answer')}
                    </button>
                    <button onClick={() => dig(node.concept, 'unsure')}
                      className={'flex-1 py-2 rounded-lg text-xs font-bold border ' + c.pillInactive}>
                      {t('tg_unsure')}
                    </button>
                    <button onClick={() => dig(node.concept, 'passed')}
                      className={'flex-1 py-2 rounded-lg text-xs font-bold border ' + c.pillInactive}>
                      {t('tg_got_it')}
                    </button>
                  </div>
                </div>
              ))}
            </div>
          </div>
        )}

        {/* Dig results */}
        {digResults && renderDig()}
      </div>
    );
    return sv ? <AnswerCard title={t('your_answer')} className="mt-4">{answer}</AnswerCard> : answer;
  };

  // ══════════════════════════════════════════
  // DIG RESULTS
  // ══════════════════════════════════════════
  const renderDig = () => {
    if (!digResults?.refresher) return null;
    const r = digResults.refresher;
    return (
      <div className={'p-5 rounded-2xl border-2 ' + c.infoBox}>
        <div className="flex items-center gap-2 mb-3">
          <span className="text-lg">⛓️</span>
          <p className={'text-base font-bold ' + c.text}>{t('tg_dig_title')} {digResults.concept || digTarget}</p>
        </div>

        {r.in_plain_english && (
          <div className={'p-4 rounded-xl ' + c.card + ' border mb-3'}>
            <p className={'text-xs font-bold ' + c.textMuted + ' uppercase mb-1'}>{t('tg_plain_english')}</p>
            <p className={'text-sm ' + c.text}>{r.in_plain_english}</p>
          </div>
        )}

        {r.key_insight && (
          <div className={'p-3 rounded-lg ' + c.tipBg + ' mb-3'}>
            <p className={'text-xs font-bold ' + c.tipText + ' mb-1'}>{t('tg_key_insight')}</p>
            <p className={'text-sm ' + c.tipText}>{r.key_insight}</p>
          </div>
        )}

        {r.visual_or_analogy && (
          <div ref={visualRef} className={'p-3 rounded-lg mb-3 scroll-mt-24 ' + (digFocus === 'visual' ? c.tipBg + ' border-2' : c.cardAlt)}>
            <p className={'text-xs font-bold ' + c.textMuted + ' mb-1'}>{t('tg_analogy')}</p>
            <p className={'text-xs ' + c.text}>{r.visual_or_analogy}</p>
          </div>
        )}

        {r.formal_definition && (
          <div className={'p-3 rounded-lg ' + c.cardAlt + ' mb-3'}>
            <p className={'text-xs font-bold ' + c.textMuted + ' mb-1'}>{t('tg_formal_def')}</p>
            <p className={'text-xs ' + c.text + ' font-mono'}>{r.formal_definition}</p>
          </div>
        )}

        {r.worked_example && (
          <div ref={exampleRef} className={'rounded-xl p-4 mb-3 scroll-mt-24 ' + (digFocus === 'example' ? c.tipBg + ' border-2' : c.card + ' border')}>
            <p className={'text-xs font-bold ' + c.textMuted + ' uppercase mb-1'}>{t('tg_worked_example')}</p>
            <p className={'text-sm ' + c.text + ' whitespace-pre-wrap'}>{r.worked_example}</p>
          </div>
        )}

        {r.practice_problems?.length > 0 && (
          <div className="space-y-2 mb-3">
            <p className={'text-xs font-bold ' + c.textMuted + ' uppercase'}>{t('tg_dig_practice')}</p>
            {r.practice_problems.map((pp, i) => (
              <div key={i} className={c.card + ' border rounded-xl p-3'}>
                <p className={'text-xs font-semibold ' + c.text + ' mb-1'}>{t('tg_problem')} {i + 1}: {pp.problem}</p>
                <details data-print-hide className="mt-1">
                  <summary className={'text-xs font-bold cursor-pointer ' + linkStyle}>{t('tg_show_hint')}</summary>
                  <div className="mt-2 space-y-1">
                    {pp.hint && <p className={'text-xs ' + c.tipText}>{t('tg_hint')} {pp.hint}</p>}
                    <p className={'text-xs ' + c.successTxt}>✅ {pp.answer}</p>
                  </div>
                </details>
              </div>
            ))}
          </div>
        )}

        {r.common_mistakes?.length > 0 && (
          <div className="space-y-1 mb-3">
            {r.common_mistakes.map((m, i) => (
              <div key={i} className={'p-2 rounded-lg ' + c.warningBox}>
                <p className={'text-xs ' + c.warningTxt}>⚠️ {m}</p>
              </div>
            ))}
          </div>
        )}

        {digResults.connects_forward && (
          <div className={'p-3 rounded-lg ' + c.successBox}>
            <p className={'text-xs font-bold ' + c.successTxt + ' mb-1'}>{t('tg_now_connects')}</p>
            <p className={'text-xs ' + c.successTxt}>{digResults.connects_forward}</p>
          </div>
        )}
      </div>
    );
  };

  // History
  const renderHistory = () => {
    if (sessionHistory.length === 0) return null;
    const formatDate = (iso) => { try { const d = new Date(iso); const diff = Math.floor((new Date() - d) / 86400000); return diff === 0 ? t('tg_today') : diff === 1 ? t('tg_yesterday') : diff < 7 ? t('tg_days_ago', { count: diff }) : d.toLocaleDateString(userLocale || 'en-US', { month: 'short', day: 'numeric' }); } catch { return ''; } };
    return (
      <div data-print-hide className={'mt-6 p-4 rounded-2xl border ' + c.histBg}>
        <button onClick={() => setShowHistory(!showHistory)} className="w-full flex items-center gap-2 text-start">
          <span>📝</span>
          <span className={'text-sm font-bold ' + c.text + ' flex-1'}>{t('tg_past_gaps')}</span>
          <span className={'text-xs ' + c.textMuted}>{sessionHistory.length}</span>
          <Caret open={showHistory} />
        </button>
        {showHistory && (
          <div className="mt-3 space-y-2">
            {sessionHistory.map(entry => (
              <div key={entry.id} className={'rounded-xl border ' + c.card + ' p-3'}>
                <div className={'text-sm font-semibold ' + c.text}>{entry.concept}</div>
                <div className={'text-xs ' + c.textMuted + ' mt-0.5'}>
                  {formatDate(entry.date)}{entry.subject ? ` · ${entry.subject}` : ''}{entry.likelyGap ? ` · ${t('tg_hist_gap')} ${entry.likelyGap}` : ''}
                </div>
              </div>
            ))}
          </div>
        )}
      </div>
    );
  };

  // Any sign the user has begun — drives the PF-16 reset on the title row.
  const hasInput = !!(digResults || results || digTarget || concept.trim() || subject.trim() || whatIKnow.trim() || whereItBroke.trim());

  return (
    <div className={`space-y-4 ${c.text}`}>
      {!results && renderInput()}
      {results ? (
        <div>
          {renderHeaderRow()}
        </div>
      ) : null}
      {results && renderResults()}
      {results && (
        <div data-print-hide className={'p-4 rounded-2xl border ' + c.card}>
          <p className={'text-xs font-bold ' + c.textMuted + ' uppercase tracking-wide mb-2'}>{t('tg_related_tools')}</p>
          <p className={'text-xs ' + c.textSecondary}>{t('tg_related_text')} <a href="/AnalogyEngine" className={linkStyle}>🔀 {t('tg_recall_link')}</a> {t('tg_related_rest')}</p>
        </div>
      )}
      {error && (
        <div className={'mt-4 p-4 ' + c.danger + ' border rounded-xl flex items-start gap-3'}>
          <span className="text-base">⚠️</span>
          <p className="text-sm">{error}</p>
        </div>
      )}
      {renderHistory()}
    </div>
  );
};

MissingLink.displayName = 'MissingLink';
export default MissingLink;
