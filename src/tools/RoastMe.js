import React, { useState, useCallback, useEffect, useRef } from 'react';
import { useClaudeAPI } from '../hooks/useClaudeAPI';
import { useTheme } from '../hooks/useTheme';
import { usePersistentState } from '../hooks/usePersistentState';
import { useRegisterActions } from '../components/ActionBarContext';
import { useTranslation } from '../i18n/useTranslation';
import { currencySymbol } from '../utils/formatLocale';
import { pickExample } from '../utils/exampleRotation';
import { revealSection } from '../utils/revealSection';

const BRAND = '\n\n— Generated by DeftBrain · deftbrain.com';

// ════════════════════════════════════════════════════════════
// COMPONENT
// ════════════════════════════════════════════════════════════
const RoastMe = ({ tool }) => {
  const { callToolEndpoint, loading, userLocale, userCurrency, userRegion } = useClaudeAPI();
  const { isDark } = useTheme();
  const { t } = useTranslation();
  const sym = currencySymbol(userLocale, userCurrency);

  // ── Localized constants (depend on t) ──
  const CONTENT_TYPES = [
    { value: 'auto',     label: t('rm_ct_auto'),     icon: '✨' },
    { value: 'resume',   label: t('rm_ct_resume'),   icon: '📄' },
    { value: 'dating',   label: t('rm_ct_dating'),   icon: '💘' },
    { value: 'linkedin', label: t('rm_ct_linkedin'), icon: '💼' },
    { value: 'email',    label: t('rm_ct_email'),    icon: '📨' },
    { value: 'social',   label: t('rm_ct_social'),   icon: '📱' },
    { value: 'other',    label: t('rm_ct_other'),    icon: '🤷' },
  ];

  const HEAT_LEVELS = [
    { value: 'gentle',   label: t('rm_heat_gentle'),   icon: '😊', desc: t('rm_heat_gentle_desc') },
    { value: 'medium',   label: t('rm_heat_medium'),   icon: '🔥', desc: t('rm_heat_medium_desc') },
    { value: 'scorched', label: t('rm_heat_scorched'), icon: '💀', desc: t('rm_heat_scorched_desc') },
  ];

  // Five, rotated across every content type and heat level.
  const EXAMPLES = [
    { content: t('rm_ex1', { sym }), contentType: 'linkedin', heatLevel: 'medium' },
    { content: t('rm_ex2', { sym }), contentType: 'social',   heatLevel: 'gentle' },
    { content: t('rm_ex3'),          contentType: 'dating',   heatLevel: 'scorched' },
    { content: t('rm_ex4'),          contentType: 'email',    heatLevel: 'medium' },
    { content: t('rm_ex5'),          contentType: 'social',   heatLevel: 'scorched' },
  ];

  // ── Theme — verbatim from CONVENTIONS.md PF-2 ──
  const c = {
    card:          isDark ? 'bg-zinc-800' : 'bg-white',
    cardAlt:       isDark ? 'bg-zinc-700/50' : 'bg-slate-50',
    input:         isDark ? 'bg-zinc-900 border-zinc-600 text-zinc-100 placeholder-zinc-400 focus:border-[#7fb3e0] focus:ring-[#7fb3e0]/20' : 'bg-white border-gray-300 text-gray-900 placeholder-gray-400 focus:border-[#142a43] focus:ring-[#142a43]/15',
    text:          isDark ? 'text-zinc-50' : 'text-gray-900',
    textSecondary: isDark ? 'text-zinc-300' : 'text-gray-600',
    textMuted:     isDark ? 'text-zinc-400' : 'text-gray-500',
    required:      isDark ? 'text-amber-400' : 'text-amber-700',
    labelText:     isDark ? 'text-zinc-200' : 'text-gray-700',
    accentTxt:     isDark ? 'text-[#7fb3e0]' : 'text-[#165b9a]',
    btnPrimary:    isDark ? 'bg-[#2f6fb0] hover:bg-[#3a7cc0] text-white' : 'bg-[#142a43] hover:bg-[#234568] text-white',
    // Waiting for input: an outline, not a smudge. Empty fill keeps "filled"
    // meaning "ready"; the border and label carry the visibility. Important
    // modifiers because tools carry their own border/text utilities on the
    // submit and Tailwind resolves conflicts by stylesheet order, not class
    // order. See the PF-13 exception in audit/audit_v2-3-2.py.
    btnIdle:       isDark ? '!bg-transparent !border-2 !border-[#7fb3e0]/85 !text-[#a9cdef] cursor-not-allowed' : '!bg-transparent !border-2 !border-[#142a43]/80 !text-[#142a43] cursor-not-allowed',
    btnSecondary:  isDark ? 'bg-zinc-700 hover:bg-zinc-600 text-zinc-200'
                          : 'bg-gray-100 hover:bg-gray-200 text-gray-700',
    border:        isDark ? 'border-zinc-700' : 'border-gray-200',
    success:       isDark ? 'bg-emerald-900/20 border-emerald-700 text-emerald-200'
                          : 'bg-emerald-50 border-emerald-300 text-emerald-800',
    warning:       isDark ? 'bg-amber-900/20 border-amber-700 text-amber-200'
                          : 'bg-amber-50 border-amber-300 text-amber-800',
    danger:        isDark ? 'bg-red-900/20 border-red-700 text-red-200'
                          : 'bg-red-50 border-red-200 text-red-800',
    warningBox:    isDark ? 'bg-amber-900/20 border-amber-700' : 'bg-amber-50 border-amber-300',
    pillActive:    isDark ? 'border-[#7fb3e0] bg-[#1f2530] text-zinc-100' : 'border-[#142a43] bg-[#eef3f8] text-[#142a43]',
    pillInactive:  isDark ? 'border-zinc-600 text-zinc-400 hover:border-zinc-500'
                          : 'border-gray-300 text-gray-500 hover:border-gray-400',
    // RoastMe extensions
    heatGentle:    isDark ? 'bg-emerald-900/20 border-emerald-600 text-emerald-200' : 'bg-emerald-50 border-emerald-400 text-emerald-900',
    heatMedium:    isDark ? 'bg-amber-900/20 border-amber-500 text-amber-200'       : 'bg-amber-50 border-amber-400 text-amber-900',
    heatScorched:  isDark ? 'bg-red-900/30 border-red-500 text-red-200'             : 'bg-red-50 border-red-400 text-red-900',
    quoteBg:       isDark ? 'bg-zinc-700/50' : 'bg-slate-50',
    niceBg:        isDark ? 'bg-zinc-700/40 border-zinc-600' : 'bg-slate-50 border-slate-200',
  };
  c.textMuteded   = c.textMuted;
  c.label         = c.labelText;

  const linkStyle = isDark ? 'text-[#7fb3e0] hover:text-[#a9cdef] underline underline-offset-2' : 'text-[#142a43] hover:text-[#142a43] underline underline-offset-2';

  // ── State ──
  const [content, setContent] = useState('');
  const [contentType, setContentType] = useState('auto');
  const [heatLevel, setHeatLevel] = useState('medium');
  const [error, setError] = useState('');

  // ── Refs ──
  const loadExample = () => {
    const ex = pickExample('RoastMe', EXAMPLES);
    setContent(ex.content);
    setContentType(ex.contentType);
    setHeatLevel(ex.heatLevel);
  };

  const resultsRef   = useRef(null);
  const submitRef    = useRef(null);
  const canSubmitRef = useRef(false);

  // ── Persistent state ──
  const [results, setResults] = usePersistentState('roastme-result', null);

  // ── API ──
  const handleReset = () => { setContent(''); setResults(null); setError(''); };

  const runRoast = useCallback(async () => {
    if (!content.trim()) return;
    setError('');
    setResults(null);
    try {
      const data = await callToolEndpoint('roast-me', {
        content: content.trim(),
        contentType,
        heatLevel,
        userLocale,
        userCurrency,
        userRegion,
      });
      setResults(data);
    } catch (err) {
      setError(err.message || t('rm_error'));
    }
  }, [content, contentType, heatLevel, callToolEndpoint, setResults, userLocale, userCurrency, userRegion, t]);

  // ── buildFullText ──
  const buildFullText = useCallback(() => {
    if (!results) return '';
    const lines = [`🔥 ${t('rm_copy_header')} ${results?.content_type_detected || t('rm_copy_unknown')}`, ''];
    if (results?.first_impression) lines.push(`💀 ${results?.first_impression}`, '');
    if (results?.roasts?.length) {
      results?.roasts?.forEach((r, i) => lines.push(`${i + 1}. ${r.line}`));
      lines.push('');
    }
    if (results?.summary_roast) lines.push(`🎤 ${results?.summary_roast}`, '');
    if (results?.one_nice_thing) lines.push(`😇 ${t('rm_copy_nice')} ${results?.one_nice_thing}`);
    return lines.join('\n').trim() + BRAND;
  }, [results, t]);

  // Live ref assignments
  submitRef.current    = runRoast;
  canSubmitRef.current = !!content.trim();

  useRegisterActions(buildFullText(), tool?.title || 'Roast Me');

  // Scroll to results
  useEffect(() => {
    if (!results) return;
    const timer = setTimeout(() => revealSection(resultsRef.current), 100);
    return () => clearTimeout(timer);
  }, [results]);

  // Keyboard shortcut
  useEffect(() => {
    const handler = (e) => {
      const tag = document.activeElement?.tagName;
      if (tag === 'SELECT') return;
      if (e.key === 'Enter' && (e.metaKey || e.ctrlKey) && !loading && canSubmitRef.current)
        submitRef.current?.();
    };
    document.addEventListener('keydown', handler);
    return () => document.removeEventListener('keydown', handler);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [loading]);

  const heatColor = heatLevel === 'gentle' ? c.heatGentle
    : heatLevel === 'scorched' ? c.heatScorched
    : c.heatMedium;

  // ════════════════════════════════════════════════════════════
  // RENDER
  // ════════════════════════════════════════════════════════════
  return (
    <div className={`space-y-4 ${c.text}`}>

      {/* ── Input ── site style (2026-09-27): no card; prints only as a blank
          form (with a result, the result prints). */}
      <div className="space-y-5" data-print-form {...(results ? { 'data-print-hide': '' } : {})}>

        {/* Header — PF-30: no in-card title (the page's <h1> names the tool);
            the icon rides the tagline. A pale band of the tool's color bleeding
            to the card edges, the ground the "Try an example" pill was made
            for (PF-17c). Screen only. */}
        <div
          data-print-hide
          className="-mx-4 -mt-4 sm:-mx-6 sm:-mt-6 lg:-mx-8 lg:-mt-8 px-4 sm:px-6 lg:px-8 pt-4 sm:pt-6 lg:pt-8 pb-5 flex items-start justify-between gap-3"
          style={/^#[0-9a-f]{6}$/i.test(tool?.headerColor || '') ? { background: `${tool.headerColor}${isDark ? '26' : '66'}` } : undefined}
        >
          <div className="flex-1 min-w-0">
            <p className={`text-[17px] leading-snug ${c.textSecondary}`}><span className="me-2 text-xl">{tool?.icon ?? '🔥'}</span>{t('rm_tagline')}</p>
            <button onClick={loadExample} disabled={loading} style={{ backgroundColor: (tool?.headerColor ?? '#888888') + '80' }} className="mt-2 px-4 py-2 rounded-full text-sm font-semibold border border-black/25 text-zinc-900 shadow-sm hover:brightness-105 hover:shadow transition disabled:opacity-40 whitespace-nowrap">✨ {t('try_example')}</button>
          </div>
          {(results || content.trim()) ? (
            <button onClick={handleReset} className={`shrink-0 px-3 py-2 rounded-lg text-sm font-bold min-h-[40px] ${c.btnSecondary}`}>↺ {t('start_over')}</button>
          ) : null}
        </div>

        {/* Content type */}
        <div>
          <div className={`mb-4 rounded-xl border ${c.border} ${c.cardAlt || ''} p-3`}>
            <p className={`text-[13px] font-bold ${c.textMuted} mb-1.5`}>{t('rm_every_roast')}</p>
            <ul className={`text-[13px] ${c.textSecondary} space-y-0.5`}>
              <li>🔥 {t('rm_inc_jokes')}</li>
              <li>❤️ {t('rm_inc_nice')}</li>
              <li>📸 {t('rm_inc_share')}</li>
            </ul>
          </div>

          <label className={`text-[15px] font-semibold ${c.labelText} block mb-2`}>{t('rm_what_is_this')}</label>
          <div className="flex flex-wrap gap-1.5">
            {CONTENT_TYPES.map(ct => (
              <button aria-pressed={contentType === ct.value} key={ct.value} onClick={() => setContentType(ct.value)}
                className={`px-3 py-2 rounded-lg text-[13px] font-bold border transition-colors min-h-[32px]
                  ${contentType === ct.value ? c.pillActive : c.pillInactive}`}>
                <span className="me-1">{ct.icon}</span>{ct.label}
              </button>
            ))}
          </div>
        </div>

        {/* Content */}
        <div>
          <label className={`text-[15px] font-semibold ${c.labelText} block mb-2`}>
            {t('rm_paste_label')} <span className={c.required}>*</span>
          </label>
          <textarea
            value={content}
            onChange={e => setContent(e.target.value)}
            placeholder={t('rm_ph')}
            rows={8}
            className={`w-full p-3 border rounded-lg text-[15px] ${c.input} outline-none focus:ring-2 resize-y`}
          />
          <p className={`text-xs ${c.textMuted} mt-1 text-end`}>{content.length}/3000</p>
        </div>

        {/* Heat level */}
        <div>
          <label className={`text-[15px] font-semibold ${c.labelText} block mb-2`}>{t('rm_heat_label')}</label>
          <div className="flex gap-2">
            {HEAT_LEVELS.map(h => {
              const hc = h.value === 'gentle' ? c.heatGentle : h.value === 'scorched' ? c.heatScorched : c.heatMedium;
              return (
                <button key={h.value} aria-pressed={heatLevel === h.value} onClick={() => setHeatLevel(h.value)}
                  className={`flex-1 py-3 rounded-xl border-2 text-center transition-colors min-h-[60px]
                    ${heatLevel === h.value ? `${hc} border-current` : c.pillInactive}`}>
                  <span className="text-xl block">{h.icon}</span>
                  <span className="text-[13px] font-bold block">{h.label}</span>
                  <span className={`text-xs ${c.textMuted} block`}>{h.desc}</span>
                </button>
              );
            })}
          </div>
        </div>

        {/* Submit */}
        <button title={t('cmd_enter')} onClick={runRoast} disabled={!content.trim() || loading}
          className={`relative w-full ${(!content.trim()) ? c.btnIdle : c.btnPrimary} font-bold py-3 rounded-lg flex items-center justify-center gap-2 min-h-[48px]`}>
          {loading
            ? <><span className="inline-block animate-spin text-xl">{tool?.icon ?? '🔥'}</span> {t('rm_writing')}</>
            : <><span className="text-xl">{tool?.icon ?? '🔥'}</span> {t('rm_roast_btn')}</>}
        {!loading && (
          <kbd aria-hidden="true"
            className="hidden sm:flex items-center absolute end-3 top-1/2 -translate-y-1/2 px-1.5 py-0.5 rounded border border-white/30 bg-white/15 text-[10px] font-bold tracking-wide">
            ⌘↵
          </kbd>
        )}
        </button>

        {/* Pre-result cross-ref */}
        <p data-print-hide className={`text-[13px] text-center ${c.textMuted}`}>
          {t('rm_xref_q')}{' '}
          <a href="/BragSheetBuilder" className={`text-xs ${linkStyle}`}>📋 {t('rm_brag_sheet')}</a> {t('rm_xref_rewrites')}
        </p>
      </div>

      {/* Error */}
      {error && (
        <div className={`${c.danger} border rounded-lg p-4 flex items-start gap-3`}>
          <span>⚠️</span>
          <p className="text-sm">{error}</p>
        </div>
      )}

      {/* Results */}
      {results && (
        <div className="scroll-mt-24 space-y-4" ref={resultsRef}>

          {/* First impression */}
          {results?.first_impression && (
            <div className={`${heatColor} border-2 rounded-xl p-5 text-center`}>
              <span className="text-3xl block mb-2">💀</span>
              <p className="text-[15px] font-bold">{results?.first_impression}</p>
              {results?.content_type_detected && (
                <p className={`text-xs ${c.textMuted} mt-2`}>{t('rm_detected')} {results?.content_type_detected}</p>
              )}
            </div>
          )}

          {/* Roast lines */}
          {results?.roasts?.length > 0 && (
            <div className={`border-t ${c.border} pt-5`}>
              <h3 className={`text-base font-bold ${c.text} mb-3`}>🎤 {t('rm_the_roast')}</h3>
              <div className="space-y-3">
                {results?.roasts?.map((r, i) => (
                  <div key={i} data-print-keep className={`${c.quoteBg} rounded-lg p-3`}>
                    <p className={`text-[15px] ${c.text} font-medium mb-1`}>"{r.line}"</p>
                    <div className="flex items-start gap-2">
                      {r.target && <span className={`text-xs ${c.textMuted}`}>🎯 {r.target}</span>}
                      {r.why_it_hurts && <span className={`text-xs ${c.textMuted}`}>· 💉 {r.why_it_hurts}</span>}
                    </div>
                  </div>
                ))}
              </div>
            </div>
          )}

          {/* Summary roast */}
          {results?.summary_roast && (
            <div className={`${c.warningBox} border-2 rounded-xl p-5 text-center`}>
              <p className={`text-[13px] font-bold ${c.labelText} mb-2`}>{t('rm_mic_drop')}</p>
              <p className={`text-[15px] font-bold ${c.text}`}>🎤 {results?.summary_roast}</p>
            </div>
          )}

          {/* Nice thing + share line */}
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
            {results?.one_nice_thing && (
              <div className={`${c.niceBg} border rounded-xl p-4`}>
                <p className={`text-[13px] font-bold ${c.textMuted} mb-1`}>😇 {t('rm_one_nice_thing')}</p>
                <p className={`text-[15px] ${c.textSecondary}`}>{results?.one_nice_thing}</p>
              </div>
            )}
            {results?.share_line && (
              <div className={`${c.card} border ${c.border} rounded-xl p-4`}>
                <p className={`text-[13px] font-bold ${c.accentTxt} mb-1`}>📸 {t('rm_screenshot_this')}</p>
                <p className={`text-sm font-bold ${c.text}`}>"{results?.share_line}"</p>
              </div>
            )}
          </div>

          {/* Actions */}
          <button title={t('cmd_enter')} onClick={runRoast} disabled={loading}
            className={`relative w-full ${c.btnSecondary} font-bold py-3 rounded-lg min-h-[44px]`}>
            🔥 {t('rm_roast_again')}
          {!loading && (
            <kbd aria-hidden="true"
              className="hidden sm:flex items-center absolute end-3 top-1/2 -translate-y-1/2 px-1.5 py-0.5 rounded border border-white/30 bg-white/15 text-[10px] font-bold tracking-wide">
              ⌘↵
            </kbd>
          )}
          </button>

          {/* Post-result cross-refs */}
          <div data-print-hide>
            <p className={`text-[13px] font-semibold mb-2 ${c.textMuted}`}>🔗 {t('rm_related')}</p>
            <div className="flex flex-wrap gap-3">
              <a href="/VelvetHammer"    className={`text-sm ${linkStyle}`}>🔨 {t('rm_velvet_hammer')}</a>
              <a href="/NotSoFast" className={`text-sm ${linkStyle}`}>🚪 {t('rm_rulebook_breaker')}</a>
            </div>
          </div>
        </div>
      )}
      {/* ── History ── */}
    </div>
  );
};

RoastMe.displayName = 'RoastMe';
export default RoastMe;
