            <p className={`text-[11px] ${c.textMuted}`}>
              {t('plt_jargon_hint')} <a href="/JargonAssassin" className={linkStyle}>🗡️ {t('plt_xref_jargonassassin')}</a> {t('plt_jargon_hint_after')}
            </p>
