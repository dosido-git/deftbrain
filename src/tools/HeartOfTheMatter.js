import React, { useState, useRef, useCallback, useEffect, useMemo } from 'react';
import Caret from '../components/Caret';
import { useClaudeAPI } from '../hooks/useClaudeAPI';
import { useTheme } from '../hooks/useTheme';
import { usePersistentState } from '../hooks/usePersistentState';
import { useRegisterActions } from '../components/ActionBarContext';
import { useTranslation } from '../i18n/useTranslation';
import { pickExample } from '../utils/exampleRotation';
import { revealSection } from '../utils/revealSection';
import { toolTagline } from '../utils/toolTagline';

const BRAND = '\n\n— Generated by DeftBrain · deftbrain.com';

// Owner-supplied file upload: a visitor can paste OR upload a .txt/.md
// (read client-side, no round trip), a PDF, or an audio file (both sent to
// POST /heart-of-the-matter/extract, which returns plain text — see that
// route's own comment for why PDF goes through Claude and audio through
// ElevenLabs). 20MB matches the safe raw-file ceiling under the backend's
// 30mb PDF-tier body limit once base64 inflation is accounted for (see
// backend/server.js's PDF_BODY_PREFIXES comment).
const MAX_UPLOAD_BYTES = 20 * 1024 * 1024;
const ACCEPTED_FILE_TYPES = '.txt,.md,text/plain,application/pdf,audio/*';

// ════════════════════════════════════════════════════════════
// CONSTANTS — values are stable keys; labels are localized at render time
// ════════════════════════════════════════════════════════════
const MODE_EMOJI = { distill: '🎯', understand: '💡', connect: '🔗' };

// ════════════════════════════════════════════════════════════
// MAIN COMPONENT
// ════════════════════════════════════════════════════════════
const HeartOfTheMatter = ({ tool }) => {
  const { callToolEndpoint, loading, userLocale, userCurrency, userRegion } = useClaudeAPI();
  const { isDark } = useTheme();
  const { t } = useTranslation();

  // Localized label maps (depend on t())
  // Keep the tool centered on comprehension, not studying or test preparation.
  // "Understand" reuses the study-guide endpoint and content; its own label/
  // desc keys (not a reuse of rec_understand, which already means something
  // else — the memorize/understand badge inside those results) avoid a
  // doubled emoji and avoid coupling two unrelated UI surfaces to one key.
  const MODES = [
    { value: 'distill', emoji: MODE_EMOJI.distill, label: t('rec_mode_distill_label'), desc: t('rec_mode_distill_desc') },
    { value: 'understand', emoji: MODE_EMOJI.understand, label: t('rec_mode_understand_label'), desc: t('rec_mode_understand_desc') },
    { value: 'connect', emoji: MODE_EMOJI.connect, label: t('rec_mode_connect_label'), desc: t('rec_mode_connect_desc') },
  ];
  const PRIORITIES = [
    { value: 'balanced',   label: t('rec_prio_balanced') },
    { value: 'conceptual', label: t('rec_prio_conceptual') },
    { value: 'factual',    label: t('rec_prio_factual') },
    { value: 'applied',    label: t('rec_prio_applied') },
  ];
  const TYPE_LABELS = {
    definition: t('rec_type_definition'), process: t('rec_type_process'), cause_effect: t('rec_type_cause_effect'),
    comparison: t('rec_type_comparison'), application: t('rec_type_application'), framework: t('rec_type_framework'),
    fact: t('rec_type_fact'), formula: t('rec_type_formula'),
  };

  // ── Theme — verbatim from CONVENTIONS.md PF-2 ──
  const c = {
    card:          isDark ? 'bg-zinc-800' : 'bg-white',
    cardAlt:       isDark ? 'bg-zinc-700/50' : 'bg-slate-50',
    input:         isDark ? 'bg-zinc-900 border-zinc-600 text-zinc-100 placeholder-zinc-400 focus:border-cyan-500 focus:ring-cyan-500/20'
                          : 'bg-white border-gray-300 text-gray-900 placeholder-gray-400 focus:border-cyan-500 focus:ring-cyan-100',
    text:          isDark ? 'text-zinc-50' : 'text-gray-900',
    textSecondary: isDark ? 'text-zinc-300' : 'text-gray-600',
    textMuted:     isDark ? 'text-zinc-400' : 'text-gray-500',
    required:      isDark ? 'text-amber-400' : 'text-amber-700',
    labelText:     isDark ? 'text-zinc-200' : 'text-gray-700',
    accentTxt:     isDark ? 'text-cyan-400' : 'text-cyan-600',
    btnPrimary:    isDark ? 'bg-cyan-600 hover:bg-cyan-500 text-white'
                          : 'bg-cyan-600 hover:bg-cyan-700 text-white',
    // Waiting for input: an outline, not a smudge. Empty fill keeps "filled"
    // meaning "ready"; the border and label carry the visibility. Important
    // modifiers because tools carry their own border/text utilities on the
    // submit and Tailwind resolves conflicts by stylesheet order, not class
    // order. See the PF-13 exception in audit/audit_v2-3-2.py.
    btnIdle:       isDark ? '!bg-transparent !border-2 !border-cyan-500/85 !text-cyan-300 cursor-not-allowed'
                          : '!bg-transparent !border-2 !border-cyan-600/85 !text-cyan-800 cursor-not-allowed',
    btnSecondary:  isDark ? 'bg-zinc-700 hover:bg-zinc-600 text-zinc-200'
                          : 'bg-gray-100 hover:bg-gray-200 text-gray-700',
    border:        isDark ? 'border-zinc-700' : 'border-gray-200',
    success:       isDark ? 'bg-emerald-900/20 border-emerald-700 text-emerald-200'
                          : 'bg-emerald-50 border-emerald-300 text-emerald-800',
    warning:       isDark ? 'bg-amber-900/20 border-amber-700 text-amber-200'
                          : 'bg-amber-50 border-amber-300 text-amber-800',
    danger:        isDark ? 'bg-red-900/20 border-red-700 text-red-200'
                          : 'bg-red-50 border-red-200 text-red-800',
    pillActive:    isDark ? 'border-cyan-500 bg-cyan-900/30 text-cyan-200'
                          : 'border-cyan-600 bg-cyan-100 text-cyan-900',
    pillInactive:  isDark ? 'border-zinc-600 text-zinc-400 hover:border-zinc-500'
                          : 'border-gray-300 text-gray-500 hover:border-gray-400',
    tipBg:         isDark ? 'bg-cyan-900/20 border-cyan-700' : 'bg-cyan-50 border-cyan-200',
    tipText:       isDark ? 'text-cyan-300' : 'text-cyan-700',
    inset:         isDark ? 'bg-zinc-700/60' : 'bg-slate-100',
    badge:         isDark ? 'bg-zinc-600 text-zinc-200' : 'bg-zinc-100 text-zinc-600',
    defBg:         isDark ? 'bg-fuchsia-900/30 text-fuchsia-300' : 'bg-fuchsia-50 text-fuchsia-700',
    procBg:        isDark ? 'bg-sky-900/30 text-sky-300'         : 'bg-sky-50 text-sky-700',
    factBg:        isDark ? 'bg-amber-900/30 text-amber-300'     : 'bg-amber-50 text-amber-700',
    histBg:        isDark ? 'bg-zinc-700/30 border-zinc-600'     : 'bg-slate-50 border-slate-200',
    histCard:      isDark ? 'bg-zinc-700/50 border-zinc-600'     : 'bg-white border-slate-200',
    cardAltText:   isDark ? 'text-zinc-300' : 'text-gray-600',
    warnText:      isDark ? 'text-amber-300' : 'text-amber-700',
  };
  c.label = c.labelText;
  c.textMuteded = c.textMuted;

  const linkStyle = isDark
    ? 'text-cyan-400 hover:text-cyan-300 underline underline-offset-2'
    : 'text-cyan-700 hover:text-cyan-800 underline underline-offset-2';

  // ── State ──
  const [mode, setMode]             = useState('distill');
  const [transcript, setTranscript] = useState('');
  const [subject, setSubject]       = useState('');
  const [lectureTitle, setLectureTitle] = useState('');
  const [bulletCount, setBulletCount]   = useState(10);
  const [priority, setPriority]         = useState('balanced');
  const [lectures, setLectures]         = useState([{ title: '', transcript: '' }, { title: '', transcript: '' }]);
  const [error, setError]               = useState('');
  const [expandedSections, setExpandedSections] = useState({});
  const [showHistory, setShowHistory]   = useState(false);
  const [selectedHistoryIds, setSelectedHistoryIds] = useState([]);
  const [extracting, setExtracting]     = useState(false);

  // ── Refs ──
  const resultsRef   = useRef(null);
  const submitRef    = useRef(null);
  const canSubmitRef = useRef(false);

  const lecturesInputRefs = useRef([]);
  const shouldFocusNewLecturesRef = useRef(false);
  const fileInputRef = useRef(null);
  // null = main transcript; a number = lectures[index].transcript (Connect mode)
  const uploadTargetRef = useRef(null);
  // ── Persistent state ──
  const [results, setResults] = usePersistentState('recall-results', null);
  const [sessionHistory, setSessionHistory] = usePersistentState('recall-history', []);

  // ── Helpers ──
  const addLecture    = useCallback(() => { if (lectures.length < 5) { shouldFocusNewLecturesRef.current = true; setLectures(p => [...p, { title: '', transcript: '' }]); }; }, [lectures.length]);
  const removeLecture = useCallback((i) => { if (lectures.length > 2) setLectures(p => p.filter((_, idx) => idx !== i)); }, [lectures.length]);
  const updateLecture = useCallback((i, field, val) => setLectures(p => p.map((l, idx) => idx === i ? { ...l, [field]: val } : l)), []);
  const toggleSection = useCallback((key) => setExpandedSections(prev => ({ ...prev, [key]: !prev[key] })), []);

  const charCount = useMemo(() => {
    if (mode === 'connect') return lectures.reduce((sum, l) => sum + (l.transcript?.length || 0), 0);
    return transcript.length;
  }, [mode, transcript, lectures]);

  const canSubmit = (mode === 'connect'
    ? lectures.filter(l => l.transcript?.trim()).length >= 2
    : transcript.trim().length > 0) && !extracting;

  // ── File upload ──
  const triggerUpload = useCallback((lectureIndex = null) => {
    uploadTargetRef.current = lectureIndex;
    fileInputRef.current?.click();
  }, []);

  const handleFileSelected = useCallback(async (e) => {
    const file = e.target.files?.[0];
    const lectureIndex = uploadTargetRef.current;
    e.target.value = ''; // allow re-selecting the same file next time
    if (!file) return;
    setError('');

    if (file.size > MAX_UPLOAD_BYTES) { setError(t('rec_err_file_size')); return; }

    const isText = file.type === 'text/plain' || /\.(txt|md)$/i.test(file.name);
    const isPdf = file.type === 'application/pdf';
    const isAudio = file.type.startsWith('audio/');

    const applyText = (text) => {
      if (lectureIndex === null) setTranscript(text);
      else updateLecture(lectureIndex, 'transcript', text);
    };

    if (isText) {
      try { applyText(await file.text()); }
      catch { setError(t('rec_err_file_read')); }
      return;
    }

    if (!isPdf && !isAudio) { setError(t('rec_err_file_type')); return; }

    setExtracting(true);
    try {
      const base64 = await new Promise((resolve, reject) => {
        const reader = new FileReader();
        reader.onload = () => resolve(String(reader.result).split(',')[1] || '');
        reader.onerror = () => reject(new Error('read failed'));
        reader.readAsDataURL(file);
      });
      const data = await callToolEndpoint('heart-of-the-matter/extract', {
        fileData: base64,
        mediaType: file.type || (isPdf ? 'application/pdf' : 'audio/mpeg'),
      });
      if (!data?.text?.trim()) setError(t('rec_err_file_empty'));
      else applyText(data.text);
    } catch (err) {
      setError(err.message || t('rec_err_file_extract'));
    } finally {
      setExtracting(false);
    }
  }, [callToolEndpoint, t, updateLecture]);

  // ── API ──
  // Accepts optional overrides for mode/lectures/subject so a caller that
  // just changed those via setState (which doesn't land until the next
  // render) can submit with the FRESH values immediately, rather than
  // firing on the stale closure or waiting a tick — see
  // useSelectedWithConnect below, which needs to submit the lectures it
  // just built, not whatever was on screen before.
  const submit = useCallback(async (overrides = {}) => {
    const activeMode = overrides.mode ?? mode;
    const activeLectures = overrides.lectures ?? lectures;
    const activeSubject = overrides.subject ?? subject;
    setError(''); setResults(null);
    try {
      let data;
      if (activeMode === 'distill') {
        if (!transcript.trim()) { setError(t('rec_err_paste')); return; }
        data = await callToolEndpoint('heart-of-the-matter', {
          transcript: transcript.trim(), subject: activeSubject.trim() || null,
          lectureTitle: lectureTitle.trim() || null, bulletCount, priority,
          userLocale, userCurrency, userRegion,
        });
      } else if (activeMode === 'understand') {
        if (!transcript.trim()) { setError(t('rec_err_paste')); return; }
        // Reuse the existing comprehension endpoint, but deliberately omit
        // exam-format controls. The UI also filters study/test-oriented output.
        data = await callToolEndpoint('heart-of-the-matter/study-guide', {
          transcript: transcript.trim(), subject: activeSubject.trim() || null,
          lectureTitle: lectureTitle.trim() || null,
          userLocale, userCurrency, userRegion,
        });
      } else if (activeMode === 'connect') {
        const valid = activeLectures.filter(l => l.transcript?.trim());
        if (valid.length < 2) { setError(t('rec_err_two_lectures')); return; }
        data = await callToolEndpoint('heart-of-the-matter/connect', {
          lectures: valid.map(l => ({ title: l.title.trim() || null, transcript: l.transcript.trim() })),
          subject: activeSubject.trim() || null,
          userLocale, userCurrency, userRegion,
        });
      }
      setResults(data);
      // The takeaway IS the point of Past Sessions — what the material said,
      // not just what was fed in. Each mode already produces a one-line
      // distillation of its own (lecture_summary / overview / course_
      // narrative); reuse it rather than inventing a fifth thing to generate.
      const takeaway = activeMode === 'distill' ? data?.lecture_summary
        : activeMode === 'understand' ? data?.overview
        : data?.course_narrative; // connect
      const modeLabel = activeMode === 'distill' ? t('rec_mode_distill_label')
        : activeMode === 'understand' ? t('rec_mode_understand_label')
        : t('rec_mode_connect_label');
      const validLectures = activeMode === 'connect' ? activeLectures.filter(l => l.transcript?.trim()) : [];
      setSessionHistory(prev => [{
        id: 'rc_' + Date.now(), date: new Date().toISOString(), mode: activeMode,
        title: lectureTitle.trim() || activeSubject.trim() || takeaway?.slice(0, 60) || modeLabel,
        preview: (lectureTitle.trim() || activeSubject.trim() || takeaway || modeLabel).slice(0, 40),
        subject: data?.subject_detected || activeSubject.trim() || '',
        takeaway: takeaway || '',
        results: data,
        // Snapshot of the input, kept so a session can be reopened AND so
        // "Use with Connect" has real source material to work from — not
        // just the summary of it.
        lectureTitle: lectureTitle.trim() || '',
        bulletCount, priority,
        transcript: activeMode !== 'connect' ? transcript.trim() : '',
        lectures: activeMode === 'connect' ? validLectures.map(l => ({ title: l.title?.trim() || '', transcript: l.transcript.trim() })) : [],
        // Drop any entry saved before this shape existed the first time
        // there's a fresh one to replace it with, rather than carrying dead
        // weight in storage indefinitely.
      }, ...prev.filter(e => e?.results)].slice(0, 6));
    } catch (err) { setError(err.message || t('rec_err_failed')); }
  }, [mode, transcript, subject, lectureTitle, bulletCount, priority, lectures, callToolEndpoint, setResults, setSessionHistory,
      userLocale, userCurrency, userRegion, t]);

  const handleReset = useCallback(() => {
    setTranscript(''); setSubject(''); setLectureTitle('');
    setResults(null); setError('');
    setLectures([{ title: '', transcript: '' }, { title: '', transcript: '' }]);
  }, [setResults]);

  // ── Past Sessions: reopen, and combine into a new Connect run ──
  // A session card is a memory of what was UNDERSTOOD, not a saved document —
  // reopening shows the same takeaway again rather than re-running anything.
  const reopenSession = useCallback((entry) => {
    if (!entry?.results) return;
    setMode(entry.mode);
    setResults(entry.results);
    setSubject(entry.subject || '');
    setLectureTitle(entry.lectureTitle || '');
    setBulletCount(entry.bulletCount || 10);
    setPriority(entry.priority || 'balanced');
    if (entry.mode === 'connect') {
      setLectures(entry.lectures?.length >= 2 ? entry.lectures : [{ title: '', transcript: '' }, { title: '', transcript: '' }]);
      setTranscript('');
    } else {
      setTranscript(entry.transcript || '');
      setLectures([{ title: '', transcript: '' }, { title: '', transcript: '' }]);
    }
    setError('');
    setShowHistory(false);
    setSelectedHistoryIds([]);
  }, [setResults]);

  const toggleHistorySelection = useCallback((id) => {
    setSelectedHistoryIds(prev => prev.includes(id) ? prev.filter(x => x !== id) : [...prev, id]);
  }, []);

  // A past Connect session already flattens to the lectures it combined;
  // reusing it just spreads those back in rather than nesting a summary of
  // a summary. Capped at 5 — the same limit Connect's own "add lecture" has.
  const useSelectedWithConnect = useCallback(() => {
    const chosen = sessionHistory.filter(e => selectedHistoryIds.includes(e.id));
    const built = [];
    chosen.forEach(e => {
      if (e.mode === 'connect' && e.lectures?.length) built.push(...e.lectures);
      else if (e.transcript?.trim()) built.push({ title: e.lectureTitle || e.title || '', transcript: e.transcript });
    });
    if (built.length < 2) return;
    const picked = built.slice(0, 5);
    setMode('connect');
    setLectures(picked);
    setSubject('');
    setSelectedHistoryIds([]);
    setShowHistory(false);
    // Submit right away with the lectures just built — setLectures/setMode
    // above won't land until the next render, so `submit` is handed them
    // directly rather than reading its own (still-stale) closure. It
    // already clears results/error itself.
    submit({ mode: 'connect', lectures: picked, subject: '' });
  }, [sessionHistory, selectedHistoryIds, submit]);

  // Rotated per mode — Distill/Understand/Connect each keep their own counter
  // and pool rather than Try Example always forcing you back to Distill.
  // "Understand" reuses the same rec_sg*_* example content the study-guide
  // mode has always used, since it is the same endpoint under a plainer name.
  const loadExample = useCallback(() => {
    if (mode === 'connect') {
      const ex = pickExample('HeartOfTheMatter:connect', [{ n: 'c1' }, { n: 'c2' }, { n: 'c3' }, { n: 'c4' }, { n: 'c5' }]);
      const k = f => `rec_${ex.n}_${f}`;
      setSubject(t(k('subject')));
      setLectures([
        { title: t(k('l1_title')), transcript: t(k('l1_transcript')) },
        { title: t(k('l2_title')), transcript: t(k('l2_transcript')) },
      ]);
      setResults(null); setError('');
      return;
    }
    const prefix = mode === 'understand' ? 'sg' : '';
    const pool = prefix
      ? [{ n: `${prefix}1` }, { n: `${prefix}2` }, { n: `${prefix}3` }, { n: `${prefix}4` }, { n: `${prefix}5` }]
      : [{ n: '' }, { n: '2' }, { n: '3' }, { n: '4' }, { n: '5' }];
    const ex = pickExample(`HeartOfTheMatter:${mode}`, pool);
    const k = f => `rec_ex${ex.n}_${f}`;
    setSubject(t(k('subject')));
    setLectureTitle(t(k('title')));
    setTranscript(t(k('transcript')));
    setResults(null); setError('');
  }, [mode, setResults, t]);

  // ── buildFullText ──
  const buildFullText = useCallback(() => {
    if (!results) return '';
    const lines = [];
    if (mode === 'distill' && results.bullets?.length) {
      lines.push(`🎯 ${t('rec_copy_distill')} — ${results.lecture_summary || t('rec_copy_notes_fallback')}`, '');
      results.bullets.forEach(b => lines.push(`${b.rank}. ${b.point}`));
      if (results.vocabulary?.length) {
        lines.push('', t('rec_copy_key_terms'));
        results.vocabulary.forEach(v => lines.push(`• ${v.term}: ${v.definition}`));
      }
    } else if (mode === 'understand' && results) {
      lines.push(`💡 ${t('rec_mode_understand_label')} — ${results.title || t('rec_lecture_fallback')}`, '', results.overview || '', '');
      results.concepts_to_know?.forEach(item => lines.push(`■ ${item.concept}: ${item.explanation}`));
      if (results.key_definitions?.length) {
        lines.push('', t('rec_copy_definitions'));
        results.key_definitions.forEach(d => lines.push(`• ${d.term}: ${d.definition}`));
      }
    } else if (mode === 'connect' && results) {
      if (results.course_narrative) lines.push(`🔗 ${results.course_narrative}`, '');
      results.recurring_themes?.forEach(theme => lines.push(`■ ${theme.theme}: ${theme.why_recurring}`));
    }
    const body = lines.join('\n').trim();
    return body ? body + BRAND : '';
  }, [results, mode, t]);

  // Live ref assignments
  submitRef.current    = submit;
  canSubmitRef.current = canSubmit;

  useRegisterActions(buildFullText(), tool?.title || 'Heart of the Matter');

  // Scroll to results
  useEffect(() => {
    if (!results) return;
    const timer = setTimeout(() => revealSection(resultsRef.current), 200);
    return () => clearTimeout(timer);
  }, [results]);

  // Keyboard shortcut
  useEffect(() => {
    const handler = (e) => {
      const tag = document.activeElement?.tagName;
      if (tag === 'SELECT') return;
      if (e.key === 'Enter' && (e.metaKey || e.ctrlKey) && !loading && canSubmitRef.current)
        submitRef.current?.();
    };
    document.addEventListener('keydown', handler);
    return () => document.removeEventListener('keydown', handler);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [loading]);

  useEffect(() => {
    if (shouldFocusNewLecturesRef.current) {
      const last = lecturesInputRefs.current[lectures.length - 1];
      if (last) last.focus();
      shouldFocusNewLecturesRef.current = false;
    }
  }, [lectures.length]);

  // ── Shared sub-components ──
  const Pill = ({ active, onClick, children }) => (
    <button onClick={onClick}
      className={`px-3 py-1.5 rounded-lg border text-xs font-semibold transition-all ${active ? c.pillActive : c.pillInactive}`}>
      {active && <span className="me-1">✓</span>}{children}
    </button>
  );

  const Section = ({ title, emoji, sKey, badge, defaultOpen = false, children }) => {
    const open = expandedSections[sKey] ?? defaultOpen;
    return (
      <div className={`${c.card} border ${c.border} rounded-xl overflow-hidden`}>
        <button onClick={() => toggleSection(sKey)} className="w-full flex items-center justify-between p-4 text-start hover:opacity-80">
          <div className="flex items-center gap-2">
            <span className="text-base">{emoji}</span>
            <span className={`text-sm font-semibold ${c.text}`}>{title}</span>
            {badge && <span className={`text-xs px-2 py-0.5 rounded-full ${c.badge}`}>{badge}</span>}
          </div>
          <Caret open={open} />
        </button>
        {open && <div className={`px-4 pb-4 border-t ${c.border}`}>{children}</div>}
      </div>
    );
  };

  // ════════════════════════════════════════════════════════════
  // INPUT
  // ════════════════════════════════════════════════════════════
  const renderInput = () => (
    <div className="space-y-4">
      {/* Hidden file input — shared by the main transcript and every Connect lecture row */}
      <input ref={fileInputRef} type="file" accept={ACCEPTED_FILE_TYPES} className="hidden" onChange={handleFileSelected} />

      {/* Mode tabs */}
      <div className="flex gap-1.5 overflow-x-auto pb-1">
        {MODES.map(m => (
          <button key={m.value} onClick={() => { setMode(m.value); setResults(null); setError(''); }}
            className={`flex items-center gap-2 px-4 py-3 rounded-xl border-2 transition-all flex-shrink-0 ${
              mode === m.value ? `${c.pillActive} border-2` : c.pillInactive}`}>
            <span className="text-lg">{m.emoji}</span>
            <div className="text-start">
              <p className={`text-xs font-bold ${mode === m.value ? '' : c.textMuted}`}>{m.label}</p>
              <p className={`text-[10px] ${c.textMuted}`}>{m.desc}</p>
            </div>
          </button>
        ))}
      </div>

      {/* Transcript — all modes except Connect */}
      {mode !== 'connect' ? (
        <div className={`${c.card} border ${c.border} rounded-xl p-5`}>
          <div className="flex items-start justify-between gap-3 mb-1">
            <label className={`text-base font-bold ${c.text} block`}>{t('rec_input_label')} <span className={c.required}>*</span></label>
            <button type="button" onClick={() => triggerUpload(null)} disabled={extracting}
              className={`text-xs font-semibold px-2.5 py-1 rounded-lg flex-shrink-0 whitespace-nowrap ${c.btnSecondary} disabled:opacity-50`}>
              📎 {t('rec_upload_file')}
            </button>
          </div>
          <p className={`text-xs ${c.textMuted} mb-3`}>{t('rec_input_help')} {t('rec_upload_hint')}</p>
          {extracting ? (
            <div className={`w-full h-40 flex items-center justify-center gap-2 border-2 border-dashed rounded-xl ${c.border} ${c.textMuted} text-sm`}>
              <span className="animate-spin inline-block text-xl">{tool?.icon ?? '🎯'}</span> {t('rec_extracting')}
            </div>
          ) : (
            <textarea value={transcript} onChange={e => setTranscript(e.target.value)}
              placeholder={t('rec_input_ph')}
              className={`w-full min-h-[10rem] p-4 border-2 rounded-xl ${c.input} outline-none focus:ring-2 resize-y text-sm font-mono`} />
          )}
          {charCount > 0 && (
            <p className={`text-xs ${c.textMuted} mt-1`}>
              {t('rec_chars_minutes', { chars: charCount.toLocaleString(), min: Math.round(charCount / 750) })}
            </p>
          )}
        </div>
      ) : (
        <div className="space-y-3">
          {lectures.map((lec, idx) => (
            <div key={idx} className={`${c.card} border ${c.border} rounded-xl p-4`}>
              <div className="flex items-center gap-2 mb-2">
                <span className={`text-xs font-bold ${c.badge} px-2 py-0.5 rounded-full`}>{t('rec_lecture_n', { n: idx + 1 })}</span>
                <input ref={el => { lecturesInputRefs.current[idx] = el; }} type="text" value={lec.title} onChange={e => updateLecture(idx, 'title', e.target.value)}
                  placeholder={t('rec_lecture_title_ph')}
                  className={`flex-1 px-3 py-1.5 rounded-lg border text-xs ${c.input} outline-none`} />
                <button type="button" onClick={() => triggerUpload(idx)} disabled={extracting}
                  title={t('rec_upload_file')}
                  className={`text-xs px-2 py-1.5 rounded-lg flex-shrink-0 ${c.btnSecondary} disabled:opacity-50`}>📎</button>
                {lectures.length > 2 && (
                  <button onClick={() => removeLecture(idx)} className={`text-xs px-2 py-1 rounded ${c.warnText}`}>✕</button>
                )}
              </div>
              {extracting && uploadTargetRef.current === idx ? (
                <div className={`w-full h-24 flex items-center justify-center gap-2 border-2 border-dashed rounded-xl ${c.border} ${c.textMuted} text-xs`}>
                  <span className="animate-spin inline-block text-xl">{tool?.icon ?? '🎯'}</span> {t('rec_extracting')}
                </div>
              ) : (
                <textarea value={lec.transcript} onChange={e => updateLecture(idx, 'transcript', e.target.value)}
                  placeholder={t('rec_lecture_transcript_ph')}
                  className={`w-full min-h-[6rem] p-3 border-2 rounded-xl ${c.input} outline-none focus:ring-2 resize-y text-xs font-mono`} />
              )}
            </div>
          ))}
          {lectures.length < 5 && (
            <button onClick={addLecture} className={`w-full py-3 rounded-xl border-2 border-dashed text-xs font-bold ${c.pillInactive}`}>
              {t('rec_add_lecture')}
            </button>
          )}
          {charCount > 0 && (
            <p className={`text-xs ${c.textMuted}`}>
              {t('rec_chars_across', { chars: charCount.toLocaleString(), count: lectures.filter(l => l.transcript?.trim()).length })}
            </p>
          )}
        </div>
      )}

      {/* Context + mode options */}
      <div className={`${c.card} border ${c.border} rounded-xl p-5 space-y-3`}>
        <div className="grid grid-cols-2 gap-3">
          <div>
            <label className={`text-xs font-bold ${c.textSecondary} uppercase tracking-wide mb-1 block`}>{t('rec_subject_label')}</label>
            <input type="text" value={subject} onChange={e => setSubject(e.target.value)}
              placeholder={t('rec_subject_ph')}
              className={`w-full px-3 py-2 rounded-xl border text-sm ${c.input} outline-none`} />
          </div>
          {mode !== 'connect' && (
            <div>
              <label className={`text-xs font-bold ${c.textSecondary} uppercase tracking-wide mb-1 block`}>{t('rec_topic_label')}</label>
              <input type="text" value={lectureTitle} onChange={e => setLectureTitle(e.target.value)}
                placeholder={t('rec_topic_ph')}
                className={`w-full px-3 py-2 rounded-xl border text-sm ${c.input} outline-none`} />
            </div>
          )}
        </div>

        {mode === 'distill' && (
          <>
            <div>
              <label className={`text-xs font-bold ${c.textSecondary} uppercase tracking-wide mb-2 block`}>{t('rec_bullets_label', { count: bulletCount })}</label>
              <input type="range" min={5} max={20} value={bulletCount} onChange={e => setBulletCount(Number(e.target.value))}
                className="w-full accent-cyan-600" />
            </div>
            <div>
              <label className={`text-xs font-bold ${c.textSecondary} uppercase tracking-wide mb-2 block`}>{t('rec_priority_label')}</label>
              <div className="flex flex-wrap gap-1.5">
                {PRIORITIES.map(p => <Pill key={p.value} active={priority === p.value} onClick={() => setPriority(p.value)}>{p.label}</Pill>)}
              </div>
            </div>
          </>
        )}

      </div>

      <div className="flex gap-2">
        <button title={t('cmd_enter')} onClick={() => submit()} disabled={loading || !canSubmit}
          className={`relative flex-1 ${(!canSubmit) ? c.btnIdle : c.btnPrimary} py-4 rounded-2xl text-sm font-bold flex items-center justify-center gap-2 transition-all min-h-[48px]`}>
          {loading
            ? <><span className="animate-spin inline-block text-xl">{tool?.icon ?? '🎯'}</span> {t('rec_processing')}</>
            : mode === 'distill'     ? <><span className="text-xl">{tool?.icon ?? '🎯'}</span> {t('rec_submit_distill')}</>
            : mode === 'understand' ? <><span className="text-xl">{tool?.icon ?? '🎯'}</span> {t('rec_submit_understand')}</>
            : <><span className="text-xl">{tool?.icon ?? '🎯'}</span> {t('rec_submit_connect')}</>}
        {!loading && (
          <kbd aria-hidden="true"
            className="hidden sm:flex items-center absolute end-3 top-1/2 -translate-y-1/2 px-1.5 py-0.5 rounded border border-white/30 bg-white/15 text-[10px] font-bold tracking-wide">
            ⌘↵
          </kbd>
        )}
        </button>
      </div>
      <p className={`text-xs text-center ${c.textMuted}`}>
        {t('rec_pre_xref')}{' '}
        <a href="/BrainDumpBuddy" className={linkStyle}>🧠 {t('rec_braindump')}</a>
        {' '}{t('rec_pre_xref_after')}
      </p>
    </div>
  );

  // ════════════════════════════════════════════════════════════
  // RESULTS — DISTILL
  // ════════════════════════════════════════════════════════════
  const renderDistill = () => {
    if (!results?.bullets?.length) return null;
    return (
      <div className="space-y-4">
        <div className={`p-5 rounded-2xl border-2 ${c.tipBg}`}>
          <p className={`text-xs font-bold ${c.tipText} uppercase mb-1`}>{results.subject_detected || subject || t('rec_lecture_fallback')}</p>
          <p className={`text-sm font-bold ${c.text}`}>{results.lecture_summary}</p>
        </div>
        <div className="space-y-2">
          {results.bullets.map((b, idx) => (
            <div key={idx} className={`${c.card} border ${c.border} rounded-xl p-4`}>
              <div className="flex items-start gap-3">
                <span className={`text-lg font-black ${idx < 3 ? c.tipText : c.textMuted}`}>{b.rank}</span>
                <div className="flex-1 min-w-0">
                  <p className={`text-sm ${c.text} mb-1.5`}>{b.point}</p>
                  <div className="flex flex-wrap gap-1.5">
                    {b.type && TYPE_LABELS[b.type] && (
                      <span className={`text-[9px] font-bold px-2 py-0.5 rounded-full ${
                        b.type === 'definition' ? c.defBg : b.type === 'process' || b.type === 'formula' ? c.procBg : c.factBg}`}>
                        {TYPE_LABELS[b.type]}
                      </span>
                    )}
                  </div>
                </div>
              </div>
            </div>
          ))}
        </div>

        {results.vocabulary?.length > 0 && (
          <Section title={t('rec_key_terms')} emoji="📖" sKey="vocab" badge={String(results.vocabulary.length)} defaultOpen>
            <div className="space-y-2 mt-3">
              {results.vocabulary.map((v, i) => (
                <div key={i} className={`p-3 rounded-lg ${c.inset}`}>
                  <span className={`text-xs font-bold ${c.text}`}>{v.term}</span>
                  <span className={`text-xs ${c.textSecondary}`}> — {v.definition}</span>
                </div>
              ))}
            </div>
          </Section>
        )}


      </div>
    );
  };

  // ════════════════════════════════════════════════════════════
  // RESULTS — UNDERSTAND
  // ════════════════════════════════════════════════════════════
  const renderUnderstand = () => {
    if (!results) return null;
    return (
      <div className="space-y-4">
        <div className={`p-5 rounded-2xl border-2 ${c.tipBg}`}>
          <p className={`text-base font-bold ${c.text} mb-1`}>📝 {results.title}</p>
          <p className={`text-sm ${c.textSecondary}`}>{results.overview}</p>
        </div>

        {results.concepts_to_know?.length > 0 && (
          <Section title={t('rec_concepts_to_know')} emoji="🧠" sKey="concepts" badge={String(results.concepts_to_know.length)} defaultOpen>
            <div className="space-y-3 mt-3">
              {results.concepts_to_know.map((item, i) => (
                <div key={i} className={`p-3 rounded-lg border ${c.cardAlt}`}>
                  <p className={`text-sm font-bold ${c.text} mb-1`}>{item.concept}</p>
                  <p className={`text-xs ${c.textSecondary}`}>{item.explanation}</p>
                </div>
              ))}
            </div>
          </Section>
        )}

        {results.key_definitions?.length > 0 && (
          <Section title={t('rec_key_definitions')} emoji="📖" sKey="defs" badge={String(results.key_definitions.length)}>
            <div className="space-y-2 mt-3">
              {results.key_definitions.map((d, i) => (
                <div key={i} className={`p-3 rounded-lg ${c.inset}`}>
                  <p className={`text-xs font-bold ${c.text}`}>{d.term}</p>
                  <p className={`text-xs ${c.textSecondary}`}>{d.definition}</p>
                  {d.distinguish_from && <p className={`text-[10px] ${c.tipText} mt-0.5`}>{t('rec_dont_confuse', { val: d.distinguish_from })}</p>}
                </div>
              ))}
            </div>
          </Section>
        )}

        {results.processes_and_formulas?.length > 0 && (
          <Section title={t('rec_processes_formulas')} emoji="⚙️" sKey="procs">
            <div className="space-y-3 mt-3">
              {results.processes_and_formulas.map((p, i) => (
                <div key={i} className={`p-3 rounded-lg border ${c.cardAlt}`}>
                  <p className={`text-xs font-bold ${c.text} mb-1`}>{p.name}</p>
                  <p className={`text-xs ${c.textSecondary} mb-1`}>{p.steps_or_formula}</p>
                  {p.when_to_use && <p className={`text-[10px] ${c.cardAltText}`}>{t('rec_when_to_use', { val: p.when_to_use })}</p>}
                  {p.common_mistake && <p className={`text-[10px] ${c.warnText} mt-0.5`}>{t('rec_common_mistake', { val: p.common_mistake })}</p>}
                </div>
              ))}
            </div>
          </Section>
        )}

        {results.relationships?.length > 0 && (
          <Section title={t('rec_relationships')} emoji="🔗" sKey="rels">
            <div className="space-y-2 mt-3">
              {results.relationships.map((r, i) => (
                <div key={i} className={`p-2 rounded-lg ${c.inset} flex items-center gap-2`}>
                  <span className={`text-[9px] font-bold px-2 py-0.5 rounded-full ${c.badge}`}>{r.type?.replace('_', ' ')}</span>
                  <p className={`text-xs ${c.text}`}>{r.relationship}</p>
                </div>
              ))}
            </div>
          </Section>
        )}


      </div>
    );
  };

  // ════════════════════════════════════════════════════════════
  // RESULTS — CONNECT
  // ════════════════════════════════════════════════════════════
  const renderConnect = () => {
    if (!results) return null;
    return (
      <div className="space-y-4">
        {results.course_narrative && (
          <div className={`p-5 rounded-2xl border-2 ${c.tipBg}`}>
            <p className={`text-xs font-bold ${c.tipText} uppercase mb-1`}>{t('rec_course_narrative')}</p>
            <p className={`text-sm font-bold ${c.text}`}>{results.course_narrative}</p>
          </div>
        )}

        {results.recurring_themes?.length > 0 && (
          <Section title={t('rec_recurring_themes')} emoji="🔄" sKey="themes" badge={String(results.recurring_themes.length)} defaultOpen>
            <div className="space-y-3 mt-3">
              {results.recurring_themes.map((theme, i) => (
                <div key={i} className={`p-3 rounded-lg border ${c.cardAlt}`}>
                  <p className={`text-xs font-bold ${c.text} mb-1`}>{theme.theme}</p>
                  {theme.appearances?.map((a, ai) => <p key={ai} className={`text-[10px] ${c.textSecondary} mb-0.5`}>• {a}</p>)}
                  <p className={`text-[10px] ${c.tipText} mt-1 italic`}>📋 {theme.why_recurring}</p>
                </div>
              ))}
            </div>
          </Section>
        )}

        {results.concept_chain?.length > 0 && (
          <Section title={t('rec_concept_chain')} emoji="⛓️" sKey="chain">
            <div className="space-y-2 mt-3">
              {results.concept_chain.map((ch, i) => (
                <div key={i} className={`p-3 rounded-lg ${c.inset}`}>
                  <p className={`text-xs font-bold ${c.text}`}>{ch.concept}</p>
                  <p className={`text-xs ${c.textSecondary} mt-0.5`}>{ch.progression}</p>
                </div>
              ))}
            </div>
          </Section>
        )}


        {results.contradictions_or_nuance?.length > 0 && (
          <Section title={t('rec_evolving_ideas')} emoji="💭" sKey="nuance">
            <div className="space-y-2 mt-3">
              {results.contradictions_or_nuance.map((cn, i) => (
                <div key={i} className={`p-3 rounded-lg ${c.inset}`}>
                  <p className={`text-xs font-bold ${c.text}`}>{cn.topic}</p>
                  <p className={`text-xs ${c.textSecondary} mt-0.5`}>{cn.evolution}</p>
                </div>
              ))}
            </div>
          </Section>
        )}


      </div>
    );
  };

  // ════════════════════════════════════════════════════════════
  // HISTORY
  // ════════════════════════════════════════════════════════════
  const renderHistory = () => {
    // Entries saved before this feature shipped (or from an interrupted
    // save) carry no `results` — nothing to reopen, no takeaway to show, no
    // source to connect. They fail every one of Past Sessions' three jobs,
    // so they are not shown at all rather than rendered as a dead click.
    const validHistory = sessionHistory.filter(e => e?.results);
    if (validHistory.length === 0) return null;
    const modeEmoji = (m) => MODE_EMOJI[m] || '🧠';
    const modeLabelFor = (m) => m === 'distill' ? t('rec_mode_distill_label')
      : m === 'understand' ? t('rec_mode_understand_label')
      : t('rec_mode_connect_label');
    const formatDate = (iso) => {
      try {
        const d = new Date(iso); const diff = Math.floor((new Date() - d) / 86400000);
        return diff === 0 ? t('rec_today') : diff === 1 ? t('rec_yesterday') : diff < 7 ? t('rec_days_ago', { n: diff }) : d.toLocaleDateString(userLocale || 'en-US', { month: 'short', day: 'numeric' });
      } catch { return ''; }
    };
    // Only a session with its own source material still attached can feed a
    // new Connect run — an entry saved before this feature existed has
    // neither transcript nor lectures, so it stays reopenable but not
    // selectable.
    const eligibleForConnect = (entry) => !!(entry.transcript?.trim() || entry.lectures?.length);
    return (
      <div className={`p-4 rounded-2xl border ${c.histBg}`}>
        <button onClick={() => setShowHistory(!showHistory)} className="w-full flex items-center gap-2 text-start">
          <span className="text-xl">{tool?.icon ?? '🎯'}</span>
          <span className={`text-sm font-bold ${c.text} flex-1`}>{t('rec_past_sessions')}</span>
          <span className={`text-xs ${c.textMuted}`}>{validHistory.length}</span>
          <Caret open={showHistory} />
        </button>
        {showHistory && (
          <div className="mt-3 space-y-2">
            {validHistory.map(entry => {
              const selected = selectedHistoryIds.includes(entry.id);
              const canSelect = eligibleForConnect(entry);
              const metaParts = [entry.subject, modeLabelFor(entry.mode), formatDate(entry.date)].filter(Boolean);
              const takeaway = entry.takeaway?.length > 140 ? entry.takeaway.slice(0, 140).trim() + '…' : entry.takeaway;
              return (
                <div key={entry.id}
                  onClick={() => reopenSession(entry)}
                  role="button" tabIndex={0}
                  onKeyDown={(e) => { if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); reopenSession(entry); } }}
                  className={`rounded-xl border ${c.histCard} p-3 flex items-start gap-3 cursor-pointer hover:opacity-90 transition-opacity`}>
                  {canSelect && (
                    <input type="checkbox" checked={selected}
                      onClick={(e) => e.stopPropagation()}
                      onChange={() => toggleHistorySelection(entry.id)}
                      aria-label={t('rec_history_select')} title={t('rec_history_select')}
                      className="mt-1 flex-shrink-0" />
                  )}
                  <span className="text-lg flex-shrink-0">{modeEmoji(entry.mode)}</span>
                  <div className="flex-1 min-w-0">
                    <div className={`text-sm font-semibold ${c.text} truncate`}>{entry.title}</div>
                    <div className={`text-xs ${c.textMuted} mt-0.5`}>{metaParts.join(' · ')}</div>
                    {takeaway && <p className={`text-xs ${c.textSecondary} mt-1 leading-snug`}>{takeaway}</p>}
                  </div>
                </div>
              );
            })}
            {selectedHistoryIds.length >= 2 && (
              <button onClick={useSelectedWithConnect}
                className={`w-full py-2.5 rounded-xl text-xs font-bold ${c.btnPrimary}`}>
                🔗 {t('rec_history_use_connect', { count: selectedHistoryIds.length })}
              </button>
            )}
          </div>
        )}
      </div>
    );
  };

  // ════════════════════════════════════════════════════════════
  // MAIN RENDER
  // ════════════════════════════════════════════════════════════
  return (
    <div className={`space-y-4 ${c.text}`}>

      {/* ── Input phase: unified card (header + input) ── */}
      {!results && (
        <div className={`${c.card} border ${c.border} rounded-xl shadow-sm px-5 pt-2.5 pb-5 space-y-4`}>
          <div className="pb-3 border-b border-zinc-500">
            <div className="flex items-start justify-between gap-3">
              <div>
                {/* PF-30 — the wrapper already prints the name as the page <h1>. */}
                <p className={`text-base ${c.textSecondary}`}>
                  <span className="me-2 text-xl">{tool?.icon ?? '🎯'}</span>{toolTagline(tool?.tagline ?? t('rec_tagline'))}
                </p>
                <button onClick={loadExample} disabled={loading} style={{ backgroundColor: (tool?.headerColor ?? '#888888') + '80' }} className="mt-2 px-4 py-2 rounded-full text-sm font-semibold border border-black/25 text-zinc-900 shadow-sm hover:brightness-105 hover:shadow transition disabled:opacity-40 whitespace-nowrap">✨ {t('try_example')}</button>
                {/* Scope chips — signal the breadth of accepted inputs (non-interactive) */}
                <div className="mt-2 flex flex-wrap items-center gap-1.5">
                  <span className={`text-xs ${c.textMuted}`}>{t('rec_scope_label')}</span>
                  {t('rec_scope_items').split(' · ').map((item) => (
                    <span key={item} className={`px-2 py-0.5 rounded-full text-xs ${c.badge}`}>{item}</span>
                  ))}
                </div>
              </div>
              {/* PF-16: the tool's one reset, on the title row, from the first keystroke. */}
              {(results || lectureTitle.trim() || subject.trim() || transcript.trim()) ? (
                <button onClick={handleReset} className={`${c.btnSecondary} px-3 py-1.5 rounded-lg text-xs font-semibold flex-shrink-0 whitespace-nowrap`}>
                  ↺ {t('rec_start_over')}
                </button>
              ) : null}
            </div>
          </div>
          {renderInput()}
        </div>
      )}

      {/* ── Results phase: persistent header card with reset (ternary, not && — see PF-3 replace-mode note) ── */}
      {results ? (
        <div className={`${c.card} border ${c.border} rounded-xl shadow-sm px-5 pt-2.5 pb-5`}>
          <div className="pb-3 border-b border-zinc-500">
            <div className="flex items-start justify-between gap-3">
              <div>
                {/* PF-30 — the wrapper already prints the name as the page <h1>. */}
                <p className={`text-base ${c.textSecondary}`}>
                  <span className="me-2 text-xl">{tool?.icon ?? '🎯'}</span>{toolTagline(tool?.tagline ?? t('rec_tagline'))}
                </p>
              </div>
              {/* PF-16: "Edit Input" below only offers a partial reset (keeps
                  the pasted material); a full Start Over was missing here
                  entirely once results existed. */}
              <button onClick={() => handleReset()} className={`${c.btnSecondary} px-3 py-1.5 rounded-lg text-xs font-semibold flex-shrink-0 whitespace-nowrap`}>
                ↺ {t('rec_start_over')}
              </button>
            </div>
          </div>
        </div>
      ) : null}

      {/* ── Results body ── */}
      {results && (
        <div data-copy-results ref={resultsRef} className="scroll-mt-24 space-y-4">
          {mode === 'distill'     && renderDistill()}
          {mode === 'understand' && renderUnderstand()}
          {mode === 'connect'     && renderConnect()}

          {/* Edit Input — partial reset, returns to input form keeping content */}
          <button onClick={() => { setResults(null); setError(''); }}
            className={`w-full py-3 rounded-xl text-xs font-bold flex items-center justify-center gap-1.5 ${c.btnSecondary}`}>
            <span>✏️</span> {t('rec_edit_input')}
          </button>

          {/* Post-result cross-refs */}
          <div className={`${c.cardAlt} border ${c.border} rounded-xl p-4`}>
            <p className={`text-xs font-semibold uppercase tracking-wide mb-3 ${c.textMuted}`}>🔗 {t('rec_related')}</p>
            <div className="flex flex-wrap gap-3">
              <a href="/BrainDumpBuddy" className={`text-xs ${linkStyle}`}>🧠 {t('rec_braindump')}</a>
              <a href="/MissingLink"          className={`text-xs ${linkStyle}`}>⛓️ {t('rec_missinglink')}</a>
            </div>
          </div>
        </div>
      )}

      {/* ── Error ── */}
      {error && (
        <div className={`p-4 ${c.danger} border rounded-xl flex items-start gap-3`}>
          <span>⚠️</span>
          <p className="text-sm">{error}</p>
        </div>
      )}

      {renderHistory()}
    </div>
  );
};

