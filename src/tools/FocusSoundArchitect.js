// 16s (was 4s): a short loop repeats often enough to read as a mechanical
// tick-tick-tick under the hood, which flattens every texture toward
// "the same static." Longer buffers make the loop seam far less audible.
const BUFFER_SECONDS = 16;

const BRAND = '\n\n— Generated by DeftBrain · deftbrain.com';

function generateWhiteNoise(length) {
  const data = new Float32Array(length);
  for (let i = 0; i < length; i++) data[i] = Math.random() * 2 - 1;
  return data;
}

function generatePinkNoise(length) {
  const data = new Float32Array(length);
  let b0 = 0, b1 = 0, b2 = 0, b3 = 0, b4 = 0, b5 = 0, b6 = 0;
  for (let i = 0; i < length; i++) {
    const white = Math.random() * 2 - 1;
    b0 = 0.99886 * b0 + white * 0.0555179;
    b1 = 0.99332 * b1 + white * 0.0750759;
    b2 = 0.96900 * b2 + white * 0.1538520;
    b3 = 0.86650 * b3 + white * 0.3104856;
    b4 = 0.55000 * b4 + white * 0.5329522;
    b5 = -0.7616 * b5 - white * 0.0168980;
    data[i] = (b0 + b1 + b2 + b3 + b4 + b5 + b6 + white * 0.5362) * 0.11;
    b6 = white * 0.115926;
  }
  return data;
}

function generateBrownNoise(length) {
  const data = new Float32Array(length);
  let last = 0;
  for (let i = 0; i < length; i++) {
    const white = Math.random() * 2 - 1;
    last = (last + (0.02 * white)) / 1.02;
    data[i] = last * 3.5;
  }
  return data;
}

function createNoiseLayer(ctx, noiseGenerator, filterOptions, initialGain = 0) {
  const sr = ctx.sampleRate;
  const bufferSize = sr * BUFFER_SECONDS;
  const buffer = ctx.createBuffer(2, bufferSize, sr);
  const dataL = noiseGenerator(bufferSize);
  const dataR = noiseGenerator(bufferSize);
  // Crossfade the loop seam (~100ms of the tail blended into the head) —
  // without it the raw wrap discontinuity clicks once per loop, which reads
  // as a periodic mechanical tick, worst on brown noise (random DC drift).
  const fade = Math.min(Math.floor(sr * 0.1), bufferSize >> 2);
  for (const data of [dataL, dataR]) {
    for (let i = 0; i < fade; i++) {
      const w = i / fade;
      data[bufferSize - fade + i] = data[bufferSize - fade + i] * (1 - w) + data[i] * w;
    }
  }
  buffer.copyToChannel(dataL, 0);
  buffer.copyToChannel(dataR, 1);
  const source = ctx.createBufferSource();
  source.buffer = buffer;
  source.loop = true;
  const gain = ctx.createGain();
  gain.gain.value = initialGain;
  let lastNode = source;
  let filter = null;
  if (filterOptions) {
    filter = ctx.createBiquadFilter();
    filter.type = filterOptions.type || 'lowpass';
    filter.frequency.value = filterOptions.frequency || 1000;
    if (filterOptions.Q) filter.Q.value = filterOptions.Q;
    lastNode.connect(filter);
    lastNode = filter;
  }
  lastNode.connect(gain);
  source.start(0);
  return {
    // Exposed so callers can attach an LFO to the filter's own frequency
    // param (e.g. a gust sweeping the cutoff) — null when no filter was
    // requested, so callers must guard before using it.
    filter,
    connect: (dest) => gain.connect(dest),
    setVolume: (v) => { gain.gain.value = v; },
    setVolumeSmooth: (v) => {
      gain.gain.cancelScheduledValues(ctx.currentTime);
      gain.gain.setTargetAtTime(v, ctx.currentTime, 0.08);
    },
    stop: () => { try { source.stop(); source.disconnect(); gain.disconnect(); } catch (e) { } },
  };
}

// Shared helper: a gain node whose value an LFO drives up and down around a
// center, used throughout below so each type gets real audible movement
// instead of a fixed filter cutoff sitting on top of static noise.
function attachLfo(ctx, targetParam, { frequency, depth, type = 'sine', phase = 0 }) {
  const lfo = ctx.createOscillator();
  lfo.type = type;
  lfo.frequency.value = frequency;
  const depthGain = ctx.createGain();
  depthGain.gain.value = depth;
  lfo.connect(depthGain);
  depthGain.connect(targetParam);
  // Web Audio oscillators have no phase param; approximate an offset start
  // by delaying the start slightly (only matters for the ear when two LFOs
  // need to feel offset from each other, e.g. ocean's wave-then-hiss).
  lfo.start(ctx.currentTime + phase);
  return lfo;
}

// ═══════════════════════════════════════
// RAIN — a mid/high patter bed (the "body" of rain) with an audible
// intensity swell, plus a quiet gated shimmer standing in for individual
// droplets and a soft low rumble for depth. Deliberately NOT low-passed
// like wind/fire — the patter band is what makes rain read as rain.
// ═══════════════════════════════════════
function createRainLayer(ctx) {
  const gain = ctx.createGain(); gain.gain.value = 0;
  const stops = [];

  const patter = createNoiseLayer(ctx, generateWhiteNoise, { type: 'bandpass', frequency: 1800, Q: 0.7 }, 1);
  const patterGain = ctx.createGain(); patterGain.gain.value = 0.5;
  patter.connect(patterGain); patterGain.connect(gain);
  stops.push(() => patter.stop());

  const shimmer = createNoiseLayer(ctx, generateWhiteNoise, { type: 'highpass', frequency: 6500, Q: 0.5 }, 1);
  const shimmerGain = ctx.createGain(); shimmerGain.gain.value = 0.1;
  shimmer.connect(shimmerGain); shimmerGain.connect(gain);
  const shimmerLfo = attachLfo(ctx, shimmerGain.gain, { frequency: 1.3, depth: 0.08, type: 'square' });
  stops.push(() => { shimmer.stop(); shimmerLfo.stop(); });

  const rumble = createNoiseLayer(ctx, generateBrownNoise, { type: 'lowpass', frequency: 220 }, 1);
  const rumbleGain = ctx.createGain(); rumbleGain.gain.value = 0.18;
  rumble.connect(rumbleGain); rumbleGain.connect(gain);
  stops.push(() => rumble.stop());

  // Intensity: the patter's own filter and volume rise and fall together —
  // rain audibly picking up and easing off, ~18s per cycle.
  const intensityLfo = attachLfo(ctx, patter.filter.frequency, { frequency: 0.055, depth: 700 });
  const intensityVolLfo = attachLfo(ctx, patterGain.gain, { frequency: 0.055, depth: 0.18 });
  stops.push(() => { intensityLfo.stop(); intensityVolLfo.stop(); });

  return {
    connect: (dest) => gain.connect(dest),
    setVolume: (v) => { gain.gain.value = v; },
    setVolumeSmooth: (v) => { gain.gain.cancelScheduledValues(0); gain.gain.setTargetAtTime(v, ctx.currentTime, 0.08); },
    stop: () => { stops.forEach(fn => { try { fn(); } catch (e) { } }); try { gain.disconnect(); } catch (e) { } },
  };
}

// ═══════════════════════════════════════
// OCEAN — a real wave cycle: the low body swells in volume and brightens
// as it "crashes," the surf hiss peaks just after, and a much slower tide
// LFO varies the whole thing over minutes so it never feels on a loop.
// ═══════════════════════════════════════
function createOceanLayer(ctx) {
  const gain = ctx.createGain(); gain.gain.value = 0;
  const stops = [];

  const base = createNoiseLayer(ctx, generateBrownNoise, { type: 'lowpass', frequency: 350 }, 1);
  const baseGain = ctx.createGain(); baseGain.gain.value = 0.35;
  base.connect(baseGain); baseGain.connect(gain);
  stops.push(() => base.stop());

  const surf = createNoiseLayer(ctx, generateWhiteNoise, { type: 'bandpass', frequency: 2800, Q: 0.6 }, 1);
  const surfGain = ctx.createGain(); surfGain.gain.value = 0.1;
  surf.connect(surfGain); surfGain.connect(gain);
  stops.push(() => surf.stop());

  // Wave cycle (~13s): body volume + brightness swell together.
  const waveVolLfo = attachLfo(ctx, baseGain.gain, { frequency: 0.075, depth: 0.28 });
  const waveFilterLfo = attachLfo(ctx, base.filter.frequency, { frequency: 0.075, depth: 220 });
  stops.push(() => { waveVolLfo.stop(); waveFilterLfo.stop(); });

  // Surf peaks a beat after the wave body (slightly offset rate + phase).
  const surfLfo = attachLfo(ctx, surfGain.gain, { frequency: 0.078, depth: 0.16, phase: 1.6 });
  stops.push(() => surfLfo.stop());

  // Tide: a slow ~100s drift in overall presence.
  const tideLfo = attachLfo(ctx, gain.gain, { frequency: 0.01, depth: 0.12 });
  stops.push(() => tideLfo.stop());

  return {
    connect: (dest) => gain.connect(dest),
    setVolume: (v) => { gain.gain.value = v; },
    setVolumeSmooth: (v) => { gain.gain.cancelScheduledValues(0); gain.gain.setTargetAtTime(v, ctx.currentTime, 0.08); },
    stop: () => { stops.forEach(fn => { try { fn(); } catch (e) { } }); try { gain.disconnect(); } catch (e) { } },
  };
}

// ═══════════════════════════════════════
// WIND — a broad low-mid body (no patter, no rustle — that's what keeps it
// distinct from rain and forest) with real gusts: volume and filter cutoff
// sweep together on a slow cycle, plus a faster irregular gust layered on
// top so it isn't perfectly periodic, and a narrow "howl" band that only
// emerges at the peak of a gust.
// ═══════════════════════════════════════
function createWindLayer(ctx) {
  const gain = ctx.createGain(); gain.gain.value = 0;
  const stops = [];

  const wind = createNoiseLayer(ctx, generatePinkNoise, { type: 'lowpass', frequency: 700 }, 1);
  const windGain = ctx.createGain(); windGain.gain.value = 0.42;
  wind.connect(windGain); windGain.connect(gain);
  stops.push(() => wind.stop());

  const howl = createNoiseLayer(ctx, generatePinkNoise, { type: 'bandpass', frequency: 1100, Q: 7 }, 1);
  const howlGain = ctx.createGain(); howlGain.gain.value = 0;
  howl.connect(howlGain); howlGain.connect(gain);
  stops.push(() => howl.stop());

  // Main gust (~9s): volume + brightness rise together, howl rises with it.
  const gustVolLfo = attachLfo(ctx, windGain.gain, { frequency: 0.11, depth: 0.3 });
  const gustFilterLfo = attachLfo(ctx, wind.filter.frequency, { frequency: 0.11, depth: 350 });
  const gustHowlLfo = attachLfo(ctx, howlGain.gain, { frequency: 0.11, depth: 0.09 });
  stops.push(() => { gustVolLfo.stop(); gustFilterLfo.stop(); gustHowlLfo.stop(); });

  // A second, irregular gust at a non-integer-ratio rate so gusts don't
  // line up into an obvious repeating pattern.
  const accentLfo = attachLfo(ctx, gain.gain, { frequency: 0.037, depth: 0.14, type: 'triangle' });
  stops.push(() => accentLfo.stop());

  return {
    connect: (dest) => gain.connect(dest),
    setVolume: (v) => { gain.gain.value = v; },
    setVolumeSmooth: (v) => { gain.gain.cancelScheduledValues(0); gain.gain.setTargetAtTime(v, ctx.currentTime, 0.08); },
    stop: () => { stops.forEach(fn => { try { fn(); } catch (e) { } }); try { gain.disconnect(); } catch (e) { } },
  };
}

// ═══════════════════════════════════════
// FOREST — a narrower, brighter leaf bed than wind (so the two don't
// collapse into the same sound), plus two independent chirp voices that
// are actually gated on and off like calls, not a continuously-present
// tone, and a slow presence envelope so the birds come and go.
// ═══════════════════════════════════════
function createForestLayer(ctx) {
  const gain = ctx.createGain(); gain.gain.value = 0;
  const stops = [];

  const leaves = createNoiseLayer(ctx, generatePinkNoise, { type: 'bandpass', frequency: 1000, Q: 0.5 }, 1);
  const leavesGain = ctx.createGain(); leavesGain.gain.value = 0.32;
  leaves.connect(leavesGain); leavesGain.connect(gain);
  stops.push(() => leaves.stop());
  const breezeLfo = attachLfo(ctx, leavesGain.gain, { frequency: 0.07, depth: 0.1 });
  stops.push(() => breezeLfo.stop());

  const chirpA = createNoiseLayer(ctx, generateWhiteNoise, { type: 'bandpass', frequency: 3500, Q: 12 }, 1);
  const chirpAGain = ctx.createGain(); chirpAGain.gain.value = 0;
  chirpA.connect(chirpAGain); chirpAGain.connect(gain);
  const chirpALfo = attachLfo(ctx, chirpAGain.gain, { frequency: 1.7, depth: 0.16, type: 'square' });
  stops.push(() => { chirpA.stop(); chirpALfo.stop(); });

  const chirpB = createNoiseLayer(ctx, generateWhiteNoise, { type: 'bandpass', frequency: 5200, Q: 10 }, 1);
  const chirpBGain = ctx.createGain(); chirpBGain.gain.value = 0;
  chirpB.connect(chirpBGain); chirpBGain.connect(gain);
  const chirpBLfo = attachLfo(ctx, chirpBGain.gain, { frequency: 1.1, depth: 0.11, type: 'square', phase: 0.4 });
  stops.push(() => { chirpB.stop(); chirpBLfo.stop(); });

  // Presence envelope: the whole chirp mix fades in and out over ~40s so
  // birds feel like they come and go rather than looping on top.
  const presenceGain = ctx.createGain(); presenceGain.gain.value = 0.6;
  chirpAGain.disconnect(); chirpAGain.connect(presenceGain);
  chirpBGain.disconnect(); chirpBGain.connect(presenceGain);
  presenceGain.connect(gain);
  const presenceLfo = attachLfo(ctx, presenceGain.gain, { frequency: 0.025, depth: 0.4 });
  stops.push(() => presenceLfo.stop());

  return {
    connect: (dest) => gain.connect(dest),
    setVolume: (v) => { gain.gain.value = v; },
    setVolumeSmooth: (v) => { gain.gain.cancelScheduledValues(0); gain.gain.setTargetAtTime(v, ctx.currentTime, 0.08); },
    stop: () => { stops.forEach(fn => { try { fn(); } catch (e) { } }); try { gain.disconnect(); presenceGain.disconnect(); } catch (e) { } },
  };
}

