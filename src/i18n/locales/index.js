// src/i18n/locales/index.js
// ──────────────────────────────────────────────────────────────────────
// Runtime entry point for the translation catalog.
//
// THE CATALOG IS NOT IMPORTED HERE ANY MORE. It used to be: 126 static
// imports of ./tools/<tool>.js, each carrying all thirteen languages,
// merged into one RESOURCES object. That put every string of every tool in
// every language into the main bundle — 15 MB of a 19.9 MB download, and
// twelve-thirteenths of it in languages the visitor cannot read.
//
// Authoring did not change. Each tool still owns one file under ./tools/
// holding all thirteen languages, which is the right shape for writing and
// reviewing copy. scripts/build-locales.js reads that directory (it
// auto-discovers, so adding a tool needs no edit here) and pivots it into
// one flat file per language under ./generated/. Those are build artifacts:
// regenerated by prestart and prebuild, gitignored, never edited by hand.
//
// To localize a new tool: create src/i18n/locales/tools/<tool>.js exporting
// `export const <name> = { en: {...}, ... }`. That is the whole step — the
// generator, localization-audit.js and localization-smoke.js all discover it.
//
// ONE DEV GOTCHA: a running dev server reads ./generated/, which is built by
// predev:frontend and NOT rebuilt on save. Edit a locale file mid-session and
// the new keys render as their own names (BR_SEC_ABOUT) until you run
// `npm run build:locales`. Production is never affected — prebuild regenerates.
// ──────────────────────────────────────────────────────────────────────

import { base } from './base';

// English is deliberately static. t() falls back to English for any missing
// key, so bundling it means a visitor whose language is still downloading
// reads correct English rather than raw key names — and English readers,
// who are nearly all of them, wait for nothing at all.
import en from './generated/en.json';

const LANGS = Object.keys(base);

// Every other language is its own chunk, fetched only if chosen. The
// template literal is what tells webpack to split ./generated/*.json; keep
// it literal, not a variable holding the path, or it silently bundles all
// thirteen again.
export function loadLanguage(lang) {
  if (lang === 'en') return Promise.resolve(en);
  return import(
    /* webpackChunkName: "locale-[request]" */
    `./generated/${lang}.json`
  ).then(m => m.default || m);
}

export const SUPPORTED_LANGUAGES = LANGS;
export { en as EN_RESOURCES };
